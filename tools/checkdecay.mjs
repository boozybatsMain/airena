#!/usr/bin/env node
/**
 * ГЕЙТ «ЭФФЕКТ СРАБОТАЛ — И ЕГО НЕТ».
 *
 * ── откуда правило ────────────────────────────────────────────────────────
 *
 * Заказ основателя 04.09, дословно: «лужи на полу слишком долго держатся,
 * слишком яркие и слишком заметные. Эффект сработал — пусть исчезает сразу
 * после эффекта, не моментально, а постепенно. Никакого мусора и визуального
 * шума». Это не вкус одного модуля: это свойство слоя, и до этого гейта оно
 * жило дисциплиной десяти файлов. Дисциплина не сработала дважды — после
 * общей чистки в дереве всё ещё оставались 20 с у штатного луча Nova, 16 и
 * 10 с у времени, и оба места были снабжены аргументом, почему именно им
 * можно. Правило, у которого нет проверки, — это пожелание.
 *
 * ── что именно проверяется ────────────────────────────────────────────────
 *
 * Гейт ЗАПУСКАЕТ каждую форму каждого модуля вхолостую — без браузера, без
 * WebGPU, на подставном `vfx` — и ловит ВСЁ, что модуль просит нарисовать:
 * следы на полу (`kit.decal`), меши со своим сроком (`spawnMesh`) и пачки
 * частиц (`Particles.emit`). У каждого просчитывается момент, когда его на
 * экране гарантированно нет, и он сравнивается с длительностью САМОЙ ФОРМЫ.
 *
 * Три порога, и каждый — не круглое число, а следствие:
 *
 *   ХВОСТ ≤ 5.0 с после конца формы. Самая длинная законная форма грамматики
 *   — стена и щит по 5 с; хвост, равный ей, — это уже второй такой же эффект
 *   поверх первого. Реальные модули после чистки 04.09 держатся в 2.2–4.5.
 *
 *   ВЫДЕРЖКА следа ≤ `DECAL_HOLD_MAX` (8 с) — тот же потолок, что зажат в
 *   `kit.decal`. Здесь он проверяется НА ВХОДЕ, чтобы модуль не полагался
 *   молча на зажим: зажатое значение и осознанное значение выглядят на экране
 *   одинаково, а читаются в коде противоположно.
 *
 *   УХОД следа ≥ 0.6 с. Обратная сторона того же заказа: «не моментально».
 *   След, который исчезает за три кадра, — это выключатель, и он читается как
 *   баг рендера, а не как затухание.
 *
 * ── почему без браузера ───────────────────────────────────────────────────
 *
 * Потому что иначе гейт стоил бы 25 минут GPU и не попал бы в `npm test`.
 * Модули строят узловые материалы и геометрию — это чистый JS, компиляция
 * шейдера случается только у настоящего рендерера, которого здесь нет. Всё,
 * что модуль умеет сказать про ВРЕМЯ, он говорит в аргументах вызовов, и
 * именно они здесь и записываются.
 *
 *   node tools/checkdecay.mjs
 *   node tools/checkdecay.mjs --falsify   ломает правило и проверяет, что гейт краснеет
 */

import { registerHooks } from 'node:module';

/*
 * 'three' → 'three/webgpu' НА ВРЕМЯ ЭТОГО ПРОЦЕССА.
 *
 * Во вьювере это делает importmap страницы (`src/viewer/index.html`: "three":
 * "/vendor/three.webgpu.js"), поэтому модули пишут `import * as THREE from
 * 'three'` и получают узловые материалы. В node тот же специфер приводит к
 * обычной сборке, где `MeshBasicNodeMaterial` нет вовсе, — и гейт молча
 * пропускал бы 78 форм из 90 с «не конструктор». Пропуск, который выглядит как
 * зелёный прогон, хуже красного: правило перестаёт проверяться, а страница
 * гейта продолжает утверждать, что проверяется.
 *
 * Хук — та же подмена, что и importmap, и ровно в том же месте цепочки:
 * разрешение имени. Ничего, кроме имени 'three', он не трогает.
 */
registerHooks({
  resolve(spec, ctx, next) { return next(spec === 'three' ? 'three/webgpu' : spec, ctx); },
});

const THREE = await import('three');
const { ELEMENTS } = await import('../src/skills/registry.js');
const kit = await import('../src/viewer/vfx/kit.js');

const FALSIFY = process.argv.includes('--falsify');

/* Пороги — политика слоя, а не вкус гейта: они объявлены в `kit.js`
   рядом с потолком выдержки, там же и объяснены. */
const MAX_TAIL = kit.TAIL_MAX;
const MIN_FADE = kit.FADE_MIN;
/*
 * НОСИТЕЛЬ СТАТУСА — НЕ ХВОСТ. `status` — единственная форма, чью длительность
 * симуляция продлевает тиками (горение подсыпает секунды, пока горит), поэтому
 * её носитель заводится с потолком в минуту и гасит себя сам по `until`,
 * которое записывает сим. Считать этот потолок хвостом значило бы обвинять
 * модуль в шестидесяти секундах, которых на экране не бывает. Всё, что живёт
 * дольше этого порога, из подсчёта хвоста исключается — и тут же проверяется
 * отдельно: такой носитель имеет право быть ТОЛЬКО у `status`.
 */
const CARRIER_MIN = 20;

let bad = 0;
