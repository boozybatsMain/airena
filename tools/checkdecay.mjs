/*
 * ── ГОНЯЕТСЯ НАСТОЯЩИЙ `Vfx`, А НЕ ЗАГЛУШКА ──────────────────────────────
 *
 * Первая версия гейта подставляла руками собранный объект с полями `body`,
 * `add`, `flights`. Он разошёлся с настоящим на первом же прогоне: у живого
 * `Vfx` поле `add` — это ПУЛ ЧАСТИЦ (алиас тела плюс половина в свечение), а
 * не `scene.add`, и сорок шесть форм упали с «vfx.add.emit is not a
 * function». Заглушка, которая расходится с предметом, проверяет заглушку.
 *
 * Поэтому здесь живой `Vfx` из `vfx.js`: он строит настоящие пулы, настоящие
 * материалы и настоящий диспетчер `play`, и единственное, что подменено, —
 * `spawnMesh` (его во вьювере даёт `main.js`) и источники света. Сроки
 * частиц потом читаются ПРЯМО ИЗ ПУЛА: раскладка `cfg` — (born, life, size,
 * форма) со смещением `off.cfg`, и это то же число, по которому частица
 * гаснет на экране.
 */
const { Vfx } = await import('../src/viewer/vfx.js');

function makeVfx(rec, { warm = true } = {}) {
  const scene = new THREE.Scene();
  /* Ссылка вперёд: обработчик `spawnMesh` переводит часы того же `vfx`,
     который в этот момент ещё строится. */
  const vfxRef = { now: 0 };
  const vfx = new Vfx(scene, {
    spawnMesh(obj, life, update) {
      const secs = Number(life) || 0;
      rec.push({ what: 'mesh', end: secs, obj, update });
      /*
       * Обновление зовётся ОДИН РАЗ на конце жизни: часть форм кладёт след или
       * рождает частицы именно там (лужа навеса — в момент, когда колба
       * разбилась), и без этого вызова гейт их бы не увидел.
       *
       * ЧАСЫ ПРИ ЭТОМ ПЕРЕВОДЯТСЯ ВПЕРЁД, и это не деталь. Метка, положенная
       * из хода формы, рождается не в нуле, а тогда, когда её положили; гейт,
       * читавший только `at`, считал её родившейся сразу и недосчитывал ей
       * ровно жизнь носителя. Поймал это агент молнии: удар зоны с неба на
       * 2.4 с просил выдержку `D + burnAfter` от МОМЕНТА УДАРА, то есть гаснул
       * на 8.3 с при зоне 3.0 — хвост 5.3 при потолке 5.0, а гейт был зелёным.
       */
      const back = vfxRef.now;
      vfxRef.now = secs;
      if (warm && typeof update === 'function') { try { update(obj, 1); } catch { /* поздняя ветка не обязана быть достижимой */ } }
      vfxRef.now = back;
      return obj;
    },
  });
  vfx.now = 0;
  /* Часы у гейта одни: `vfxRef` — окно в то же поле, через которое их двигает
     `spawnMesh`. */
  Object.defineProperty(vfxRef, 'now', {
    get: () => vfx.now, set: (v) => { vfx.now = v; },
  });
  return vfx;
}

/**
 * ПРОГОН НОСИТЕЛЯ ПО ВРЕМЕНИ. Возвращает, был ли уход щелчком.
 *
 * Носитель статуса — это меш с обновлением, которое читает `vfx.now`. Гейт
 * двигает часы шагами по его жизни и смотрит на непрозрачность и `visible`
 * каждого потомка: если непрозрачность падает больше чем вдвое за шаг короче
 * `FADE_MIN`, или объект прячется при ненулевой непрозрачности — это
 * выключатель, а не затухание.
 */
/*
 * КАКИЕ ФОРМЫ ОБЯЗАНЫ УХОДИТЬ ЗАТУХАНИЕМ, А КАКИЕ — ПРИЛЁТОМ.
 *
 * Деление не выдумано под гейт, оно уже есть в грамматике доставок. Носитель
 * бывает СТОЯЧИЙ и БЕГУЩИЙ. Стоячий — зона, оболочка, статус, конус, луч,
 * стена: он остаётся на месте и сам является остатком эффекта, поэтому обязан
 * гаснуть. Бегущий — болт, навес, прыжок, рывок, мигание, а также события
 * замаха и удара: он кончается тем, что ДОЛЕТЕЛ, и его исчезновение — это
 * смена сцены, а не обрыв. Требовать от колбы навеса, чтобы она полсекунды
 * растворялась в воздухе уже ПОСЛЕ попадания, значит ломать попадание.
 *
 * Замер, на котором это видно: у пяти стихий подряд «lob» давал ровно 0.07 с —
 * один шаг пробы, то есть снятие меша в миг приземления. Заказ основателя
 * («эффект произошёл — и его нет, не резко, а плавно») — про ОСТАТОК на
 * экране; навес остатка не оставляет, у него след и всплеск.
 */
const STANDING = new Set(['zone', 'self', 'status', 'cone', 'beam', 'wall']);

function probeCarrier(vfx, rec, e, formLife = null, form = '') {
  const carriers = rec.filter((r) => r.what === 'mesh' && r.update && (r.end || 0) > 0);
  if (!carriers.length) return { snap: false, blind: true, note: 'носителя нет — форма живёт частицами' };
  const dur = Number(e.duration) || Number(formLife) || 4;
  /*
   * ШАГ ПРОБЫ ОКРУГЛЯЛ ТОЛЬКО В СВОЮ ПОЛЬЗУ.
   *
   * Было `FADE_MIN / 8` = 0.075 с при пороге 0.18 с. Точка входа берётся как
   * ПОСЛЕДНИЙ отсчёт выше половины пика, точка выхода — как ПЕРВЫЙ ниже пяти
   * процентов; при таком шаге измеренная длительность завышена до двух шагов,
   * то есть до +0.15 с — почти на весь порог. Судья приёмки не поверил
   * зелёному, прогнал тот же гейт шагом 0.01 с и нашёл ШЕСТЬ форм, которые
   * уходят быстрее собственного порога слоя, а печатаются со знаком «✓»:
   * arc/wall 0.14, gravity/status 0.14, kinetic/self 0.14, arc/beam 0.17,
   * ember/beam 0.17, kinetic/wall 0.17.
   *
   * Инструмент, ошибающийся ТОЛЬКО в сторону зачёта, — это не измерение, а
   * поблажка. Шаг уменьшен в двенадцать раз (0.006 с): ошибка округления
   * стала 0.012 с при пороге 0.18, то есть меньше семи процентов. Прогон при
   * этом остаётся секундным: окно короткое, а считается по нему арифметика,
   * а не рендер.
   */
  const STEP = kit.FADE_MIN / 100;
  /*
   * ── МЕРИТСЯ ЭФФЕКТ ЦЕЛИКОМ, А НЕ КАЖДЫЙ ЕГО МЕШ ПО ОТДЕЛЬНОСТИ ────────
   *
   * Форма — это не один носитель: у луча отдельно ядро, отдельно рубашка,
   * отдельно кольцо у цели, и КАЖДЫЙ из них имеет право кончиться разом.
   * Первая версия брала худшего из них и обвиняла форму — сорок форм из
   * девяноста «краснели» на том, что у эффекта просто есть короткая деталь.
   * Зритель видит СУММУ: пока горит хоть один меш, эффект на экране есть.
   * Поэтому в каждый отсчёт берётся максимум по всем носителям, и уже эта
   * общая кривая обязана уходить не щелчком.
   *
   * ОГИБАЮЩАЯ, А НЕ МГНОВЕННАЯ ЯРКОСТЬ: скользящий максимум вперёд на два
   * `FADE_MIN`. У пульсирующего статуса (молния бьёт разрядами) вход обязан
   * быть мгновенным, и запрещать это значило бы запрещать ритм.
   *
   * ОКНО — только конец: от `dur − FADE_MIN` и до конца самого долгого
   * носителя (но не дальше `CARRIER_MIN`: у статуса потолок минутный).
   * Правило заказа — про то, КАК ЭФФЕКТ УХОДИТ, а не про то, что он делает,
   * пока идёт.
   */
  const T0 = Math.max(0, dur - kit.FADE_MIN);
  const LAST = Math.min(CARRIER_MIN, Math.max(...carriers.map((c) => c.end)));
  /*
   * ТРЕБОВАНИЕ СОРАЗМЕРНО ФОРМЕ, А НЕ ОТСЕКАЕТ ЕЁ ПО ДЛИНЕ.
   *
   * Здесь стоял порог: формы короче двух `FADE_MIN` (1.2 с) выводились из
   * замера вовсе. Довод был верный — требовать от замаха в полсекунды 0.18 с
   * затухания значит отдать под уход треть его жизни и получить кисель вместо
   * щелчка кастинга. А решение оказалось плохим, и это видно по последствию:
   * агент молнии удлинил веер конуса с 0.8 до 1.25 с, прямо написав в отчёте,
   * что делает это, ЧТОБЫ ГЕЙТ ЕГО ИЗМЕРИЛ. Порог-отсечка создаёт мёртвую
   * зону и вознаграждает за то, чтобы из неё выбраться, — а живут в этой зоне
   * как раз самые быстрые формы, где щелчок заметнее всего.
   *
   * Правильнее не отсекать, а МАСШТАБИРОВАТЬ: уход обязан занимать не меньше
   * четверти жизни носителя, но и не больше `0.3 · FADE_MIN` в абсолюте.
   * Полусекундному замаху хватит 0.125 с, полуторасекундной зоне нужно 0.18 —
   * и ни у кого нет причины расти ради проверки.
   */
  if (form && !STANDING.has(form)) {
    return { snap: false, blind: true, note: `«${form}» — бегущий носитель: кончается прилётом, а не остатком` };
  }
  const T1 = LAST + kit.FADE_MIN;
  const ts = [], as = [];
  let hidden = false;
  for (let t = T0; t <= T1; t += STEP) {
    vfx.now = t;
    let total = 0;
    for (const c of carriers) {
      /*
       * ЖИЗНЬ КОНЧИЛАСЬ — МЕША БОЛЬШЕ НЕТ. Пул снимает носитель со сцены в
       * конце его срока, и если к этому мигу он ещё непрозрачен, зритель
       * видит ровно тот щелчок, на который жаловался основатель. Поэтому
       * после «end» вклад ноль: не «оставим последний кадр навсегда», а
       * «здесь его убрали». Первая версия держала u = 1 бесконечно, и
       * кривая никогда не доходила до нуля — сорок форм получали пустое
       * «НЕ ИЗМЕРЕНО» вместо честного приговора.
       */
      if (t > c.end) continue;
      try { c.update(c.obj, Math.min(1, t / Math.max(0.001, c.end))); } catch { continue; }
      let a = 0, vis = false;
      /*
       * ВИДИМОСТЬ НАСЛЕДУЕТСЯ. `traverse` обходит всех потомков подряд, а
       * модули прячут ГРУППУ: у детей при этом `visible` остаётся true, и
       * гейт считал спрятанную фигуру горящей. Кинетика из-за этого
       * получала «НЕ ИЗМЕРЕНО» вместо точного «выключатель» — приговор
       * верный, повод названный неверно.
       */
      const shown = (o) => { for (let n = o; n; n = n.parent) if (!n.visible) return false; return true; };
      c.obj.traverse?.((o) => {
        if (!o.material) return;
        if (!shown(o)) return;
        vis = true;
        const m = Array.isArray(o.material) ? o.material[0] : o.material;
        const f = m?.userData?.fade;
        a = Math.max(a, f ? f.value : (m?.opacity ?? 0));
      });
      /*
       * ПРЯТАТЬ В КОНЦЕ ЖИЗНИ — НЕ ВЫКЛЮЧАТЕЛЬ. Болт гасит себя в миг
       * попадания, и дальше горит удар: это смена сцены, а не обрыв. Ловим
       * только то, что спряталось РАНЬШЕ срока — там за мешем ничего нет.
       */
      if (!vis && a > 0.05 && t < c.end - STEP) hidden = true;
      total = Math.max(total, vis ? a : 0);
    }
    ts.push(t); as.push(total);
  }
  vfx.now = 0;
  /* «Окно пустое» — это НЕ проверка. Две строки (gravity/self, time/self)
     проходили с галочкой и этим текстом; судья пересчитал и был прав. */
  if (!as.length) return { snap: false, blind: true, note: 'окно пустое — мерить было нечего' };
  /*
   * ОГИБАЮЩАЯ, А НЕ МГНОВЕННАЯ ЯРКОСТЬ: скользящий максимум вперёд на два
   * `FADE_MIN`. У пульсирующего статуса (молния бьёт разрядами) вход обязан
   * быть мгновенным, и запрещать это значило бы запрещать ритм. Гейт судит
   * только КАК ЭФФЕКТ УХОДИТ, а не что он делает, пока идёт.
   */
  /*
   * ОКНО ОГИБАЮЩЕЙ СОРАЗМЕРНО ФОРМЕ. Два `FADE_MIN` — это 1.2 с, а «charge»
   * живёт 0.5: скользящий максимум длиннее самого сигнала держит кривую на
   * пике до последнего отсчёта, и гейт печатал «падает за 0.07 c» ровно на
   * тридцати формах — то есть ШАГ ПРОБЫ, а не спад. Число одно и то же у
   * жара, мороза, дуги и радиации; совпадение такого рода означает, что
   * мерили инструмент, а не предмет. Окно урезано третью жизни носителя.
   */
  const span = Math.max(1, Math.round(Math.min(kit.FADE_MIN * 2, LAST / 3) / STEP));
  const env = as.map((_, i) => Math.max(...as.slice(i, i + span + 1)));
  const peak = Math.max(...env);
  if (peak <= 0.05) return { snap: false, blind: true, note: 'к концу окна носители уже погасли' };
  let on = -1, off = -1;
  for (let i = 0; i < env.length; i++) if (env[i] >= peak * 0.5) on = i;
  for (let i = on + 1; i < env.length; i++) if (env[i] <= peak * 0.05) { off = i; break; }
  /*
   * ТРЕБОВАНИЕ РАСТЁТ ВМЕСТЕ С ФОРМОЙ — НО В ТЕХ ЖЕ ЕДИНИЦАХ, ЧТО И ЗАМЕР.
   *
   * Судья приёмки написал: порог 0.18 с не зависит от длины формы, и двадцать
   * форм из сорока трёх уходят за 0.19–0.25 с при носителях в три-шесть
   * секунд; «зелёный цвет здесь означает „не мгновенно“, а не „плавно“».
   * Замечание верное, и первая попытка его закрыть была неверной: я поставил
   * порог «не меньше 15 % жизни носителя» — и получил 34 красных строки,
   * включая те формы, которые гаснут правильно.
   *
   * Ошибка была в ЕДИНИЦАХ. Проба меряет не длительность затухания, а участок
   * «половина пика → пять процентов». У сглаженного полиномом ухода этот
   * участок равен 0.365 его длины, у прямой — 0.45. То есть требование
   * «уход ≥ 0.9 с» на языке пробы означает 0.33 с, а не 0.9; поставив 0.6,
   * я потребовал бы от шестисекундной оболочки полутора секунд растворения —
   * киселя, которого никто не просил.
   *
   * Здесь — то же намерение в правильных единицах: участок растёт как
   * 0.045·LAST (это примерно двенадцатая часть жизни в пересчёте на
   * длительность ухода), не опускается ниже прежних 0.18 с и упирается в
   * потолок 0.30 с — иначе минутный статус пришлось бы гасить секундами.
   * Замах 0.4 с — 0.10, конус 1.2 с — 0.18, зона 4.2 с — 0.19, оболочка
   * 6.3 с — 0.28.
   */
  const need = Math.min(0.30, Math.max(Math.min(kit.FADE_MIN * 0.3, LAST * 0.25), LAST * 0.045));
  /*
   * «НЕ ДОГОРЕЛ» — ЭТО НЕ ЗЕЛЁНЫЙ. Если общая кривая к концу окна так и не
   * дошла до нуля, утверждение было бы пустым, а пустое утверждение хуже
   * отсутствующего: судья приёмки нашёл пять таких строк со знаком ✓.
   */
  if (off < 0) return { snap: true, note: 'НЕ ИЗМЕРЕНО: к концу окна общая кривая не дошла до нуля' };
  const took = ts[off] - ts[on];
  const snap = hidden || took < need;
  return {
    snap,
    note: hidden ? 'меш спрятан при ненулевой непрозрачности — это выключатель'
      : `общая огибающая падает за ${took.toFixed(2)} c (нужно ≥ ${need.toFixed(2)}, носитель ${LAST.toFixed(2)} c)`,
  };
}

/** Когда гаснет последняя частица пула: max(born + life) по кольцу. */
function lastParticle(pool) {
  const A = pool.arr, S = pool.stride, O = pool.off.cfg;
  let end = 0;
  for (let i = 0; i < pool.max; i++) {
    const born = A[i * S + O], life = A[i * S + O + 1];
    if (life > 0) end = Math.max(end, born + life);
  }
  return end;
}

/** Обнулить кольца пулов: иначе форма унаследует частицы предыдущей. */
function clearPools(vfx) {
  for (const pool of [vfx.body, vfx.glow]) { pool.arr.fill(0); pool.head = 0; }
}

