/**
 * Гейт гантлета: прибор баланса не разъехался.
 *
 *   node tools/checkgauntlet.mjs
 *   node tools/checkgauntlet.mjs --falsify
 *
 * ── зачем в гейтах, а не только в инструменте ──────────────────────────────
 *
 * `tools/gauntlet.mjs` умеет проверять сам себя и печатать «прибор кривой» —
 * но он не входил в `npm test`, то есть его вердикт никого не останавливал.
 * Ревью нашло гантлет красным и работающим: он уже отвечал игроку на экране,
 * при том что сам себя объявил негодным.
 *
 * Проверяется два свойства, и оба нужны:
 *
 *   РАЗНОРОДНОСТЬ. Члены гантлета обязаны бить РАЗНЫХ соперников. Если все
 *     пятеро бьют одних и тех же, это не пять способов выиграть, а один в
 *     пяти обличьях, и форма распределения перестаёт что-либо значить.
 *
 *   ОТСЧЁТ. Вердикт «доминирует» считается относительно лучшего из самих
 *     пятерых (`BASELINE.bestMin`). Если поле поехало, а число в коде
 *     осталось, вердикт врёт — и врёт в сторону «всё в порядке».
 *
 * Наличие сильнейшего в поле ошибкой НЕ считается: кандидата надо об кого-то
 * испытывать. При мозге без планов сильнейшая стратегия — живучесть, и это
 * измеренный факт про игру, а не про прибор.
 */

import { BASELINE, GAUNTLET, isDiverse, readShape } from '../src/skills/gauntlet.js';
import { VIABILITY_ROUNDS, viability } from '../src/server/forge/viability.js';
import { KIT_PRESETS } from '../src/server/forge/pipeline.js';
import { compileKit } from '../src/skills/compile.js';
import { POOL_SIZE, closePool, runJobs, superviseSelf } from './matchpool.mjs';

superviseSelf('AIRENA_CHECKGAUNTLET_CHILD');

/*
 * ДВЕНАДЦАТЬ, А НЕ ЧЕТЫРЕ.
 *
 * На четырёх сидах сетка 12.5 п.п., и на ней у поля пропадает то самое
 * свойство, ради которого гейт написан: цикл не виден, а «лучший худший»
 * читается как 50% против 33.8% на двадцати. Гейт, меряющий на разрешении, где
 * проверяемого свойства не существует, проверяет шум.
 *
 * Двенадцать сидов на пару — это 600 боёв и около минуты. Дорого для гейта, но
 * дешевле, чем зелёная галочка, которая ничего не значит.
 */
const ROUNDS = 12;
let bad = 0;
const ok = (name, pass, note) => {
  console.log(`  ${pass ? '✓' : '✗'} ${name}${note ? `  ${note}` : ''}`);
  if (!pass) bad++;
};

console.log('\n  ГЕЙТ ГАНТЛЕТА\n');

{
  const broken = GAUNTLET.filter((g) => compileKit(g.kit).problems.length);
  ok('все пятеро законны', broken.length === 0,
    broken.length ? broken.map((g) => g.id).join(', ') : `${GAUNTLET.length} наборов`);
}

const jobs = []; const meta = [];
for (let i = 0; i < GAUNTLET.length; i++) {
  for (let j = 0; j < GAUNTLET.length; j++) {
    for (let s = 0; s < ROUNDS; s++) {
      for (const flip of [false, true]) {
        jobs.push(flip
          /* Сиды РАЗНЕСЕНЫ, а не подряд. Стояло `2000 + s`: двенадцать соседних
             чисел в детерминированной симуляции дают двенадцать похожих боёв,
             и поле читалось иначе, чем у `gauntletfield.mjs` с тем же числом
             сидов — 54% против 37.5%. Тот же шаг, что в `viability.js`, чтобы
             гейт и продукт мерили одно. */
          ? { a: GAUNTLET[j].kit, b: GAUNTLET[i].kit, seed: 900 + s * 7919, sym: false, real: true }
          : { a: GAUNTLET[i].kit, b: GAUNTLET[j].kit, seed: 900 + s * 7919, sym: false, real: true });
        meta.push({ i, j, flip });
      }
    }
  }
}
const out = await runJobs(jobs);
const score = GAUNTLET.map(() => GAUNTLET.map(() => ({ w: 0, n: 0 })));
for (let k = 0; k < out.length; k++) {
  const m = meta[k]; const r = out[k];
  if (r === 'error') continue;
  const cell = score[m.i][m.j];
  cell.n++;
  const mine = m.flip ? 'gorilla' : 'octopus';
  if (r === mine) cell.w++;
  else if (r === null) cell.w += 0.5;
}
const table = score.map((row) => row.map((c) => (c.n ? c.w / c.n : NaN)));

const div = isDiverse(table);
ok('гантлет разнороден: члены бьют разных', div.ok,
  `${div.unique} различных стилей из ${div.of}`);

const mins = table.map((row, i) => Math.min(...row.filter((_, j) => j !== i).filter(Number.isFinite)));
const maxs = table.map((row, i) => Math.max(...row.filter((_, j) => j !== i).filter(Number.isFinite)));
const bestMin = Math.max(...mins);

/*
 * ОТСЧЁТ ОБЯЗАН БЫТЬ ВЫШЕ ПОЛЯ, А НЕ РАВЕН ЕМУ.
 *
 * Раньше здесь сверялось «отсчёт совпадает с полем»: `bestMin` был буквально
 * худшим результатом лучшего из пятерых. Замер показал, чего это стоит — три
 * СТАРТОВЫХ набора игры получали вердикт «это дыра, её и надо резать», потому
 * что рукодельные наборы сильнее пяти случайных. Смысл вердикта изменён:
 * «доминирует» значит «сильнее всего, что мы отгружаем», и проверять надо два
 * неравенства, а не одно совпадение.
 */
const drifted = (measured, recorded) => Math.abs(measured - recorded) > 0.12;
ok('отсчёт выше поля', BASELINE.bestMin > bestMin,
  `в поле ${(bestMin * 100).toFixed(0)}%, отсчёт ${(BASELINE.bestMin * 100).toFixed(0)}%`);
ok('и не оторван от поля', BASELINE.bestMin - bestMin < 0.35,
  `разрыв ${((BASELINE.bestMin - bestMin) * 100).toFixed(0)} п.п. — выше 35 отсчёт перестаёт быть достижимым`);

/*
 * И НИ ОДИН СТАРТОВЫЙ НАБОР ИГРЫ НЕ «ДЫРА».
 *
 * Это тот самый дефект, найденный ревью: арифметика была верна, а продукт
 * собирался сказать человеку про свой же стартовый набор, что его надо резать.
 * Проверяется продуктовым путём — `viability()`, а не таблицей, — потому что
 * игроку отвечает именно он.
 */
for (const [name, preset] of Object.entries(KIT_PRESETS)) {
  const v = await viability(preset.kit, preset.archetype || 'octopus');
  ok(`стартовый набор «${name}» не объявлен дырой`, v.shape.verdict !== 'dominant',
    `${v.shape.verdict}, худший ${(v.shape.min * 100).toFixed(1)}%`);
}

/*
 * ВЕРДИКТ «ДОМИНИРУЕТ» ОБЯЗАН БЫТЬ ДОСТИЖИМ НА ТОЙ СЕТКЕ, ГДЕ ЕГО СЧИТАЮТ.
 *
 * Здесь стояло `readShape([1,1,1,1,1]).verdict === 'dominant'` — рукодельный
 * вектор из единиц, истинный при любом пороге ≤ 1. То есть проверка
 * достижимости не проверяла достижимость.
 *
 * Считает вердикт `viability.js`, и он играет `per` боёв на соперника, где
 * `per = round(VIABILITY_ROUNDS / 5)`. Значит винрейт против каждого — это
 * дробь со знаменателем `per`, и порог обязан на эту сетку ЛОЖИТЬСЯ, причём
 * не в единицу: требовать чистого прохода без единого поражения против всех
 * пятерых значит снова завести вердикт, который не выпадает.
 */
/*
 * И считается это `ceil`, а не `floor`. Стояло `floor`, то есть «ближайшая
 * достижимая доля СНИЗУ», — а порог надо взять, значит нужна ближайшая
 * СВЕРХУ. С `floor` условие истинно при любом пороге меньше единицы, и
 * проверка достижимости не могла упасть: подмена `bestMin` на 0.99 давала
 * зелёную галочку с надписью «порог 99%, максимум без чистого прохода 75%» —
 * гейт печатал собственное опровержение и ставил плюс.
 *
 * Ровно тот дефект, который эта волна объявила исправленным (D122),
 * повторённый внутри исправления.
 */
const per = Math.max(2, Math.round(VIABILITY_ROUNDS / GAUNTLET.length)) || 2;
/*
 * Ближайшая достижимая доля НЕ НИЖЕ порога — её и надо взять, чтобы вердикт
 * выпал. Если она равна единице, вердикт требует чистого прохода.
 *
 * Вынесено в функцию НЕ ради красоты. Негативный контроль ниже раньше
 * переписывал эту же арифметику у себя — и потому страховкой не был: я вернул
 * `Math.floor` вместо `Math.ceil` в этой строке, гейт напечатал собственное
 * опровержение («порог 34% → брать надо 25%») и поставил ✓. Контроль обязан
 * звать ТО ЖЕ выражение, иначе он проверяет свою копию.
 */
/* СТРОГО больше: `readShape` объявляет доминирующим только того, кто ПРЕВЗОШЁЛ
   отсчёт, а не сравнялся с ним. Значит достижимой должна быть ближайшая
   ступень сетки СВЕРХУ, а не сама величина отсчёта: при отсчёте ровно на
   ступени (0.75 при шаге 12.5) взять надо следующую. */
const needFor = (thr) => (Math.floor(thr * per + 1e-9) + 1) / per;
const reachableAt = (thr) => needFor(thr) <= 1 - 1 / per;
const need = needFor(BASELINE.bestMin);
const reachable = reachableAt(BASELINE.bestMin);
ok('вердикт «доминирует» достижим на сетке viability', reachable,
  `${per} боёв на соперника → шаг ${(100 / per).toFixed(1)} п.п., порог ${(BASELINE.bestMin * 100).toFixed(0)}%`
  + ` → брать надо ${(need * 100).toFixed(0)}%, максимум без чистого прохода ${((1 - 1 / per) * 100).toFixed(0)}%`);

/*
 * И «доминирует» не должен выпадать на самих пятерых — но с тем же допуском,
 * что и проверка отсчёта выше.
 *
 * Здесь стояло строгое сравнение без допуска, и оно не могло пройти: отсчёт
 * снят на двадцати сидах (33.8%), гейт меряет на двенадцати (37.5%), сильнейший
 * законно оказывается выше записанной константы на четыре пункта — и гейт
 * объявлял поломкой обычную разницу выборок. Две проверки одного и того же
 * обязаны пользоваться одним допуском, иначе они противоречат друг другу.
 */
ok('никто из пятерых не отрывается от отсчёта', !mins.some((m) => m - BASELINE.bestMin > 0.12),
  `сильнейший держит ${(Math.max(...mins) * 100).toFixed(0)}% при отсчёте ${(BASELINE.bestMin * 100).toFixed(0)}%`);

/*
 * ПОЛЕ ОБЯЗАНО РАЗЛИЧАТЬ, а «пол» ему для этого не нужен.
 *
 * Здесь стояло «в поле есть и потолок, и пол»: требовалось, чтобы кто-то из
 * пятерых не брал больше 45% ни у кого. То есть гейт требовал наличия МЕШКА
 * ДЛЯ БИТЬЯ — и на новой пятёрке справедливо покраснел, потому что мешка в ней
 * нет: слабейший берёт 55% у одного из соперников.
 *
 * Но поле без мешка для битья лучше, а не хуже. Требование было моим
 * изобретением, а не свойством прибора. Различает поле не мешок, а РАЗБРОС:
 * если «худший результат» у всех пятерых одинаков, кандидату не с чем себя
 * сравнивать. Замерено: 0.338 у сильнейшего против 0 у слабейшего.
 */
const spread = Math.max(...mins) - Math.min(...mins);
ok('поле различает: разброс «худших» достаточен', spread >= 0.2,
  `от ${(Math.min(...mins) * 100).toFixed(0)}% до ${(Math.max(...mins) * 100).toFixed(0)}%, разброс ${(spread * 100).toFixed(0)} п.п. при пороге 20`);

/*
 * И ЦИКЛ. Он не украшение: транзитивное поле — это лестница, а кандидат,
 * испытанный об лестницу, получает место в очереди вместо формы. Прежняя
 * пятёрка была лестницей и гейт этого не спрашивал; поэтому спрашивается.
 */
const cyc = [];
for (let i = 0; i < table.length; i++) {
  for (let j = i + 1; j < table.length; j++) {
    for (let k = i + 1; k < table.length; k++) {
      const beats = (a, b) => Number.isFinite(table[a][b]) && table[a][b] > 0.5;
      if (j !== k && beats(i, j) && beats(j, k) && beats(k, i)) cyc.push(`${GAUNTLET[i].id}→${GAUNTLET[j].id}→${GAUNTLET[k].id}`);
    }
  }
}
ok('поле нетранзитивно: есть цикл', cyc.length > 0,
  cyc.length ? cyc.join(', ') : 'поле — лестница, кандидат получит место в очереди вместо формы');

/*
 * ── НЕГАТИВНЫЕ КОНТРОЛИ ───────────────────────────────────────────────────
 *
 * Они стояли под флагом `--falsify`, то есть в `npm test` не запускались
 * никогда — а проверка, которую никто не запускает, не проверка. Стоят они
 * доли миллисекунды: это арифметика над выдуманными таблицами, без единого
 * боя. Держать такое за флагом незачем.
 */
{
  const same = [0, 1, 2, 3, 4].map((i) => [0, 1, 2, 3, 4].map((j) => (i === j ? 0.5 : (j < 2 ? 1 : 0))));
  ok('однородное поле ловится', !isDiverse(same).ok,
    `все бьют одних и тех же → стилей ${isDiverse(same).unique}`);
  /* И ИДЕАЛЬНАЯ ЛЕСТНИЦА — отдельным контролем, потому что она проходила.
     Прежний контроль назывался `ladder`, но лестницей не был: его таблица
     неантисимметрична, то есть описывала поле, которого не бывает. */
  const ladder = [0, 1, 2, 3, 4].map((i) => [0, 1, 2, 3, 4].map((j) => (i === j ? 0.5 : (j > i ? 1 : 0))));
  ok('идеальная лестница ловится', !isDiverse(ladder).ok,
    `каждый бьёт всех ниже себя → стилей ${isDiverse(ladder).unique}`);
  /*
   * Положительный контроль — КАНОНИЧЕСКОЕ камень-ножницы-бумага на пятерых:
   * каждый бьёт двух следующих по кругу и проигрывает двум предыдущим. Это
   * поле без всякого порядка силы, пять разных рисунков, и проверка обязана
   * его пропустить. Иначе она умеет только отказывать, а такая проверка
   * запрещает всё и не измеряет ничего.
   */
  const rps = [0, 1, 2, 3, 4].map((i) => [0, 1, 2, 3, 4].map((j) => {
    if (i === j) return 0.5;
    const d = (j - i + 5) % 5;
    return d === 1 || d === 2 ? 0.8 : 0.2;
  }));
  ok('разнородное поле не ловится зря', isDiverse(rps).ok,
    `камень-ножницы-бумага на пятерых → стилей ${isDiverse(rps).unique}`);
  ok('уехавший отсчёт ловится', drifted(bestMin, bestMin + 0.3),
    'та же функция, что и выше, на подменённом числе');
  ok('точный отсчёт не ловится зря', !drifted(bestMin, bestMin + 0.01));
  /* ТА ЖЕ функция, что выше, на выдуманных порогах. 0.99 на этой сетке требует
     чистого прохода, значит проверка обязана его не пропустить. Проверено:
     подмена `ceil` на `floor` в `needFor` красит гейт. */
  ok('недостижимый порог ловится', !reachableAt(0.99), 'порог 99% на этой сетке требует чистого прохода');
  /* Две ступени от верха, а не одна: при СТРОГОМ сравнении порог, равный
     «максимуму без чистого прохода», уже требует чистого прохода — брать надо
     ступень выше. Контроль на 1-1/per проверял бы не достижимость, а
     арифметику округления, и падал бы по делу. */
  ok('достижимый порог не ловится зря', reachableAt(1 - 2 / per),
    `порог ${((1 - 2 / per) * 100).toFixed(0)}% берётся ${((1 - 1 / per) * 100).toFixed(0)}%`);
  ok('вердикт «доминирует» выпадает на векторе выше отсчёта',
    readShape(new Array(5).fill(Math.min(1, BASELINE.bestMin + 0.05))).verdict === 'dominant');
  ok('и не выпадает на векторе ниже отсчёта',
    readShape(new Array(5).fill(BASELINE.bestMin - 0.05)).verdict !== 'dominant');
}

console.log(bad ? `\n  ПРОВАЛ: ${bad}\n` : '\n  ДЕРЖИТ\n');
closePool();
process.exit(bad ? 1 : 0);
