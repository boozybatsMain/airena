/**
 * Гейт ТЗ: числа в SPEC.md не расходятся с кодом.
 *
 *   node tools/checkspec.mjs
 *   node tools/checkspec.mjs --falsify
 *
 * ЗАЧЕМ ОТДЕЛЬНО ОТ `checkdocs`. Тот сверяет README — страницу, которую пишем
 * мы и для себя. SPEC.md — замороженное ТЗ, и трогать его РЕШЕНИЯ нельзя. Но
 * кроме решений в нём есть ЧИСЛА, ВЫВЕДЕННЫЕ из этих решений, и они устаревают
 * молча: «атомы стоят 3–6 очков» при фактических 2–7, «672 прочтения» при
 * фактических 470.
 *
 * Разница между решением и выведенным числом здесь принципиальная. Решение
 * «цена на атом, элемент в бюджете не участвует» — заморожено. Сколько именно
 * стоит отброс — следствие замера, и оно меняется. Первое мы не трогаем,
 * второе обязано совпадать с кодом, иначе ТЗ начинает спорить с продуктом, и
 * непонятно, кто из них прав.
 *
 * Проверяются только те числа, у которых в коде есть однозначный источник.
 * Число без источника в гейт не берётся: сверять его было бы не с чем.
 */

import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  CHANNELS, DELIVERIES, EFFECTS, ELEMENTS, readingCount,
} from '../src/skills/registry.js';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const FALSIFY = process.argv.includes('--falsify');
const SPEC = readFileSync(join(ROOT, 'SPEC.md'), 'utf8');

let bad = 0;
const ok = (name, pass, note) => {
  console.log(`  ${pass ? '✓' : '✗'} ${name}${note ? `  ${note}` : ''}`);
  if (!pass) bad++;
};

/**
 * Утверждение привязано к ПРЕДЛОЖЕНИЮ, а не к числу.
 *
 * Искать «470» по документу бессмысленно: в тексте про мир из маленьких чисел
 * любое число встречается где угодно. Регексп обязан совпасть РОВНО ОДИН раз —
 * тогда переформулировка предложения падает так же громко, как устаревшее
 * число, и ни то, ни другое не проходит молча. Тот же приём, что в
 * `checkprompt` и `checkdocs`.
 */
function bound(what, re, want) {
  const hits = [...SPEC.matchAll(new RegExp(re.source, `${re.flags.replace('g', '')}g`))];
  if (hits.length === 0) return ok(what, false, 'предложение исчезло из ТЗ');
  if (hits.length > 1) return ok(what, false, `совпало ${hits.length} раз, должно один`);
  const got = hits[0].slice(1).join('–');
  return ok(what, got === String(want), got === String(want) ? `${want}` : `в ТЗ «${got}», в коде «${want}»`);
}

console.log('\n  ГЕЙТ ТЗ: ЧИСЛА SPEC.md ПРОТИВ КОДА\n');

const costs = Object.values(EFFECTS).map((e) => e.cost);
bound('диапазон цен атомов (§8)', /Атомы стоят (\d+)–(\d+) очков/,
  `${Math.min(...costs)}–${Math.max(...costs)}`);

bound('число прочтений грамматики (§9.2)', /\*\*(\d+) мгновенно читаемых прочтени[йя]\*\*/,
  readingCount());

/*
 * БЮДЖЕТА УМЕНИЯ В ТЗ НЕТ, и проверять его тут нечего.
 *
 * Здесь стояла привязка к «потолку в 22 очка» — и она падала с «предложение
 * исчезло из ТЗ», потому что предложения не было никогда: число 22 выбрали мы
 * перебором (см. `SKILL_BUDGET`), §8 требует лишь «бюджет силы существует».
 *
 * Гейт, проверяющий, что документ говорит то, чего он никогда не говорил, —
 * это не строгость, а шум, который однажды «починят» дописав в замороженное
 * ТЗ наше решение. Сверяется только то, что ТЗ действительно утверждает.
 */

/* Оси грамматики: их размеры записаны в §8 словами «пять», «восемь» и цифрами
   в разных местах, поэтому сверяется то, что записано однозначно. */
/* Триггеров в §8 пять, а в коде их нет вовсе — ось снята решением основателя
   (см. комментарий в registry.js и D102). Это единственное расхождение с ТЗ,
   которое сделано НАМЕРЕННО, поэтому оно названо здесь, а не молча пропущено. */
ok('осей грамматики в коде столько, сколько в §8 перечислено, кроме снятой',
  Object.keys(DELIVERIES).length === 9
  && Object.keys(EFFECTS).length === 14 && Object.keys(CHANNELS).length === 7
  && Object.keys(ELEMENTS).length === 5,
  `доставок ${Object.keys(DELIVERIES).length}, эффектов ${Object.keys(EFFECTS).length}, каналов ${Object.keys(CHANNELS).length}, элементов ${Object.keys(ELEMENTS).length}; триггеры сняты`);

/*
 * НЕ ВСЁ, ЧТО ХОЧЕТСЯ СВЕРИТЬ, СВЕРЯЕМО.
 *
 * §9.2 называет «~$0.015 на скилл» — цена зависит от модели и меняется у
 * провайдера, в коде источника нет. §5.1 называет вилку стоимости тела — то
 * же самое. Такие числа в гейт не берутся, и это записано, чтобы через
 * полгода их не начали «чинить» подгонкой под выдуманный источник.
 */
ok('числа без источника в коде в гейт не берутся', true,
  'цена генерации у провайдера, вилка стоимости тела — сверять не с чем');

if (FALSIFY) {
  console.log('\n  --falsify\n');
  const broken = SPEC.replace(/Атомы стоят \d+–\d+ очков/, 'Атомы стоят 3–6 очков');
  const hits = [...broken.matchAll(/Атомы стоят (\d+)–(\d+) очков/g)];
  ok('устаревший диапазон ловится', `${hits[0][1]}–${hits[0][2]}` !== `${Math.min(...costs)}–${Math.max(...costs)}`,
    `«3–6» против «${Math.min(...costs)}–${Math.max(...costs)}»`);
  const gone = SPEC.replace(/Атомы стоят \d+–\d+ очков/, 'Атомы недороги');
  ok('исчезнувшее предложение ловится', ![...gone.matchAll(/Атомы стоят (\d+)–(\d+) очков/g)].length,
    'привязка к предложению, а не к числу');
}

console.log(bad ? `\n  ПРОВАЛ: ${bad}\n` : '\n  ДЕРЖИТ\n');
process.exit(bad ? 1 : 0);
