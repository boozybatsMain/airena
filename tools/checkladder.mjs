/**
 * Гейт лестницы: рейтинг обязан предсказывать исход, и надо знать — с какого боя.
 *
 *   node tools/checkladder.mjs
 *   node tools/checkladder.mjs --falsify    сломать K и показать, что гейт ловит
 *
 * ЗАЧЕМ. На живых данных корреляция «рейтинг ↔ доля побед» вышла 0.18 — то есть
 * лестница почти ничего не предсказывала. Из такой цифры можно сделать два
 * противоположных вывода: «Эло настроено неправильно» и «боёв пока слишком
 * мало». Пока не знаешь, какой верен, любая правка K — угадывание.
 *
 * Здесь это разделено. Сила существ ЗАДАНА, поэтому известно, к чему рейтинг
 * обязан сойтись; дальше меряется, за сколько боёв он сходится. Если система
 * настроена верно, малая корреляция на живых данных — это возраст лестницы, а
 * не её поломка, и лечится ожиданием, а не K.
 *
 * ЧЕГО ЭТОТ ГЕЙТ НЕ ДЕЛАЕТ. Он не проверяет, что бой честный, — для этого есть
 * `kitbalance` и `falsify`. Здесь бой сведён к монете, вероятность которой
 * задана разницей сил: проверяется арифметика лестницы, а не арена.
 */

import { K_BASE, K_PLACEMENT, PLACEMENT_FIGHTS, START_RATING, clampRating, expectedScore, rate }
  from '../src/server/ladder.js';

const FALSIFY = process.argv.includes('--falsify');

/* Детерминированный генератор: гейт, зависящий от Math.random, падает раз в
   двадцать прогонов и приучает не верить гейтам. */
let seed = 20260829;
const rnd = () => {
  seed = (seed * 1664525 + 1013904223) >>> 0;
  return seed / 4294967296;
};

const N = 40;
/*
 * Разброс генератора — 37 процентных пунктов (§1). Переводим в шкалу Эло:
 * разница, дающая 68.5% побед сильнейшему, это 400 * log10(p/(1-p)) ≈ 135.
 * Значит истинные силы лежат в полосе примерно ±70 вокруг старта.
 */
const SPREAD = 135;
const truth = Array.from({ length: N }, (_, i) => START_RATING - SPREAD / 2 + (SPREAD * i) / (N - 1));

/** Спирмен: сравниваем ПОРЯДКИ, а не значения — рейтинг и сила в разных шкалах. */
function spearman(a, b) {
  const rank = (v) => {
    const idx = v.map((x, i) => [x, i]).sort((p, q) => p[0] - q[0]);
    const r = new Array(v.length);
    idx.forEach(([, i], k) => { r[i] = k; });
    return r;
  };
  const ra = rank(a); const rb = rank(b);
  const m = (v) => v.reduce((s, x) => s + x, 0) / v.length;
  const ma = m(ra); const mb = m(rb);
  let n = 0; let da = 0; let db = 0;
  for (let i = 0; i < ra.length; i++) {
    n += (ra[i] - ma) * (rb[i] - mb);
    da += (ra[i] - ma) ** 2;
    db += (rb[i] - mb) ** 2;
  }
  return n / Math.sqrt(da * db);
}

/**
 * Один сезон.
 *
 * `mode` — как подбирается соперник:
 *   'nearest'  строго ближайший по рейтингу (как было в `pickOpponent`);
 *   'window'   случайный из тех, кто в окне ±`WINDOW` (как стало).
 */
const WINDOW = 120;
function season(perCreature, kOverride, mode = 'window', blind = false) {
  const rating = truth.map(() => START_RATING);
  const fights = truth.map(() => 0);
  const steps = [];
  const total = Math.round((N * perCreature) / 2);
  for (let t = 0; t < total; t++) {
    const a = Math.floor(rnd() * N);
    let b = -1;
    if (mode === 'nearest') {
      let best = Infinity;
      for (let j = 0; j < N; j++) {
        if (j === a) continue;
        const d = Math.abs(rating[j] - rating[a]);
        if (d < best) { best = d; b = j; }
      }
    } else {
      const pool = [];
      for (let j = 0; j < N; j++) if (j !== a && Math.abs(rating[j] - rating[a]) <= WINDOW) pool.push(j);
      b = pool.length ? pool[Math.floor(rnd() * pool.length)] : (a + 1) % N;
    }
    /* Исход — монета по истинным силам. Ничьи здесь не моделируются: они
       симметричны и порядок не меняют. */
    /* `blind` — контроль: исход не зависит от силы. Рейтинг, который и тогда
       «предсказывает», предсказывает собственный шум. */
    const p = blind ? 0.5 : expectedScore(truth[a], truth[b]);
    const score = rnd() < p ? 1 : 0;
    let d;
    if (kOverride) {
      const ea = expectedScore(rating[a], rating[b]);
      d = { a: kOverride * (score - ea), b: kOverride * ((1 - score) - (1 - ea)) };
    } else {
      d = rate(rating[a], rating[b], score, fights[a], fights[b]);
    }
    if (fights[a] >= PLACEMENT_FIGHTS && fights[b] >= PLACEMENT_FIGHTS) steps.push(Math.abs(d.a));
    rating[a] = clampRating(rating[a] + d.a);
    rating[b] = clampRating(rating[b] + d.b);
    fights[a]++; fights[b]++;
  }
  steps.sort((x, y) => x - y);
  return { rho: spearman(rating, truth), step: steps.length ? steps[Math.floor(steps.length / 2)] : 0 };
}

let bad = 0;
const ok = (name, pass, note) => {
  console.log(`  ${pass ? '✓' : '✗'} ${name}${note ? `  ${note}` : ''}`);
  if (!pass) bad++;
};

console.log('\n  ГЕЙТ ЛЕСТНИЦЫ\n');
console.log(`  ${N} существ, силы заданы в полосе ${SPREAD} Эло (= разброс генератора, §1)`);
console.log(`  K: ${K_PLACEMENT} первые ${PLACEMENT_FIGHTS} боёв, дальше ${K_BASE}\n`);

/* Три прогона на точку и медиана: один прогон — это один бросок монеты
   сорок раз, и по нему нельзя отличить кривую от шума. Ровно на этом и
   спотыкалась первая версия гейта: она рисовала немонотонную кривую и
   предлагала объяснять её содержательно. */
const median = (v) => v.slice().sort((x, y) => x - y)[Math.floor(v.length / 2)];
const RUNS = [0, 1, 2, 3, 4, 5, 6, 7, 8];
const run = (n, mode) => median(RUNS.map(() => season(n, null, mode).rho));
const POINTS = [5, 10, 20, 40, 80, 160];
const curve = POINTS.map((n) => [n, run(n, 'window')]);
const near = POINTS.map((n) => [n, run(n, 'nearest')]);
console.log('  боёв   окно ±120   строго ближайший');
for (let i = 0; i < POINTS.length; i++) {
  console.log(`  ${String(POINTS[i]).padStart(4)}       ${curve[i][1].toFixed(2)}          ${near[i][1].toFixed(2)}`);
}
console.log('');

/*
 * ЧТО ЭТОТ ЗАМЕР ПОКАЗАЛ, И ПОЧЕМУ ОН ОТМЕНИЛ ПРАВКУ, КОТОРУЮ Я СОБИРАЛСЯ СДЕЛАТЬ.
 *
 * Повод был такой: на живых данных корреляция «рейтинг ↔ доля побед» вышла
 * 0.18, и напрашивался вывод «подбор ближайшего соперника не даёт лестнице
 * информации — надо подбирать из окна». Правка выглядела очевидной.
 *
 * Замер её отменил: окно ±120 и строгий ближайший сходятся практически
 * одинаково (0.81 против 0.85 к 160 боям). Причина медленной сходимости не в
 * подборе, а в том, что РАЗБРОС УЗКИЙ. Сила генератора укладывается в 135 Эло
 * (§1), то есть сильнейший выигрывает у слабейшего 68.5% — чтобы разложить
 * сорок существ внутри такой полосы, нужны сотни боёв. Это арифметика, а не
 * настройка.
 *
 * СЛЕДСТВИЕ ДЛЯ ПРОДУКТА, а не для кода: 0.18 на молодой лестнице — это норма,
 * и лечится она временем, а не K. Показывать место как приговор до сотни боёв
 * нельзя, и §10.4 уже требует процентиль вместо номера. Поднимать K, чтобы
 * «лестница быстрее заработала», — значит менять измерение силы на измерение
 * везения; ровно это и проверяет `--falsify`.
 *
 * ПОРОГИ взяты по замеру с запасом на шум (три прогона, медиана), а не
 * назначены красивыми числами.
 */
const at = (n) => curve.find(([k]) => k === n)[1];
ok('после 20 боёв рейтинг ещё не приговор', at(20) < 0.9,
  `корреляция ${at(20).toFixed(2)} — место показывать рано`);
ok('к 40 боям порядок узнаваем', at(40) >= 0.45, `корреляция ${at(40).toFixed(2)}, порог 0.45`);
ok('к 160 боям порядок крепкий', at(160) >= 0.78, `корреляция ${at(160).toFixed(2)}, порог 0.78`);
ok('лестница монотонно уточняется', at(160) >= at(40) && at(40) >= at(5),
  `${at(5).toFixed(2)} → ${at(40).toFixed(2)} → ${at(160).toFixed(2)}`);
ok('подбор из окна не хуже подбора ближайшего', Math.abs(at(160) - near[near.length - 1][1]) < 0.15,
  `окно ${at(160).toFixed(2)} против ближайшего ${near[near.length - 1][1].toFixed(2)}`);

/*
 * ШАГ РЕЙТИНГА — ЕДИНСТВЕННОЕ, ЧТО ЗДЕСЬ ОХРАНЯЕТ K.
 *
 * Сначала порог на K стоял по корреляции: сломать K и показать, что порядок
 * рассыпался. Замер это опроверг. K=600 (впятеро против шахматного дефолта)
 * даёт корреляцию 0.79 против 0.83 у настоящего — на девяти прогонах разница
 * тонет в шуме. Причина простая: большой K добавляет рейтингу РАЗБРОС, но не
 * СМЕЩЕНИЕ, а Спирмен по сорока существам разброс усредняет.
 *
 * Значит гейт на корреляции не охраняет K и не должен делать вид, что
 * охраняет. Зато F5 требует буквально другого: «один матч двигает рейтинг
 * понемногу, а не решает его». Это про РАЗМЕР ШАГА, и вот он к K чувствителен
 * прямо и линейно.
 *
 * Порог не назначен, а выведен. У равных соперников ожидание 0.5, значит
 * |score − E| = 0.5 и шаг равен ровно K/2. Поэтому порог — K_BASE/2 плюс
 * копейка на округление: любое K больше базового даёт шаг пропорционально
 * больше и ловится сразу. Считается только после калибровки: первые двадцать
 * боёв шагают втрое крупнее нарочно.
 */
const MAX_STEP = K_BASE / 2 + 0.1;
const step = median(RUNS.map(() => season(160, null, 'window').step));
ok('один бой двигает рейтинг понемногу (F5)', step <= MAX_STEP,
  `медианный шаг после калибровки ${step.toFixed(1)} очка, порог ${MAX_STEP}`);

if (FALSIFY) {
  /*
   * Гейт обязан уметь падать. Ломаем ровно то, за чем он поставлен: K=200
   * заставляет рейтинг верить каждому бою, и порядок перестаёт сходиться.
   */
  /*
   * Порог здесь — ТОТ ЖЕ, что у настоящего гейта. Первая версия сравнивала
   * сломанный прогон с 0.85, тогда как гейт требует 0.75, и «поймали» она
   * показывала на значении 0.76 — которое настоящий гейт пропустил бы. Проверка
   * фальсификации, которая мягче проверяемого, доказывает не то, что гейт
   * ловит, а то, что автор невнимателен.
   */
  /*
   * ГДЕ У ГЕЙТА ЕСТЬ СИЛА — ЗАМЕРЕНО, А НЕ ПРЕДПОЛОЖЕНО.
   *
   * Первая версия ломала K и сравнивала результат с 0.85, тогда как сам гейт
   * требует 0.78. «Поймали» показывалось на значении, которое настоящий гейт
   * пропустил бы. Проверка фальсификации, которая строже проверяемого,
   * доказывает не силу гейта, а невнимательность автора.
   *
   * Замер по пяти прогонам на точку:
   *
   *     боёв    K обычный   K=200   K=600   слепой исход
   *       20        0.44     0.48    0.46      0.07
   *       40        0.54     0.52    0.53     -0.06
   *      160        0.85     0.69    0.67      0.00
   *      320        0.85     0.78    0.85      0.02
   *
   * Читается так. До 80 боёв гейт к K НЕЧУВСТВИТЕЛЕН вовсе: на этом отрезке
   * лестница ещё не знает порядка ни при каком K, и ставить туда порог значило
   * бы охранять пустоту. Чувствительность появляется к 160 (0.85 против 0.68) —
   * туда порог и поставлен. А контроль «слепой исход» ловится на любом
   * отрезке: рейтинг, которому нечего измерять, не выдаёт порядка вообще.
   */
  console.log('\n  --falsify: слепой исход — измерять нечего');
  ok('гейт это ловит', median(RUNS.map(() => season(160, null, 'window', true).rho)) < 0.78,
    `корреляция ${median(RUNS.map(() => season(160, null, 'window', true).rho)).toFixed(2)} против порога 0.78`);

  console.log('\n  --falsify: K=600 — рейтинг верит одному бою впятеро сильнее');
  const bigStep = median(RUNS.map(() => season(160, 600, 'window').step));
  ok('шаг ловится', bigStep > MAX_STEP, `шаг ${bigStep.toFixed(1)} против порога ${MAX_STEP}`);
  const bigRho = median(RUNS.map(() => season(160, 600, 'window').rho));
  console.log(`     а корреляция при этом ${bigRho.toFixed(2)} — то есть порядок она не ломает`);
}

console.log(bad ? `\n  ПРОВАЛ: ${bad}\n` : '\n  ДЕРЖИТ\n');
process.exit(bad ? 1 : 0);
