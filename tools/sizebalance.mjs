/*
 * ЦЕНЫ ОБЯЗАНЫ СОВПАСТЬ — ИНАЧЕ ЛИГА МЕРИТ ЦЕНУ, А НЕ ТЕЛО.
 *
 * Это не украшение отчёта. Тело, которому досталось меньше очков, проигрывает
 * законно, и такой прогон отвечал бы на вопрос «дороже ли сильнее», ответ на
 * который известен заранее. Расхождение возможно ровно одним путём — раздача
 * упёрлась в потолки осей и не смогла потратить весь бюджет, — и тогда чинить
 * надо доли выше, а не смотреть таблицу.
 */
{
  const off = BUILDS.map((b) => Math.abs(b.cost - BUILD_BUDGET));
  if (Math.max(...off) > 0.05) {
    console.log('\n  Тела получились РАЗНОЙ ЦЕНЫ — замер не проводится.');
    console.log(`  Потолок ${BUILD_BUDGET}, а собралось: ${BUILDS.map((b) => `${b.name} ${b.cost}`).join(', ')}.`);
    console.log('  Значит доли в SHARES упёрлись в потолки осей: поправить доли, а не читать таблицу.\n');
    closePool();
    process.exit(2);
  }
}

/*
 * ПРОВЕРКА ПРИБОРА — ГЕЙТ.
 *
 * Одинаковые тела обязаны давать половину. Если прибор кривой, цифры ниже —
 * мнение, оформленное как число, и печатать их нельзя. Ровно на этом
 * попалась лига атомов (D60).
 *
 * ПРО ПОЛОВИНУ, А НЕ ПРО НИЧЬЮ. Сначала здесь стояло «одинаковые стороны
 * обязаны давать ничью», и это работало ровно до тех пор, пока эталонный мозг
 * не начал применять все свои умения (D105). Пока половина набора была мертва,
 * бои кончались обоюдным ничем; как только мозг стал бить, они стали
 * РЕШИТЕЛЬНЫМИ — и при полностью одинаковых сторонах исход решает спавн.
 * Спавн зеркалится (каждый сид играется в обе стороны), поэтому честное
 * требование — не «ничья», а «половина побед». Требовать ничью значит
 * требовать, чтобы бой был бессодержательным.
 */
{
  const same = BUILDS.map((_, i) => [i, i]);
  const { jobs, meta } = jobsFor(same);
  const out = await runJobs(jobs);
  let wins = 0; let n = 0;
  for (let k = 0; k < out.length; k++) {
    const r = out[k];
    if (r === 'error') continue;
    n++;
    /* «Первый» — тот, кто стоит на синей стороне в этой перестановке. */
    if (r === 'blue') wins += meta[k].flip ? 0 : 1;
    else if (r === 'orange') wins += meta[k].flip ? 1 : 0;
    else wins += 0.5;
  }
  const rate = n ? wins / n : 0;
  const ok = Math.abs(rate - 0.5) <= 0.05;
  console.log(`\n  прибор: одинаковые тела → ${(rate * 100).toFixed(1)}% побед${ok ? ' — перекоса нет' : ''}`);
  if (!ok) {
    console.log('\n  Прибор показывает собственный перекос — замер не проводится.');
    console.log('  При полностью одинаковых сторонах и зеркальных сидах обязана быть половина.\n');
    closePool();
    process.exit(2);
  }
}

