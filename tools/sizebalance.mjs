/**
 * Лига размеров: не даёт ли какой-то размер бесплатного преимущества.
 *
 *   node tools/sizebalance.mjs                  текущие показатели
 *   AIRENA_SIZE_HP_POW=1.8 AIRENA_SIZE_SPEED_POW=0.1 node tools/sizebalance.mjs
 *                                              попробовать другие показатели
 *   node tools/sizebalance.mjs --rounds=8
 *
 * ── зачем ──────────────────────────────────────────────────────────────────
 *
 * Размер существа выбирает модель, и у него есть цена: мелкий теряет здоровье,
 * но выигрывает в скорости и в том, что по нему труднее попасть. Вопрос, на
 * который отвечает этот прибор, ровно один: **не выигрывает ли какой-то размер
 * просто так**. Если мелкий берёт 70% у крупного при одинаковом наборе и
 * одинаковом мозге — значит показатели степени подобраны неверно, и «сделай
 * комара» станет доминирующей стратегией независимо от замысла игрока.
 *
 * ЧИСЛО СИДОВ ЗДЕСЬ — ЧАСТЬ ПРИБОРА. В `npm test` он гонялся на шести, и на
 * шести сидах перекос в четырнадцать пунктов (0.90 брал 64.4%) был неотличим от
 * шума: гейт был зелёным, а ось — сломанной. Двадцать сидов это 160 боёв на
 * размер, две сигмы около восьми пунктов, и заявленный порог в двадцать
 * пунктов на такой выборке уже что-то значит.
 *
 * Площадь цели падает как КВАДРАТ размера, поэтому здоровье обязано расти
 * быстрее линейного — иначе мелкий доминирует по построению. Насколько
 * быстрее, теорией не берётся: попадание зависит от скорости снаряда, ширины
 * конуса, дальности и от того, как мозг держит дистанцию. Поэтому — замер.
 *
 * ── как устроен ────────────────────────────────────────────────────────────
 *
 * Симметричная арена: обе стороны — один архетип, один мозг, один набор.
 * Различается ТОЛЬКО размер. Каждый размер против каждого, зеркально, по
 * `rounds` сидов на сторону. Ничья — половина очка.
 *
 * Как и в лиге атомов, сначала гоняется проверка самого прибора: одинаковые
 * размеры обязаны дать ничью. Если не дают — считать нечего, и таблица не
 * печатается.
 */

import { POOL_SIZE, closePool, runJobs, superviseSelf } from './matchpool.mjs';

/* Пул изредка падает SIGSEGV и уносит процесс молча — надзиратель
   перезапускает счёт с меньшей параллельностью (см. `superviseSelf`). */
superviseSelf('AIRENA_SIZE_CHILD');
import { SIZE_MAX, SIZE_MIN } from '../src/core/config.js';

const arg = (name, def) => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? Number(hit.split('=')[1]) : def;
};
/* Умолчание — то же число, которым гоняет `npm test`. Стояло 6, и голый вызов
   инструмента падал там, где гейт проходил: разные числа сидов у одной
   проверки — это две разные проверки под одним именем. */
const ROUNDS = arg('rounds', 20);

/* Пять точек по диапазону: концы, середина и две между — этого хватает, чтобы
   увидеть наклон, и не столько, чтобы прогон шёл час. */
const SIZES = [SIZE_MIN, 0.9, 1.0, 1.2, SIZE_MAX];

/**
 * Отклонение от половины, начиная с которого размер выигрывает просто так.
 *
 * ── 0.12, А НЕ 0.20 ───────────────────────────────────────────────────────
 *
 * Двадцать пунктов и беда, ради которой этот гейт поднимали до двадцати сидов,
 * НЕ ПЕРЕСЕКАЛИСЬ: при `SIZE_SPEED_POW=0.25` размер 0.90 брал 64.4%, то есть
 * 14.4 пункта, — и гейт печатал «ни один размер не доминирует» и выходил с
 * нулём. Конфигурация, объявленная сломанной в том же журнале, проходила
 * зелёной.
 *
 * Порог поставлен ниже той беды и выше сегодняшнего состояния: 12 против
 * замеренных 9.7 п.п. на сорока сидах. Запас в два пункта — это меньше сигмы
 * на двадцати сидах, поэтому гейт остаётся чувствительным к настоящему сдвигу
 * и не краснеет от одного боя: разрешение прибора печатается рядом с каждой
 * строкой и считается из выборки.
 */
const DOMINATES = 0.12;
/**
 * Ниже этого прибор не различает — и это ЗАВИСИТ ОТ ЧИСЛА БОЁВ.
 *
 * Здесь стояла константа 0.07 при любом `--rounds`, и на шести сидах (как в
 * `npm test`) она равнялась примерно одной сигме: то есть «выше половины на
 * 10.4 п.п.» печаталось про величину, неотличимую от нуля. Прибор сообщал
 * число и не сообщал, значит ли оно что-нибудь.
 *
 * Считается из выборки: для доли σ ≈ 0.5/√n, берём две сигмы. При `--rounds=20`
 * это 160 боёв на размер и порог около 8 п.п.; при 40 — 320 и около 5.6.
 */
const resolution = (n) => (n > 0 ? 2 * 0.5 / Math.sqrt(n) : 1);

/*
 * Набор, на котором меряется размер.
 *
 * Он обязан УМЕТЬ ПРОМАХИВАТЬСЯ — иначе преимущество мелкого («в меня труднее
 * попасть») не измеряется вовсе. Луч и зона попадают почти всегда; снаряд
 * летит и мимо него можно уйти, конус узкий. Поэтому снаряд плюс конус.
 */
const KIT = [
  { delivery: 'bolt', effects: ['damage'], element: 'kinetic' },
  { delivery: 'cone', effects: ['damage'], element: 'kinetic' },
  { delivery: 'self', effects: ['heal'], element: 'frost' },
];

function jobsFor(pairs) {
  const jobs = []; const meta = [];
  for (const [i, j] of pairs) {
    for (let s = 0; s < ROUNDS; s++) {
      for (const flip of [false, true]) {
        jobs.push({
          a: KIT, b: KIT, seed: 1000 + s, sym: true,
          sizes: flip
            ? { octopus: SIZES[j], gorilla: SIZES[i] }
            : { octopus: SIZES[i], gorilla: SIZES[j] },
        });
        meta.push({ i, j, flip });
      }
    }
  }
  return { jobs, meta };
}

async function league(pairs, label) {
  const { jobs, meta } = jobsFor(pairs);
  console.log(`\n  ${label}: ${jobs.length} боёв на ${POOL_SIZE} воркерах`);
  const out = await runJobs(jobs, (d, t) => process.stdout.write(`\r  ${label}: ${d}/${t}   `));
  process.stdout.write('\r');
  const score = SIZES.map(() => ({ w: 0, n: 0 }));
  for (let k = 0; k < out.length; k++) {
    const m = meta[k]; const r = out[k];
    if (r === 'error') continue;
    /* Кто был «первым» в паре, зависит от flip: осьминог — это либо i, либо j. */
    const first = m.flip ? m.j : m.i;
    const second = m.flip ? m.i : m.j;
    score[first].n++; score[second].n++;
    if (r === 'octopus') score[first].w++;
    else if (r === 'gorilla') score[second].w++;
    else { score[first].w += 0.5; score[second].w += 0.5; }
  }
  return score;
}

const t0 = Date.now();
console.log('\n  ЛИГА РАЗМЕРОВ');
console.log('  Обе стороны: один архетип, один мозг, один набор (снаряд+конус+лечение).');
console.log(`  Различается только размер. ${ROUNDS} сидов на пару и сторону.\n`);

/*
 * ПРОВЕРКА ПРИБОРА — ГЕЙТ.
 *
 * Одинаковые размеры обязаны давать ничью. Если прибор кривой, цифры ниже —
 * мнение, оформленное как число, и печатать их нельзя. Ровно на этом
 * попалась лига атомов (D60).
 */
{
  /*
   * ПРОВЕРКА — ПРО ПОЛОВИНУ, А НЕ ПРО НИЧЬЮ.
   *
   * Сначала здесь стояло «одинаковые размеры обязаны давать ничью», и это
   * работало ровно до тех пор, пока эталонный мозг не начал применять все
   * свои умения (D105). Пока половина набора была мертва, бои кончались
   * обоюдным ничем; как только мозг стал бить, они стали РЕШИТЕЛЬНЫМИ — и
   * при полностью одинаковых сторонах исход решает спавн.
   *
   * Спавн зеркалится (каждый сид играется в обе стороны), поэтому честное
   * требование — не «ничья», а «половина побед». Требовать ничью значит
   * требовать, чтобы бой был бессодержательным.
   */
  const same = SIZES.map((_, i) => [i, i]);
  const { jobs, meta } = jobsFor(same);
  const out = await runJobs(jobs);
  let w = 0; let n = 0;
  for (let k = 0; k < out.length; k++) {
    const r = out[k];
    if (r === 'error') continue;
    n++;
    /* «Первый» — тот, кто стоит на слоте осьминога в этой перестановке. */
    if (r === 'octopus') w += meta[k].flip ? 0 : 1;
    else if (r === 'gorilla') w += meta[k].flip ? 1 : 0;
    else w += 0.5;
  }
  const rate = n ? w / n : 0;
  const ok = Math.abs(rate - 0.5) <= 0.05;
  console.log(`  прибор: одинаковые размеры → ${(rate * 100).toFixed(1)}% побед${ok ? ' — перекоса нет' : ''}`);
  if (!ok) {
    console.log('\n  Прибор показывает собственный перекос — замер не проводится.');
    console.log('  При полностью одинаковых сторонах и зеркальных сидах обязана быть половина.\n');
    closePool();
    process.exit(2);
  }
}

const pairs = [];
for (let i = 0; i < SIZES.length; i++) for (let j = i + 1; j < SIZES.length; j++) pairs.push([i, j]);
const score = await league(pairs, 'РАЗМЕРЫ');

console.log('\n  размер   винрейт   что это значит');
let worst = 0;
for (let i = 0; i < SIZES.length; i++) {
  const s = score[i];
  const rate = s.n ? s.w / s.n : 0;
  worst = Math.max(worst, Math.abs(rate - 0.5));
  const bar = '█'.repeat(Math.round(rate * 26)).padEnd(26, '·');
  const off = Math.abs(rate - 0.5);
  const RESOLUTION = resolution(s.n);
  /*
   * ПОМЕТКА И ПОРОГ ГОВОРЯТ ОДНО И ТО ЖЕ.
   *
   * Здесь стояло «выигрывает просто так» с семи пунктов, а внизу печаталось
   * «ни один размер не доминирует» с двадцати. Один и тот же прогон сообщал
   * обе вещи разом, и читатель выбирал, какой строке верить.
   *
   * Семь пунктов — это разрешение прибора, ниже него молчим совсем. Между
   * семью и двадцатью печатается ЧИСЛО, а не оценка: сказать «внутри
   * разрешения» про 10.4 п.п. — значит объявить шумом полуторакратное
   * превышение шума. Прибор сообщает, сколько намерил; судит порог.
   */
  const note = off < RESOLUTION ? ''
    : (off < DOMINATES
      ? `  ← ${rate > 0.5 ? 'выше' : 'ниже'} половины на ${(off * 100).toFixed(1)} п.п., но не доминирует`
      : (rate > 0.5 ? '  ← ВЫИГРЫВАЕТ ПРОСТО ТАК' : '  ← ПРОИГРЫВАЕТ ПРОСТО ТАК'));
  console.log(`  ${SIZES[i].toFixed(2).padStart(6)}   ${(rate * 100).toFixed(1).padStart(5)}%   ${bar}${note}`);
}

/*
 * ПОРОГ — ПРО ДОМИНИРОВАНИЕ, А НЕ ПРО РАВЕНСТВО.
 *
 * Требовать 50% от каждого размера этот прибор не позволяет: на десяти сидах
 * он даёт одинаковые 20 п.п. и при hp^2.0, и при hp^2.2 — то есть внутри
 * этого плато он не различает, и подбор там был бы подгонкой шума.
 *
 * Зато доминирование он ловит уверенно: на первой версии показателей мелкий
 * брал 97.5%, и это было видно сразу. Порог 12 п.п. — граница между «ось с
 * ценой» и «доминирующая стратегия», и она СТРОГАЯ: конфигурация, которую этот
 * же журнал объявил сломанной (14.4 п.п. у размера 0.90), обязана падать.
 */
console.log(`\n  худшее отклонение от половины: ${(worst * 100).toFixed(1)} п.п.`);
console.log(worst < DOMINATES
  ? `  Ни один размер не доминирует (порог ${(DOMINATES * 100).toFixed(0)} п.п., строго).`
  : '  Размер даёт преимущество — показатели степени в config.js надо править.');
console.log(`\n  ${Math.round((Date.now() - t0) / 1000)} с\n`);
closePool();
process.exit(worst < DOMINATES ? 0 : 1);
