/**
 * Лига телосложений: не даёт ли какое-то законное тело бесплатного преимущества.
 *
 *   node tools/sizebalance.mjs                  текущие цены осей
 *   AIRENA_TUNING=cand.json node tools/sizebalance.mjs
 *                                              попробовать другие цены
 *   node tools/sizebalance.mjs --rounds=8
 *
 * ── зачем ──────────────────────────────────────────────────────────────────
 *
 * Тело существа больше не наследуется ни от кого: нет ни архетипов, ни двух
 * записей с характеристиками. Есть ОСИ (`BUILD_AXES`), у каждой единицы своя
 * цена, а у набора — потолок (`BUILD_BUDGET`). Значит и вопрос сменился.
 *
 * Раньше спрашивали: не выигрывает ли какой-то РАЗМЕР просто так. Теперь:
 * **не выигрывает ли какое-то ТЕЛОСЛОЖЕНИЕ ТОЙ ЖЕ ЦЕНЫ просто так**. Если за
 * тридцать очков можно собрать тело, которое берёт 70% боёв у другого тела за
 * те же тридцать очков при одинаковом наборе и одинаковом мозге, — значит
 * цена оси в `config.js` подобрана неверно, и «сделай вот такое» станет
 * доминирующей стратегией независимо от замысла игрока. Свобода без верной
 * цены — это не свобода, это один правильный ответ, который ещё надо угадать.
 *
 * Прибор тот же, что был: симметричная арена, один мозг, один набор, зеркальные
 * сиды. Сменилась ось, по которой он смотрит.
 *
 * ЧИСЛО СИДОВ ЗДЕСЬ — ЧАСТЬ ПРИБОРА. В `npm test` он гонялся на шести, и на
 * шести сидах перекос в четырнадцать пунктов был неотличим от шума: гейт был
 * зелёным, а ось — сломанной. Двадцать сидов это 160 боёв на телосложение, две
 * сигмы около восьми пунктов, и заявленный порог на такой выборке уже
 * что-то значит.
 *
 * ── как устроен ────────────────────────────────────────────────────────────
 *
 * Симметричная арена: обе стороны — один мозг, один набор. Различается ТОЛЬКО
 * телосложение, и все телосложения стоят ОДИНАКОВО. Каждое против каждого,
 * зеркально, по `rounds` сидов на сторону. Ничья — половина очка.
 *
 * Тела не выписаны числами, а СОБИРАЮТСЯ из осей на запуске: доли бюджета →
 * очки → значения. Поэтому правка цен, границ или потолка в `config.js` (или
 * через `AIRENA_TUNING`) сразу меняет и участников лиги, а не только то, что
 * измеряется. Выписанные числами тела пережили бы первую же правку цен и
 * стали бы измерять прошлую редакцию мира.
 *
 * Как и в лиге атомов, сначала гоняется проверка самого прибора: одинаковые
 * тела обязаны дать половину. Если не дают — считать нечего, и таблица не
 * печатается.
 *
 * ── ЧТО ЭТОТ ПРИБОР ПОКАЗЫВАЕТ ПРЯМО СЕЙЧАС: ГЕЙТ КРАСНЫЙ ──────────────────
 *
 * Первый же прогон на новых осях, `--rounds=20` (400 боёв, прибор при этом
 * чист — одинаковые тела дали ровно 50.0%):
 *
 *     тело      hp   радиус   винрейт
 *     мелкое    60     0.60     85.0%
 *     ровное   210     1.30     65.6%
 *     быстрое  180     1.58     48.1%
 *     вёрткое  180     1.44     31.9%
 *     живучее  360     2.00     19.4%
 *
 * Шестикратный запас здоровья проигрывает вчистую малому радиусу: 35 пунктов
 * перекоса при пороге 12. Это не шум и не особенность одного мозга — это
 * ГЕОМЕТРИЯ. Площадь цели падает как КВАДРАТ радиуса, а цена радиуса линейна,
 * как и цена здоровья; линейной ценой квадратичную выгоду не уравновесить ни
 * при каком наклоне. В мире архетипов это компенсировал показатель степени
 * (`hp ∝ size^1.5`), который вместе с осью размера и ушёл.
 *
 * Чинится это в `src/core/config.js` — ценой осей, а не здесь: прибор своё
 * дело сделал, назвал виновную ось и вышел с единицей. Пока цена не
 * исправлена, гейт красный, и это правильное состояние: зелёный гейт на
 * сломанной оси — ровно то, против чего написан весь этот файл.
 */

import { POOL_SIZE, closePool, runJobs, superviseSelf } from './matchpool.mjs';

/* Пул изредка падает SIGSEGV и уносит процесс молча — надзиратель
   перезапускает счёт с меньшей параллельностью (см. `superviseSelf`). */
superviseSelf('AIRENA_BUILD_CHILD');
import { BUILD_AXES, BUILD_BUDGET, buildCost } from '../src/core/config.js';

const arg = (name, def) => {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? Number(hit.split('=')[1]) : def;
};
/* Умолчание — то же число, которым гоняет `npm test`. Стояло 6, и голый вызов
   инструмента падал там, где гейт проходил: разные числа сидов у одной
   проверки — это две разные проверки под одним именем. */
const ROUNDS = arg('rounds', 20);

const AXES = Object.keys(BUILD_AXES);

/**
 * Сколько ОЧКОВ стоит пройти ось от дешёвого конца до дорогого.
 *
 * Вес обязателен: с появлением `weight` цена оси перестала совпадать с её
 * длиной. Без него распределитель считал, что на дешёвой оси можно потратить
 * десять очков, а стоила она четыре, — и телосложения выходили разной цены,
 * то есть лига сравнивала бы не тела, а бюджеты. Прибор это поймал сам и
 * отказался мерить, что и правильно.
 */
const capOf = (name) => {
  const a = BUILD_AXES[name];
  return ((a.max - a.min) / a.per) * (a.weight ?? 1);
};

/**
 * Значение оси по числу потраченных на неё очков.
 *
 * У `radius` цена убывает (мелкая цель дороже), поэтому ноль очков — это
 * `max`, а не `min`. Это единственная ось, где «дёшево» значит «крупно», и
 * поэтому единственная, где отсчёт идёт от другого конца.
 */
const valueAt = (name, pts) => {
  const a = BUILD_AXES[name];
  const p = Math.max(0, Math.min(capOf(name), pts));
  /* Очки -> длина оси: делим на вес, потому что в очках он уже учтён. */
  const along = p / (a.weight ?? 1) * a.per;
  const v = a.inverse ? a.max - along : a.min + along;
  return Math.round(v * 1000) / 1000;
};

/**
 * Собрать законное тело: доли бюджета -> очки -> значения осей.
 *
 * Раздача идёт «наливом»: доля, упёршаяся в потолок своей оси, отдаёт остаток
 * остальным. Без этого набор с одной жадной осью тратил бы меньше бюджета, чем
 * остальные, — и лига сравнивала бы не телосложения, а цены. Ровно та ошибка,
 * от которой лигу атомов пришлось лечить фиксированным кулдауном.
 */
function buildFrom(share) {
  const pts = Object.fromEntries(AXES.map((n) => [n, 0]));
  let left = BUILD_BUDGET;
  let open = AXES.filter((n) => (share[n] || 0) > 0);
  for (let guard = 0; guard < AXES.length + 2 && left > 1e-9 && open.length; guard++) {
    const sum = open.reduce((a, n) => a + share[n], 0);
    let used = 0;
    for (const n of open) {
      const add = Math.min((left * share[n]) / sum, capOf(n) - pts[n]);
      pts[n] += add; used += add;
    }
    left -= used;
    open = open.filter((n) => capOf(n) - pts[n] > 1e-9);
    if (used <= 1e-12) break;
  }
  return Object.fromEntries(AXES.map((n) => [n, valueAt(n, pts[n])]));
}

/**
 * Пять телосложений одной цены.
 *
 * Доли, а не очки: потолок бюджета — величина настраиваемая, и таблица очков
 * пережила бы его правку молча, раздав кому-то меньше, чем он может потратить.
 * Доли переживают её правильно.
 *
 * Крайности взяты нарочно и в обе стороны по каждой из двух осей, где легче
 * всего спрятать бесплатную выгоду: «толстое и крупное» против «хрупкого и
 * мелкого» (здоровье против размера цели) и «быстрое» против «вёрткого»
 * (скорость по прямой против скорости разворота). «Ровное» — контроль: при
 * сегодняшних числах оно совпадает с `DEFAULT_BUILD`, то есть с телом
 * существа, о теле которого ничего не сказано.
 */
const SHARES = {
  ровное: { hp: 1, maxSpeed: 1, accel: 1, turnRate: 1, radius: 1, jumpHeight: 1 },
  живучее: { hp: 2, maxSpeed: 1, accel: 1, turnRate: 1, radius: 0, jumpHeight: 1 },
  мелкое: { hp: 0, maxSpeed: 1, accel: 1, turnRate: 1, radius: 2, jumpHeight: 1 },
  быстрое: { hp: 0.8, maxSpeed: 2, accel: 2, turnRate: 0.6, radius: 0.6, jumpHeight: 0 },
  вёрткое: { hp: 0.8, maxSpeed: 0.4, accel: 0.8, turnRate: 2, radius: 0.8, jumpHeight: 1.2 },
};

const BUILDS = Object.entries(SHARES).map(([name, share]) => {
  const build = buildFrom(share);
  return { name, build, cost: buildCost(build) };
});

/**
 * Отклонение от половины, начиная с которого телосложение выигрывает просто так.
 *
 * ── 0.12, А НЕ 0.20 ───────────────────────────────────────────────────────
 *
 * Двадцать пунктов и беда, ради которой этот гейт поднимали до двадцати сидов,
 * НЕ ПЕРЕСЕКАЛИСЬ: перекос в 14.4 пункта гейт печатал как «никто не
 * доминирует» и выходил с нулём. Конфигурация, объявленная сломанной в том же
 * журнале, проходила зелёной.
 *
 * Порог оставлен там же, где был на прошлой оси: 12 пунктов — граница между
 * «ось с ценой» и «доминирующая стратегия». Запас до неё меньше сигмы на
 * двадцати сидах, поэтому гейт остаётся чувствительным к настоящему сдвигу и
 * не краснеет от одного боя: разрешение прибора печатается рядом с каждой
 * строкой и считается из выборки.
 */
const DOMINATES = 0.12;
/**
 * Ниже этого прибор не различает — и это ЗАВИСИТ ОТ ЧИСЛА БОЁВ.
 *
 * Здесь стояла константа 0.07 при любом `--rounds`, и на шести сидах (как в
 * `npm test`) она равнялась примерно одной сигме: то есть «выше половины на
 * 10.4 п.п.» печаталось про величину, неотличимую от нуля. Прибор сообщал
 * число и не сообщал, значит ли оно что-нибудь.
 *
 * Считается из выборки: для доли σ ≈ 0.5/√n, берём две сигмы. При `--rounds=20`
 * это 160 боёв на тело и порог около 8 п.п.; при 40 — 320 и около 5.6.
 */
const resolution = (n) => (n > 0 ? 2 * 0.5 / Math.sqrt(n) : 1);

/*
 * Набор, на котором меряются тела.
 *
 * Он обязан УМЕТЬ ПРОМАХИВАТЬСЯ — иначе преимущество мелкого («в меня труднее
 * попасть») не измеряется вовсе. Луч и зона попадают почти всегда; снаряд
 * летит и мимо него можно уйти, конус узкий. Поэтому снаряд плюс конус.
 */
const KIT = [
  { delivery: 'bolt', effects: ['damage'], element: 'kinetic' },
  { delivery: 'cone', effects: ['damage'], element: 'kinetic' },
  { delivery: 'self', effects: ['heal'], element: 'frost' },
];

function jobsFor(pairs) {
  const jobs = []; const meta = [];
  for (const [i, j] of pairs) {
    for (let s = 0; s < ROUNDS; s++) {
      for (const flip of [false, true]) {
        jobs.push({
          a: KIT, b: KIT, seed: 1000 + s, sym: true,
          /* Стороны арены — это ЦВЕТА, blue и orange, и больше ничего: ни
             вида, ни архетипа за ними нет. Тело каждой приезжает вот этим
             полем, наравне с набором и сидом. */
          builds: flip
            ? { blue: BUILDS[j].build, orange: BUILDS[i].build }
            : { blue: BUILDS[i].build, orange: BUILDS[j].build },
        });
        meta.push({ i, j, flip });
      }
    }
  }
  return { jobs, meta };
}

async function league(pairs, label) {
  const { jobs, meta } = jobsFor(pairs);
  console.log(`\n  ${label}: ${jobs.length} боёв на ${POOL_SIZE} воркерах`);
  const out = await runJobs(jobs, (d, t) => process.stdout.write(`\r  ${label}: ${d}/${t}   `));
  process.stdout.write('\r');
  const score = BUILDS.map(() => ({ w: 0, n: 0 }));
  for (let k = 0; k < out.length; k++) {
    const m = meta[k]; const r = out[k];
    if (r === 'error') continue;
    /* Кто был «первым» в паре, зависит от flip: синяя сторона — это либо i,
       либо j. */
    const first = m.flip ? m.j : m.i;
    const second = m.flip ? m.i : m.j;
    score[first].n++; score[second].n++;
    if (r === 'blue') score[first].w++;
    else if (r === 'orange') score[second].w++;
    else { score[first].w += 0.5; score[second].w += 0.5; }
  }
  return score;
}

