/**
 * Гейт: «ЧЬЯ ВИНА» ОПРЕДЕЛЯЕТСЯ ОДИНАКОВО ВО ВСЕХ МЕСТАХ.
 *
 * Код отказа генерации проходит через два независимых списка:
 *
 *   `OUR_CODES`  (src/server/forge/pipeline.js) — конвейер решает, называть ли
 *                отказ своим или свалить на модель (`brain_failed`);
 *   `OUR_FAULT`  (src/server/limits.js)         — лимит решает, списывать ли
 *                игроку попытку из трёх суточных.
 *
 * Списки жили порознь, и над одним из них стоял комментарий «два списка в
 * одной папке однажды уже разошлись и назвали один код противоположно». Он
 * предупреждал — и не проверял ничего, поэтому они разошлись снова: `http`
 * был нашим для конвейера и НЕ нашим для лимита.
 *
 * Цена замерена 01.09. На ключе OpenRouter кончились деньги, провайдер стал
 * отвечать `402 … you can only afford 453 tokens` — до модели не доезжал ни
 * один токен промпта. Конвейер честно называл это своим, лимит списывал
 * попытку игроку, а экран говорил «попытка засчитана: модель ответила».
 * Восемь генераций подряд легли так, и ни одна не сказала правды.
 *
 * Правило: код, который конвейер назвал СВОИМ, обязан быть своим и для
 * лимита. Обратное неверно намеренно — у лимита есть свои коды
 * (`server_restarted`, `no_creature`), до конвейера не доходящие вовсе.
 *
 *   node tools/checkfaults.mjs
 */

import { OUR_CODES } from '../src/server/forge/pipeline.js';
import { OUR_FAULT } from '../src/server/limits.js';

let failed = 0;
const ok = (name, good, note = '') => {
  console.log(`  ${good ? '✓' : '✗'} ${name}${note ? `  ${note}` : ''}`);
  if (!good) failed++;
};

console.log('\n  ГЕЙТ ЧЬЕЙ ВИНЫ\n');

const limit = new Set(OUR_FAULT);
const missing = [...OUR_CODES].filter((c) => !limit.has(c));

ok('каждый код, который конвейер назвал своим, не списывается с игрока',
  missing.length === 0,
  missing.length ? `не хватает в OUR_FAULT: ${missing.join(', ')}` : `${OUR_CODES.size} кодов сверено`);

/*
 * Отдельно — самый дорогой из них. `http` покрывает 402 «кончились деньги»,
 * 429 приезжает как `rate`, 5xx — как `http`. Все три означают одно: игрок
 * ни при чём. Проверяются поимённо, потому что именно их удаление выглядит
 * безобидной уборкой списка.
 */
for (const c of ['http', 'rate', 'no_key', 'network']) {
  ok(`«${c}» не съедает суточную попытку игрока`, limit.has(c));
}

ok('у лимита есть и свои коды, до конвейера не доходящие',
  OUR_FAULT.some((c) => !OUR_CODES.has(c)),
  'иначе списки просто склеили, а не согласовали');

console.log(failed ? `\n  ПРОВАЛ: ${failed}\n` : '\n  ДЕРЖИТ\n');
process.exit(failed ? 1 : 0);
