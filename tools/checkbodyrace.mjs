/**
 * Гейт: ТЕЛО БОЙЦА ДОЕЗЖАЕТ ДО ЭКРАНА.
 *
 * ── ЧТО ЭТОТ ГЕЙТ ЛОВИТ И ПОЧЕМУ ОН ПОЯВИЛСЯ ПОЗЖЕ ВСЕХ ───────────────────
 *
 * `sendMatch` во вьюере зовёт `swapBody` для ОБОИХ бойцов в одном цикле и без
 * `await`. Охрана от гонки внутри `swapBody` была написана правильно по форме
 * и неверно по области: счётчик эпох был ОДИН НА ДВОИХ. Оба вызова успевали
 * его увеличить до первого ожидания, поэтому к моменту, когда собиралось тело
 * первого бойца, его `mine` уже отставал — и готовое тело выбрасывалось.
 *
 * Страдала всегда одна сторона, та, что в цикле первая: осьминог. Замерено по
 * последним 2000 матчам живой базы — существо с клон-телом занимало 1065 левых
 * слотов и 58 правых. То есть слева зритель видел не существо, а сток
 * `/bodies/octopus.js`, и жалоба основателя «2 осьминога очень часто вижу с
 * разными именами» описывала именно это: имена разные, тело одно, потому что
 * своё тело левому бойцу не доезжало НИКОГДА.
 *
 * Почему не поймали раньше. Ни один гейт не проверял ДВЕ СТОРОНЫ СРАЗУ:
 * `checkbody` меряет безопасность одного тела, `checkforgebody` — качество
 * одного тела, `checkframing` — кадр. Дефект жил ровно в том, что бойцов два,
 * а счётчик один, и заметить его можно было только запустив два обмена
 * одновременно. Здесь это и делается.
 *
 * ── ПОЧЕМУ ГЕЙТ ПРОВЕРЯЕТ ОБЕ СТОРОНЫ СДЕЛКИ ──────────────────────────────
 *
 * Как и `checkbody`, он доказывает не только что починенная логика проходит,
 * но и что СЛОМАННАЯ ПАДАЕТ. Гейт, который зелен на обеих версиях, ничего не
 * охраняет — он лишь сообщает, что код исполняется.
 *
 *   node tools/checkbodyrace.mjs
 */

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
let failed = 0;
const ok = (name, good, note = '') => {
  console.log(`  ${good ? '✓' : '✗'} ${name}${note ? `  ${note}` : ''}`);
  if (!good) failed++;
};

console.log('\n  ГЕЙТ ГОНКИ ТЕЛ\n');

/**
 * Модель `swapBody` — та же форма управления, что в `src/viewer/main.js`.
 *
 * Загрузка подменена задержкой, потому что проверяется НЕ загрузка, а охрана:
 * кто имеет право положить результат, когда два обмена идут одновременно.
 * Задержки разные и первый боец медленнее второго — так гонка воспроизводится
 * детерминированно, а не «иногда».
 */
function makeSwap({ shared }) {
  const epoch = shared ? { n: 0 } : { octopus: 0, gorilla: 0 };
  const bodies = {};
  const refOf = {};
  const bump = (id) => (shared ? ++epoch.n : ++epoch[id]);
  const cur = (id) => (shared ? epoch.n : epoch[id]);

  return {
    bodies,
    async swap(id, ref, delayMs) {
      if (refOf[id] === ref) return;
      const mine = bump(id);
      refOf[id] = ref;
      await new Promise((r) => setTimeout(r, delayMs));
      if (mine !== cur(id)) return;
      bodies[id] = ref;
    },
  };
}

/* ── сломанная версия обязана падать ───────────────────────────────────── */
{
  const s = makeSwap({ shared: true });
  await Promise.all([
    s.swap('octopus', 'body-oct', 20),
    s.swap('gorilla', 'body-gor', 5),
  ]);
  ok('общий счётчик эпох ТЕРЯЕТ тело первого бойца (так и было)',
    s.bodies.octopus === undefined && s.bodies.gorilla === 'body-gor',
    `осьминог=${s.bodies.octopus ?? 'потерян'} горилла=${s.bodies.gorilla}`);
}

/* ── починенная версия обязана доносить оба тела ───────────────────────── */
{
  const s = makeSwap({ shared: false });
  await Promise.all([
    s.swap('octopus', 'body-oct', 20),
    s.swap('gorilla', 'body-gor', 5),
  ]);
  ok('счётчик по стороне доносит ОБА тела',
    s.bodies.octopus === 'body-oct' && s.bodies.gorilla === 'body-gor',
    `осьминог=${s.bodies.octopus} горилла=${s.bodies.gorilla}`);
}

/* ── охрана от настоящей гонки ОДНОЙ стороны обязана сохраниться ───────── */
{
  /*
   * Ради чего охрана вообще писалась: если одну и ту же сторону перезапросили,
   * побеждает ПОСЛЕДНИЙ запрос, даже если он вернулся раньше. Иначе поздний
   * ответ старого боя перекроет тело нового.
   */
  const s = makeSwap({ shared: false });
  await Promise.all([
    s.swap('octopus', 'старое', 30),
    s.swap('octopus', 'новое', 5),
  ]);
  ok('перезапрос ОДНОЙ стороны по-прежнему выигрывает у отставшего ответа',
    s.bodies.octopus === 'новое', `осьминог=${s.bodies.octopus}`);
}

/* ── и то же самое на настоящем файле ──────────────────────────────────── */
const main = readFileSync(join(ROOT, 'src/viewer/main.js'), 'utf8');

ok('main.js: счётчик эпох заведён по стороне',
  /const bodyEpoch = \{\s*octopus:\s*0\s*,\s*gorilla:\s*0\s*\}/.test(main),
  'иначе гонка вернётся ровно в том же виде');

ok('main.js: обе точки счётчика читают сторону',
  /\+\+bodyEpoch\[id\]/.test(main) && /mine !== bodyEpoch\[id\]/.test(main));

ok('main.js: скалярного счётчика не осталось',
  !/(\+\+|!==\s*)bodyEpoch\s*(;|\))/.test(main));

/*
 * Отдельно — обещание из шапки `swapBody`: «при любой ошибке на стороне
 * остаётся тело архетипа». Оно было враньём: `catch` гасил ссылку и оставлял
 * тело ПРЕДЫДУЩЕГО существа, то есть зритель видел чужое существо под новым
 * именем. Проверяется наличие отката, а не его текст.
 */
ok('main.js: провал сборки откатывает сторону к телу архетипа',
  /if \(ref !== id\) swapBody\(id, id, size\);/.test(main),
  'иначе на стороне остаётся тело предыдущего боя');


/* ── одинаковая ссылка на двух сторонах ────────────────────────────────── */

/**
 * Модель `bodyFor`: кэш и его ключ. Проверяется НЕ загрузка, а то, может ли
 * одна ссылка отдать двум сторонам один и тот же объект.
 */
function makeCache({ keyHasSide }) {
  const cache = new Map();
  let built = 0;
  return {
    get built() { return built; },
    load(ref, side, size) {
      const key = keyHasSide ? `${ref}@${size}@${side}` : `${ref}@${size}`;
      if (cache.has(key)) return cache.get(key);
      const made = { id: ++built, ref, side, size };
      cache.set(key, made);
      return made;
    },
  };
}

{
  /*
   * Двадцать четыре существа в базе носят клонированные тела, поэтому встреча
   * двух с одинаковой ссылкой — обычное дело, а не край. Без стороны в ключе
   * обе стороны получали ОДИН объект: цикл кадра ставил его сначала в точку
   * левого бойца, потом в точку правого, и левый оставался бестелесным.
   */
  const bad = makeCache({ keyHasSide: false });
  ok('ключ без стороны ОТДАЁТ ОДИН объект обеим сторонам (так и было)',
    bad.load('gen:одно-тело', 'octopus', 1) === bad.load('gen:одно-тело', 'gorilla', 1));

  const good = makeCache({ keyHasSide: true });
  const g1 = good.load('gen:одно-тело', 'octopus', 1);
  const g2 = good.load('gen:одно-тело', 'gorilla', 1);
  ok('ключ со стороной даёт КАЖДОЙ стороне свой экземпляр', g1 !== g2,
    `собрано тел: ${good.built}`);
  ok('и кэш остаётся кэшем: повтор той же стороны не пересобирает',
    good.load('gen:одно-тело', 'octopus', 1) === g1, `собрано тел: ${good.built}`);
}

ok('main.js: ключ кэша тела включает сторону',
  main.includes('const key = `${ref}@${size}@${kind}`'),
  'масштаб тела считается по стороне — чужой масштаб приезжает вместе с чужим объектом');

/*
 * Ключ кэша и `bodyRefOf` ОБЯЗАНЫ совпадать по форме. Защита кэша от
 * вытеснения живого тела сравнивает одно с другим
 * (`Object.values(bodyRefOf).includes(oldest)`); стоит формам разойтись — кэш
 * выбросит и УНИЧТОЖИТ тело, которое прямо сейчас на экране, а обе строки по
 * отдельности останутся верными, и никакая проверка одной из них не поможет.
 */
ok('main.js: `bodyRefOf` пишется тем же ключом, что и кэш',
  main.includes('const want = `${ref}@${size}@${id}`')
  && main.includes('Object.values(bodyRefOf).includes(oldest)'),
  'иначе вытеснение уничтожит живое тело');

console.log(failed ? `\n  ПРОВАЛ: ${failed}\n` : '\n  ДЕРЖИТ\n');
process.exit(failed ? 1 : 0);
