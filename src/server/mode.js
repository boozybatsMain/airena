/**
 * РЕЖИМ СТЕНДА: ОДНО МЕСТО, А НЕ ЧЕТЫРЕ КОПИИ.
 *
 * `const DEV = process.env.AIRENA_DEV === '1'` было выписано четырьмя
 * одинаковыми строками — в `app.js`, `api.js`, `http.js` и `session.js`.
 * Одинаковые строки расходятся; но хуже расхождения оказалось само правило.
 *
 * ── ПОЧЕМУ ПРАВИЛО ПЕРЕВЁРНУТО ───────────────────────────────────────────
 *
 * Дев-режим был ВКЛЮЧАЕМЫМ: без `AIRENA_DEV=1` сервер поднимался с закрытой
 * стеной аккаунта, и на локальной странице появлялось «здесь войти не
 * получится: страница открыта не внутри платформы». То есть чтобы завести
 * существо у себя на машине, надо было ЗАРАНЕЕ ВСПОМНИТЬ переменную, о
 * которой сообщает только текст отказа при старте — а если сервер уже поднят
 * кем-то другим (или другой командой, как здесь), не сообщает ничего.
 *
 * В `wall.js` про это есть комментарий: «Цена этой строки — вопрос основателя
 * „почему я СНОВА не могу потестить создание существа“, заданный не в первый
 * раз». Комментарий написан, а причина осталась: тот круг чинил ТЕКСТ отказа,
 * а не то, что дев-режим надо угадывать. Основатель упёрся в ту же стену
 * снова.
 *
 * Признак местного стенда есть, и он надёжнее переменной: `AIRENA_SECRET`.
 * В продакшене он ОБЯЗАТЕЛЕН — без него `session.js` не даёт подписывать
 * сессии и процесс падает на старте. Значит «секрета нет» = «это не
 * продакшен», и другого прочтения быть не может. На этом и стоим:
 *
 *   секрета нет            → дев-стенд, стена аккаунта проходится локально;
 *   секрет есть            → продакшен, дев-вход закрыт;
 *   AIRENA_DEV=1           → дев-стенд принудительно (например, с секретом);
 *   AIRENA_PROD=1          → продакшен принудительно, что бы ни было ещё.
 *
 * Тихо включиться в продакшене этот режим не может: там секрет задан всегда,
 * иначе сервер не стартует. То есть опасного умолчания мы не заводим — мы
 * убираем умолчание ОПАСНОЕ ДЛЯ РАЗРАБОТКИ: «по умолчанию не работает».
 */
const forcedProd = process.env.AIRENA_PROD === '1';
const forcedDev = process.env.AIRENA_DEV === '1';
const hasSecret = !!process.env.AIRENA_SECRET;

export const DEV = forcedProd ? false : (forcedDev || !hasSecret);

/** Одна строка в лог при старте: режим не должен быть догадкой. */
export function announceMode(log = console.error) {
  if (!DEV) return;
  log(forcedDev
    ? '  дев-стенд (AIRENA_DEV=1): стена аккаунта проходится локальной личностью'
    : '  дев-стенд (AIRENA_SECRET не задан): стена аккаунта проходится локальной личностью');
}
