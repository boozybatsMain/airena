/* Тело большое: осьминог — тысяча строк. Потолок выше мозгового. */
export const BODY_MAX_CHARS = 400_000;

/**
 * Топливо. Сборка идёт один раз и строит тысячи полигонов, кадр — шестьдесят
 * раз в секунду и только двигает суставы. Бюджеты поэтому разные на два
 * порядка, и оба заведомо выше честного использования: цель — поймать
 * бесконечный цикл, а не сэкономить.
 */
export const BODY_FUEL_BUILD = 40_000_000;
export const BODY_FUEL_POSE = 400_000;

/**
 * Разобрать тело и вернуть безопасный для отправки исходник.
 *
 * Возвращает `{ ok, problems, source }`. `source` — уже с учётом топлива:
 * отдавать наружу неинструментированный вариант нельзя, иначе третья стена
 * стоит, а вторая нет.
 */
export function analyseBody(source) {
  const a = analyse(source, {
    maxChars: BODY_MAX_CHARS,
    globals: BODY_GLOBALS,
    named: BODY_NAMED,
    entry: 'build',
    outsideRu: 'THREE или TSL',
    vocabularyRu: 'THREE, TSL, буферы, Math и console',
  });
  if (!a.ok) return { ok: false, problems: a.problems, source: null };

  /* Точка входа обязана существовать и называться `build`: вьювер зовёт
     именно её, и «модель назвала функцию иначе» должно быть отказом с
     объяснением, а не пустым экраном. */
  const hasBuild = a.ast.body.some((n) => (
    (n.type === 'FunctionDeclaration' && n.id?.name === 'build')
    || (n.type === 'VariableDeclaration' && n.declarations.some((d) => d.id?.name === 'build'))
  ));
  if (!hasBuild) {
    return {
      ok: false,
      problems: [{ code: 'no_build', message: 'нет функции build(THREE, TSL) на верхнем уровне' }],
      source: null,
    };
  }

  let out;
  try {
    /* Размечается то, что РАЗОБРАЛОСЬ: `analyse` мог снять обёртку модуля
       (`import`/`export`), и разметка исходного текста снова упёрлась бы в
       неё — отказ выглядел бы как «не размечается», хотя дело в обёртке. */
    out = instrument(a.source ?? source);
  } catch (e) {
    return { ok: false, problems: [{ code: 'instrument', message: `не размечается: ${e.message}` }], source: null };
  }
  /* `instrument` возвращает `{code, points}`; наружу уезжает только код,
     а число точек — в отчёт: тело без единой точки учёта означает, что
     разметка ничего не нашла, и это повод посмотреть, а не радоваться. */
  return { ok: true, problems: [], source: out.code, points: out.points };
}
