/**
 * Живой показ боя.
 *
 * Здесь важен один порядок, и он не переставляется: **сначала бой посчитан,
 * потом показан.** Зачётный прогон headless стоит 70 мс и уже записан в
 * таблицу (A3); показ — это ПОВТОР записанного, кадр в кадр, в реальном
 * времени. Детерминизм (A2) делает повтор точным, а не похожим.
 *
 * Что это даёт помимо честности:
 *  — обрыв связи не теряет бой: клиент переподключается и получает тот же
 *    матч с нужной секунды (D14);
 *  — клиент физически не может сообщить исход: он получает кадры и всё;
 *  — F5a («длительность боя держит сервер») выполняется буквально —
 *    таймер здесь, а не в браузере.
 *
 * Протокол — тот же, что уже понимает `src/viewer/main.js`, и это намеренно:
 * боевой экран утверждён поэлементно (§10.6), и переписывать его ради нового
 * сообщения значит рисковать утверждённым ради необязательного.
 */

import { CURTAIN } from './arena-loop.js';
import { runIsolated } from './sandbox/index.js';
import { kitOf } from './arena-loop.js';
import { DELIVERIES, EFFECTS } from '../skills/registry.js';

/**
 * Подписи умений для боевого HUD: короткое имя, которым мозг зовёт умение,
 * и русское название, которое читает игрок.
 */
function kitLabels(c, snapshot) {
  /*
   * ПОДПИСИ — ИЗ СНИМКА БОЯ, А НЕ ИЗ СТРОКИ СУЩЕСТВА.
   *
   * Кадры уже собирались из `matchRow.kits` (снимок на момент боя), а
   * подписи, `kind`, дальности и телеграф брались из ТЕКУЩЕГО набора. Смена
   * набора мгновенна и бесплатна (D3), поэтому расхождение достижимо, и
   * воспроизведено живьём: бой сыгран «снаряд/конус/на себя», после смены
   * набора повтор тех же кадров подписан «луч/зона/на себя», вьювер выбирал
   * анимацию каста по чужой доставке и рисовал телеграф умения, которого в
   * этом бою не было.
   *
   * Это тот же дефект, что чинили для размеров, в третьем месте. У старых
   * матчей снимка нет — они честно читаются по текущей строке, как и кадры.
   */
  const defs = snapshot || kitOf(c);
  if (!defs) return null;
  /*
   * VFX-IR едет ВМЕСТЕ С ПОДПИСЬЮ УМЕНИЯ, а не отдельным сообщением.
   *
   * Вьюверу он нужен ровно там же, где `kind` и `windup`: в момент, когда
   * умение сработало, надо знать, чем его украсить. Отдельный канал означал
   * бы ещё одну гонку — декорация приехала, а набор ещё нет, — и первые
   * касты боя шли бы голыми. Это тот же довод, по которому вместе с именем
   * едут тело и набор: это три части одного ответа на вопрос «кто дерётся».
   *
   * Сломанный JSON здесь не роняет бой: декорации просто не будет. VFX
   * никогда не влияет на симуляцию (§9.2), и он не вправе влиять даже на
   * то, начнётся ли трансляция.
   */
  /* Декорация снимка не имеет: VFX-IR не влияет на симуляцию (§9.2), поэтому
     он берётся текущий. Ключи IR — имена умений `k1..k3`, и если набор с тех
     пор сменился, украшение просто не найдётся по имени. Это видимая мелочь
     против невидимой лжи о геометрии умения. */
  let ir = null;
  try { ir = c.vfx_json ? JSON.parse(c.vfx_json) : null; } catch { ir = null; }
  const out = {};
  for (const [name, d] of Object.entries(defs)) {
    const eff = d.effects.map((e) => EFFECTS[e.id]?.ru || e.id).join('+');
    /* `kind` едет вместе с подписью не для HUD, а для ТЕЛА: по доставке
       вьювер выбирает, какую анимацию играть на касте (см. poseAction).
       Без него существо с набором из грамматики стреляло молча и неподвижно —
       HUD показывал каст, а тело продолжало идти. */
    /*
     * Геометрия и тайминг едут вместе с подписью — иначе умение из грамматики
     * нельзя ни телеграфировать, ни показать полосой каста.
     *
     * `cfg.skills` знает только четыре захардкоженных умения, и вьювер брал
     * замах оттуда: для `k1` там undefined, значит `casting === false`, значит
     * ни полосы над головой, ни фигуры на полу. Для КАЖДОГО существа, которое
     * заведёт игрок, замах был невидим — то есть «по замаху видно, что сейчас
     * будет» не работало ровно там, где это единственный способ читать бой.
     */
    out[name] = {
      ru: `${DELIVERIES[d.kind]?.ru || d.kind}·${eff}`,
      element: d.element,
      kind: d.kind,
      windup: d.windup,
      recover: d.recover,
      /* Режется ли путь укрытием. Навес летит по дуге, зона ставится в точку —
         обоим укрытие безразлично, и телеграф, обрезанный о стену, обещает им
         дальность, которой они не лишены. */
      needsLos: !!d.needsLos,
      ...(d.range !== undefined ? { range: d.range } : {}),
      ...(d.halfAngle !== undefined ? { halfAngle: d.halfAngle } : {}),
      ...(d.distance !== undefined ? { distance: d.distance } : {}),
      ...(d.radius !== undefined ? { radius: d.radius } : {}),
      /* D160: воздушная фаза прыжка. Вьювер делит анимацию на `jump` и `land`
         по этому числу; без него прыжок из грамматики играл бы один общий
         клип и приземлялся бы визуально раньше, чем механически. */
      ...(d.airborne !== undefined ? { airborne: d.airborne } : {}),
      ...(ir && ir[name] ? { vfx: ir[name] } : {}),
    };
  }
  return out;
}
import { TICK_HZ } from '../core/config.js';

/**
 * Сколько трансляций держим в памяти одновременно.
 *
 * Кадры одного боя — около 0.7 МБ JSON. Тридцать два это ~22 МБ кадров плюс
 * накладные кучи. Было 24; D161 поднял темп боёв примерно впятеро, и при 24
 * `evict` начинал выбрасывать трансляции, к которым зрителей ещё не успели
 * подключить. Замер ревью показал и обратную сторону: при 48 тридцать
 * анонимных сокетов, спамящих повтором, поднимали RSS с 281 МБ до 1586 МБ.
 * Тридцать два — между этими двумя измерениями.
 */
const MAX_BROADCASTS = 32;
/**
 * Сколько боёв считается одновременно.
 *
 * Каждый расчёт — отдельный воркер (изолят), и их столько же, сколько ядер
 * минус хвост на всё остальное. Было 4 и стало 6 вместе с ростом темпа; выше
 * этого память растёт быстрее, чем очередь успевает разбираться (см. замер
 * у `MAX_BROADCASTS`).
 */
const MAX_OPENING = 6;
/** Сколько секунд после конца боя трансляция ещё жива (для догоняющих). */
const LINGER_SECONDS = 12;

/**
 * Сколько отложенных трансляций держим и как долго они годны.
 *
 * Очередь существует ради одного случая — волны матчей после рестарта, — и
 * ей незачем быть длинной: бой, дождавшийся своей очереди через полминуты,
 * уже неинтересен, а слот он займёт. Двадцать записей это примерно две волны
 * популяции в сотню существ.
 */
const QUEUE_MAX = 20;
const QUEUE_STALE_MS = 20_000;

/**
 * Сколько зритель ДОСМАТРИВАЕТ доигравший бой, прежде чем его переведут.
 *
 * Замер ревью: между `over` и следующим `match` на анонимном сокете проходило
 * 0.000 с в 54 переходах из 54 — потому что где-то всегда идёт чужой бой, и
 * перебивка «доигравший → любой идущий» срабатывала в ТОМ ЖЕ тике, что и
 * `finish`. На клиенте это значит, что `result.showInline()` и
 * `result.hideInline()` вызываются в одном кадре: карточка итога создаётся и
 * тут же уничтожается. Для гостя она — единственная точка, где написано
 * «СДЕЛАТЬ СВОЁ».
 *
 * Число чуть меньше отдыха (D161): к моменту, когда своё существо выходит на
 * арену, итог уже прочитан, и переключение не спорит с ним.
 */
const RESULT_LINGER_MS = 4_500;

export class Live {
  constructor(db, { compile, now = Date.now } = {}) {
    this.db = db;
    this.compile = compile;
    this.now = now;
    this.broadcasts = new Map();   // matchId -> Broadcast
    this.opening = new Set();      // matchId, пока считаются кадры
    /* Матчи, которым не хватило слота: очередь, а не потеря (см. `open`). */
    this.queue = [];
    /*
     * СЧЁТЧИК ПОТЕРЬ. Отказ `open()` возвращался как `null`, вызывающий его
     * глотал, и «зачётный бой сыгран и никому не показан» не оставлял следа
     * нигде. Число видно в `/api/health`.
     */
    this.dropped = { ranked: 0, showcase: 0, replay: 0 };
    /* Слушатели «показ доиграл» — по ним цикл боёв ставит настоящий отдых. */
    this.finished = new Set();
    this.libCache = new Map();
    this.sockets = new Set();
    this.featured = null;          // matchId, который смотрят гости
    this.timer = null;
  }

  start() {
    if (this.timer) return;
    this.timer = setInterval(() => this.pump(), 1000 / TICK_HZ);
    this.timer.unref?.();
  }

  stop() { if (this.timer) { clearInterval(this.timer); this.timer = null; } }

  /**
   * Открыть трансляцию только что сыгранного матча.
   *
   * Кадры считаются заново тем же `(seed, brains)` — 70 мс. Хранить их с
   * зачётного прогона было бы дешевле по CPU и дороже по смыслу: тогда
   * «показ равен зачёту» держалось бы на том, что кто-то не забыл передать
   * массив, а не на детерминизме.
   */
  async open(matchRow, { a, b, featured = false, kind = 'ranked' }) {
    if (this.broadcasts.has(matchRow.id)) return this.broadcasts.get(matchRow.id);
    /* Заглушка на время расчёта: без неё два кадра подряд открывают один и
       тот же матч дважды и зритель получает две трансляции одного боя. */
    if (this.opening.has(matchRow.id)) return null;
    /*
     * СКОЛЬКО БОЁВ МОЖНО СЧИТАТЬ ОДНОВРЕМЕННО.
     *
     * `open()` прогоняет весь бой в изоляте и держит его кадры в памяти. На
     * одно и то же id повтор не запускается (`opening` выше), но id матчей
     * много: поток команд `replay` с разными id — а прислать его может любой
     * анонимный сокет — плодит изоляты без предела и кладёт арену для ВСЕХ,
     * включая тех, кто просто смотрел.
     *
     * `MAX_BROADCASTS` от этого не спасает: он ограничивает, сколько
     * трансляций ХРАНИТСЯ, а не сколько считается прямо сейчас.
     */
    /*
     * ПЕРЕПОЛНЕНИЕ — ЭТО ОЧЕРЕДЬ, А НЕ ПОТЕРЯ.
     *
     * Здесь стоял голый `return null`, а вызывающий (`app.js`, `loop.on`)
     * глотал результат через `.catch(() => {})`. Из этого следовало худшее,
     * что может сделать этот файл: ЗАЧЁТНЫЙ бой игрока сыгран, записан в
     * таблицу, сдвинул рейтинг — и не показан никому. Замерено две потери за
     * сто секунд, обе на существах игроков, обе в первые две секунды после
     * рестарта, когда вся популяция стартует разом.
     *
     * Очередь короткая и с приоритетом: бой игрока важнее витринного, потому
     * что витринных всегда можно сыграть ещё, а этот — единственный.
     * `pump` разбирает её по мере освобождения слотов.
     */
    if (this.opening.size >= MAX_OPENING) {
      /*
       * ── КЛАСС ВАЖНЕЕ ПОРЯДКА ПРИХОДА ──────────────────────────────────
       *
       * Первая версия делила очередь по флагу `featured`. Но `featured:false`
       * носит и ЗАЧЁТНЫЙ бой игрока, и повтор по ссылке от анонимного сокета
       * — то есть повтор попадал в тот же высший класс. Замерено: тридцать
       * сокетов, шлющих по одному `replay` в секунду (в рамках собственного
       * лимита сервера), утопили 44 зачётных боя из 56, включая два боя
       * существа владельца. `unshift`/`shift` вдобавок делали порядок
       * обратным: непрерывный поток повторов вечно давил бой игрока в хвост.
       *
       * Теперь класс задаётся явно, очередь — строго FIFO внутри класса, а
       * ПОВТОР В ОЧЕРЕДЬ НЕ ВСТАЁТ ВОВСЕ: у него есть кому пожаловаться —
       * зритель нажал кнопку и может нажать ещё раз, — а у зачётного боя
       * второго шанса нет.
       */
      if (kind === 'replay') { this.dropped.replay++; return null; }
      const dup = this.queue.some((q) => q.matchRow.id === matchRow.id);
      if (!dup && this.queue.length < QUEUE_MAX) {
        const item = { matchRow, a, b, featured, kind, at: this.now() };
        const rank = (k) => (k === 'ranked' ? 0 : 1);
        /* Вставка за последним элементом своего класса: FIFO внутри класса,
           классы по порядку. Очередь короткая, линейный поиск дешевле кучи. */
        let at = this.queue.length;
        while (at > 0 && rank(this.queue[at - 1].kind) > rank(kind)) at--;
        this.queue.splice(at, 0, item);
      } else if (!dup) {
        this.dropped[kind === 'ranked' ? 'ranked' : 'showcase']++;
      }
      return null;
    }
    this.opening.add(matchRow.id);
    let frames;
    try {
      const out = await runIsolated(
        { [matchRow.aSlot]: a.brain_source, [matchRow.bSlot]: b.brain_source },
        { seed: matchRow.seed, record: true, curtainSeconds: CURTAIN,
          /*
           * Наборы БОЯ, а не наборы существа сейчас.
           *
           * Набор меняется мгновенно и бесплатно, и повтор, собранный по
           * текущей строке, показывал другой бой, чем тот, чей результат и
           * дельта рейтинга лежат рядом на экране. Снимок пишется вместе с
           * матчем; у старых матчей его нет, и они честно повторяются по
           * текущей строке — задним числом объявить их непросматриваемыми
           * было бы хуже.
           */
          kits: matchRow.kits || { [matchRow.aSlot]: kitOf(a), [matchRow.bSlot]: kitOf(b) },
          /*
           * РАЗМЕРЫ БОЯ — ПО ТОМУ ЖЕ ПРАВИЛУ, ЧТО И НАБОРЫ.
           *
           * Их тут не было вовсе, и это худший вид расхождения: рейтинговый
           * бой считался с размерами (`arena-loop`), а трансляция — без них,
           * то есть игрок смотрел ДРУГОЙ бой, чем тот, за который ему
           * начислена дельта. Замерено: на одинаковых сидах и наборах
           * победитель расходился в 11 случаях из 12.
           *
           * Хуже того, вьювер уже получал настоящий размер и масштабировал по
           * нему меш — то есть существо рисовалось на полтора коллайдера, а
           * кадры были сняты для одного. Ровно то, что запрещает комментарий
           * в самом `loadBody`: картинка обязана совпадать с физикой.
           */
          sizes: matchRow.sizes || { [matchRow.aSlot]: a.size ?? 1, [matchRow.bSlot]: b.size ?? 1 } },
      );
      frames = out.frames;
    } catch (e) {
      this.opening.delete(matchRow.id);
      return null;
    }
    this.opening.delete(matchRow.id);
    const bc = {
      id: matchRow.id,
      seed: matchRow.seed,
      frames,
      at: 0,
      startedAt: this.now(),
      over: null,
      meta: {
        [matchRow.aSlot]: { id: a.id, name: a.name, model: a.brain_model, library: !!a.is_library, size: a.size ?? 1 },
        [matchRow.bSlot]: { id: b.id, name: b.name, model: b.brain_model, library: !!b.is_library, size: b.size ?? 1 },
      },
      /* Ссылка на тело, а не тело: исходник в тысячу строк не место в
         сообщении о начале боя — вьювер запросит его сам и один раз. */
      bodies: {
        [matchRow.aSlot]: a.body_safe ? `gen:${a.id}` : matchRow.aSlot,
        [matchRow.bSlot]: b.body_safe ? `gen:${b.id}` : matchRow.bSlot,
      },
      /*
       * ТРЕНИРОВОЧНЫЙ — ЭТО ВИД МАТЧА, А НЕ ВИД СОПЕРНИКА.
       *
       * Здесь стояло «кто-то из двоих библиотечный», и экран итога говорил
       * проигравшему: «соперник измеренно слабее среднего». Половина
       * библиотеки при этом сильнее большей части лестницы — среди них есть
       * существо с 94% побед. То есть человеку сообщали, что он уступил
       * заведомо слабому, и это была неправда ровно в тот момент, когда
       * обиднее всего.
       *
       * Настоящий признак записан в самой строке матча: `kind = 'training'`
       * ставится только когда соперника выбрал не подбор по рейтингу, а
       * измеренный спарринг-партнёр первого боя (§7.3, D6). Берём его.
       */
      training: matchRow.training !== undefined
        ? !!matchRow.training
        : matchRow.kind === 'training',
      /*
       * D8 — «мозг сломался, бой не в зачёт» — доезжает до экрана.
       *
       * Правило есть в симуляции и в базе: после FAULT_LIMIT падений мозг
       * выключается, матч помечается `brain_fault` и рейтинг не двигает. А в
       * сообщении об окончании боя признака не было ВООБЩЕ, и клиентский код,
       * который должен был показать «этот бой не считается», не мог сработать
       * ни разу. Игрок видел поражение, которого по нашим же правилам не
       * произошло.
       */
      faulted: Array.isArray(matchRow.faulted) ? matchRow.faulted
        : (matchRow.kind === 'brain_fault' ? ['?'] : []),
      ranked: matchRow.ranked !== undefined ? !!matchRow.ranked : matchRow.kind !== 'brain_fault',
      trainingRate: matchRow.trainingRate ?? null,
      kits: {
        [matchRow.aSlot]: kitLabels(a, matchRow.kits?.[matchRow.aSlot]),
        [matchRow.bSlot]: kitLabels(b, matchRow.kits?.[matchRow.bSlot]),
      },
      result: matchRow,
      watchers: new Set(),
    };
    this.broadcasts.set(matchRow.id, bc);
    /* Витриной становится только ВИТРИННЫЙ бой или бой, открытый расписанием.
       Повтор по ссылке (`featured: false`, приходит из `attachTo`) не должен
       назначать себя витриной для всех гостей только потому, что успел
       первым в окно, когда прежняя витрина удалилась. */
    /*
     * ПОВТОР — ЛИЧНАЯ ТРАНСЛЯЦИЯ, И ОН НЕ ВИДЕН ЧУЖИМ.
     *
     * Повтор по ссылке живёт в той же карте, что и настоящие бои, и до этой
     * метки он был для всех остальных обычной ИДУЩЕЙ трансляцией: `pick`
     * предпочитает самую молодую, а повтор всегда самый молодой. Любой
     * анонимный сокет, нажав «повторить», срывал каждого зрителя с живого
     * боя на старый, поданный как живой.
     *
     * Витриной повтор тоже стать не может: условие ниже раньше пускало его,
     * если `this.featured` в этот момент пуст.
     */
    bc.private = kind === 'replay';
    if (!bc.private && (featured || !this.featured || !this.broadcasts.has(this.featured))) {
      this.featured = matchRow.id;
    }
    this.evict();
    return bc;
  }

  evict() {
    while (this.broadcasts.size > MAX_BROADCASTS) {
      /* Выкидываем самую старую БЕЗ зрителей. Трансляция со зрителем не
         выселяется никогда: зритель посреди боя, у которого пропала картинка,
         не отличает это от поломки. */
      let victim = null;
      for (const [id, b] of this.broadcasts) {
        if (b.watchers.size) continue;
        if (!victim || b.startedAt < victim.startedAt) victim = b;
      }
      if (!victim) break;
      this.broadcasts.delete(victim.id);
      if (this.featured === victim.id) this.featured = null;
    }
  }

  /** Подписать сокет на существо (или на витрину, если существа нет). */
  attach(ws, { creatureId = null, dev = false, owned = false, accountId = null } = {}) {
    /* `owned` — принадлежит ли `creatureId` этому аккаунту. Отдельно от самого
       id, потому что гость выбирает библиотечного стартера: следить за ним
       можно, называть его своим — нельзя (D162). */
    const sub = { ws, creatureId, owned, accountId, dev, matchId: null, cursor: 0, alive: true, pinned: false };
    this.sockets.add(sub);
    ws.on('close', () => { this.detach(sub); });
    this.deliver(sub);
    return sub;
  }

  detach(sub) {
    sub.alive = false;
    this.sockets.delete(sub);
    for (const b of this.broadcasts.values()) b.watchers.delete(sub);
  }

  /**
   * Кого ждут подключённые сокеты и никак не дождутся.
   *
   * Витрина показывает «кого-нибудь», а гость выбрал конкретное существо. Без
   * этого его выбор — клик в никуда: библиотечные в расписание боёв не
   * ставятся, и выбранное существо может не подраться ни разу.
   *
   * Отдаётся ОДИН id, самый старый из ожидающих: витрина показывает по одному
   * бою, и очередь честнее лотереи.
   */
  wanted() {
    /*
     * Спрашивают об этом в момент, когда витрина ДОИГРАЛА, а зрители всё ещё
     * приклеены к ней (линг). Условие «сокет без матча» в этот момент ложно
     * для всех, и `prefer` был null всегда — то есть выбор стартера гостем
     * (D2) не влиял на витрину ни разу.
     *
     * Считаем «свободным» и того, чья трансляция уже кончилась. И отдаём
     * только тех, кого витрина вообще может поставить, — своё существо
     * игрока `showcase()` всё равно отбросит по `is_library`, а очередь
     * оно при этом займёт.
     */
    for (const sub of this.sockets) {
      if (!sub.alive || !sub.creatureId || sub.owned) continue;
      /* Витрина ставит только БИБЛИОТЕЧНОЕ существо, и `showcase()` небиблиотечное
         молча отбросит. Отдавать его отсюда значит занять единственное место в
         очереди предпочтений тем, что заведомо не сработает: гость, следящий за
         чужим ИГРОВЫМ существом, — законное состояние. */
      if (!this.isLibrary(sub.creatureId)) continue;
      const b = sub.matchId ? this.broadcasts.get(sub.matchId) : null;
      if (!b || b.over) return sub.creatureId;
    }
    return null;
  }

  /** Библиотечное ли это существо. Единственный запрос `Live` к базе, и он
      дешёвый — по первичному ключу, с коротким кешем на жизнь процесса. */
  isLibrary(id) {
    if (!this.db) return false;
    if (this.libCache.has(id)) return this.libCache.get(id);
    const row = this.db.prepare('SELECT is_library FROM creature WHERE id = ?').get(id);
    const v = !!(row && row.is_library);
    this.libCache.set(id, v);
    return v;
  }

  /** Участвует ли это существо в этой трансляции. */
  static inBroadcast(b, creatureId) {
    return b.meta[b.result.aSlot]?.id === creatureId || b.meta[b.result.bSlot]?.id === creatureId;
  }

  /**
   * Что показать этому сокету прямо сейчас.
   *
   * ИДУЩИЙ БОЙ ВСЕГДА ВАЖНЕЕ ДОИГРАВШЕГО, и это не мелочь порядка.
   *
   * Трансляция живёт в карте ещё `LINGER_SECONDS` после конца — чтобы
   * опоздавший увидел исход. Перебор карты без проверки `over` находил
   * СТАРУЮ трансляцию раньше новой (Map сохраняет порядок вставки), и сокет
   * оставался на доигравшем бое все двенадцать секунд линга.
   *
   * Замерено: между концом боя и следующим на экране проходило ровно 12.0 с
   * вместо обещанных пяти — то есть D161 не выполнялся ровно там, где его
   * видно, и виноват был не отдых, а этот перебор.
   */
  pick(sub) {
    /* Личная трансляция (повтор) видна только тому, кто её попросил. */
    const open = (b) => !b.private || b.id === sub.matchId;
    if (sub.creatureId) {
      let stale = null;
      for (const b of this.broadcasts.values()) {
        if (!open(b) || !Live.inBroadcast(b, sub.creatureId)) continue;
        if (!b.over) return b;
        if (!stale) stale = b;
      }
      if (stale) return stale;
    }
    const f = this.featured ? this.broadcasts.get(this.featured) : null;
    if (f && !f.over) return f;
    /*
     * Витрина доиграла — берём САМЫЙ МОЛОДОЙ идущий бой, а не первый попавшийся.
     *
     * Замер: входные секунды новичка были 1.3, 3.1, 4.0, 7.2, 21.3, 29.6,
     * 33.7, 35.1, 41.7, 43.0 — то есть в среднем он попадал в середину чужой
     * драки и ни разу к началу. Пустой экран и застывший одинаково плохи, но
     * «вошёл на сорок третьей секунде» — это ещё и бой, из которого ничего
     * не понять.
     */
    let young = null;
    for (const b of this.broadcasts.values()) {
      if (b.over || !open(b)) continue;
      if (!young || b.at < young.at) young = b;
    }
    return young || f;
  }

  /**
   * Идёт ли прямо сейчас СОБСТВЕННЫЙ бой этого сокета.
   *
   * Нужен отдельно от `pick`, потому что `deliver` вызывается и для тех, кто
   * уже что-то смотрит: без этого различия свой бой можно было пропустить
   * целиком (см. `deliver`).
   */
  ownBroadcast(sub) {
    if (!sub.creatureId) return null;
    /* Только ИДУЩИЙ бой: доигравший собственный бой не должен перебивать
       ничего, он уже показан. С проверкой `over` это ещё и единственное
       место, откуда «свой бой забирает экран» может сработать вовремя. */
    for (const b of this.broadcasts.values()) {
      if (b.private && b.id !== sub.matchId) continue;
      if (!b.over && Live.inBroadcast(b, sub.creatureId)) return b;
    }
    return null;
  }

  deliver(sub) {
    const b = this.pick(sub);
    if (!b) {
      /*
       * «Нет боя» — это состояние, а не ошибка, и сообщается оно ОДИН РАЗ на
       * вход в него.
       *
       * `pump()` зовёт `deliver` для каждого сокета без матча КАЖДЫЙ ТИК, и
       * сообщение уходило тридцать раз в секунду. Клиент на каждое пересобирал
       * панель ожидания: кнопка гостя — единственное его действие — создавалась
       * и уничтожалась тридцать раз в секунду, а вместе с ней тридцать раз в
       * секунду уходил запрос `/api/starters`. Нажать на такую кнопку можно
       * только случайно.
       *
       * Флаг снимается при выдаче матча — там же, где сокет получает трансляцию.
       */
      if (!sub.idleSent) {
        sub.idleSent = true;
        send(sub.ws, { type: 'idle' });
      }
      return;
    }
    sub.idleSent = false;
    if (sub.matchId === b.id) return;
    this.unwatchAll(sub);
    sub.matchId = b.id;
    b.watchers.add(sub);
    /* Догоняющий получает тот же матч с текущей секунды — D14. */
    sub.cursor = b.at;
    this.sendMatch(sub, b);
  }

  /** Сообщение о начале боя — одно на оба пути подключения. */
  sendMatch(sub, b) {
    send(sub.ws, {
      type: 'match',
      seed: b.seed,
      matchId: b.id,
      atSecond: b.frames[Math.min(b.at, b.frames.length - 1)]?.t ?? 0,
      training: b.training,
      tags: { octopus: b.meta.octopus?.name ?? '—', gorilla: b.meta.gorilla?.name ?? '—' },
      kits: b.kits || null,
      bodies: b.bodies || null,
      names: { octopus: b.meta.octopus?.name ?? '—', gorilla: b.meta.gorilla?.name ?? '—' },
      ids: { octopus: b.meta.octopus?.id ?? null, gorilla: b.meta.gorilla?.id ?? null },
      /*
       * ЧЬЯ ЭТО СТОРОНА — РЕШАЕТ СЕРВЕР, И ДЛЯ КАЖДОГО СОКЕТА СВОЯ (D162).
       *
       * Вьювер знал только слоты — `octopus` и `gorilla`, циан и оранж, — и
       * ни одного признака принадлежности. Из этого следовало ровно то, на
       * что пожаловался основатель: обе опасные зоны рисовались одним и тем
       * же красным `0xff4d3d`, и та, что сейчас ударит ТЕБЯ, была пиксель в
       * пиксель как та, которую кастует твоё существо.
       *
       * Знание об этом на клиенте было — `arena.js` сравнивал `m.ids` с
       * `session.creature.id`, — но использовалось на один бейдж и во вьювер
       * не уезжало. Здесь оно уже есть: у сокета лежит `creatureId`, по
       * которому и подбирается трансляция. Считаем один раз, на месте.
       *
       * null означает «ни одна из сторон не твоя», и это ЗАКОННОЕ значение:
       * гость смотрит витрину, владелец — чужой бой. Экран обязан сказать
       * об этом словами, а не оставить человека гадать.
       */
      mine: sub.owned && sub.creatureId
        ? (b.meta.octopus?.id === sub.creatureId ? 'octopus'
          : (b.meta.gorilla?.id === sub.creatureId ? 'gorilla' : null))
        : null,
      /*
       * За кем зритель СЛЕДИТ, если это не его существо: выбранный гостем
       * стартер из библиотеки. Экран обязан различать «твоё» и «за этим ты
       * следишь», иначе гостю сообщат, что библиотечное существо — его.
       */
      following: !sub.owned && sub.creatureId
        ? (b.meta.octopus?.id === sub.creatureId ? 'octopus'
          : (b.meta.gorilla?.id === sub.creatureId ? 'gorilla' : null))
        : null,
      /* Размер существа: вьювер масштабирует тело под НЕГО, а не под
         фиксированный радиус архетипа, иначе кит и комар снова станут
         одинаковыми, а коллайдер разойдётся с картинкой. */
      sizes: { octopus: b.meta.octopus?.size ?? 1, gorilla: b.meta.gorilla?.size ?? 1 },
      meta: {
        octopus: b.meta.octopus ? { model: b.meta.octopus.model, effort: '—', chars: null } : null,
        gorilla: b.meta.gorilla ? { model: b.meta.gorilla.model, effort: '—', chars: null } : null,
      },
    });
    if (b.frames[0]) send(sub.ws, { type: 'frame', frame: b.frames[Math.min(sub.cursor, b.frames.length - 1)] });
    /*
     * ИТОГ ДОГОНЯЮЩЕМУ.
     *
     * `finish()` рассылает `over` ТЕКУЩИМ зрителям и больше никогда. Сокет,
     * подключившийся к доигравшей трансляции (переподключение, вход в окно
     * линга), получал `match`, один последний кадр — и тишину: неподвижная
     * арена, полосы здоровья, часы стоят, итога нет. Замерено: 10+ секунд
     * такой картинки после разрыва сразу за концом боя.
     */
    if (b.over) send(sub.ws, b.over.msg);
  }

  /**
   * Снять подписчика со всех трансляций, но НЕ отключать сокет.
   *
   * Имя было `detach`, и оно перекрыло одноимённый метод выше — тот, что
   * закрывает сокет: помечает `alive = false` и убирает из `this.sockets`.
   * В классе побеждает последнее определение, поэтому обработчик
   * `ws.on('close')` перестал освобождать сокет вообще: множество росло без
   * предела, `pump()` каждый тик обходил мёртвых, и сервер уходил в никуда от
   * одного анонимного соединения, которое просто переподключалось.
   *
   * Разные вещи — разные имена. Это «перестань смотреть», а не «уходи».
   */
  unwatchAll(sub) {
    for (const b of this.broadcasts.values()) b.watchers.delete(sub);
  }

  /**
   * Подключить к КОНКРЕТНОЙ трансляции, а не к главной.
   *
   * `deliver` выбирает трансляцию сам — по правилам витрины: своё существо,
   * иначе показательный бой. Для перемотки по ссылке это ровно неверное
   * поведение: игрок открыл ссылку на определённый бой, а получал тот,
   * который сейчас идёт на главной. Замерено: пять сокетов подряд просили
   * один и тот же id и пять раз получили другой.
   */
  attachTo(sub, matchId) {
    const b = this.broadcasts.get(matchId);
    if (!b) return false;
    /* Перемотка по ссылке — осознанный выбор зрителя, и автоматика «свой бой
       забирает экран» его не отменяет: игрок открыл конкретный бой. Метка
       снимается при следующей смене существа (`cmd:'watch'`). */
    sub.pinned = true;
    if (sub.matchId !== b.id) {
      this.unwatchAll(sub);
      sub.matchId = b.id;
      b.watchers.add(sub);
    }
    sub.cursor = b.at;
    this.sendMatch(sub, b);
    return true;
  }

  /** Один тик реального времени: продвинуть все трансляции и разослать кадры. */
  pump() {
    for (const b of this.broadcasts.values()) {
      if (b.at < b.frames.length) {
        const frame = b.frames[b.at++];
        for (const sub of b.watchers) {
          if (sub.alive && sub.matchId === b.id) send(sub.ws, { type: 'frame', frame });
        }
        if (b.at >= b.frames.length && !b.over) this.finish(b);
      } else if (b.over && this.now() - b.over.at > LINGER_SECONDS * 1000) {
        for (const sub of [...b.watchers]) { sub.matchId = null; b.watchers.delete(sub); }
        this.broadcasts.delete(b.id);
        if (this.featured === b.id) this.featured = null;
      }
    }
    /*
     * Очередь отложенных трансляций (см. `open`). Разбирается ДО раздачи
     * кадров: чем раньше бой откроется, тем меньше его начала пропустит
     * зритель, а зачётный бой игрока пропускать нельзя вовсе.
     *
     * Просроченные выбрасываются: показывать бой, который кончился минуту
     * назад, — это не «догнать», это занять слот.
     */
    while (this.queue.length && this.opening.size < MAX_OPENING) {
      const item = this.queue.shift();
      if (this.now() - item.at > QUEUE_STALE_MS) continue;
      if (this.broadcasts.has(item.matchRow.id)) continue;
      this.open(item.matchRow, { a: item.a, b: item.b, featured: item.featured, kind: item.kind }).catch(() => {});
    }

    /* Сокеты без матча пробуют подцепиться каждый тик — так «вошёл посреди
       боя → попадает сразу на арену» (§6.2) работает само собой. */
    for (const sub of this.sockets) if (sub.alive && !sub.matchId) this.deliver(sub);

    /*
     * СВОЙ БОЙ ЗАБИРАЕТ ЭКРАН У ЧУЖОГО (D162).
     *
     * `deliver` вызывался только для сокетов БЕЗ матча, а сам он выходил на
     * первой же строке, если сокет уже что-то смотрит. Из этого следовало,
     * что зритель, попавший на чужую трансляцию, оставался на ней до её
     * конца плюс двенадцать секунд линга — а собственная трансляция живёт
     * ровно эти же двенадцать секунд после конца боя. То есть свой бой
     * можно было пропустить ЦЕЛИКОМ, ни разу не увидев, и никакой ошибки
     * при этом не происходило.
     *
     * Пропущенный собственный бой — это самое дорогое, что может потерять
     * этот экран: игрок пришёл смотреть, как дерётся ЕГО существо.
     *
     * Перебивается только ЧУЖОЙ бой. Свой на свой не меняется (первое
     * условие), и перемотка по ссылке (`attachTo`) не трогается: у неё
     * `sub.pinned`, и пока он стоит, автоматика молчит.
     */
    for (const sub of this.sockets) {
      if (!sub.alive || !sub.matchId || sub.pinned) continue;
      /*
       * Перебиваем в двух случаях, и второй так же важен, как первый:
       *   1) начался СВОЙ бой, а сокет смотрит чужой;
       *   2) сокет смотрит ДОИГРАВШИЙ бой, а где-то идёт живой.
       * Второй случай — это и есть пауза между боями: без него зритель
       * досматривал доигравший бой все двенадцать секунд линга, хотя новый
       * уже шёл.
       */
      const cur = this.broadcasts.get(sub.matchId);
      /* Итог надо успеть прочитать. Пока окно не вышло, зритель остаётся на
         доигравшем бое — даже если рядом уже идёт новый. */
      if (cur && cur.over && this.now() - cur.over.at < RESULT_LINGER_MS) continue;
      const own = this.ownBroadcast(sub);
      const next = own || ((cur && cur.over) ? this.pick(sub) : null);
      if (!next || next.id === sub.matchId || next.over) continue;
      /* Чужой бой уже кончился и досматривается — не дёргаем; иначе не
         дёргаем тем более, потому что свой важнее. */
      this.unwatchAll(sub);
      sub.matchId = next.id;
      next.watchers.add(sub);
      sub.cursor = next.at;
      this.sendMatch(sub, next);
    }
  }

  finish(b) {
    const m = b.result;
    b.over = { at: this.now() };
    /* Метка перемотки снимается вместе с концом ссылочного боя: иначе
       `sub.pinned` стоит навсегда и «свой бой забирает экран» после одной
       открытой ссылки не срабатывает уже никогда. */
    for (const sub of b.watchers) if (sub.matchId === b.id) sub.pinned = false;
    const payload = {
      type: 'over',
      matchId: m.id,
      winner: m.winner === null ? null
        : (m.winner === b.meta[m.aSlot]?.id ? m.aSlot : m.bSlot),
      reason: m.reason,
      stats: m.result ? { octopus: m.result.octopus, gorilla: m.result.gorilla } : {},
      logs: { octopus: [], gorilla: [] },
      deltas: m.deltas ?? null,
      training: b.training,
      /* D8: чей мозг выключился и считается ли бой. Без этих полей экран
         итога физически не может показать правило, которое уже работает. */
      faulted: b.faulted || [],
      ranked: b.ranked !== false,
      trainingRate: b.trainingRate ?? null,
    };
    /*
     * Только тем, кто смотрит ИМЕННО ЭТОТ бой.
     *
     * Кадры уже рассылались с проверкой `sub.matchId === b.id`, а итог — без
     * неё, и этого хватало: зритель, переведённый на следующий бой, оставался
     * в списке зрителей предыдущего и получал ЕГО итог — чужого победителя и
     * чужую дельту рейтинга поверх боя, который ещё идёт. Проверка теперь
     * одна и та же в обоих местах, а `detach` больше не оставляет зрителя в
     * двух списках сразу.
     */
    /* Сохраняем, чтобы отдать догоняющему: `sendMatch` шлёт его тому, кто
       подключился к уже доигравшей трансляции. */
    b.over.msg = payload;
    for (const sub of b.watchers) if (sub.alive && sub.matchId === b.id) send(sub.ws, payload);
    /*
     * КОНЕЦ ПОКАЗА — СОБЫТИЕ, А НЕ РАСЧЁТ.
     *
     * Занятость бойцов ставилась по `frames.length / TICK_HZ`, то есть по
     * НОМИНАЛЬНЫМ тридцати кадрам в секунду. Замер на ненагруженном сервере
     * дал 28.9–29.7: таймер `pump` дрожит, и резерв истекал примерно на 3.5%
     * раньше конца показа — плюс две секунды на полном бое. Отдых в пять
     * секунд превращался в три с половиной, а следующий бой начинался, пока
     * предыдущий ещё на экране.
     *
     * Считать нечего: момент известен точно, и он здесь.
     */
    for (const fn of this.finished) { try { fn(b); } catch { /* слушатель не роняет показ */ } }
  }

  /** Подписаться на «показ доиграл». Возвращает отписку. */
  onFinish(fn) { this.finished.add(fn); return () => this.finished.delete(fn); }

  describe() {
    const b = this.featured ? this.broadcasts.get(this.featured) : null;
    if (!b) return null;
    return {
      matchId: b.id,
      atSecond: Math.round((b.at / TICK_HZ) * 10) / 10,
      totalSeconds: Math.round((b.frames.length / TICK_HZ) * 10) / 10,
      training: b.training,
      /* Доиграла ли витрина. `describe()` возвращает трансляцию ещё
         LINGER_SECONDS после конца, чтобы опоздавший увидел исход, — но
         «показывается» и «идёт» это разные вещи, и планировщик витрины
         обязан различать их (D161). */
      over: !!b.over,
      /* Сколько миллисекунд назад она кончилась. null, пока идёт. */
      overFor: b.over ? this.now() - b.over.at : null,
    };
  }
}

function send(ws, v) {
  if (ws.readyState === 1) {
    try { ws.send(JSON.stringify(v)); } catch { /* сокет умер между проверкой и отправкой */ }
  }
}
