/**
 * Может ли существо драться. Замер, а не догадка.
 *
 * ЗАЧЕМ. Грамматика проверяет законность (§8), бюджет — цену, L2 — что в наборе
 * есть хоть один источник урона. Ни одна из этих проверок не отвечает на
 * вопрос, ради которого существо создаётся: способно ли оно попасть по
 * противнику.
 *
 * Ответ оказался «часто нет». Три существа, собранные продуктовым путём и
 * заселённые в библиотеку, дали в сумме **ноль побед из 1754 боёв**. У каждого
 * набор законный, в бюджете, с источником урона — и каждый собран моделью «по
 * смыслу»: «мотылёк, который слепит» получил ослепление, ускорение и один
 * рывок с уроном. Рывок — удар в упор, а мотылёк лёгкий и дальнобойный: тело и
 * набор не подходят друг другу, и существо не попадает вообще.
 *
 * Хуже того, это видно не только в лестнице. Показательный бой — первое, что
 * видит человек, и 14% последних боёв кончались двойным КО БЕЗ ЕДИНОГО
 * ПОПАДАНИЯ: две фигуры ходят пятьдесят секунд и обе умирают от арены.
 *
 * ЧТО ЗДЕСЬ МЕРИТСЯ. Несколько боёв против эталонного мозга на обеих сторонах,
 * и два числа: попадает ли существо вообще и выигрывает ли хоть иногда. Это
 * грубая нижняя граница, а не оценка силы — её меряет `tools/kitbalance.mjs`.
 * Цель одна: не выпустить существо, которое не может закончить бой.
 *
 * ГДЕ ПРИМЕНЯЕТСЯ И КАК. Для библиотеки — запрет: витрина не имеет права
 * показывать бой, в котором ничего не происходит. Для существа ИГРОКА — только
 * предупреждение: отказать человеку в его замысле мы не вправе, а набор он
 * меняет мгновенно и бесплатно (D3). Разница не в строгости, а в том, чьё это
 * существо.
 */

import { readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import { DEFAULT_BUILD } from '../../core/config.js';
import { runIsolated } from '../sandbox/index.js';
import { compileKit } from '../../skills/compile.js';
import { GAUNTLET, readShape } from '../../skills/gauntlet.js';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '../../..');

/** Сколько боёв. Мало намеренно: это проверка на ноль, а не измерение силы. */
/*
 * Двадцать боёв — по четыре на каждого из пятерых гантлета.
 *
 * Было шесть, то есть по одному на соперника: ответ получался 0% или 100% и
 * ничего не значил.
 */
/*
 * СОРОК, А НЕ ДВАДЦАТЬ, и это про разрешение, а не про строгость.
 *
 * Двадцать на пятерых — по четыре боя, шаг 25 п.п. На такой сетке набор с
 * истинными 39% читается как 50%, и вердикт переворачивается от одного боя.
 * Именно так три стартовых набора игры получили «это дыра»: не потому, что они
 * дыры, а потому, что сетка не умела показать разницу между 39 и 50.
 *
 * Сорок — по восемь, шаг 12.5 п.п., около четырёх секунд. Это ответ игроку на
 * нажатие «проверить набор», и четыре секунды под спиннером он переживёт;
 * неверный вердикт — нет.
 */
export const VIABILITY_ROUNDS = 40;

let referenceCache = null;
function reference() {
  if (!referenceCache) {
    referenceCache = {
      octopus: readFileSync(join(ROOT, 'brains/kit-stub/octopus.js'), 'utf8'),
      gorilla: readFileSync(join(ROOT, 'brains/kit-stub/gorilla.js'), 'utf8'),
    };
  }
  return referenceCache;
}

/**
 * Прогнать существо против эталона и посчитать попадания и победы.
 *
 * Мозг берётся ЭТАЛОННЫЙ, а не сгенерированный, и это важно: проверяется
 * НАБОР с телом, а не пилот. Существо, чей набор не может попасть, не спасёт
 * никакой мозг; существо, чей мозг плох, а набор рабочий, — это другая
 * проблема и другой разговор.
 *
 * @returns {{ok: boolean, hits: number, wins: number, rounds: number, why: string|null}}
 */
/**
 * @param {object} [opts.build] ТЕЛОСЛОЖЕНИЕ существа: его собственные числа.
 *   Замер набора без него — это замер набора на чужом теле. Замерено на одном
 *   наборе против гантлета: 100/100/0/100/100 на одном теле и 50/50/25/100/25
 *   на другом. Соперник гантлета всегда на теле по умолчанию: прибор не
 *   меняется вместе с испытуемым.
 */
export async function viability(kit, { rounds = VIABILITY_ROUNDS, build = null } = {}) {
  const built = compileKit(kit);
  if (built.problems.length) {
    return { ok: false, hits: 0, wins: 0, rounds: 0, why: 'набор не собирается' };
  }
  const ref = reference();
  /* Сторона выбирается ФИКСИРОВАННО, а не по виду: видов нет, а прибор обязан
     быть одним и тем же от замера к замеру. */
  const mine = 'octopus';
  const foe = 'gorilla';

  /*
   * СОПЕРНИК — НЕ ОДИН, А ПЯТЕРО РАЗНЫХ (гантлет).
   *
   * Здесь стоял один эталонный набор, и это давало ответ на неправильный
   * вопрос: любой ОДИН соперник имеет дыры, и винрейт против него говорит,
   * насколько набор эти дыры эксплуатирует, а не насколько он силён.
   *
   * Пятеро гантлета закрывают разные способы выиграть бой — сблизиться,
   * держать дистанцию, пережить, не дать применить умения, и середняк как
   * точка отсчёта. Тогда у ответа появляется ФОРМА: «бьёт всех» — это дыра,
   * «бьёт одних и сливает другим» — это стратегия с контрой, «сливает всем» —
   * это слабый набор. Три разных вердикта вместо одного процента.
   *
   * Цена: пятеро вместо одного при том же числе боёв на соперника. Сорок
   * боёв на пятерых — по восемь на каждого, около четырёх секунд.
   */
  /*
   * КАЖДЫЙ СОПЕРНИК ИГРАЕТСЯ В ОБЕ СТОРОНЫ, и без этого замер меряет тела.
   *
   * Слоты матча — это два РАЗНЫХ архетипа: осьминог 155 здоровья и 4.22
   * скорости против гориллы 205 и 5.35. Кандидат стоял всегда на одном и том
   * же слоте, и разница тел перебивала разницу наборов: набор гантлета,
   * поставленный против самого себя, брал ноль из четырёх — то есть замер
   * уверенно сообщал, что эталонный соперник слабее самого себя.
   *
   * Прогон в обе стороны это снимает: тело достаётся обоим поровну, и
   * остаётся то, ради чего замер и делается.
   */
  let hits = 0; let wins = 0; let played = 0;
  const per = Math.max(2, Math.round(rounds / GAUNTLET.length)) || 2;
  const rates = [];
  for (const g of GAUNTLET) {
    const foeKit = compileKit(g.kit);
    if (foeKit.problems.length) { rates.push(NaN); continue; }
    let w = 0; let n = 0;
    for (let i = 0; i < per; i++) {
      /* Чётные — кандидат на своём архетипе, нечётные — на чужом. */
      const flip = i % 2 === 1;
      const my = flip ? foe : mine;
      const их = flip ? mine : foe;
      let out;
      try {
        out = await runIsolated(
          { [my]: ref[my], [их]: ref[их] },
          {
            seed: 900 + i * 7919,
            kits: { [my]: built.defs, [их]: foeKit.defs },
            /* Своё тело — кандидату, соперник гантлета всегда на теле по
               умолчанию: гантлет — это прибор, и менять его вместе с
               испытуемым значит менять две вещи разом. */
            builds: { [my]: build || DEFAULT_BUILD, [их]: DEFAULT_BUILD },
          },
        );
      } catch { continue; }
      played++; n++;
      const log = out.result?.log || [];
      hits += log.filter((e) => e.type === 'damage' && e.who === my).length;
      if (out.result?.winner === my) { wins++; w++; }
      else if (out.result?.winner === null) w += 0.5;
    }
    rates.push(n ? w / n : NaN);
  }
  const shape = readShape(rates);

  if (!played) return { ok: false, hits: 0, wins: 0, rounds: 0, why: 'бои не запустились' };
  /*
   * Порог — ноль попаданий, а не какой-то винрейт.
   *
   * Ставить планку по победам значило бы решать за игрока, какой замысел
   * достаточно хорош. Ноль попаданий — не замысел, а поломка: набор, которым
   * невозможно коснуться противника ни разу за все бои, не проигрывает —
   * он не играет.
   */
  if (hits === 0) {
    return { ok: false, hits, wins, rounds: played, why: 'ни одного попадания за все бои', shape, rates };
  }
  /*
   * ФОРМА ЕДЕТ НАРУЖУ ВМЕСТЕ С ЧИСЛАМИ.
   *
   * `ok` отвечает на узкий вопрос «можно ли этим набором вообще попасть».
   * `shape` отвечает на тот, который на самом деле интересует и игрока, и
   * баланс: против кого он работает. Доминирующий набор проходит `ok` так же,
   * как ровный, — и должен быть виден отдельно.
   */
  return { ok: true, hits, wins, rounds: played, why: null, shape, rates };
}
