/**
 * Гантлет: набор эталонных соперников, намеренно разных.
 *
 * ── зачем он вообще ────────────────────────────────────────────────────────
 *
 * Любой ОДИН фиксированный соперник имеет дыры. Меряя об него, меряешь не силу
 * набора, а то, насколько хорошо набор эксплуатирует дыры ИМЕННО ЭТОГО
 * соперника. Поэтому «сбалансировать по эталону» невозможно в принципе — не
 * из-за нехватки данных, а потому что вопрос поставлен неверно.
 *
 * Правильная цель — не равенство, а ОТСУТСТВИЕ ДОМИНИРУЮЩЕЙ СТРАТЕГИИ. И
 * меряется она не средним, а формой распределения винрейтов по разным
 * соперникам:
 *
 *   высокий против ВСЕХ          → доминирующий. Вот это и режут.
 *   высокий против части         → стратегия с контрой. Это не поломка,
 *                                  это содержание игры.
 *   низкий против всех           → слабый. Игроку сказать числом.
 *
 * Отсюда прямой ответ на «что резать»: режут только то, что выигрывает у
 * всего. Связка, которая бьёт агрессора и сливает контролю, — это и есть
 * баланс, а не его отсутствие.
 *
 * ── почему именно эти пятеро ───────────────────────────────────────────────
 *
 * ИХ НЕ ПРИДУМАЛИ, ИХ НАШЛИ. Прежняя пятёрка была написана по замыслу —
 * «сближается», «держит дистанцию», «переживает», «не даёт применить»,
 * «середняк», — и на уплощённой арене (симметричные тела, один пилот,
 * кулдаун 8 у всех) она честно была разной.
 *
 * А применяется прибор в `viability.js`, на ПРОДУКТОВОМ поле: осьминог против
 * гориллы, у каждого свой мозг, кулдаун считается из цены умения. Там та
 * пятёрка схлопывалась в ЛЕСТНИЦУ — `turtle` брал у всех, `controller` не брал
 * ни у кого, между ними один порядок силы. Замерено `tools/gauntletfield.mjs`:
 * стилей 2 из 5. Кандидат, испытанный об лестницу, получает не форму, а место
 * в очереди — а весь смысл гантлета в форме.
 *
 * Замысел не помог, потому что замысел мерили не тем прибором. Поэтому пятёрку
 * ИЩЕТ `tools/gauntletpick.mjs`: случайные законные наборы играют между собой
 * на продуктовом поле, и побеждает пятёрка, у которой ЕСТЬ ЦИКЛ, а при равенстве
 * — больше различных рисунков побед.
 *
 * Найденная так пятёрка (`node tools/gauntletpick.mjs --pool=90 --rounds=10
 * --tries=7`, сид 20260830) даёт 4 стиля из 5 против прежних 2 и два цикла.
 *
 * ТАБЛИЦА (20 сидов ×2 стороны, продуктовое поле; проценты — сколько берёт
 * строка):
 *
 *               луч   поджиг  слеп   рывок  лекарь   худшее
 *     лучевой     ·     95%   100%    88%    71%      71%
 *     поджигатель 5%     ·     20%    55%    10%       5%
 *     слепильщик  0%    80%     ·     49%    63%       0%
 *     рывковый   13%    45%    51%     ·     15%      13%
 *     лекарь     29%    90%    38%    85%     ·       29%
 *
 * Циклов два: поджигатель → рывковый → слепильщик и слепильщик → лекарь →
 * рывковый. Цикл — единственная форма, в которой «нет доминирующей стратегии»
 * является свойством ПОЛЯ, а не удачей замера.
 *
 * ── ПОЧЕМУ ПЯТЁРКА СМЕНИЛАСЬ ВТОРОЙ РАЗ ───────────────────────────────────
 *
 * Прошлая была разнородной и слабой. Замер: `dash+лечение` брал у неё 63%,
 * `мигание+лечение` — 88%, и даже ТРИ УМЕНИЯ С УРОНОМ — 75%. То есть любой
 * приличный набор бил всю пятёрку, и вердикт «доминирует» выпадал на обычных
 * наборах.
 *
 * Причина была в поиске: представителем каждого стиля брался самый «средний» —
 * тот, чей винрейт ближе к половине. Пул случайный, случайный законный набор
 * слаб, и «средний из слабых» — просто слабый. Прибор, у которого потолок ниже
 * обычного игрока, меряет не силу кандидата, а слабость поля.
 *
 * Теперь представитель стиля — САМЫЙ СИЛЬНЫЙ в стиле, и потолок поля поднялся с
 * 33.8% до 71.3%.
 *
 * Перепроверять: `node tools/gauntletfield.mjs --rounds=20`.
 *
 * Каждый обязан быть законным и годным (`viability`): гонять кандидата против
 * соперника, который сам не может закончить бой, — это мерить об пустоту.
 */

