/**
 * Прочитать форму распределения винрейтов.
 *
 * @param {number[]} rates винрейт против каждого соперника гантлета
 * @returns {{verdict, ru, max, min, spread}}
 */
export function readShape(rates) {
  const clean = rates.filter((r) => Number.isFinite(r));
  if (!clean.length) return { verdict: 'unknown', ru: 'замер не удался', max: null, min: null, spread: null };
  const max = Math.max(...clean);
  const min = Math.min(...clean);
  const spread = max - min;

  /*
   * СТРОГО БОЛЬШЕ, а не «не меньше». `bestMin` — это худший результат лучшего
   * из самих пятерых, поэтому при нестрогом сравнении сильнейший член гантлета
   * объявляет доминирующим САМ СЕБЯ, и проверка «никто из пятерых не
   * доминирует» не может пройти по построению. «Сильнее всей пятёрки» значит
   * лучше лучшего, а не вровень с ним.
   */
  if (min > BASELINE.bestMin) {
    return {
      verdict: 'dominant', max, min, spread,
      ru: 'держится против всех пятерых лучше, чем лучший из них самих — это дыра, её и надо резать',
    };
  }
  if (max <= 0.25) {
    return {
      verdict: 'weak', max, min, spread,
      ru: 'проигрывает всем пятерым — набором трудно выиграть у кого угодно',
    };
  }
  if (spread >= 0.3) {
    return {
      verdict: 'situational', max, min, spread,
      ru: 'сильный против одних и слабый против других — это стратегия с контрой, так и должно быть',
    };
  }
  return { verdict: 'even', max, min, spread, ru: 'держится ровно против всех — крепкий универсальный набор' };
}

/**
 * Разнороден ли гантлет: бьют ли его члены РАЗНЫХ соперников.
 *
 * Прежняя проверка требовала, чтобы никто не бил всех остальных, и падала на
 * «живучем». Но сильнейший в поле — это нормально и даже нужно: кандидата
 * надо об кого-то испытывать. Ненормально другое — если все пятеро бьют одних
 * и тех же, тогда это не пять способов выиграть, а один способ в пяти
 * обличьях.
 *
 * @param {number[][]} table winrate[i][j] — i против j
 */
export function isDiverse(table) {
  /*
   * ДИАГОНАЛЬ ИСКЛЮЧЕНА, И БЕЗ ЭТОГО ПРОВЕРКА НЕ МОГЛА УПАСТЬ.
   *
   * Здесь стояло `j === undefined ? '' : ...` — условие, которое не бывает
   * истинным, потому что `map` всегда даёт индекс. То есть диагональ входила
   * в рисунок. А диагональ — это набор против самого себя, и она по
   * построению ровно 0.5: оба исхода одинаковы, один засчитан, другой нет.
   * Значит у КАЖДОЙ строки символ `=` стоял в своей позиции, все пять
   * рисунков были различны ВСЕГДА, и порог `unique >= 3` не мог не пройти.
   *
   * Ровно то состояние, которое эта функция объявлена ловить, она пропускала:
   *
   *   пятеро, каждый бьёт тех же двоих и сливает тем же троим
   *   → было: unique 5, «разнороден»;  стало: unique 1, отказ.
   *
   * `mins` в этом же файле диагональ исключает с самого начала. Разошлись две
   * функции, читающие одну таблицу, — и разошлись молча.
   */
  /*
   * Позиции при этом НЕ СДВИГАЮТСЯ. Если просто выбросить свою клетку из
   * строки, у соседних строк на одном месте окажутся разные соперники, и две
   * одинаковые по смыслу строки станут разными на вид. Поэтому своя клетка
   * помечается точкой, а сравнение идёт по колонкам, где обе строки заданы.
   */
  const patterns = table.map((row, i) => row
    .map((r, j) => (j === i ? '.' : (r > 0.5 ? '1' : (r < 0.5 ? '0' : '='))))
    .join(''));

  /*
   * «Одинаковых на общих колонках» может быть несколько подряд, а отношение
   * это не транзитивное: A совпал с B, B с C, а A с C — нет. Считается
   * жадно: строка заводит новый стиль, если разошлась с КАЖДЫМ уже
   * заведённым. Порядок фиксирован порядком гантлета, то есть повторяем.
   */
  const styles = [];
  for (const p of patterns) {
    const same = (q) => p.split('').every((c, k) => c === '.' || q[k] === '.' || c === q[k]);
    if (!styles.some(same)) styles.push(p);
  }
  const unique = styles.length;
  /*
   * Порог 0.8, а не 0.6, и это не вкусовщина: при 0.6 идеальная ЛЕСТНИЦА
   * проходила. У неё соседние строки совпадают на общих колонках, поэтому
   * жадное слияние даёт ровно три стиля из пяти — то есть ровно порог. А
   * лестница — это форма, которую шапка этого файла называет поломкой.
   *
   * При 0.8 требуется четыре стиля из пяти: лестница (3) отказывает, прежняя
   * пятёрка (2) отказывает, нынешняя (5) проходит. Проверено обоими
   * негативными контролями в `tools/checkgauntlet.mjs`.
   */
  return { ok: unique >= Math.ceil(table.length * 0.8), unique, of: table.length, patterns };
}
