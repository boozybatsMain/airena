/**
 * `constants_version` — F9.
 *
 * Каждый мозг записывает, против каких чисел он написан. Версия НЕ ставится
 * руками: рука забывает её поднять ровно тогда, когда это важнее всего —
 * в спешке перед релизом, после правки одной цифры. Поэтому версия
 * вычисляется из самих чисел: хеш раскрываемой части конфигурации.
 *
 * «Раскрываемая часть» — то, во что мозг верит: числа, доехавшие до промпта,
 * и ПРАВИЛА, из которых эти числа получены (см. последний раздел шапки — с
 * исчезновением архетипов тело стало персональным, и в хеш попадает оболочка
 * возможного, а не чьи-то показатели). Если число не доехало ни тем, ни другим
 * путём, мозг про него не знает, и его изменение мозг не дезинформирует. Это же
 * свойство делает версию честной: она меняется тогда и только тогда, когда
 * меняется то, во что мозг верит.
 *
 * F9 требует нулевого неверсионированного дрейфа как релизного гейта —
 * `tools/checkstale.mjs` сравнивает записанные таблицы; эта версия даёт ему
 * короткое имя, которое можно положить в БД, в матч и на экран.
 *
 * ── почему грамматики §8 здесь НЕТ, хотя её цены уезжают в промпт ────────────
 *
 * Вопрос законный: раз промпт называет цену атома, а цена меняется по
 * результатам замера баланса, — почему смена цены не поднимает версию?
 *
 * Потому что версия отвечает на вопрос «во что верит мозг», а мозг в цены не
 * верит. По F10 он получает ЖИВЫЕ параметры своего набора и набора противника
 * в перцепции на каждом решении, и смена набора не требует перегенерации —
 * это записано как отдельное решение, а не как следствие. Цены нужны шагу,
 * который СОБИРАЕТ набор, и этот шаг проверяется сервером при сборке и ещё раз
 * при допуске к матчу (A3). Ошибиться в цене мозг может, но обмануться —
 * нет: неверный набор не проедет.
 *
 * Поднимать версию на смене цены значило бы объявлять устаревшими все мозги
 * ради правки, которая доказуемо не может их дезинформировать, — то есть
 * ломать F10 руками F9.
 *
 * Что смена цены ЛОМАЕТ на самом деле — уже сохранённые наборы, которые
 * стояли впритык к бюджету. Это ловит `tools/checkkits.mjs`, и он про людей,
 * а не про версии.
 *
 * ── почему в хеше ПРАВИЛА ТЕЛА, а не тела ───────────────────────────────────
 *
 * Здесь стояла таблица бойцов: `fighters: FIGHTERS`, две записи с числами.
 * Это работало ровно потому, что тел было два и они были ОБЩИЕ на весь мир:
 * «во что верит мозг» и «что лежит в конфиге» были одним и тем же объектом.
 *
 * Архетипов больше нет, числа тела принадлежат существу (`build_json`), и на
 * этом обобщение упирается не в код, а в ПОНЯТИЕ. Глобальная версия отвечает
 * на вопрос «против какого МИРА написан этот мозг». Персональные числа миром
 * не являются: их столько же, сколько существ, они появляются по одному на
 * каждое нажатие «создать», и хеш, который их накрывает, менялся бы при
 * каждой регистрации. Такая версия называла бы не мир, а население — то есть
 * объявляла бы устаревшими все мозги ровно тогда, когда не изменилось ничего.
 *
 * Поэтому версионируется то, что осталось общим: ГРАНИЦЫ И ЦЕНЫ ОСЕЙ
 * (`BUILD_AXES`) и ПОТОЛОК (`BUILD_BUDGET`). Это не «почти тело», это другой
 * предмет — оболочка возможного. Мозг, написанный в мире, где быстрее верхней
 * границы `maxSpeed` не бывает и дороже потолка не купишь, держит это
 * допущение в каждой дистанции, которую он считает, даже не прочитав таблицу
 * ни разу (числа здесь не цитируются нарочно: их правит замер баланса, и
 * цитата успела бы устареть до конца этой строки). Сдвиньте
 * границу — и каждое персональное число, напечатанное в его промпте, окажется
 * взято из другого распределения. Это и есть дезинформация, которую F9 ловит.
 *
 * Почему это НЕ противоречит абзацу выше про цены грамматики: цены набора
 * мозг не читает вовсе, а параметры своих умений получает ЖИВЫМИ в перцепции
 * на каждом решении (F10) — устареть там нечему. Числа тела приезжают иначе:
 * они впечатаны в ПРОМПТ в момент генерации и застывают в коде мозга вместе с
 * ним. Разница не в важности числа, а в том, доезжает ли поправка до уже
 * написанного мозга сама.
 *
 * Персональная половина версионируется там, где ей и место: рядом с существом.
 * `build_json` пишется при рождении одной транзакцией с `brain_source`, и
 * «против какого тела написан этот мозг» читается из той же строки БД.
 */

import { createHash } from 'node:crypto';

import {
  ARENA_HALF, BUILD_AXES, BUILD_BUDGET, MATCH_SECONDS, OBSTACLES, SKILLS,
  SUDDEN_DEATH_AT, SUDDEN_DEATH_RAMP, THINK_HZ, TICK_HZ, WALL_HEIGHT,
} from './config.js';

/** Раскрываемая часть: то, что уезжает в промпт, плюс правила, породившие его числа. */
export function disclosed() {
  return {
    /*
     * ПРАВИЛА ТЕЛА, А НЕ ТЕЛА. См. шапку: персональные числа сюда не влезают
     * по определению, а границы и цены осей — влезают и обязаны.
     */
    build: { axes: BUILD_AXES, budget: BUILD_BUDGET },
    skills: SKILLS,
    arena: { half: ARENA_HALF, wallHeight: WALL_HEIGHT, obstacles: OBSTACLES },
    tickHz: TICK_HZ,
    thinkHz: THINK_HZ,
    matchSeconds: MATCH_SECONDS,
    suddenDeathAt: SUDDEN_DEATH_AT,
    suddenDeathRamp: SUDDEN_DEATH_RAMP,
  };
}

/** Устойчивая сериализация: порядок ключей не должен менять версию. */
function stable(v) {
  if (Array.isArray(v)) return `[${v.map(stable).join(',')}]`;
  if (v && typeof v === 'object') {
    return `{${Object.keys(v).sort().map((k) => `${JSON.stringify(k)}:${stable(v[k])}`).join(',')}}`;
  }
  /* Числа приводим к фиксированному виду: 0.35 и 0.350000000001 — это одна
     константа, и разная версия у них означала бы ложную тревогу гейта. */
  if (typeof v === 'number') return Number(v.toFixed(6)).toString();
  return JSON.stringify(v);
}

let cached = null;

/** Короткая версия вида `c-9f3a21`. */
export function constantsVersion() {
  if (cached) return cached;
  const h = createHash('sha256').update(stable(disclosed())).digest('hex');
  cached = `c-${h.slice(0, 8)}`;
  return cached;
}

/** Полный хеш — для отчётов и для сравнения между релизами. */
export function constantsHash() {
  return createHash('sha256').update(stable(disclosed())).digest('hex');
}
