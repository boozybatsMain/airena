/**
 * «Что оно думало» — то, чем F11 заменил закрытый исходник.
 *
 * ЖЁСТКОЕ ОГРАНИЧЕНИЕ: карточка НЕ ВЫЗЫВАЕТ МОДЕЛЬ. Никогда. Бои идут раз в
 * минуту на существо, вечно (§6.2, Q3), а вирусная посадочная — это сотни
 * тысяч открытий. Любой вызов модели здесь — та же экономическая смерть,
 * ради которой §7.2а запретил LLM в адаптации.
 *
 * Поэтому карточка собирается из двух вещей, которые уже есть бесплатно:
 * реплик `api.say()`, записанных в лог матча, и самих событий боя. Всё, что
 * здесь написано, игрок видел своими глазами — и это сильнее пересказа.
 */

import { get, track } from '../lib/api.js';
import { h, mount, empty } from '../lib/dom.js';
import { paintFrames } from '../ui/frames.js';


/*
 * Имена умений приходят С СЕРВЕРА, вместе с разбором боя.
 *
 * Собственный словарь здесь был, знал четыре захардкоженных умения и на всё
 * остальное отвечал самим идентификатором: игрок читал «ОБЖИГ — k1 закрыт
 * укрытием». Знать больше клиент и не мог — имя умения из грамматики зависит
 * от набора конкретного существа в конкретном бою.
 *
 * Запасной вариант оставлен на случай старого ответа без поля `skills`: он
 * покроет четыре базовых, а не покроет ничего — покажет идентификатор, что
 * всё-таки лучше пустоты.
 */
const FALLBACK_RU = {
  laser: 'луч', blink: 'рывок', smash: 'удар', charge: 'разгон', jump: 'прыжок',
};
let SKILL_RU = FALLBACK_RU;
/**
 * Имя умения — ПО СТОРОНЕ, а не по плоской таблице.
 *
 * У обоих бойцов умения зовутся `k1..k3`; плоский словарь означал, что имена
 * одной стороны затирают имена другой, и разбор печатал игроку название
 * умения ПРОТИВНИКА под его собственным `k1`. Сервер отдаёт `bySide`;
 * плоская таблица остаётся запасной для четырёх захардкоженных имён и для
 * старых ответов без этого поля.
 */
const ru = (s, side = null) => {
  const per = side && SKILL_RU.bySide && SKILL_RU.bySide[side];
  return (per && per[s]) || SKILL_RU[s] || FALLBACK_RU[s] || s;
};

export async function enter(root, args, ctx) {
  root.className = 'on veil';

  /*
   * Событие шлёт ТОТ экран, который открылся. Оно кормит метрику «дошёл ли
   * игрок до доказательства авторства» (F11), а отправлялось из панели итога
   * боя — то есть срабатывало всегда, и метрика показывала 100% независимо от
   * того, открывал ли кто-нибудь разбор хоть раз.
   */
  track('tactics_opened', { matchId: args.matchId });
  document.body.classList.add('overlay');

  mount(root, h('div.overlay-card',
    h('div.panel.lift', { dataset: { frame: JSON.stringify({ seed: 77 }) } },
      h('div.bg'), h('div.fr'),
      h('div.in',
        h('div.hcut', 'ЧТО ОНО ДУМАЛО'),
        h('div.beats', { id: 'beats' },
          [0, 1, 2].map(() => h('div.skel', { style: { height: '18px', margin: '7px 0' } }))),
        /*
         * Подпись говорит про ЭТОТ бой, а не про продукт вообще, и потому
         * проставляется ПОСЛЕ загрузки матча.
         *
         * Строка стояла статической и утверждала «это написала нейросеть» в
         * том числе под боем двух рукописных эталонов — а они и есть первое,
         * что видит гость. Утверждение, ради которого F11 закрыл исходник,
         * оказывалось ложным ровно там, где оно доказательство.
         */
        h('div#author.t-body', { style: { marginTop: '18px', color: 'var(--dim)', fontSize: '13px' } },
          'Исходник мы не показываем — ни свой, ни чужой.'),
        h('div.row', { style: { marginTop: '16px' } },
          h('button.btn.big', { onclick: () => history.back() }, 'НАЗАД'),
          ctx.state.session?.creature ? null
            : h('button.btn.primary', { onclick: () => ctx.go('/new') }, 'СДЕЛАТЬ СВОЁ'))))));
  paintFrames(root);

  let m;
  try {
    m = await get(`/api/match/${args.matchId}`);
    /* Словарь этого боя: имена умений обоих наборов. */
    if (m.skills) SKILL_RU = m.skills;
    const au = root.querySelector('#author');
    if (au) au.textContent = authorLine(m);
  } catch (e) {
    mount(root.querySelector('#beats'),
      h('div.t-body', 'Этот бой мы уже не помним подробно.'));
    return;
  }

  const nameOf = (slot) => (slot === m.a.slot ? m.a.name : m.b.name);
  const isOr = (slot) => slot === 'orange';
  const lines = [];

  for (const b of m.beats || []) {
    const who = b.who;
    const side = m.a.name === who ? m.a.slot : m.b.slot;
    const or = side === 'orange';
    if (b.type === 'say') {
      /* Кавычки ставит сам `<q>`, и добавлять свои значило удваивать их:
         на экране стояло `««eight arms, one beam»»`. Вид кавычек задан в
         `kit.css` — русские ёлочки, а не английские лапки по умолчанию. */
      lines.push({ t: b.t, or, html: [h('q', b.text), ' — сказало ', who] });
    } else if (b.type === 'hit') {
      lines.push({ t: b.t, or, html: [who, ' попало: ', ru(b.skill, side), ' на ', String(Math.round(b.amount))] });
    } else if (b.type === 'blocked') {
      lines.push({ t: b.t, or, html: [who, ' — ', ru(b.skill, side), ' закрыт укрытием'] });
    } else if (b.type === 'dodged') {
      /* D160: единственное место разбора, где видно, что прыжок сработал.
         До этой ветки причина 'airborne' схлопывалась в «мимо». */
      lines.push({ t: b.t, or, html: [who, ' — ', ru(b.skill, side), ' прошло под прыжком'] });
    } else if (b.type === 'evade') {
      lines.push({ t: b.t, or, html: [who, ' уклонилось — удар пришёлся в неуязвимость'] });
    } else if (b.type === 'miss') {
      lines.push({ t: b.t, or, html: [who, ' — ', ru(b.skill, side), ' мимо'] });
    } else if (b.type === 'death') {
      /*
       * КОНЕЦ БОЯ — САМАЯ ВАЖНАЯ СТРОКА РАЗБОРА, И ЕЁ ЗДЕСЬ НЕ БЫЛО.
       *
       * Тип `death` сервер шлёт, а разбор его молча выбрасывал. Разбор
       * заканчивался на очередном попадании, и на боях, где мозг молчал, это
       * выглядело так: восемь одинаковых строк «попало: луч на 27» и обрыв.
       * Экран, который по F11 ЗАМЕНЯЕТ игроку закрытый исходник мозга,
       * заканчивался ничем ровно там, где должен был сказать главное.
       */
      lines.push({ t: b.t, or, html: [h('b', {}, who), ' выбыло — бой окончен'] });
    }
  }

  /*
   * РАЗБОР, КОТОРЫЙ НИЧЕГО НЕ РАЗЛИЧАЕТ, — ЭТО НЕ РАЗБОР.
   *
   * Заглушки были на «нет строк» и «не сказало ни слова», но не на случай,
   * когда строки есть и они все одинаковые. Замерено на настоящем бою: девять
   * событий, восемь из которых «попало: луч на 27» одной стороной. Игрок
   * читает заевшую пластинку ровно в тот момент, ради которого §10.5 держит
   * этот экран, — «стоп, это правда нейросеть написала?».
   *
   * Честнее сказать вслух: бой был односторонний, показывать в нём нечего.
   */
  const shape = (l) => (Array.isArray(l.html) ? l.html.map((x) => (typeof x === 'string' ? x : '·')).join('') : '');
  const distinct = new Set(lines.map(shape)).size;
  const monotonous = lines.length >= 5 && distinct <= 2;

  const said = lines.filter((l) => Array.isArray(l.html) && l.html[0]?.tagName === 'Q');
  const box = root.querySelector('#beats');
  if (monotonous && !said.length) {
    mount(box, empty('БОЙ БЫЛ ОДНОСТОРОННИМ',
      'Разбирать нечего: одна сторона била одним и тем же, вторая не ответила '
      + 'и ничего не сказала. Так выглядит бой, в котором решение принято на первой секунде.'));
    return;
  }
  if (!lines.length) {
    mount(box, empty('БОЙ НЕ ОСТАВИЛ СЛЕДА',
      'От этого боя не сохранилось ни реплик, ни разбора. Такое бывает с самыми короткими.'));
    return;
  }

  mount(box, [
    said.length ? null : h('div.t-body', { style: { marginBottom: '10px', color: 'var(--dim)' } },
      'В этом бою существо не сказало ни слова. Осталось то, что оно делало:'),
    lines.slice(0, 14).map((l) => h(`div.beat${l.or ? '.or' : ''}`,
      h('div.t', fmt(l.t)), h('div.x', l.html))),
  ]);
}

const fmt = (t) => `${Math.floor(t / 60)}:${String(Math.floor(t % 60)).padStart(2, '0')}`;

export function leave() { document.body.classList.remove('overlay'); }

/** Кто написал мозги этого боя — по моделям сторон, а не по продукту вообще. */
function authorLine(m) {
  const models = [m?.a?.model, m?.b?.model].map((x) => String(x || ''));
  const ours = models.filter((x) => /рукописн/i.test(x)).length;
  if (ours === 2) {
    return 'Оба мозга здесь наши — это эталонные спарринг-партнёры. Исходник мы не показываем ни свой, ни чужой.';
  }
  if (ours === 1) {
    return 'Один мозг написала нейросеть, второй наш — эталонный спарринг-партнёр. Исходник мы не показываем ни свой, ни чужой.';
  }
  return 'Это написала нейросеть. Исходник мы не показываем — ни свой, ни чужой.';
}
