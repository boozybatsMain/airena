/**
 * Посадочная с клипа: показать настоящий бой за две секунды, без аккаунта.
 *
 * Отличие от арены — не в содержимом, а в том, чего нет: вкладок, меню,
 * регистрации и генерации до первого боя (N5). §10.5 отводит на это первые
 * две секунды, и вход в матч не требует ни одного клика: клиент просит
 * сервер повторить конкретный бой по его id (A16 — только серверный id,
 * никаких клиентских тегов мозгов), и кадры начинают идти сами.
 */

import { get } from '../lib/api.js';
import { $, h, mount } from '../lib/dom.js';
import * as arena from './arena.js';

let onOver = null;
/* Бой, о котором ссылка. События других боёв этот экран не показывает. */
let wanted = null;
let onMatch = null;

export async function enter(root, args, ctx) {
  root.className = '';
  document.body.classList.remove('overlay');

  const clock = $('#clock .s');
  if (clock) clock.textContent = `бой из клипа · №${args.matchId.slice(-6)}`;

  let m = null;
  try { m = await get(`/api/match/${args.matchId}`); } catch { /* ниже */ }

  /*
   * ССЫЛКА, КОТОРАЯ УЖЕ НЕ РАБОТАЕТ, ОБЯЗАНА КУДА-ТО ВЕСТИ.
   *
   * Клип живёт дольше боя: ссылку пересылают через неделю, а до того успевают
   * смениться константы (A2 — на других константах бой воспроизводится лишь
   * приблизительно, и приблизительно мы не показываем). Раньше в обоих
   * случаях экран писал строчку в подпись под часами и замирал: пустая арена,
   * ни кадра, ни кнопки. Человек пришёл по чужой ссылке и упёрся в ничто —
   * причём именно в той точке воронки, ради которой экран и существует.
   *
   * Промаха ссылки достаточно, чтобы показать живой бой вместо мёртвого:
   * подпись объясняет, что случилось, а арена продолжает идти сама.
   */
  const gone = !m ? 'Этого боя больше нет.'
    : m.constantsVersion !== ctx.state.session?.constantsVersion
      ? 'Этот бой шёл по прошлым правилам и точно не повторится.'
      : null;
  if (gone) {
    note(`${gone} Показываем то, что идёт сейчас.`);
    fallback(root, ctx);
    return;
  }
  /*
   * ЖДЁМ ИМЕННО ТОТ БОЙ, О КОТОРОМ ССЫЛКА.
   *
   * Экран слал `replay` и больше никогда не сверял, что пришедшие `match` и
   * `over` — те самые. А если бой ещё идёт или кончился меньше двенадцати
   * секунд назад — то есть ровно случай «поделился тем, что смотрю», — его
   * трансляция уже в памяти, и сокет подключает к её КОНЦУ. Замерено: часы
   * стоят на 11.9, здоровье «0 / 155», карточка «БОЙ ЗАКОНЧЕН» на первой
   * секунде; двенадцать секунд не шевелится ничего, потом под карточкой
   * начинается ДРУГОЙ бой и доигрывается. Экран не говорит ни слова.
   *
   * Поэтому: события чужого боя игнорируются, а повтор просится ещё раз.
   */
  wanted = args.matchId;
  askReplay(args.matchId);

  /*
   * КОНЕЦ БОЯ — НЕ КОНЕЦ ЭКРАНА.
   *
   * Посадочная с клипа доигрывала бой и останавливалась: ни кнопки, ни
   * следующего шага, ни объяснения, что это было. Человек пришёл по чужой
   * ссылке, посмотрел сорок секунд и упёрся в неподвижную арену — то есть
   * ровно та точка воронки, ради которой экран существует, ничем не
   * заканчивалась.
   *
   * Предложение зависит от того, кто смотрит: у гостя своего существа ещё
   * нет, и правильное действие — сделать своё; у владельца — вернуться к
   * своему бою.
   */
  /* Пока идёт не тот бой, экран ждёт: сокет догонит по второму запросу. */
  onMatch = (ev) => {
    if (!wanted || !ev.detail?.matchId) return;
    if (ev.detail.matchId !== wanted) {
      note('Тот бой уже идёт — ждём, пока сервер его отмотает.');
      askReplay(wanted);
    } else {
      note('Мозги здесь пишет нейросеть. Мы в них не вмешиваемся.');
    }
  };
  addEventListener('airena:match', onMatch);

  onOver = endCard(root, ctx);
  addEventListener('airena:over', onOver);
}

function endCard(root, ctx) {
  return (ev) => {
    /* Конец ЧУЖОГО боя эту карточку не показывает: иначе человек, пришедший
       по ссылке, читает «бой закончен» про бой, которого не видел. */
    if (wanted && ev?.detail?.matchId && ev.detail.matchId !== wanted) return;
    const mine = ctx.state.session?.creature;
    /*
     * АВТОРСТВО — ПО МОДЕЛЯМ ЭТОГО БОЯ, А НЕ УТВЕРЖДЕНИЕМ ПРО ПРОДУКТ.
     *
     * Карточка говорила «этот бой писала нейросеть — оба существа думали
     * сами» безусловно. На паре рукописных эталонов — а это витринные и
     * тренировочные бои, то есть большинство того, на что дают ссылку, — в
     * одном кадре оказывались два взаимоисключающих утверждения: подпись под
     * часами «оба мозга здесь наши», карточка «писала нейросеть». Экран
     * существует ради этого утверждения (F11), и врал именно оно.
     */
    const models = ctx.state.match?.meta
      ? ['octopus', 'gorilla'].map((k) => String(ctx.state.match.meta[k]?.model || ''))
      : [];
    const ours = models.filter((x) => /рукописн/i.test(x)).length;
    const claim = ours === 2
      ? 'Здесь дрались два наших эталона — на них проверяют игру. Существа игроков пишет нейросеть, и своё можно сделать за одну строчку описания.'
      : (ours === 1
        ? 'Один мозг здесь написала нейросеть, второй наш — эталонный спарринг-партнёр. Своё существо делается за одну строчку описания.'
        : 'Этот бой писала нейросеть — оба существа думали сами, мы в них не вмешивались. Своё можно сделать за одну строчку описания.');
    mount(root, h('div.overlay-card',
      h('div.panel.lift',
        h('div.bg'), h('div.fr'),
        h('div.in',
          h('div.hcut', 'БОЙ ЗАКОНЧЕН'),
          h('div.t-body', { style: { marginTop: '8px', maxWidth: '46ch' } }, claim),
          h('div.row', { style: { marginTop: '18px', gap: '10px' } },
            /* Маршруты берутся из ROUTES в app.js: `/new` и `/creature/<id>`,
               а не выдуманные `/create` и `/creature`. Кнопка, ведущая на
               несуществующий маршрут, роняет игрока на арену без объяснения —
               и делает это в единственной точке, ради которой экран есть. */
            h('button.btn.primary.big', {
              onclick: () => { location.hash = mine ? `#/creature/${mine.id}` : '#/new'; },
            }, mine ? 'К СВОЕМУ СУЩЕСТВУ' : 'СДЕЛАТЬ СВОЁ'),
            h('button.btn.ghost.big', {
              onclick: () => { location.hash = '#/arena'; },
            }, 'СМОТРЕТЬ ДАЛЬШЕ'))))));
    root.className = 'on veil';
    document.body.classList.add('overlay');
  };
}

/*
 * Подмена мёртвого боя живым.
 *
 * Маршрут не меняем: подмена — это не «мы вас увели», а «здесь показываем
 * другое». Если бы мы переписали hash на `#/arena`, ссылка в адресной строке
 * перестала бы совпадать с тем, что человек открыл, и обратно по «назад» он
 * попал бы на тот же тупик. Вместо этого просим сокет отдать текущий бой и
 * оставляем ту же концовку с предложением сделать своё существо.
 */
function fallback(root, ctx) {
  try { window.__airenaSend?.({ cmd: 'watch' }); } catch { /* сокета ещё нет */ }
  setTimeout(() => { try { window.__airenaSend?.({ cmd: 'watch' }); } catch { /* тем более */ } }, 700);
  onOver = endCard(root, ctx);
  addEventListener('airena:over', onOver);
}

function note(text) {
  const el = $('#clock .byline');
  if (el) el.textContent = text;
}

/** Просим сокет вьювера повторить конкретный бой. */
function askReplay(matchId) {
  const send = () => {
    try { window.__airenaSend?.({ cmd: 'replay', matchId }); } catch { /* сокета ещё нет */ }
  };
  send();
  setTimeout(send, 700);
  setTimeout(send, 2000);
}

export function leave() {
  wanted = null;
  if (onMatch) { removeEventListener('airena:match', onMatch); onMatch = null; }
  if (onOver) { removeEventListener('airena:over', onOver); onOver = null; }
  document.body.classList.remove('overlay');
  /*
   * УХОДЯ, НЕ ОСТАВЛЯЕМ УТВЕРЖДЕНИЯ.
   *
   * Здесь ставилась общая формулировка про авторство — и держалась до
   * следующего сообщения `match`, то есть весь остаток ТЕКУЩЕГО боя. На паре
   * рукописных эталонов подпись мгновенно менялась с правды на неправду в
   * момент нажатия «смотреть дальше». Подпись про конкретный бой ставит
   * вьювер по его моделям; наше дело — не мешать.
   */
}
