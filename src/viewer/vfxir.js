/**
 * Интерпретатор VFX-IR уровня 1 (§9.2).
 *
 * Играет ДЕКОРАЦИЮ, написанную моделью, поверх read-kit, который нарисовал
 * `vfx.js`. Здесь нет ни одной строки, приходящей от автора: IR — это набор
 * имён из закрытых таблиц `src/vfx/ir.js` и чисел в проверенных пределах, а
 * что именно делает имя `swirl`, решено ЗДЕСЬ и никем больше.
 *
 * Отсюда и безопасность уровня 1, и его потолок. Автор не может нарисовать
 * то, чего мы не предусмотрели, — но и не может уронить чужой браузер. §9.2
 * называет это прямо: единственный дизайн, где риск переносится с автора на
 * зрителя, — это уровень 3, и он отвергнут письменно.
 *
 * ЧЕГО ЗДЕСЬ НЕТ И ПОЧЕМУ:
 *   ЦВЕТА. Автор выбирает ступень палитры (0, 1, 2), а сама палитра пришла от
 *     элемента и заблокирована. Перекрасить эффект нечем — не потому, что мы
 *     проверяем, а потому, что поля нет.
 *   ГЕОМЕТРИИ. Спрайт выбирается именем из четырёх; меш строит `vfx.js`.
 *   ВРЕМЕНИ СВЕРХ ПРЕДЕЛА. Жизнь и задержка проверены на входе, но
 *     клампятся и здесь: вьювер обязан пережить IR, приехавший из базы,
 *     записанной прошлой версией правил.
 */

