const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, Number.isFinite(v) ? v : lo));

/*
 * БЮДЖЕТ СЧИТАЕТСЯ НА КАСТ И НА СЕКУНДУ, А НЕ НА ВЫЗОВ.
 *
 * Предел «частиц на один каст» принуждался внутри одного вызова `playIr` — а
 * вызывается он на КАЖДОЙ записи `world.fx`. Один каст зоны даёт их
 * тринадцать: `pushImpact` тикает каждые полсекунды, self и targeted
 * расщепляются на две. Значит законный набор из трёх зон с законным IR
 * умножал бюджет в тринадцать раз.
 *
 * Замерено на настоящем бою: 176 проигрываний IR на 24 каста, пик 24
 * проигрывания в секунду — 2880 частиц в секунду в кольцо на 3000. То есть
 * декорация вытесняла из кольца read-kit, не тронув ни одного запретного
 * поля: правило «добавлять, но не заменять» обходилось не через грамматику,
 * а через переполнение.
 *
 * Три предохранителя, и каждый закрывает свою дыру:
 *
 *   УДАР И СТАТУС НЕ УКРАШАЮТСЯ. Декорация принадлежит КАСТУ, а не каждому
 *     тику урона от него. Это же и правильнее по §9.2: удар в точке
 *     попадания принадлежит эффекту и рисуется read-kit.
 *   ОДИН КАСТ — ОДНА ДЕКОРАЦИЯ. Повтор той же пары (кто, умение) в пределах
 *     полсекунды — это тот же каст, разложенный на записи.
 *   ПОТОЛОК В СЕКУНДУ. Сколько бы касто́в ни случилось разом, декорация не
 *     может занять больше трети кольца за секунду. Остальное — read-kit,
 *     которому кольцо принадлежит первым.
 */
/*
 * ОКНО ДЕДУПА ШИРЕ, ЧЕМ ШАГ ТИКА, и сравнение нестрогое.
 *
 * Было 0.5 со строгим `<`. Зона тикает ровно через 0.5 с, и `0.5 < 0.5`
 * ложно — то есть дедуп не срабатывал ни разу на самом частом случае, ради
 * которого он и написан. Атом `wall` на зоне давал сорок проигрываний на
 * двадцать касто́в.
 *
 * 0.75 — с запасом больше шага тика (0.5) и заметно меньше самого короткого
 * кулдауна умения, поэтому два РАЗНЫХ каста одного умения в это окно не
 * попадают.
 */
const CAST_GAP = 0.75;
const PER_SECOND = 900;
const lastCast = new Map();
let windowStart = 0;
let windowSpent = 0;

function allowance(vfx, e) {
  /* Удар и статус — не касты. */
  if (e.kind === 'impact' || e.kind === 'status') return 0;

  /*
   * ЗАПИСЬ БЕЗ УМЕНИЯ — НЕ КАСТ, А МЕБЕЛЬ МИРА.
   *
   * Атом `wall` ставит в мир временный солид и пишет свою запись `fx` — без
   * `skill`, потому что стена принадлежит не умению, а арене: она стоит,
   * когда каст давно кончился, и мешает обоим. Симуляция это знает и поля не
   * заполняет.
   *
   * Декорация же принадлежит КАСТУ. Украшать стену значит украшать
   * последствие второй раз (read-kit её уже нарисовал) и, что хуже,
   * привязывать декорацию к ключу `кто|undefined` — общему для всех умений
   * этой стороны. На враждебном, но законном наборе из трёх зон со стеной это
   * давало сорок проигрываний на двадцать касто́в.
   */
  if (!e.skill) return 0;

  /*
   * КАСТ ДЛИТСЯ СТОЛЬКО, СКОЛЬКО ЖИВЁТ ДОСТАВКА.
   *
   * Фиксированное окно — неверный механизм, и это видно на зоне. Зона стоит
   * три секунды и тикает каждые полсекунды; при окне в 0.75 с декорация
   * играла на каждом втором тике — три раза вместо одного. Расширять окно до
   * трёх секунд нельзя: тогда склеятся два РАЗНЫХ каста быстрого умения.
   *
   * Правильная граница не во времени, а в смысле: пока живёт та же доставка,
   * это тот же каст. Её длительность приезжает в самой записи (`duration` у
   * зоны и стены), и окно берётся по ней. Для мгновенных доставок остаётся
   * `CAST_GAP` — он больше шага тика и меньше самого короткого кулдауна.
   */
  /*
   * ЭТОТ ПРЕДОХРАНИТЕЛЬ СЕГОДНЯ НЕ СРАБАТЫВАЕТ НИ РАЗУ — И ЭТО ЗАМЕРЕНО.
   *
   * Перебраны все законные сочетания доставок и эффектов: ни одно не даёт
   * больше одной записи `fx` С УМЕНИЕМ на один каст. Значит после проверки
   * «есть умение» выше дедуп по времени не отбрасывает ничего, и гейт,
   * снятый вместе с ним, не падает.
   *
   * Оставлен намеренно и с этой подписью. Он стоит один `Map.get` на запись,
   * а защищает от изменения, которое очень легко сделать: любой новый атом,
   * пишущий свою запись на тике (как `wall`), но с заполненным `skill`, тут
   * же вернёт умножение бюджета. Записано, чтобы через полгода его не сняли
   * как «мёртвый код» — он не мёртвый, он сторожевой.
   */
  const key = `${e.who}|${e.skill}`;
  const span = Math.max(CAST_GAP, Number.isFinite(e.duration) ? e.duration : 0);
  const was = lastCast.get(key);
  if (was !== undefined && vfx.now - was <= span) return 0;
  lastCast.set(key, vfx.now);
  /* Карта не растёт: сторон две, умений три, плюс запас на смену набора. */
  if (lastCast.size > 32) lastCast.clear();

  if (vfx.now - windowStart >= 1) { windowStart = vfx.now; windowSpent = 0; }
  const left = PER_SECOND - windowSpent;
  return Math.max(0, Math.min(MAX_PARTICLES, left));
}

/** Для гейта: забыть состояние между проверками. */
export function resetBudget() { lastCast.clear(); windowStart = 0; windowSpent = 0; }

/**
 * Детерминированный шум по номеру частицы.
 *
 * Не `Math.random`. Реплей обязан совпадать кадр в кадр (A2), а эффект,
 * рассыпанный случайно, даёт при повторе другую картинку — и разбор боя,
 * снятый со стенда, перестаёт совпадать с тем, что видел игрок. Число тут
 * дешёвое и полностью определяется номером.
 */
function noise(i, salt) {
  const x = Math.sin((i + 1) * 12.9898 + salt * 78.233) * 43758.5453;
  return x - Math.floor(x);
}

/* ── ЭМИТТЕРЫ ──────────────────────────────────────────────────────────────
 *
 * Каждый возвращает {pos, vel} для k-й частицы из n. Центр `c` и направление
 * `dir` приходят от read-kit: это точка каста и куда он смотрит. Автор не
 * выбирает ни то, ни другое — он выбирает, КАК из этой точки полетит.
 */
const EMIT = {
  ring: (k, n, c, dir, speed) => {
    const a = (k / n) * Math.PI * 2;
    return { pos: [c.x, c.y, c.z], vel: [Math.cos(a) * speed, 0.2, Math.sin(a) * speed] };
  },
  burst: (k, n, c, dir, speed) => {
    const a = noise(k, 1) * Math.PI * 2;
    const up = 0.2 + noise(k, 2) * 0.9;
    const s = speed * (0.5 + noise(k, 3) * 0.7);
    return { pos: [c.x, c.y, c.z], vel: [Math.cos(a) * s, up * s, Math.sin(a) * s] };
  },
  cone: (k, n, c, dir, speed) => {
    const spread = (noise(k, 4) - 0.5) * 0.8;
    const ca = Math.cos(spread); const sa = Math.sin(spread);
    const dx = dir.x * ca - dir.z * sa; const dz = dir.x * sa + dir.z * ca;
    const s = speed * (0.6 + noise(k, 5) * 0.6);
    return { pos: [c.x, c.y, c.z], vel: [dx * s, (noise(k, 6) - 0.3) * 0.6, dz * s] };
  },
  trail: (k, n, c, dir, speed) => {
    /* Шлейф раскладывается РАВНОМЕРНО по пути, а не случайно: случайная
       россыпь на коротком отрезке сбивается в комок и читается как клякса. */
    const u = n > 1 ? k / (n - 1) : 0;
    const back = u * 1.8;
    return {
      pos: [c.x - dir.x * back, c.y + (noise(k, 7) - 0.5) * 0.3, c.z - dir.z * back],
      vel: [(noise(k, 8) - 0.5) * speed * 0.4, (noise(k, 9) - 0.2) * speed * 0.3, (noise(k, 10) - 0.5) * speed * 0.4],
    };
  },
  spiral: (k, n, c, dir, speed) => {
    const a = (k / n) * Math.PI * 6;
    const r = 0.2 + (k / n) * 0.9;
    return {
      pos: [c.x + Math.cos(a) * r, c.y + (k / n) * 1.2, c.z + Math.sin(a) * r],
      vel: [Math.cos(a + 1.2) * speed * 0.5, speed * 0.35, Math.sin(a + 1.2) * speed * 0.5],
    };
  },
  rain: (k, n, c, dir, speed) => {
    const a = noise(k, 11) * Math.PI * 2;
    const r = noise(k, 12) * 1.4;
    return {
      pos: [c.x + Math.cos(a) * r, c.y + 2.2 + noise(k, 13) * 1.2, c.z + Math.sin(a) * r],
      vel: [0, -speed * 0.6, 0],
    };
  },
};

