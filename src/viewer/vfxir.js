/*
 * СЛЕД НА ПОЛУ.
 *
 * Второй такой же случай: `decal` проверялся валидатором, ехал в базу и не
 * рисовался ничем. Здесь он рисуется настоящим мешем через тот же
 * `spawnMesh`, которым read-kit кладёт свои фигуры, — то есть живёт и гаснет
 * по общим правилам вьювера, а не заводит свой цикл.
 *
 * Все три формы ПЛОСКИЕ и лежат на полу чуть выше нуля: арена белая (§10.1),
 * и след, утопленный в пол, даёт z-fighting, а поднятый — парит.
 */
function decalMesh(kind, colour, radius) {
  const mat = new THREE.MeshBasicMaterial({
    color: colour, transparent: true, opacity: 0.7, depthWrite: false, side: THREE.DoubleSide,
  });
  if (kind === 'ring') return new THREE.Mesh(new THREE.RingGeometry(radius * 0.72, radius, 32), mat);
  if (kind === 'scorch') return new THREE.Mesh(new THREE.CircleGeometry(radius, 24), mat);
  if (kind === 'cross') {
    const g = new THREE.PlaneGeometry(radius * 2.2, radius * 0.16);
    const a = new THREE.Mesh(g, mat);
    const b = new THREE.Mesh(g, mat);
    b.rotation.z = Math.PI / 2;
    a.add(b);
    return a;
  }
  return null;
}

/**
 * Цвет следа — САМАЯ ТЁМНАЯ ступень палитры, а не выбранная автором.
 *
 * Пол арены белый (§10.1). Первая версия красила след той же ступенью, что и
 * частицы, — и на морозной палитре (яркости 0.93 / 0.65 / 0.22) получалось
 * бледное пятно на белом: замерено глазом с верхнего ракурса, следа не видно
 * ни одного из трёх. Частицам светлая ступень идёт, потому что они летят и
 * гаснут; следу — нет, он лежит.
 *
 * Это НЕ нарушение «автор выбирает ступень»: ступень выбирает, каким будет
 * ЭФФЕКТ, а след — это метка на полу, и её задача одна — быть видимой. Правило
 * измеримое: берётся ступень с наименьшей яркостью по WCAG, то есть с
 * наибольшим контрастом к белому. У всех пяти элементов это третья ступень с
 * яркостью 0.05–0.22, и гейт проверяет, что так и останется.
 */
export function floorInk(P) {
  const lum = (c) => {
    const f = (v) => (v <= 0.03928 ? v / 12.92 : ((v + 0.055) / 1.055) ** 2.4);
    return 0.2126 * f(c.r) + 0.7152 * f(c.g) + 0.0722 * f(c.b);
  };
  let best = P[0];
  for (const c of P) if (lum(c) < lum(best)) best = c;
  return best;
}

/**
 * Цвет частицы: НАСТОЯЩАЯ интерполяция между выбранными ступенями.
 *
 * ── чем это было раньше и почему это было ничем ────────────────────────────
 *
 * Стояло `hue(P, k + stop * 2)`, где `hue` возвращает цвет по фиксированному
 * циклу `[1,2,1,0,2,1]`. То есть выбор автора превращался в СДВИГ ВНУТРИ
 * ЦИКЛА, а не в выбор цвета: доля средней ступени оставалась ровно 50% при
 * всех девяти сочетаниях `from`/`to`, крайние гуляли на пару частиц из сорока.
 * Ось валидировалась, канонизировалась, лежала в базе, занимала место в
 * промпте — и не влияла ни на один пиксель.
 *
 * Собственный гейт это пропустил, потому что сравнивал строки: перестановка
 * тех же цветов даёт другую строку. Ровно та проверка «нарисовалось ли
 * что-то» вместо «отличается ли», которую D70 объявляла исправленной. Второй
 * раз подряд — значит правило надо не повторять, а проверять по существу.
 *
 * ── почему просто взять P[stop] тоже нельзя ────────────────────────────────
 *
 * Первая ступень каждой палитры почти белая: это блик, и он задуман. Но пол
 * арены белый (§10.1), и `from=0, to=0` дал бы эффект, которого не видно
 * вовсе. Поэтому цвет интерполируется честно, а затем поднимается до
 * минимального контраста к белому — подмешиванием самой тёмной ступени той
 * же палитры. Автор остаётся в своей палитре, эффект остаётся видимым, а
 * разница между сочетаниями остаётся настоящей.
 */
function gradient(P, from, to, t) {
  const a = P[clamp(from, 0, P.length - 1)];
  const b = P[clamp(to, 0, P.length - 1)];
  const c = a.clone().lerp(b, t);
  const lum = 0.2126 * c.r + 0.7152 * c.g + 0.0722 * c.b;
  /* 0.82 — светлее этого частица на белом полу перестаёт читаться; проверено
     гейтом по контрасту, а не на глаз. */
  if (lum > 0.82) c.lerp(floorInk(P), (lum - 0.82) / 0.18 * 0.55);
  return c;
}

/** Ускорение по имени движения. Скорость уже заложена в `vel` эмиттера. */
const ACC = {
  linear: () => [0, 0, 0],
  ease_out: (v) => [-v[0] * 1.8, -v[1] * 1.8, -v[2] * 1.8],
  gravity: () => [0, -6.5, 0],
  rise: () => [0, 3.2, 0],
  swirl: (v) => [-v[2] * 2.2, -1.5, v[0] * 2.2],
};

/**
 * Сыграть IR одного умения поверх уже нарисованного read-kit.
 *
 * @param {import('./vfx.js').Vfx} vfx
 * @param {object|null} ir канонизированный IR (или null — тогда ничего)
 * @param {object} e запись из `world.fx`
 * @param {{shake?: (a: number) => void, flash?: (a: number) => void}} hooks
 * @returns {boolean} рисовала ли
 */
export function playIr(vfx, ir, e, hooks = {}) {
  if (!ir || !Array.isArray(ir.layers) || !ir.layers.length) return false;

  const P = palette(e.element);
  /* Точка и направление — от read-kit. Если координат нет (статус, импакт без
     геометрии), берём то, что есть, и не выдумываем: декорация без места
     лучше декорации не на месте. */
  const c = new THREE.Vector3(
    Number.isFinite(e.x1) ? e.x1 : (Number.isFinite(e.x) ? e.x : (e.x0 ?? 0)),
    1.1,
    Number.isFinite(e.z1) ? e.z1 : (Number.isFinite(e.z) ? e.z : (e.z0 ?? 0)),
  );
  const dir = new THREE.Vector3(
    (e.x1 ?? c.x) - (e.x0 ?? c.x),
    0,
    (e.z1 ?? c.z) - (e.z0 ?? c.z),
  );
  if (dir.lengthSq() < 1e-6) dir.set(1, 0, 0); else dir.normalize();

  /*
   * БЮДЖЕТ ПРИНУЖДАЕТСЯ И ЗДЕСЬ, а не только на входе.
   *
   * Валидатор стоит на записи, а этот код читает то, что уже лежит в базе, —
   * в том числе записанное прошлой версией пределов. Вьювер, который верит
   * базе на слово, однажды получит каст на три тысячи частиц и уронит кадр
   * зрителю. Правило то же, что у сервера с ценами умений: цифра, пришедшая
   * снаружи, не авторитетна, даже если снаружи — это мы вчера.
   */
  let left = allowance(vfx, e);
  if (left <= 0) return false;
  let drew = false;

  let decaled = false;
  for (const l of ir.layers.slice(0, 3)) {
    const emit = EMIT[l.emitter];
    const acc = ACC[l.motion];
    if (!emit || !acc) continue;

    const n = Math.min(Math.max(1, Math.round(l.count) || 1), left);
    if (n <= 0) break;
    left -= n;
    windowSpent += n;

    const life = clamp(l.life, 0.05, MAX_LIFE);
    const delay = clamp(l.delay ?? 0, 0, MAX_DELAY);
    const speed = clamp(l.speed ?? 3, 0, 14);
    const size = clamp(l.size ?? 0.18, 0.05, 1.2);
    const from = clamp(Math.round(l.from), 0, 2);
    const to = clamp(Math.round(l.to), 0, 2);
    const born = vfx.now + delay;
    const shape = SHAPE_INDEX[l.sprite] ?? 0;
    /* Каждая форма читается при своём размере: искра — точка, штрих — длинный
       и тонкий. Множитель живёт в грамматике рядом с именем, чтобы «искра»
       значила одно и то же и на сервере, и на экране. */
    /* Итоговый размер клампится ПОСЛЕ множителя формы, а не до: штрих с
       коэффициентом 1.6 на предельном размере вышел бы за предел, и предел
       снова оказался бы пожеланием. */
    const shapeScale = SPRITES[l.sprite]?.scale ?? 1;
    const drawSize = clamp(size * shapeScale, 0.05, 1.2);

    vfx.add.emit(n, (k, w) => {
      const { pos, vel } = emit(k, n, c, dir, speed);
      const a = acc(vel);
      w.pos(pos[0], pos[1], pos[2]);
      w.vel(vel[0], vel[1], vel[2]);
      w.gravity(a[0], a[1], a[2]);
      /*
       * Градиент по ПАЧКЕ, а не по времени жизни: цвет частицы задаётся один
       * раз при рождении, шейдер его не меняет. Первые частицы ближе к
       * ступени A, последние к B; читается как градиент, потому что гаснут
       * они вразнобой.
       */
      const t = n > 1 ? k / (n - 1) : 0;
      w.color(gradient(P, from, to, t));
      /*
       * Разброс жизни — ТОЛЬКО ВНИЗ.
       *
       * Было `0.7 + noise*0.6`, то есть до 1.3 предела: частица при
       * максимальной жизни жила 3.25 с при объявленных 2.5. Предел, который
       * можно превысить разбросом, — это не предел, а пожелание, и заметил
       * это гейт, которому пришлось смягчить собственный порог, чтобы
       * пройти. Смягчать надо было не порог.
       */
      w.life(born, life * (0.6 + noise(k, 14) * 0.4), drawSize, shape);
    });
    /*
     * След кладётся ОДИН на слой, а не по частице: это метка места, а не
     * ещё одна пачка искр. Радиус берётся от размера частиц и числа —
     * плотная пачка оставляет пятно шире редкой.
     */
    /* Следов не больше одного на каст: три слоя со следом давали три меша
       с собственной геометрией и материалом на каждый каст, а живут они по
       секунде с лишним. На замеренном бою это 120 одновременных мешей. */
    if (l.decal && l.decal !== 'none' && !decaled && typeof vfx.spawnMesh === 'function') {
      decaled = true;
      const radius = clamp(0.6 + n * 0.02 + size * 2, 0.5, 3.4);
      const mesh = decalMesh(l.decal, floorInk(P), radius);
      if (mesh) {
        mesh.position.set(c.x, 0.02, c.z);
        mesh.rotation.x = -Math.PI / 2;
        const kids = mesh.children.slice();
        vfx.spawnMesh(mesh, Math.min(life * 1.4, MAX_LIFE), (o, u) => {
          o.material.opacity = 0.55 * (1 - u) ** 1.4;
          for (const kid of kids) kid.material.opacity = o.material.opacity;
          o.scale.setScalar(0.7 + u * 0.45);
        });
      }
    }
    drew = true;
  }

  /*
   * Экранный эффект СКЛАДЫВАЕТСЯ со штатным и ограничен сверху.
   *
   * Вьювер уже толкает камеру на попадание. Если позволить автору добавлять
   * сколько угодно, чужой бой станет невозможно смотреть — а чужие бои и есть
   * трансляция арены, то есть первое, что видит гость.
   */
  if (ir.screen === 'shake' && hooks.shake) hooks.shake(clamp(ir.screenAmount, 0, MAX_SHAKE));
  if (ir.screen === 'flash' && hooks.flash) hooks.flash(clamp(ir.screenAmount, 0, MAX_SHAKE));
  return drew;
}
