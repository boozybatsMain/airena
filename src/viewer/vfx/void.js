/**
 * ДОЛЯ КВАДА В КРЕСТЕ — осталась ОДНОМУ РАЗРЕЗУ (`riftMat`).
 *
 * Стена ушла на выпуклую коробку, пасть — на биллборд: креста, у которого
 * половины кажут друг другу кромки, в файле больше нет нигде, кроме разреза,
 * где обе половины вытянуты вдоль ОДНОЙ оси и их силуэты совпадают не по
 * обещанию, а по построению (шум разреза берётся вдоль `uv.x`, то есть вдоль
 * общей оси, и одинаков у обеих половин).
 *
 * Крест из двух перпендикулярных плоскостей виден с любого азимута — но с
 * промежуточного видны ОБЕ, и кромка одной ложится поперёк тела другой.
 * Судья прочёл это на кадре стены (crop 730,370,960,570) как z-fighting:
 * «два смещённых сиреневых ромба». Лечится не порядком отрисовки, а весом.
 * Для двух перпендикулярных плоскостей с общей осью `A` выполняется
 *   (N₁·V)² + (N₂·V)² = 1 − (A·V)²,
 * поэтому доля (N·V)²/(1−(A·V)²) — РАЗБИЕНИЕ ЕДИНИЦЫ: квад, стоящий ребром
 * к глазу, гаснет полностью, и пара кромок на экране всегда ровно одна.
 * Корень — чтобы на 45° композит двух альф давал 0.91, а не 0.75 (a+b−ab).
 * Ось берётся из матрицы объекта, а не из униформы: материал общий (пул), и
 * униформа оси переписывалась бы соседним разрезом.
 */
function faceShare(ax, ay, az) {
  const V = cameraPosition.sub(positionWorld).normalize();
  const A = modelWorldMatrix.mul(vec4(ax, ay, az, 0)).xyz.normalize();
  const av = tdot(A, V), nv = tdot(normalWorld, V);
  return nv.mul(nv).div(oneMinus(av.mul(av)).max(float(0.06))).clamp(0, 1).sqrt();
}

/**
 * ЦВЕТ СВЕТЯЩЕЙСЯ КРОМКИ. `P[1]` (#a98cf0) — уже пастель, и это видно по
 * самой палитре: (169,140,240) при насыщенности 0.42, то есть ровно посреди
 * запрещённой §10.1 полосы. Кадром судимого состояния это подтверждается
 * косвенно, но убедительно: яма статуса, где кромка красилась `P[1]·1.4`,
 * дала средний (137,129,150) при S = 0.136 и 2251 пиксель из 4198 внутри
 * полосы (`r70/void/r0`, t = 0.60, трансляция). Отдельного замера ПО САМОЙ
 * КРОМКЕ ни в одном кадре нет — предыдущий круг такую цифру приводил, но она
 * ничем на диске не подтверждается, и здесь её больше нет.
 *
 * Зелёная составляющая срезается, синяя поднимается над единицей: тон
 * остаётся тем же фиолетовым, насыщенность самого цвета — 0.98, а яркость
 * держит синяя, уходящая в bloom.
 */
function spark(P) { return vec3(P[1].r * 0.45, P[1].g * 0.08, P[1].b * 1.35); }

function planeMat() {
  return new THREE.MeshBasicNodeMaterial({
    transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: THREE.NormalBlending,
  });
}

/**
 * Общий граф дыры: почти чёрная сердцевина, рваный край по шуму, узкая
 * фиолетовая кромка и ТОЛЬКО она в bloom. `open` — доля, до которой дыра
 * раскрыта (0 — закрыта, 1 — полностью).
 *
 * СЕРДЦЕВИНА НЕПРОЗРАЧНА, И ЭТО ГЛАВНОЕ ЧИСЛО ВСЕГО ФАЙЛА. При альфе 0.96
 * сквозь дыру проходили четыре процента БЕЛОГО HDR-ПОЛА, и этого хватало,
 * чтобы чёрного не осталось вовсе. Замер этого круга, кадр
 * `void-status-t0_60-side` в судейском окне (880,420,1110,560): 8565
 * изменённых пикселей, средний цвет (85,64,137), и темнее 60 — СТО
 * ЧЕТЫРНАДЦАТЬ штук, полтора процента. Судья написал «пастельная сиреневая
 * лужа, в которой нет ни капли чёрного», и он был прав по числам: сквозь
 * четыре процента пол просвечивал так, что сетка плитки читалась насквозь.
 * При альфе 1.0 тот же цвет ложится как есть.
 */
function holeGraph(m, P) {
  const fade = withFade(m);
  const open = uniform(1), seed = uniform(1), spin = uniform(0), lobes = uniform(0);
  m.userData.u = { fade, open, seed, spin, lobes };
  const q0 = uv().sub(vec2(0.5, 0.5)).mul(2 * SPAN);
  const d = q0.length();
  /*
   * ПОВОРОТ РВАНОГО КРАЯ (`spin`) — ЕДИНСТВЕННЫЙ СПОСОБ ПОКАЗАТЬ ВРАЩЕНИЕ
   * БИЛЛБОРДА. Пасть всегда стоит лицом к глазу (см. `mouthMat`), и поворот
   * самого меша на экране не виден вовсе — вертящийся квад, обращённый к
   * камере, даёт тот же кадр. Судья написал про снаряд «нет вращения»; чтобы
   * оно было, вертеться должен УЗОР, а не меш. Крутится только вход шума:
   * `d` от поворота не зависит, поэтому размер дыры не дышит.
   *
   * Поворот сидит в униформе и по умолчанию НОЛЬ: яма, зона, конус и щит
   * получают ровно прежний кадр, крутится только голова прокола.
   */
  const cs = tcos(spin), sn = tsin(spin);
  const q = vec2(q0.x.mul(cs).sub(q0.y.mul(sn)), q0.x.mul(sn).add(q0.y.mul(cs)));
  const n = mx_fractal_noise_float(vec3(q.mul(2.6), seed), 3, 2.0, 0.5, 1).mul(0.5).add(0.5);
  /*
   * ЛУЧИ (`lobes`) — ЧТОБЫ УДАР НЕ ЧИТАЛСЯ СТАТУСОМ. Судья снял очки за то,
   * что на 26 м «яма статуса» и «яма удара» — одно и то же тёмное пятно с
   * фиолетовой кромкой, и различаются только размером. Размер на трансляции
   * не различие: круг остаётся кругом. Пятилучевой разрыв — различие в РОДЕ
   * силуэта, и оно видно с любого расстояния, на котором виден сам силуэт.
   * По умолчанию ноль: круглыми остаются все ямы, кроме ударной.
   */
  const star = tcos(tatan(q.x, q.y).mul(5)).mul(lobes);
  /* Край рваный: разрыв не бывает круглым. */
  const edge = d.add(n.sub(0.5).mul(0.4)).sub(star).div(open.max(0.001));
  const inside = oneMinus(smoothstep(float(0.90), float(1.02), edge));
  /*
   * КРОМКА — УЗКАЯ ПОЛОСА, и в судимом состоянии она такой не была. Полоса
   * 0.62–1.12 занимала ПОЛОВИНУ радиуса дыры и красилась `P[1]·1.4` — той
   * самой пастелью, что разобрана у `spark`. На крупных формах — зоне, щите —
   * это незаметно: там чёрная середина огромна. На мелких видно в упор:
   * судимая яма статуса, где наружу выходила ровно эта полоса, дала средний
   * (137,129,150) при S = 0.136 и 2251 пиксель из 4198 в запрещённой полосе
   * (`r70/void/r0`, t = 0.60, трансляция). Полоса вдвое уже (0.80–1.12),
   * чёрное доходит до 0.9 радиуса, а цвет кромки — насыщенный фиолет со
   * срезанной зелёной, а не пастель. Замер после правки, та же форма и тот же
   * глаз (`r70c/void/r1`): S = 0.766, в полосе 690 пикселей из 13020.
   */
  const rim = smoothstep(float(0.80), float(0.94), edge).mul(oneMinus(smoothstep(float(1.00), float(1.12), edge)));
  /* СЕРДЦЕВИНА ФИОЛЕТОВАЯ, а не нейтрально-чёрная (§10.1 требует «тёмное И
     насыщенное»), и с ГЛУБИНОЙ: к центру она уходит в `P[2]·0.10`, у края
     остаётся `P[2]·0.34`. Ровная заливка на кадре читалась плоской
     наклейкой — у ямы обязан быть низ. */
  const depth = mix(col(P[2]).mul(0.34), col(P[2]).mul(0.10), oneMinus(smoothstep(float(0.0), float(0.86), edge)));
  m.colorNode = mix(depth, spark(P), rim.clamp(0, 1));
  m.opacityNode = inside.max(rim.mul(0.95)).mul(fade).clamp(0, 1);
  /*
   * Пол НЕ ЦВЕТЁТ (§10.1): в bloom уходит только кромка, и слабо — 0.22
   * вместо 0.35. Широкое слабое свечение на белом полу — обратная ловушка
   * того же параграфа: замер этого круга по яме статуса дал 5328 из 14687
   * изменённых пикселей в полосе 0.15 ≤ S < 0.45, и это был не сам ободок,
   * а его ореол вокруг.
   */
  return markGlow(m, rim.mul(fade).mul(0.22).clamp(0, 0.22));
}

/** Плоская дыра на полу. */
/* Кольцо ШЕСТЬ, а не четыре: дыру теперь кладут не только луч, конус, зона и
   щит, но и замах (яма под рукой) и удар. При кольце в четыре штуки пятая
   живая дыра забирала бы материал у первой и гнала её `fade` по своей
   огибающей — поломка, на которой уже сгорел накал лазера. */
function holeMat(P) {
  return pooled(`void:hole:${hex(P)}`, () => holeGraph(planeMat(), P), 6);
}

/**
 * ЯМА СТАТУСА — СВОЙ МАТЕРИАЛ, А НЕ ОБЩЕЕ КОЛЬЦО.
 *
 * Статус живёт секундами и держит материал всё это время, а кольцо `pooled`
 * — четыре штуки на всю стихию: пятая дыра любого другого каста забирает
 * материал статуса и гонит его `fade` по своей огибающей (ровно та поломка,
 * на которой сгорел накал лазера). Ключ по телу даёт максимум два живых
 * материала — по одному на бойца — и ни одного столкновения.
 *
 * Кромка здесь ТЁМНАЯ, а не сиреневая, и это замер судимого состояния
 * (`r70/void/r0`, статус t = 0.60, трансляция, против пустого пола): при
 * кромке `P[1]·1.4` и альфе 0.77 белый HDR-пол просвечивает четвертью своей
 * яркости и даёт средний (137,129,150) — пастель, «сиреневая дымка»,
 * запрещённая шапкой этого файла. Из 4198 изменённых пикселей 2251 сидел
 * ВНУТРИ полосы 0.15–0.45, с S ≥ 0.45 было ПЯТЬ, темнее 60 — 67. (Предыдущий
 * круг приводил тут «136 насыщенных и 95 темнее 110»; по тем же кадрам у меня
 * выходит 5 и 909 — считалось, видимо, иначе, и цифры заменены на свои.)
 * Тёмный фиолетовый в кромке и волосяная светлая линия по самому краю дают то
 * же прочтение, но ТЁМНЫМ и НАСЫЩЕННЫМ, как требует §10.1.
 *
 * ЧЕГО ТОЙ ПРАВКЕ НЕ ХВАТИЛО — замер этого круга, судейское окно
 * (880,420,1110,560) на кадре `void-status-t0_60-side`: насыщенность
 * поднялась (7113 пикселей из 8565 с S ≥ 0.45), а ЧЁРНОГО как не было, так и
 * нет — темнее 60 всего 114 штук. Сквозь альфу 0.97·0.97 проходило шесть
 * процентов белого HDR-пола, и на кадре сквозь яму читалась сетка плитки.
 * Правки три, и все три — про это: альфа сердцевины ровно 1.0, полоса
 * дальней кромки сужена (0.58–0.90 занимала треть радиуса), а рваность края
 * снижена с 0.34 до `TORN` — при 0.34 яма выходила амёбой и читалась ЛУЖЕЙ,
 * то есть родом кислоты, а не разрывом.
 */
/** Рваность края ямы статуса: 0 — круг, 0.34 — амёба (см. выше). */
const TORN = 0.2;
function statusMat(P, who) {
  return pooled(`void:hole:st:${who}:${hex(P)}`, () => {
    const m = planeMat();
    const fade = withFade(m);
    const open = uniform(1), seed = uniform(1);
    m.userData.u = { fade, open, seed };
    const q = uv().sub(vec2(0.5, 0.5)).mul(2 * SPAN);
    const d = q.length();
    const n = mx_fractal_noise_float(vec3(q.mul(2.6), seed), 3, 2.0, 0.5, 1).mul(0.5).add(0.5);
    const edge = d.add(n.sub(0.5).mul(TORN)).div(open.max(0.001));
    const inside = oneMinus(smoothstep(float(0.88), float(1.0), edge));
    const rim = smoothstep(float(0.74), float(0.94), edge).mul(oneMinus(smoothstep(float(0.99), float(1.08), edge)));
    /*
     * Волосяная линия по самому краю — единственное, что тут светится, и она
     * УЖЕ прежней (0.94–0.98 против 0.90–0.97), а зелёная составляющая в ней
     * срезана: тот же фиолетовый тон, но насыщенный. Предыдущий круг приводил
     * здесь «1434 светлых пикселя из 7567 со средним (190,170,219)»; кадра,
     * который бы это подтверждал, на диске нет, и цифра снята. Что проверено
     * кадром — итог: в судейском окне (880,420,1110,560, поперечный глаз,
     * t = 0.60) в полосе 0.15–0.45 было 1251 пиксель из 8565, стало 428 из
     * 7736.
     */
    const hair = smoothstep(float(0.94), float(0.98), edge).mul(oneMinus(smoothstep(float(0.99), float(1.04), edge)));
    /* Дно ямы ЧЕРНЕЕ её краёв: ровная заливка читалась плоским пятном. */
    const depth = mix(col(P[2]).mul(0.30), col(P[2]).mul(0.08), oneMinus(smoothstep(float(0.0), float(0.8), edge)));
    m.colorNode = mix(mix(depth, col(P[2]).mul(0.85), rim.clamp(0, 1)), spark(P), hair.clamp(0, 1));
    m.opacityNode = inside.max(rim.mul(0.97)).max(hair.mul(0.97)).mul(fade).clamp(0, 1);
    return markGlow(m, hair.mul(fade).mul(0.18).clamp(0, 0.18));
  }, 2);
}

let HOLE_GEO = null;
function hole(P, { x, z, r, seed, y = 0.027, mat = null, lobes = 0 }) {
  if (!HOLE_GEO) HOLE_GEO = shared(new THREE.PlaneGeometry(1, 1).rotateX(-Math.PI / 2));
  const m = mat || holeMat(P);
  m.userData.u.seed.value = seed;
  /* Материал ямы статуса — свой (`statusMat`), и лучей у него нет: проверка
     не на вкус, а на то, что уровень пришёл из чужого графа. */
  if (m.userData.u.lobes) m.userData.u.lobes.value = lobes;
  if (m.userData.u.spin) m.userData.u.spin.value = 0;
  const mesh = new THREE.Mesh(HOLE_GEO, m);
  mesh.position.set(x, y, z);
  /* Меш во столько же раз больше, во сколько растянуты uv (см. `SPAN`):
     размер формы от этого не меняется, срез рваного края — исчезает. */
  mesh.scale.setScalar(r * 2 * SPAN);
  mesh.renderOrder = 3;
  mesh.frustumCulled = false;
  return { mesh, set(fade, open = 1) { m.userData.fade.value = fade; m.userData.u.open.value = open; } };
}

/* ── пасть: дыра, стоящая в воздухе ─────────────────────────────────────── */

/**
 * ПАСТЬ — тот же граф дыры, но развёрнутый ЛИЦОМ К ГЛАЗУ прямо в вершинном
 * узле: центр объекта переводится в видовое пространство, а углы квада
 * кладутся по осям экрана. Тот же приём, что у марева в `kit`.
 *
 * Размер берётся из МАТРИЦЫ ОБЪЕКТА (длина мировой проекции локальной оси
 * X — то есть масштаб меша), а не из униформы: материал общий, кольцо на
 * четыре штуки, и униформа размера переписывалась бы соседним кастом.
 */
function mouthMat(P) {
  return pooled(`void:mouth:${hex(P)}`, () => {
    const m = holeGraph(planeMat(), P);
    const sx = modelWorldMatrix.mul(vec4(1, 0, 0, 0)).xyz.length();
    m.vertexNode = cameraProjectionMatrix.mul(
      modelViewMatrix.mul(vec4(0, 0, 0, 1)).add(vec4(positionLocal.xy.mul(sx), 0, 0)),
    );
    return m;
  }, 4);
}

let MOUTH_GEO = null;
/**
 * ПАСТЬ — дыра, стоящая в воздухе: ОДИН квад, всегда лицом к камере.
 *
 * ЧТО БЫЛО СНАЧАЛА. Замах строил дыру из `HOLE_GEO`, уже повёрнутой в пол
 * (`.rotateX(-π/2)`), и гасил поворот присваиванием `rotation.x = 0` — то
 * есть НЕ ДЕЛАЛ НИЧЕГО. Задуманная «пасть в лицо камере» выходила
 * горизонтальным диском на высоте 1.1 м и сминалась наклоном камеры
 * 0.46 рад в щепку: 130 px >25 и 58 px >60 на трансляции, слабейший замах из
 * десяти стихий (замер круга 0).
 *
 * ЧЕМ ЭТО ЧИНИЛИ ДО ЭТОГО ЗАМЕРА — крестом из двух вертикальных квадов, под
 * обещание, что «две соосные окружности проецируются в эллипсы с общим
 * центром, и на 45° половины совпадают». Обещание неверно. Рваный край
 * считается по `uv`, а `rotateY(π/2)` разворачивает вторую половину так, что
 * её шум идёт ЗЕРКАЛЬНО: силуэты не совпадают, они отражаются. Кадр показал
 * это в упор — увеличение пасти удара (`void-impact-t0_30-broadcast`, окно
 * 735,435,825,525): два смещённых рваных силуэта и бледная лаванда между
 * ними, 769 из 2643 изменённых пикселей в запрещённой полосе насыщенности
 * 0.15–0.45. Ровно тот дефект («два смещённых сиреневых ромба, читается как
 * z-fighting»), за который судья снял очки на стене, только переехавший на
 * другую форму.
 *
 * ОДИН КВАД ЛИЦОМ К ГЛАЗУ шва иметь не может ни при каком азимуте — швов
 * нет, потому что нет второй поверхности. Он же даёт максимальную площадь на
 * экране: крест на 45° показывал две половины по `faceShare` ≈ 0.71 каждая,
 * биллборд — весь диск целиком.
 */
function mouth(P, { x, y, z, r, seed }) {
  if (!MOUTH_GEO) MOUTH_GEO = shared(new THREE.PlaneGeometry(1, 1));
  const m = mouthMat(P);
  m.userData.u.seed.value = seed;
  const mesh = new THREE.Mesh(MOUTH_GEO, m);
  mesh.position.set(x, y, z);
  mesh.scale.setScalar(r * 2 * SPAN);
  mesh.renderOrder = 10;
  mesh.frustumCulled = false;
  return {
    mesh,
    set(fade, open = 1, spin = 0) {
      m.userData.fade.value = fade;
      m.userData.u.open.value = open;
      m.userData.u.spin.value = spin;
      m.userData.u.lobes.value = 0;
    },
  };
}

/**
 * `riftMat` — РАЗРЕЗ в воздухе: почти чёрная щель с фиолетовой кромкой,
 * искажающая то, что за ней. Поперёк (`uv().y`) сердцевина узкая, кромка ещё
 * уже; вдоль (`uv().x`) щель сходит на нет к обоим концам — у разреза нет
 * торцов, он просто кончается.
 */
function riftMat(P) {
  return pooled(`void:rift:${hex(P)}`, () => {
    const m = planeMat();
    const fade = withFade(m);
    const head = uniform(1);
    m.userData.u = { fade, head };
    const dy = tabs(uv().y.sub(0.5)).mul(2);
    const along = uv().x;
    /* Щель шире посередине и сходит к концам — форма пореза, а не бруса. */
    const belly = smoothstep(float(0.0), float(0.22), along).mul(oneMinus(smoothstep(head.sub(0.22), head, along)));
    const w = belly.mul(0.85).add(0.15);
    const core = oneMinus(smoothstep(w.mul(0.42), w.mul(0.72), dy));
    const rim = smoothstep(w.mul(0.6), w.mul(0.86), dy).mul(oneMinus(smoothstep(w.mul(1.0), w.mul(1.25), dy)));
    /*
     * КРОМКА — `spark`, А НЕ `P[1]·1.5`, И ЭТО НЕ ВКУС.
     *
     * `P[1]·1.5` — это (0.99, 0.82, 1.41) в линейном: насыщенность 0.42, то
     * есть ровно середина запрещённой §10.1 полосы. Судья измерил её на
     * снаряде: «бледный ореол», окно (760,415,820,485) кадра
     * `r1/bolt/void-bolt-t0_06-broadcast` — средний (120,109,111) при
     * S = 0.154, и 243 пикселя из 440 внутри полосы 0.15 ≤ S < 0.45. `spark`
     * держит ту же синюю яркость (1.27 против 1.41), но срезает зелёную:
     * насыщенность самого цвета 0.97.
     *
     * ЛУЧ ЭТИМ НЕ СЛОМАН, И ЭТО ПРОВЕРЕНО ИМЕННО ПОТОМУ, ЧТО МАТЕРИАЛ ОБЩИЙ.
     * Луч — форма, которую судья назвал отличной, и кромка у него та же.
     * Замер против пустого пола, арена рядов 120–790: t = 0.30 трансляция
     * 49755/17373 → 49829/17575, поперечный 152401/31364 → 152492/31509;
     * t = 0.60 трансляция 31920/15528 → 31937/15689. Разница — сотые доли
     * процента, то есть шум съёмки; доля пикселей в запрещённой полосе при
     * этом слегка УПАЛА (37.3% → 36.8%).
     */
    m.colorNode = mix(vec3(0.012, 0.008, 0.026), spark(P), rim.clamp(0, 1));
    /* Крест разреза — с весом по оси разреза (`faceShare`): иначе на 45° обе
       половины показывают друг другу кромки. */
    const alpha = core.mul(0.97).max(rim.mul(0.92)).mul(belly).mul(fade).mul(faceShare(1, 0, 0)).clamp(0, 1);
    m.opacityNode = alpha;
    /*
     * Кромка тянет картинку за собой — то, что за разрезом, смещено. Свечение
     * идёт ЧЕТВЁРТЫМ АРГУМЕНТОМ той же метки, а не отдельным `markGlow`:
     * обе метки пишут в `material.mrtNode`, и вторая стирала первую — то есть
     * искажения у разреза не было вовсе с самого его появления.
     */
    return markDistort(m, vec2(0, 1).mul(rim).mul(0.4), rim.mul(fade).mul(0.5), rim.mul(alpha).mul(0.4));
  }, 4);
}

let RIFT_A = null, RIFT_B = null;
function riftGeo() {
  if (!RIFT_A) {
    RIFT_A = shared(new THREE.PlaneGeometry(1, 1).translate(0.5, 0, 0));
    RIFT_B = shared(new THREE.PlaneGeometry(1, 1).rotateX(Math.PI / 2).translate(0.5, 0, 0));
  }
  return [RIFT_A, RIFT_B];
}

/** Разрез от `a` до `b`: крест из двух квадов, ручка `set(fade, head)`. */
function rift(P, a, b, width) {
  const m = riftMat(P);
  const g = new THREE.Group();
  for (const geo of riftGeo()) {
    const mesh = new THREE.Mesh(geo, m);
    mesh.frustumCulled = false;
    mesh.renderOrder = 10;
    g.add(mesh);
  }
  const dx = b[0] - a[0], dy = b[1] - a[1], dz = b[2] - a[2];
  const len = Math.hypot(dx, dy, dz) || 0.01;
  g.position.set(a[0], a[1], a[2]);
  g.rotation.y = yawFor(dx / len, dz / len);
  g.rotation.z = Math.asin(clampN(dy / len, -1, 1));
  g.scale.set(len, width, width);
  return { group: g, len, set(fade, head = 1) { m.userData.fade.value = fade; m.userData.u.head.value = head; } };
}

/* ── плита отсутствия: стена ────────────────────────────────────────────── */

/**
 * `slabMat` — то, что стоит на месте прохода: почти чёрное тело с рваным
 * верхом и светящимся контуром по рёбрам.
 *
 * ПОЧЕМУ НЕ КРЕСТ ИЗ ДВУХ КВАДОВ, КАК БЫЛО. Стена — самая крупная форма
 * пустоты, и на ней шов креста виден в упор: вертикальный квад давал тёмный
 * ромб, горизонтальное перо на высоте 1.1 м — второй, светлый, поперёк, и
 * судья прочёл пару как z-fighting поверх штатной плиты. Веса `faceShare`
 * тут мало: с трансляции перо стоит к глазу под 26°, его доля 0.32 — оно
 * гаснет лишь на две трети. Коробка же ВЫПУКЛАЯ: с `FrontSide` каждый
 * экранный пиксель кроет ровно одна грань, и шов невозможен в принципе.
 *
 * Кромка считается по границе ГРАНИ в её собственных uv (у коробки каждая
 * грань размечена 0..1), поэтому одна формула красит все видимые рёбра.
 */
function slabMat(P) {
  return pooled(`void:slab:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.FrontSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    const seed = uniform(1);
    m.userData.u = { fade, seed };
    const q = uv();
    const p = positionGeometry;
    /*
     * Шум берётся по ГОРИЗОНТАЛИ (x, z) и не зависит от высоты: иначе рваный
     * верх идёт волной не по длине стены, а по её толщине.
     *
     * И берётся он в МИРОВЫХ метрах, а не в долях коробки. Коробка растянута
     * неравномерно (4 м в длину, 0.5 м в глубину), а `positionGeometry`
     * одинаково даёт ±0.5 по обеим осям: на длинной грани семь периодов шума
     * ложились на четыре метра, на торцевой — те же семь на полметра, то есть
     * у торца гребень выходил в восемь раз чаще, чем у длинной грани. Правка
     * геометрическая и проверяется этим отношением; отдельного кадра «до»
     * с пильчатым торцом на диске нет — предыдущий круг такой замер
     * упоминал, но подтвердить его нечем.
     */
    const pw = positionWorld;
    const grain = mx_noise_float(vec3(pw.x.mul(1.75), pw.z.mul(1.75), seed)).mul(0.5).add(0.5);
    /* Верх РВАНЫЙ: у разрыва нет ровной кромки. */
    const cut = smoothstep(float(0.20).add(grain.mul(0.20)), float(0.40).add(grain.mul(0.20)), p.y);
    const body = oneMinus(cut);
    const border = q.x.min(oneMinus(q.x)).min(q.y).min(oneMinus(q.y));
    const edge = oneMinus(smoothstep(float(0.006), float(0.022).add(grain.mul(0.012)), border));
    const rim = edge.mul(body).max(cut.mul(oneMinus(cut)).mul(4).clamp(0, 1));
    m.colorNode = mix(vec3(0.010, 0.007, 0.024), col(P[1]).mul(1.5), rim.clamp(0, 1));
    /* Тело почти непрозрачно: на белом полу плита в 0.8 выцвела бы в серое. */
    m.opacityNode = body.mul(0.97).max(rim.mul(0.95)).mul(fade).clamp(0, 1);
    return markGlow(m, rim.mul(fade).mul(0.4).clamp(0, 0.4));
  }, 4);
}

let SLAB_GEO = null;
/** Плита от `x` на ширину `w`, глубину `d`; ручка `set(fade)`. */
function slab(P, { x, z, w, d, seed }) {
  if (!SLAB_GEO) SLAB_GEO = shared(new THREE.BoxGeometry(1, 1, 1));
  const m = slabMat(P);
  m.userData.u.seed.value = seed;
  const mesh = new THREE.Mesh(SLAB_GEO, m);
  mesh.position.set(x, 0, z);
  mesh.scale.set(w, 0.01, d);
  mesh.renderOrder = 10;
  mesh.frustumCulled = false;
  return { mesh, set(fade) { m.userData.fade.value = fade; } };
}

/* ── частицы: всё летит ВНУТРЬ ──────────────────────────────────────────── */

/**
 * `intake` — вещество, СТЯГИВАЕМОЕ в точку. Это единственный вид частиц у
 * пустоты: у неё нечему разлетаться. Частица рождается на радиусе `from` и
 * летит к центру так, чтобы дойти за свою жизнь.
 */
function intake(vfx, P, { x, y = 0.6, z, n, from, life = 0.5, size = 0.14, at = null, rng, glow = 0.35, light = 0.4 }) {
  const born = at ?? vfx.now;
  const put = (pool, c1, c2, k) => pool.emit(Math.max(1, Math.round(n * k)), (i, s) => {
    const a = rng() * TAU, e2 = (rng() - 0.5) * 1.2;
    const d = from * (0.7 + rng() * 0.5);
    const px = x + Math.cos(e2) * Math.sin(a) * d, py = y + Math.sin(e2) * d * 0.6, pz = z + Math.cos(e2) * Math.cos(a) * d;
    const L = life * (0.75 + rng() * 0.5);
    s.pos(px, Math.max(0.05, py), pz);
    /* Скорость подобрана так, чтобы частица пришла в центр к концу жизни. */
    s.vel((x - px) / L, (y - Math.max(0.05, py)) / L, (z - pz) / L);
    s.gravity(0, 0, 0);
    s.color(c1, c2);
    s.life(born + rng() * 0.08, L, rnd(size * 0.6, size * 1.4, rng), kit.SHAPE.streak);
    s.ext(0, 0.75, 1, k === 1 ? 0 : glow);
  });
  /* Тёмная доля — в пул тел (её видно на белом полу), светлая — в свечение.
     `light` — сколько светлых на одну тёмную: на белом полу светлая доля
     читается бледной пастелью (§10.1), и формам, у которых втянутое вещество
     несёт весь кадр, её надо уметь прижать. */
  put(vfx.body, P[2], P[2], 1);
  put(vfx.glow, P[0], P[1], light);
}

/** Хлопья отслаивающейся реальности: тёмные чипы, падающие в дыру. */
function flakes(vfx, P, { x, y = 0.5, z, n, radius, life = 0.8, size = 0.16, at = null, rng }) {
  const born = at ?? vfx.now;
  vfx.body.emit(n, (i, s) => {
    const a = rng() * TAU, d = Math.sqrt(rng()) * radius;
    const px = x + Math.sin(a) * d, pz = z + Math.cos(a) * d;
    s.pos(px, y + rng() * 0.4, pz);
    s.vel((x - px) * 0.8, -0.4 - rng() * 0.8, (z - pz) * 0.8);
    s.gravity(0, -1.2, 0);
    s.color(P[2], P[2]);
    s.life(born, rnd(life * 0.7, life * 1.3, rng), rnd(size * 0.6, size * 1.4, rng), kit.SHAPE.chip);
    s.ext(rnd(-6, 6, rng), 0.7, 0, 0);
  });
}

/**
 * ШРАМ — СОБСТВЕННЫЙ НЕПРОЗРАЧНЫЙ СЛЕД ПУСТОТЫ. ЧЕРЕЗ ЧАШУ `kit` ТЁМНОГО
 * СЛЕДА НЕ ПОЛУЧИТЬ, И ЭТО ИЗМЕРЕНО ДВАЖДЫ.
 *
 * Ветка `crater` в `kit` даёт чаше альфу `bowl·0.75`: сквозь неё проходит
 * четверть белого HDR-пола, и эта четверть держит след светлым при ЛЮБОМ
 * тоне. Прошлый круг зашёл с двух сторон — покрасил чернила в тёмное и
 * насыщенное и положил вторую воронку вдвое меньшего радиуса внутрь первой,
 * чтобы доля пола под серединой упала с 0.25 до 0.0625, — и оба приёма на
 * трансляции не сработали. Замер кадра `r2-before/cone/void-cone-t1_20-
 * broadcast` против пустого пола (единственная форма, чью воронку не
 * закрывает тело): 3086 изменённых пикселей, средний (172,159,174),
 * S = 0.125, темнее 60 — НОЛЬ, темнее 110 — 192 штуки. Судимая, СОВСЕМ не
 * подкрашенная воронка на том же кадре давала (167,158,171) при S = 0.110:
 * разница 5/1/3 по каналам, то есть ничего. На кадре это серая присыпка.
 *
 * Поэтому след пустоты рисует сам модуль, тем же примитивом, которым он
 * рисует дыру: ПЛОСКОСТЬ С АЛЬФОЙ РОВНО 1.0. Судья указал на это прямо —
 * яма статуса держит четверть своих пикселей темнее 60 там, где путь воронки
 * держит 6.7% темнее 110. Пол под шрамом не просвечивает вовсе, и тон в нём
 * виден целиком.
 *
 * ШРАМ НЕ ГАСНЕТ, А ЗАРАСТАЕТ. Затухание непрозрачного тёмного пятна ведёт
 * его через серую середину — ту самую пастель, которую §10.1 запрещает. Здесь
 * гаснет не альфа, а РАДИУС: `open` идёт от единицы к нулю, и каждый пиксель
 * до конца остаётся либо цветом стихии, либо чистым полом. Это заодно и
 * грамматика пустоты: дыра не выцветает, она затягивается.
 *
 * ШРАМ НЕ СВЕТИТСЯ ВОВСЕ. Он лежит на полу и живёт секунды: §10.1 запрещает
 * полу цвести, а широкое слабое свечение на белом — вторая ловушка того же
 * параграфа (лазер собрал ею 9233 пастельных пикселя из 13200). Ни `markGlow`,
 * ни `markDistort` здесь нет.
 *
 * Воронка `kit` остаётся ОДНА и по полному радиусу — как рваная губа вокруг
 * шрама и как общий для всех стихий вид следа; шрам кроет её до 0.92 радиуса,
 * так что светлый вал породы выходит наружу только узким кольцом.
 *
 * ЗАМЕР ПОСЛЕ ПРАВКИ, тот же кадр `cone t1.20 broadcast` против пустого пола:
 * 3086 → 4107 изменённых пикселей, средний (172,159,174) при S = 0.125 →
 * (63,42,106) при S = 0.620, темнее 60 — НОЛЬ → 903, темнее 110 — 192 →
 * 2784, в запрещённой полосе 15.4% → 4.0%. Поперечный глаз: (149,133,159)
 * S = 0.195 → (56,34,103) S = 0.680, полоса 20.6% → 2.5%.
 *
 * След удара на t = 1.20, трансляция (судья: «бледная лиловая пудра, 2.4%
 * темнее 60»): 2827/789 → 3621/3385, средний (156,146,167) S = 0.175 →
 * (50,28,104) S = 0.784, темнее 60 — 77 (2.7%) → 1079 (29.8%), полоса
 * 13.3% → 3.2%. Поперечный глаз: полоса 26.5% → 5.1%, темнее 60 — 3.0% →
 * 44.6%.
 *
 * Тот же шрам вытянул след щита (`self`, t = 0.60, трансляция): 4053/1160 →
 * 5539/5088, (166,153,177) S = 0.161 → (70,44,121) S = 0.654; и след конуса
 * на живой фазе (t = 0.30): S = 0.476 → 0.636 при полосе 14.4% → 9.1%.
 */
function scarMat(P) {
  return pooled(`void:scar:${hex(P)}`, () => {
    const m = planeMat();
    const fade = withFade(m);
    const open = uniform(1), seed = uniform(1);
    m.userData.u = { fade, open, seed };
    const q = uv().sub(vec2(0.5, 0.5)).mul(2 * SPAN);
    const d = q.length();
    const n = mx_fractal_noise_float(vec3(q.mul(2.2), seed), 3, 2.0, 0.5, 1).mul(0.5).add(0.5);
    const edge = d.add(n.sub(0.5).mul(0.5)).div(open.max(0.001));
    const inside = oneMinus(smoothstep(float(0.90), float(1.02), edge));
    /* Кромка узкая (0.86–0.96 при сердцевине, сплошной до 0.90 радиуса):
       широкая фиолетовая полоса по краю следа, живущего восемь секунд, — это
       и есть «сиреневая дымка» из шапки файла. */
    const rim = smoothstep(float(0.86), float(0.96), edge).mul(oneMinus(smoothstep(float(0.99), float(1.06), edge)));
    /* Дно ТЕМНЕЕ краёв: ровная заливка читается наклейкой, а не ямой. */
    const depth = mix(col(P[2]).mul(0.28), col(P[2]).mul(0.06), oneMinus(smoothstep(float(0.0), float(0.9), edge)));
    m.colorNode = mix(depth, spark(P).mul(0.6), rim.clamp(0, 1));
    m.opacityNode = inside.max(rim.mul(0.9)).mul(fade).clamp(0, 1);
    return m;
  }, 6);
}

/**
 * Шрам на полу: `hold` секунд держится, `close` секунд ЗАТЯГИВАЕТСЯ.
 * `rise` — секунды раскрытия (у дыры оно быстрое: она не набегает, она есть).
 */
function scar(vfx, P, { x, z, radius, hold, close = 4, rise = 0.12, seed }) {
  const m = scarMat(P);
  m.userData.u.seed.value = seed;
  const mesh = new THREE.Mesh(HOLE_GEO || (HOLE_GEO = shared(new THREE.PlaneGeometry(1, 1).rotateX(-Math.PI / 2))), m);
  mesh.position.set(x, 0.021, z);
  mesh.scale.setScalar(radius * 2 * SPAN);
  mesh.renderOrder = 3;
  mesh.frustumCulled = false;
  const LIFE = hold + close;
  vfx.spawnMesh(mesh, LIFE, (o, u) => {
    const t = u * LIFE;
    const open = t < rise ? Math.max(0.001, t / rise) : (t > hold ? Math.max(0.001, 1 - (t - hold) / close) : 1);
    m.userData.fade.value = 1;
    m.userData.u.open.value = open;
  });
}

/** След пустоты: губа воронки от `kit` плюс собственный непрозрачный шрам. */
function mark(vfx, { x, z, radius, hold, fade = 4, rise = 0.22, tint, seed, P }) {
  kit.decal(vfx, { type: 'crater', x, z, radius, hold, fade, rise, tint, seed });
  scar(vfx, P, { x, z, radius: radius * 0.92, hold, close: fade, seed: (seed % 7) + 1 });
}

