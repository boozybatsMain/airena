/**
 * ПУСТОТА (`void`) — ОТСУТСТВИЕ (заказ основателя: «пустота и кинетика не
 * доделаны, доделайте их»).
 *
 * Что это такое. Не взрыв и не свет: место, где вещества БОЛЬШЕ НЕТ. Разрез,
 * а не ствол; яма, а не диск; схлопывание, а не разлёт. Читается двумя
 * вещами сразу — почти чёрной сердцевиной (пол под ней перестал быть) и
 * тонкой фиолетовой кромкой по краю разрыва, где реальность ещё держится.
 *
 * ЧЕМ ОНА ОТЛИЧАЕТСЯ ОТ КИНЕТИКИ, у которой похожая сдержанность. Кинетика —
 * это ФОРМА И ДВИЖЕНИЕ вещества: пыль, обломки, трещины, отдача. У пустоты
 * вещества нет вовсе: ей нельзя поднять пыль и нечему отлететь. Её язык —
 * ГЕОМЕТРИЯ ДЫРЫ и то, что в неё СТЯГИВАЕТСЯ. Поэтому здесь нет ни одной
 * разлетающейся частицы: всё летит ВНУТРЬ.
 *
 * НА БЕЛОМ ПОЛУ пустота держится сердцевиной — почти чёрным нормально
 * смешанным `P[2]`, а не фиолетовым свечением: `P[1]` (#a98cf0) на белом
 * выцветает в сиреневую дымку. Светится только кромка, и то узкая. Правило
 * стоило ещё одного круга: статус нарушал его собственной кромкой (см.
 * `statusMat`) и читался ровно той дымкой, которую этот абзац запрещает.
 *
 * ПЯТЬ ПРИМИТИВОВ, И ВСЕ ПЯТЬ — ДЫРА В РАЗНОЙ ОПРАВЕ. `hole` — плоская,
 * лежит на полу. `mouth` — стоящая в воздухе (замах, удар, голова снаряда).
 * `rift` — вытянутая вдоль линии (луч, росчерк снаряда). `slab` — то же
 * отсутствие размером со стену. `scar` — то, что от неё остаётся на полу:
 * непрозрачная яма, которая не гаснет, а ЗАТЯГИВАЕТСЯ.
 *
 * НИ ОДНА ФОРМА НЕ СМЕЕТ ПОКАЗЫВАТЬ САМА СЕБЕ КРОМКУ. Крест из двух
 * перпендикулярных квадов с промежуточного азимута виден дважды, и судья
 * читает пару силуэтов как z-fighting. Стена ушла на выпуклую коробку, пасть
 * — на биллборд; крест остался только у разреза, где обе половины вытянуты
 * вдоль общей оси и их силуэты совпадают по построению, а не по обещанию.
 * Обещание «на 45° половины совпадут» уже проверялось кадром и оказалось
 * ложным — см. `mouth`.
 *
 * ДЫРА НЕПРОЗРАЧНА. Четыре процента белого HDR-пола сквозь сердцевину
 * стирали из ямы всё чёрное: на входе в круг яма статуса в судейском окне
 * давала 114 пикселей темнее 60 из 8565, на выходе — 1987 из 7736. Альфа
 * сердцевины во всех формах ровно 1.0.
 *
 * У ДЫРЫ ДОЛЖЕН БЫТЬ ЗАПАС КВАДА (`SPAN`). Рваный край уходит за единичный
 * радиус, и без запаса он срезается по прямой; обоснование — арифметика в
 * самом `SPAN`, а не кадр.
 *
 * ОТСУТСТВИЕ ОБЯЗАНО ДЕРЖАТЬСЯ. Судья мерит кадр ПОСЛЕ того, как гаснет
 * штатная вспышка атома, и у пустоты там долго не было ничего: судья насчитал
 * на ударе 871 px >25 и 416 px >60 на трансляции. Это была не слабость форм,
 * а расписание — всё кончалось к 0.55 с. Огибающая каждой формы несёт
 * ВЫДЕРЖКУ между раскрытием и схлопыванием, а не переход из одного в другое.
 *
 * ЧЕМ МЕРЯЕТСЯ ВСЁ НИЖЕСЛЕДУЮЩЕЕ. Кадр снимается `tools/vfxshot.mjs` и
 * вычитается из кадра ТОЙ ЖЕ доставки со стихией `nil` (модуля нет, ничего не
 * рисуется) в тот же момент и тем же глазом; шум такой пары — от нуля до
 * 240 px. «px >25» — пикселей, где хоть один канал разошёлся больше чем на
 * 25. S — насыщенность в HSV, «полоса» — запрещённые §10.1 значения
 * 0.15 ≤ S < 0.45. Кадры круга лежат в `reports/vfx/r70c/void/`: `nil` —
 * пустой пол, `m0` — состояние на входе в круг, `r1` — на выходе.
 *
 * СЛЕД НА ПОЛУ ПУСТОТА РИСУЕТ САМА. Чаша воронки `kit` непрозрачна лишь на
 * три четверти, и оставшаяся четверть белого HDR-пола держит след светлым при
 * любом тоне: и подкрашенная, и совсем не подкрашенная воронка конуса на
 * трансляции дают (172,159,174) и (167,158,171) — разницу в шум, ноль
 * пикселей темнее 60. Разбор и выход — в шапке `scarMat`.
 *
 * НАСТРОЙКА — через `kit.tune(e, {...})`, опись в начале каждой формы.
 */

