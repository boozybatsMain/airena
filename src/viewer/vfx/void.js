/**
 * ЧЕРНИЛА ГУБЫ ВОРОНКИ: ЗЕЛЁНУЮ ВОН, ЯРКОСТЬ НЕ ТРОГАТЬ.
 *
 * `kit` красит чашу воронки как `mix(порода, tint·0.5, 0.7)`, а вал — как
 * `mix(светлая порода, tint, 0.45)`. То есть тон входит в чашу с весом 0.35,
 * а в вал — с весом 0.45 поверх СВЕТЛОЙ породы (0.6,0.58,0.54). Отсюда
 * правило: чем ярче чернила, тем бледнее вал, и наоборот.
 *
 * Круг до прошлого выкрутил яркость (×4.0 / ×0.12 / ×4.2) и получил ловушку
 * §10.1 с другой стороны — бледно-лавандовую присыпку вместо бурого гравия.
 * Насыщенность дешевле всего поднять, ОБНУЛИВ ЗЕЛЁНУЮ, а не задирая синюю:
 * яркость тогда не растёт. При ×1.28 / ×0 / ×1.0 чаша по формуле `kit`
 * выходит около (70,50,98) — насыщенность 0.49 при яркости 98.
 *
 * ЧЕГО ЭТИ ЧЕРНИЛА НЕ МОГУТ, И ЭТО ИЗМЕРЕНО. Альфа чаши — `bowl·0.75`, и
 * четверть белого HDR-пола сквозь неё проходит при любом тоне. Кадр
 * `r2-before/cone/void-cone-t1_20-broadcast` против пустого пола: средний
 * (172,159,174), S = 0.125, темнее 60 — НОЛЬ из 3086. Судимая, совсем не
 * подкрашенная воронка на том же кадре — (167,158,171) при S = 0.110. Пять
 * единиц по красному каналу и ноль по зелёному: тон в чаше есть, а увидеть
 * его нельзя. Прошлый круг пробовал добрать вложенной второй воронкой —
 * приведённые выше числа сняты уже С НЕЙ, то есть не помогло и это.
 *
 * Поэтому чернила остались ровно тем, чем они годятся: тоном ГУБЫ вокруг
 * шрама. Тёмное держит собственный непрозрачный шрам модуля — см. `scarMat`.
 *
 * Один экземпляр на палитру, без аллокаций на каст.
 */
const INKS = new Map();
function ink(P) {
  const k = P[2].getHexString();
  let c = INKS.get(k);
  /*
   * ЗЕЛЁНЫЙ ГАСИТСЯ, А НЕ ОБНУЛЯЕТСЯ (ARENA-AAA, 06.09). Было
   * `setRGB(r · 1.28, 0, b)` — канал в ноль, и это давало #410063: оттенок
   * 279°, ЭКРАННАЯ НАСЫЩЕННОСТЬ 100 %, Lab C* 60. Не «губа шрама», а самый
   * насыщенный пиксель, какой в этом слое вообще возможен, — вдвое громче
   * кораллового баннера (C* 64 в исходнике, 47 % на кадре), единственного
   * акцента мира (ARENA-BRIEF §5). Довод выше — «губе нужен уклон в фиолет,
   * иначе тона в чаше не видно» — остаётся в силе, он просто больше не
   * оплачивается уничтожением канала: `#3E3363`, оттенок 254° против 244° у
   * самой ступени, C* 32, насыщенность 48 %. Уклон есть, крика нет.
   */
  if (!c) { c = P[2].clone().setRGB(P[2].r * 1.18, P[2].g * 0.88, P[2].b * 1.0); INKS.set(k, c); }
  return c;
}

