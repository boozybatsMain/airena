/**
 * Молния · СТАТУС — наэлектризованное тело (план §3 A9).
 *
 * Запись `status` приходит на КАЖДОЕ применение: зона подкладывает горение,
 * оглушение, корни, слепоту, немоту, усиление и ослабление каждые 0.5 с, а
 * каст `self` + `shield` кладёт `self` и `status: shield` в один тик. Поэтому
 * ОДНО ТЕЛО — ОДИН ЭФФЕКТ (§P10): карта `STATUS` по паре «тело:эффект»;
 * пришла запись на живой эффект — двигаем срок и НИЧЕГО не заводим.
 *
 * Как это выглядит. Разряды ползут ПО КАПСУЛЕ тела (`surfaceSegs`, A0.3 —
 * тот же примитив, что у щита; принцип P2), вспышками по 0.15 с каждые
 * 0.4 с: тело бьёт током, а не носит наклейку. Клетки держатся внутри
 * вспышки, между вспышками рисунок новый — это разные разряды.
 *
 * ИСКЛЮЧЕНИЕ — ГОРЕНИЕ: у него между вспышками остаётся тусклая сетка и с
 * тела капают угольки, потому что реестр обещает ШЛЕЙФ, а не удар, и потому
 * что жеста функции у горения нет (см. `SMOULDER` ниже — там замер).
 *
 * `shield` уходит в решётку щита (`self.js`): её открывает именно эта запись,
 * она же несёт длительность. Лечение, очищение и усиление — те же вспышки,
 * но реже (раз в 0.8 с) и в светлом `P[1]`: это не удар током, а подпитка.
 */

import * as THREE from 'three';
import { clamp01, mulberry, seedOf } from '../core.js';
import * as kit from '../kit.js';
import { clampN } from './util.js';
import { boltField } from './field.js';
import { restriker, arcSparks } from './common.js';
import { shield as shieldLattice } from './self.js';
import { EFFECTS } from '../../../skills/registry.js';

/** Живые статусы по паре «тело:эффект» (§P10). */
const STATUS = new Map();

/** Длительность: из записи, из реестра, иначе одноразовая вспышка. */
export const durationOf = (e) => e.duration ?? EFFECTS[e.effect]?.duration ?? 1.5;

/* Эффекты, которые бьют током, и те, что подпитывают. */
const SHOCK = new Set(['burn', 'stun', 'root', 'blind', 'silence', 'weaken']);

/*
 * ── ГОРЕНИЕ ТЛЕЕТ МЕЖДУ ВСПЫШКАМИ, А ОСТАЛЬНЫЕ СТАТУСЫ НЕТ ────────────────
 *
 * Приговор круга 3, четыре судьи из восьми независимо: «arc/status.burn
 * рисует РОВНО НОЛЬ пикселей» — диф кадров `f3-statuses/arc-status.burn-
 * t1_00-broadcast.png` и `-top.png` против пустого кадра равен нулю на ОБОИХ
 * ракурсах, при 1 707 у жара, 8 225 у мороза и 12 907 у пустоты. «Горящее
 * существо молнии не несёт ни одной метки».
 *
 * ПРИЧИНА НЕ В ТОМ, ЧТО ГОРЕНИЕ НЕ НАРИСОВАНО. Оно нарисовано и лежит в
 * `SHOCK`. Дело в СКВАЖНОСТИ: вспышка горит `FLASH` = 0.15 с раз в
 * `PERIOD` = 0.4 с, то есть тело под током 37 % времени, а 63 % — чистое. При
 * t = 1.00 окно вспышки третье (`win` = 2), его начало 0.80, фаза 0.20 —
 * больше 0.15, и `itemsAt` честно возвращает пустой список. Судья снял кадр в
 * паузу. Прочие статусы этого не показывают только потому, что у них поверх
 * есть ЖЕСТ ФУНКЦИИ из общего слоя (`effectMark` в `vfx.js`), а горению жест
 * не дан НАМЕРЕННО — значит весь его визуал держит стихия, и стихия обязана
 * что-то держать в любой момент, а не в треть моментов.
 *
 * ПОЧЕМУ ИМЕННО ГОРЕНИЮ, А НЕ ВСЕМ. Реестр называет горение «тлеющий шлейф на
 * теле цели» (`registry.js`, burn) — ШЛЕЙФ, вещь непрерывная. Оглушение
 * («кольцо над головой»), обездвиживание («скобы у ног»), немота
 * («перечёркнутый знак») — знаки мгновенные, и пауза между разрядами у них
 * часть вещества. Поэтому тлеет ровно горение: между вспышками на капсуле
 * остаётся редкая тусклая сетка, и с тела капают угольки.
 *
 * ЧТО ВЫШЛО. `reports/vfx/r5-arc-burn3`, шесть моментов (0.15 / 0.60 / 1.00 /
 * 1.50 / 2.60 / 3.80 c) на двух ракурсах, диф против пустого кадра порогом 12:
 * 790–1955 px с трансляции и 1 773–6 078 px сверху. Ни одного нуля, и полоса
 * та же, что у соседей (жар 1 707). Оглушение при этом не сдвинулось:
 * 3 104 px против прежних 3 151.
 */
const SMOULDER = new Set(['burn']);

export function status(vfx, e, P, ctx) {
  const who = e.who || 'orange';
  const dur = durationOf(e);
  if (e.effect === 'shield') return shieldLattice(vfx, e, P, ctx, dur);

  const key = `${who}:${e.effect}`;
  const live = STATUS.get(key);
  if (live && live.until > vfx.now) { live.until = vfx.now + dur; return true; }
  const entry = { until: vfx.now + dur };
  STATUS.set(key, entry);

  const seed = seedOf(e);
  const rng = mulberry(seed);
  const shock = SHOCK.has(e.effect);
  const smoulders = SMOULDER.has(e.effect);
  /* Одноразовые (лечение, очищение) живут 0.6 с — у них нет длительности ни
     в записи, ни в реестре (§P10). */
  const oneShot = e.duration == null && EFFECTS[e.effect]?.duration == null;
  /* ОПИСЬ НАСТРАИВАЕМОГО. Значения по умолчанию — сегодняшние: запись, не
     несущая поля, даёт прежний кадр (см. `kit.tune`). Срок статуса сюда не
     входит — его несёт сама запись (`durationOf`, §P10). */
  const S = kit.tune(e, {
    period: shock ? 0.4 : 0.8,   /* через сколько бьёт следующая вспышка, с */
    flash: oneShot ? 0.6 : 0.15, /* сколько горит одна вспышка, с */
    /*
     * СЕТКА ГОРЕНИЯ ГУЩЕ И ДЛИННЕЕ, И ЭТО НЕ ВКУС, А ПЛОТНОСТЬ ЛИНИИ.
     *
     * Замер по двум прогонам подряд. Первый (пол `smoulder` при прежней
     * капсуле 1.10·r и прежних 3–6 нитях по 4 звена): 220–337 px с трансляции.
     * Второй (капсула 1.45·r, 0.62·h): 380–879 px. Оба против 1 707 у жара,
     * 8 225 у мороза и 12 907 у пустоты — то есть ноль ушёл, а читаемости
     * нет. Кадр объяснил почему: четыре блуждания по 4 звена (0.96 м линии) на
     * эллипсоиде площадью около двадцати квадратов — это не сетка, это три
     * штриха над спиной, да и те выше корпуса, потому что 0.62·h поднимает
     * оболочку на четверть выше тела.
     *
     * Отсюда три числа: капсула ПО ТЕЛУ (0.50·h — эллипсоид ровно от пола до
     * макушки, а не на четверть выше), обхват 1.40·r (сетка снаружи силуэта,
     * иначе её съедает корпус) и НИТЕЙ ВДВОЕ БОЛЬШЕ, ПО СЕМЬ ЗВЕНЬЕВ: 6–10
     * блужданий по 1.8 м — около четырнадцати метров линии вместо одного.
     * Для сравнения, решётка щита (`self.js`) кладёт 18–28 нитей по 9–12
     * звеньев и даёт 15 019 px: горение обязано быть слабее щита и заметнее
     * ничего.
     */
    threads: null,                     /* нитей по капсуле; null — от радиуса тела */
    links: smoulders ? 7 : 4,          /* звеньев в одной нити */
    radius: smoulders ? 1.40 : 1.1,    /* обхват разряда, доли радиуса тела */
    height: smoulders ? 0.50 : 0.55,   /* полувысота разряда, доли высоты тела */
    dots: 6,                     /* искр на вспышку */
    smoulder: smoulders ? 0.55 : 0,  /* доля яркости МЕЖДУ вспышками */
    embers: smoulders ? 8 : 0,       /* угольков, стекающих с тела за 0.25 с */
  });
  const PERIOD = S.period;
  const FLASH = S.flash;
  const MAX = oneShot ? 0.7 : 60;

  const bs = ctx && ctx.bodyShape ? ctx.bodyShape(who) : null;
  const shape = () => {
    const b = ctx && ctx.bodyShape ? ctx.bodyShape(who) : bs;
    const p = ctx && ctx.bodyPos ? ctx.bodyPos(who) : null;
    const r = (b ? b.r : 0.9) * S.radius;
    const ry = (b ? b.h : 2.0) * S.height;
    const x = b ? b.x : (p ? p.x : e.x ?? 0);
    const z = b ? b.z : (p ? p.z : e.z ?? 0);
    return { c: [x, ry, z], r, ry };
  };

  const field = boltField(vfx, P, 700);
  /* Вспышка: своё окно каждые PERIOD секунд; сид окна входит в сид нитей,
     так что рисунок между вспышками разный, а внутри вспышки — тот же. */
  const itemsAt = (t, g) => {
    const win = Math.floor(t / PERIOD);
    const phase = t - win * PERIOD;
    const lit = phase <= FLASH;
    if (!lit && S.smoulder <= 0) return [];
    const sp = shape();
    const nFull = S.threads ?? (smoulders
      ? clampN(Math.round(4 + 4 * sp.r), 6, 10)
      : clampN(Math.round(2 + 2 * sp.r), 3, 6));
    /* Тление: нитей на пятую часть меньше, перемычек вдвое реже, сид свой —
       рисунок ползёт по телу между ударами, а не стоит наклейкой. */
    return [{
      surface: true, c: sp.c, r: sp.r, ry: sp.ry,
      n: lit ? nFull : Math.max(3, Math.round(nFull * 0.8)), links: S.links, link: smoulders ? 0.26 : 0.24,
      width: lit ? 0.019 : 0.017, bright: lit ? (shock ? 1.0 : 0.9) : 0.9,
      rungs: smoulders ? (lit ? 1.2 : 0.7) : (lit ? 0.5 : 0.35), offset: 0.04,
      seed: (seed ^ Math.imul(win * 2 + (lit ? 1 : 2), 0x9e3779b1)) >>> 0, minY: 0.06, phase: 0,
    }];
  };
  const rs = restriker(field, seed, itemsAt, 0.05);

  const g = new THREE.Group();
  g.add(field.group);
  vfx.spawnMesh(g, MAX, (o, u) => {
    const t = u * MAX;
    /*
     * УХОД ОГИБАЮЩЕЙ, А НЕ ВЫКЛЮЧАТЕЛЕМ. Здесь стояло `g.visible = false` на
     * первом кадре после `until`. Внутренний ритм разрядов тут ни при чём —
     * он и обязан быть резким, — а вот КОНЕЦ статуса обрывался.
     *
     * Рецепт был скопирован сюда от времени, пустоты и льда, и все четыре
     * копии гасли за `kit.FADE_MIN`: гейт померил у каждой РОВНО 0.222 с
     * (0.365 от 0.6) при требовании 0.30 — носитель статуса живёт 20 с.
     * Теперь рецепт один на слой (`kit.statusFade`, окно `kit.FADE_LONG` =
     * 0.85 с), и меш по-прежнему прячется только после записанного нуля.
     */
    const left = entry.until - vfx.now;
    const env = kit.statusFade(left);
    const win = Math.floor(t / PERIOD);
    const phase = t - win * PERIOD;
    /* Огибающая вспышки: мгновенный вход, спад за последнюю треть. Между
       вспышками — ПОЛ `smoulder` (у горения 0.5, у остальных 0): тело,
       которое горит, не бывает чистым ни в один кадр (см. `SMOULDER`). */
    const k = phase > FLASH ? S.smoulder : Math.max(S.smoulder, clamp01((FLASH - phase) / (FLASH * 0.4)));
    /*
     * НА УХОДЕ РИТМ ВЫКЛЮЧАЕТСЯ, И ОСТАЁТСЯ ОДНА ОГИБАЮЩАЯ.
     *
     * Пока статус идёт, клетка ДОЛЖНА биться разрядами: пауза между вспышками
     * — часть её вещества. Но если пульс продолжается и на уходе, эффект
     * кончается не затуханием, а последней вспышкой: замер гейта — путь от
     * половины уровня до нуля за 0.08 с вместо 0.21. Поэтому после `until`
     * клетка перестаёт мигать и просто гаснет — за `kit.FADE_LONG`.
     */
    field.set({ fade: (left > 0 ? k : 1) * env, hot: rs.tick(t), reach: 1, tail: 0 });
    if (env <= 0) {
      g.visible = false;
      if (STATUS.get(key) === entry) STATUS.delete(key);
      return;
    }
    g.visible = true;
    if (left <= 0) return;
    if (o.userData.win !== win && phase < FLASH) {
      o.userData.win = win;
      const sp = shape();
      arcSparks(vfx, P, { x: sp.c[0], y: sp.c[1], z: sp.c[2], n: S.dots, speed: 4, life: 0.35, r: rng, spread: sp.r });
    }
    /* УГОЛЬКИ ГОРЕНИЯ: с тела капает раз в 0.25 с, медленно и вниз. Частицы
       живут 0.5 с, то есть пауза между порциями вдвое короче их жизни — на
       теле всегда есть хоть один уголёк, каким бы ни был момент съёмки. */
    if (S.embers > 0 && (!o.userData.em || t >= o.userData.em)) {
      o.userData.em = t + 0.25;
      const sp = shape();
      arcSparks(vfx, P, {
        x: sp.c[0], y: sp.c[1] * 1.1, z: sp.c[2], n: S.embers,
        speed: 2.2, life: 0.6, size: 0.11, gravity: -3.5, r: rng,
      });
    }
  });
  rs.tick(0);
  return true;
}
