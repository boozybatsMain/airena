/**
 * Молния · ПОЛЕ РАЗРЯДОВ: материалы трёх слоёв ленты (рубашка, свечение,
 * ядро), инстансированная геометрия сегментов и генераторы нитей: ломаная
 * со смещением середин (`strandSegs`), явная ломаная (`polySegs`),
 * ПУЧОК-КЛЕТКА (`bundleSegs`) — то, чем рисуется главный разряд луча, —
 * и треск по полу: одиночный глиф (`glyphSegs`) и ковёр глифов вдоль
 * трассы (`crackleSegs`). Это единый примитив, на котором стоят все
 * доставки (см. `../arc.js`).
 *
 * Замер эталона (Storm Lance, 1280×720, ~35 px/м): нить — ядро ~2 px чисто
 * белое, ореол 6–10 px насыщенно-синий, снаружи слабое широкое свечение.
 * На трансляционной дистанции (26 м, 46°, ~41 px/м поперёк) это ядро
 * полушириной ~0.02 м и ореол в три-четыре ядра. Оба слоя — ОБЫЧНЫЙ
 * блендинг: на белом полу аддитивного не видно (§10.1), а аддитивные ядра
 * полутора десятков нитей, лёгших друг на друга с торца, складывались в
 * HDR-столб, который bloom размазывал на весь кадр. Ядро всегда лежит ПОВЕРХ
 * синего ореола — поэтому белая нить читается и на белом полу: белое на
 * синем, а не белое на белом; пересечения и клубок у цели белеют сами,
 * потому что там ядер больше, чем рубашек. Аддитивное только широкое
 * свечение — оно работает на тёмном фоне и телах.
 *
 * Замер турнира (02.09, трансляция 26 м, столб пучка 110×110 px на 0.3 с):
 * ядро (1.45,1.5,1.6) с маской^1.2 давало 72 горячих пикселя при потолке
 * 238 на полу 224 — белых нитей с трансляции не было. Теперь ядро
 * (3.5,3.7,4.1), резкий край (~2 px) и 0.15 в bloom: наложения белеют. Почему
 * так ярко: ACES прижимает 1.7 к 243 из 255, 3.5 — к 251, и горячий пиксель
 * получается из самого ядра, а не из bloom. Bloom при таком цвете — вуаль:
 * при 0.3 столб с трансляции белел целиком (замер r4: 1465 горячих, но
 * синих 1701 против нужных 2000), при 0.15 ядро остаётся нитью.
 *
 * Замер полировки r2 (03.09, боковой глаз 26 м, 0.38 с): рубашка в 4 ядра
 * с непрозрачностью от 30 % ширины при 15 нитях в трубе 1.6 м сливалась в
 * гладкий голубой рукав с белыми каракулями — «чулок». Теперь рубашка
 * 4 ядра, непрозрачна только в середине (±1.8 ядра), снаружи мягкий спад;
 * нитей меньше и они расходятся из руки не все сразу (см. `bundleSegs`):
 * между ячейками виден пол.
 */

import * as THREE from 'three';
import * as TSL from 'three/tsl';
import { TIME, col, markGlow, mulberry, pooled, withFade } from '../core.js';
import { TAU, clampN, hex, rotateAroundNormal, tangent } from './util.js';

const {
  float, vec3, vec4, uniform, mix, smoothstep, oneMinus, attribute,
  positionLocal, cameraProjectionMatrix, modelViewMatrix, cross, select, step, mx_noise_float,
} = TSL;

/* ── материалы разряда ──────────────────────────────────────────────────── */

/**
 * Множитель ширины слоя от ширины нити (полуширина ядра в метрах). Ядро
 * 0.025 м — 2 px с трансляции; рубашка 5 ядер = 0.125 м полуширины, но
 * непрозрачна только внутри ±1.3 ядра (~2.7 px синей полосы под белой
 * нитью), дальше мягкий хвост: на 2 ядрах 0.5, на 3 — 0.2, на 4 — 0.04
 * (эталон: ореол 6–10 px при ядре 2 px, с мягким краем). При 6.5 ядра и
 * при 4 с резким краем рубашки соседних нитей сливались в сплошную трубу
 * (замер r1 и r2: «чулок»); при 4 с непрозрачными ±1.8 ядра — плоская
 * двухцветная лента (замер r2.1). Свечение 8 ядер — мягкий ореол, который
 * виден только на тёмном, плюс белая искра у оси; оно рисуется ПОСЛЕ ядра
 * (порядок 11), чтобы метка свечения на пересечениях складывалась.
 */
const LAYER = {
  jacket: { mul: 5.5, order: 7, blend: THREE.NormalBlending },
  glow: { mul: 8.0, order: 11, blend: THREE.AdditiveBlending },
  core: { mul: 1.0, order: 10, blend: THREE.NormalBlending },
};

/**
 * Тёмно-синий остывшего следа. Эталон на 1.5 с: крошки (25,58,96) на
 * тёмном полу. Прежний (0.02,0.05,0.28) на белом полу давал (51,75,163) —
 * королевский синий, а не тёмно-синий (замер r2.1 с трёх глаз); линейный
 * (0.010,0.036,0.145) — это sRGB ≈ (28,54,108); на тонкой линии с подмесом
 * пола ковёр на 1.5 с меряется ≈ (33,56,120): при (0.008,0.03,0.13) выходило
 * (26,46,108) — темнее, чем просили судьи, при (0.012,0.04,0.16) —
 * (37,59,124), чуть светлее (замер r2.2 i3/i5 с верхнего глаза).
 */
/* ГРАДУИРОВКА ПОД МИР (ARENA-AAA, 06.09). Довод выше — про СВЕТЛОТУ следа, и
   она сохранена буквально (L* 23.0 было, L* 23.0 стало). Замер, которого в
   нём не было, — насыщенность: sRGB (25,53,106) — это 76 % при Lab C* 35,
   то есть королевский синий по цвету, даже если по светлоте это тёмно-синий,
   и на кадре `live-visitor.png` решётка молнии выходила самым насыщенным
   предметом арены. Полка мира — коралловый баннер (47 % на кадре); след
   прижат до 52 % / C* 19, оттенок целеё (219° → 219°). */
const NAVY = [0.021, 0.039, 0.086];

/**
 * Кольцо 6, а не 8: инструмент съёмки греет пул шестью кастами, и седьмой
 * каст (первый глаз) при кольце 8 собирал материалы на кадре спавна —
 * первый кадр опаздывал на 40–60 мс (замер r1 по `index.json`).
 */
function boltMat(layer, P) {
  return pooled(`arc:bolt:${layer}:${hex(P)}`, () => makeBoltMat(layer, P), 6);
}

/**
 * Лента сегмента. Инстанс — один сегмент (`sa` → `sb`), квад из четырёх вершин:
 * `positionLocal.x` — доля вдоль (0..1), `positionLocal.y` — поперёк (−1..1).
 * В пространстве вида квад растягивается вдоль касательной с запасом на
 * ширину (стыки соседних сегментов перекрываются, а не рвутся) и раздвигается
 * поперёк по `cross(касательная, взгляд)` — лента всегда смотрит на камеру.
 * В пикселе — капсула: расстояние до отрезка в метрах через ширину слоя.
 *
 * Атрибут `scfg` = (полуширина ядра, яркость, фаза, u вдоль). ЗНАК яркости —
 * есть ли у сегмента белое ядро: отрицательная яркость даёт метку без ядра
 * (треск по полу — сплошные синие штрихи, а не синие колечки с белой
 * серединой; замер турнира: метки с ядром читались как макароны). У метки
 * без ядра концы ПРЯМЫЕ, а не круглые: круглые концы на штрихе шириной
 * 1.5 px читались таблетками (замер r1 с бокового и низкого глаза).
 *
 * У метки без ядра МОДУЛЬ яркости выше 0.6 — её собственный жар: 1.0 —
 * только что родилась, насыщенно-синяя; 0.6 — остыла до тёмно-синего.
 * Ниже 0.6 — прозрачность (гашение). Так каждая метка остывает по своим
 * часам (родилась поздно — синяя, пока соседки уже тёмные), а не все
 * разом от униформы `cool`: эталон на 0.8 с показывает свежие синие метки
 * рядом с тёмными.
 *
 * ФАЗА (`scfg.z`) — сид мерцания ядра; фаза < 0.5 помечает НИТЬ-ЛИДЕР
 * пучка: при прорастании только у неё фронт резкий и вдвое ярче (одна
 * яркая точка лидера, эталон ref-storm-120), у остальных нитей последние
 * 18 % пути перед фронтом гаснут плавно — фронт рваный, а не стена (замер
 * r2 на 0.06–0.12 с: пучок обрывался ровной стеной).
 *
 * Униформы: `fade` — общее затухание, `hot` — вспышка перестройки (1 в
 * момент перестройки, 0 через ~35 мс: ядро ярче на треть, рубашка и
 * свечение шире на четверть), `reach` — доля пути, до которой разряд дорос
 * (при `reach` ≥ 1 всё включено), `cool` — остывание 0..1 всего поля:
 * рубашка уходит в тёмно-синий, ядро и свечение гаснут. Нить с ядром
 * остывает на треть от `cool`: пучок гаснет числом нитей, а не сереет.
 */
function makeBoltMat(layer, P) {
  const L = LAYER[layer];
  const m = new THREE.MeshBasicNodeMaterial({
    transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: L.blend,
  });
  const fade = withFade(m);
  const hot = uniform(0), reach = uniform(1), cool = uniform(0), tailU = uniform(0);
  m.userData.u = { fade, hot, reach, cool, tail: tailU };

  const a = attribute('sa', 'vec3'), b = attribute('sb', 'vec3'), cfg = attribute('scfg', 'vec4');
  const along = positionLocal.x, across = positionLocal.y;

  /* Прорастание: фронт по `reach`. Лидер (фаза < 0.5) — резкий фронт 4 %
     и вспышка ×2.5 в 12 % за ним; остальные нити гаснут в 18 % перед
     фронтом. У каждой нити пучка своё растяжение `u` (см. `bundleSegs`),
     так что нити кончаются на разной доле пути. */
  const grown = reach.greaterThanEqual(1.0);
  const leader = step(cfg.z, float(0.5));
  const win = mix(float(0.18), float(0.04), leader);
  const on = select(grown, float(1), oneMinus(smoothstep(reach.sub(win), reach, cfg.w)));
  /* Кончик лидера — ×1.5 ядра в 12 % за фронтом, рубашку почти не трогает:
     при ×2.2 ядра и рубашке ×1.3 последние полметра у цели в кадре 0.06 с
     бокового глаза были сплошной синей полосой 0.15 м (замер r2.1). */
  const tip = select(grown, float(0), smoothstep(reach.sub(0.12), reach.sub(0.03), cfg.w).mul(leader).mul(0.5));

  /* Вспышка перестройки расширяет рубашку на четверть, не на треть: при
     трети столб с трансляции менялся вдвое между кадром во вспышке и кадром
     между ними (замер r2: 1733 против 1209 синих). */
  const widen = layer === 'core' ? tip.mul(0.15).add(1) : hot.mul(0.25).add(1).mul(tip.mul(0.08).add(1));
  const W = cfg.x.mul(L.mul).mul(widen);

  const av = modelViewMatrix.mul(vec4(a, 1)).xyz;
  const bv = modelViewMatrix.mul(vec4(b, 1)).xyz;
  const seg = bv.sub(av);
  const len = seg.length();
  const tng = seg.div(len.max(1e-4));
  const pv = av.add(tng.mul(along.mul(len.add(W.mul(2))).sub(W)));
  const view = pv.negate().normalize();
  const sideRaw = cross(tng, view);
  const sl = sideRaw.length();
  const side = select(sl.greaterThan(1e-4), sideRaw.div(sl.max(1e-4)), vec3(1, 0, 0));
  m.vertexNode = cameraProjectionMatrix.mul(vec4(pv.add(side.mul(across.mul(W))), 1));

  /* Яркость: модуль — сила слоя, знак — есть ли ядро. */
  const bright = cfg.y.abs(), withCore = step(float(0), cfg.y);
  /* Расстояние до отрезка в пикселе: за концами растёт, поперёк — по ширине;
     всё в метрах, делённых на ширину слоя. Нить — капсула (стыки звеньев
     круглые), метка без ядра — прямой срез. */
  const lenW = b.sub(a).length();
  const alongM = along.mul(lenW.add(W.mul(2))).sub(W);
  const dEnd = alongM.negate().max(alongM.sub(lenW)).max(0);
  const dAcross = across.abs().mul(W);
  const dRound = dEnd.mul(dEnd).add(dAcross.mul(dAcross)).sqrt();
  const dBox = dEnd.max(dAcross);
  const d = mix(dBox, dRound, withCore).div(W.max(1e-4));
  const mask = oneMinus(d).clamp(0, 1);
  /* Мерцание ~25 Гц от часов: нить живёт между перестройками, а не стоит.
     Глубина — 15 % ядра: при 50 % белые нити половину времени были
     голубыми, и число горячих пикселей в столбе прыгало 66–766 от кадра к
     кадру в зависимости от того, попал ли кадр во вспышку перестройки
     (замер r2); у эталона ядра ровно белые. */
  const flick = mx_noise_float(vec3(TIME.mul(23.0), cfg.z.mul(7.3), 0.7)).mul(0.5).add(0.5);
  /* ШТРИХ, ЛЕТЯЩИЙ НА КАМЕРУ, НЕ РИСУЕТСЯ. Штрихи (`u` ≥ 1.5 — флаг
     `streakItems`) — отрезки в метр длиной; тот, что летит вдоль взгляда,
     проецируется в столбик 0.3–0.5 м и с бокового глаза стоял «флагштоком»
     у кольца прицела (4–5 штук в кадре 0.38, замер r2.1). Укорочение —
     длина проекции отрезка в плоскости вида к его длине в мире; целым
     остаётся штрих, лежащий поперёк взгляда (≥ 0.9), ниже 0.72 гаснет.
     Порог высокий не зря: боковой глаз смотрит вниз под 26°, и штрих,
     летящий на него с подъёмом 15°, проецируется в 0.66 своей длины —
     ВЕРТИКАЛЬНОЙ палкой в 0.85 м (замер r2.2 i1 при порогах 0.4–0.65).
     Порог СТУПЕНЬКОЙ на 0.8, а не плавный: полупрозрачный синий штрих на
     белом полу — серо-сиреневый брусок (замер r2.2 i4 с верхнего глаза при
     переходе 0.72–0.9); направление штриха за жизнь не меняется (тяжести
     нет), так что ступенька не мигает. Метки на полу (`u` ≤ 1) не трогаем. */
  const isStreak = step(float(1.5), cfg.w);
  const fore = seg.xy.length().div(lenW.max(1e-4));
  const keep = mix(float(1), step(float(0.8), fore), isStreak);
  /* ХВОСТ (A0.1, план §3): нижняя граница освещённого окна. Разряд стоит в
     пространстве целиком, а горит только полоса `tail`..`reach` вдоль пути —
     из этого и складывается болт с НЕПОДВИЖНЫМ НАЧАЛОМ (P1): голова растёт
     вперёд, хвост отпускает руку. Растушёвка 0.08 доли пути (у болта 9 м это
     0.7 м): резкий срез читался обрубленной палкой с бокового глаза.
     `tail` ≤ 0 — окно выключено, светится всё; так ведут себя луч, конус,
     зона и второе (головное) поле. */
  const onTail = select(tailU.lessThanEqual(0), float(1), smoothstep(tailU, tailU.add(0.08), cfg.w));
  const base = fade.mul(on).mul(keep).mul(onTail);
  /* Остывание: у нити с ядром — треть от униформы; у метки без ядра — ещё
     и собственный жар из модуля яркости (1.0 → 0.6 = синяя → тёмно-синяя). */
  const heat = smoothstep(float(0.6), float(1.0), bright);
  const coolSeg = oneMinus(withCore).mul(oneMinus(heat));
  const coolK = cool.mul(oneMinus(withCore.mul(0.7))).add(coolSeg).clamp(0, 1);
  const live = oneMinus(coolK);

  if (layer === 'core') {
    /* Ядро — ОБЫЧНЫЙ блендинг, а не аддитивный. С трансляции пучок смотрит
       на камеру торцом, и полтора десятка нитей ложатся друг на друга: в
       аддитиве они складывались в HDR-столб, а bloom радиуса 0.85 размазывал
       его вуалью на весь кадр (снято в первом раунде). Белое поверх синего
       не складывается дальше белого; в bloom уходит малая доля — там, где
       ядра легли друг на друга, кадр белеет, как у эталона. */
    /* Край ядра РЕЗКИЙ (smoothstep 0.15→0.7 маски): мягкий край ^0.9 клал
       полупрозрачное белое на рубашку, и пиксели выходили ни белыми, ни
       синими — бледно-голубыми (замер r3: 116 горячих и 1831 синих в столбе
       против нужных 300 и 2000). Резкое ядро — либо белый пиксель, либо синий. */
    m.colorNode = mix(col(P[0]).mul(1.1), vec3(3.5, 3.7, 4.1), smoothstep(float(0.1), float(0.6), mask));
    const alpha = smoothstep(float(0.15), float(0.7), mask).mul(base).mul(bright).mul(withCore).mul(live)
      .mul(flick.mul(0.15).add(0.85)).mul(hot.mul(0.3).add(1.0)).mul(tip.add(1)).clamp(0, 1);
    m.opacityNode = alpha;
    /* В bloom — 0.15 у рядовой нити (больше — вуаль на столбе с трансляции,
       замер r4), но клубок и сходящиеся к удару нити (яркость 1.15–1.3)
       цветут сильнее: дальний конец — самое белое место (эталон ref-storm-380/800). */
    const heroG = smoothstep(float(1.02), float(1.25), bright);
    return markGlow(m, alpha.mul(heroG.mul(0.35).add(0.15)));
  }
  if (layer === 'glow') {
    /* Без вспышки лидера: аддитивное свечение на белом полу даёт сиреневый
       кант, и удвоенное у фронта красило лидера в лиловый (замер r2). */
    /* Слой рисуется ПОСЛЕ ядра (порядок 11): ядро с обычным блендингом
       пишет метку свечения поверх всего, что легло раньше, и два ядра на
       пересечении светились не ярче одного. Аддитивная белая искра у самой
       оси (±0.4 ядра) поверх ядра складывается: на пересечениях и в клубке
       метка свечения удваивается — там кадр белеет, как у эталона. Доля
       искры растёт с яркостью сегмента: рядовая нить +0.04, герой +0.15,
       клубок и сходящиеся нити +0.35 (при 0.5 у всех столб с трансляции
       шёл вуалью, замер r4). Искра лежит СТРОГО под непрозрачной частью
       ядра (±0.3 ядра, маска свечения > 0.96): при ±0.8 ядра она красила
       полупрозрачную юбку ядра, и весь пучок с бокового глаза белел жгутом
       (замер r2.2 i1). */
    const a1 = mask.pow(2.0).mul(0.1).mul(base).mul(bright).mul(live).mul(hot.mul(0.6).add(0.8));
    const inner = smoothstep(float(0.96), float(1.0), mask);
    const heroG = smoothstep(float(1.02), float(1.25), bright);
    const a2 = inner.mul(heroG.mul(0.31).add(0.04)).mul(withCore).mul(base).mul(live).mul(hot.mul(0.4).add(1));
    const alpha = a1.add(a2).clamp(0, 1);
    const blueC = mix(col(P[2]), col(P[1]), mask.pow(2.0).mul(0.5));
    m.colorNode = blueC.mul(a1).add(vec3(1.0, 1.0, 1.1).mul(a2)).div(alpha.max(1e-4));
    m.opacityNode = alpha;
    return markGlow(m, a1.mul(0.1).add(a2.mul(0.9)));
  }
  /* Рубашка: насыщенно-синяя, непрозрачная в середине, мягкий спад снаружи;
     мерцание её не трогает — форма стоит, пока мигает ядро. Именно она
     держит молнию на белом полу. Остывая, уходит в тёмно-синий и перестаёт
     светиться. Середина светлеет к P[1] чуть сильнее под ядром. */
  /* Цвет рубашки почти ровный: светлеет к P[1] лишь на 10 % под самым
     ядром — две полосы разного синего и делали ленту «двухцветной». */
  const liveC = mix(col(P[2]).mul(0.9), mix(col(P[2]), col(P[1]), withCore.mul(0.1).add(0.06)), mask.pow(3.0));
  m.colorNode = mix(liveC, vec3(...NAVY), coolK);
  /* Прозрачность рубашки НАСЫЩАЕТСЯ по яркости: от 0.6 она уже непрозрачна.
     Иначе градиент яркости ядра вдоль пути и любая огибающая метки давали
     полупрозрачную синюю ленту, сквозь которую белел пол, — сиреневую
     (замер r1: метки на 1.2 с (89,113,207) при цвете рубашки, который на
     непрозрачной ленте даёт (40,110,215)). */
  const sat = smoothstep(float(0.0), float(0.6), bright);
  /* Профиль поперёк — ДВА, по знаку яркости. Нить с ядром: непрозрачно при
     маске > 0.55 (±1.8 ядра от оси, ~3.7 px синего под белой нитью с
     трансляции), дальше спад ~маска^2.2 к нулю на краю (4 ядра): у каждой
     нити свой ореол, и между нитями виден пол. Резкий край от 0.3 маски (r1)
     сливал соседние рубашки в рукав; при непрозрачных ±1 ядре (r2, первая
     итерация) нити читались проволокой: 168 горячих / 1018 синих в столбе
     против нужных 300 / 2000. Метка без ядра (треск 0.0055 м, штрихи): у
     неё непрозрачная зона ±1.8 ядра — это 0.4 px, и мягкий профиль давал
     полупрозрачную бледно-сиреневую крошку вместо тёмно-синей (замер r2 на
     1.5 с); ей — сплошной штрих от 45 % маски. */
  /* r2.2: рубашка 5.5 ядра, непрозрачна в ±1.65 ядра (маска > 0.7), дальше
     МЯГКИЙ хвост (маска/0.7)^2.2 × 0.55: на 2.2 ядрах от оси 0.39, на 2.75 —
     0.26, на 3.85 — 0.085, на 4.4 — 0.035: видимый ореол ±3.7 ядра ≈ 7.5 px
     с трансляции (эталон: синий ореол 6–10 px вокруг ядра 2 px). Прежний
     профиль (непрозрачно ±1.8 ядра, спад маска^2.2 к 4 ядрам) читался
     плоской двухцветной лентой с жёстким краем: медиана рубашки
     (121,152,232) против (66,139,224) у эталона (замер r2.1); ±1.3 ядра с
     хвостом к 5 (i1–i2) — белым жгутом, синего вокруг ядра было 0.35 px. */
  /* r3 (03.09): хвост рубашки 0.8 по маске^1.7 вместо 0.55 по ^2.2. ШИРИНА
     ТА ЖЕ (слой 5.5 ядра) — меняется только непрозрачность того, что уже
     нарисовано: на 2.2 ядрах от оси 0.55 вместо 0.39, на 2.75 — 0.40 вместо
     0.26, на 3.85 — 0.16 вместо 0.085. Замер: судья мерил долю насыщенно-
     синих пикселей в коробке луча — 7059 из 40000 против 17045 из 54400 у
     эталона; ореол был нужной ширины, но настолько прозрачным, что на белом
     полу выцветал в бледно-голубой. Расширять слой нельзя (рукав, замер r1);
     делать уже нарисованное непрозрачным — можно. */
  const tail = mask.div(0.7).clamp(0, 1).pow(1.7).mul(0.8);
  const soft = mix(tail, float(1), smoothstep(float(0.6), float(0.72), mask));
  const hard = smoothstep(float(0.0), float(0.45), mask);
  const solid = mix(hard, soft, withCore).mul(mix(float(1.0), float(0.95), withCore));
  const alpha = solid.mul(base).mul(sat).mul(tip.mul(0.1).add(1)).clamp(0, 1);
  m.opacityNode = alpha;
  return markGlow(m, alpha.mul(0.08).mul(live));
}

