/**
 * КИСЛОТА (`acid`) — РАЗЪЕДАНИЕ (план §6.4).
 *
 * Что это такое. Жидкое, глянцевое, болезненно жёлто-зелёное. Струи и брызги
 * капель, ложащиеся глянцевыми лужами с тёмным мокрым ободом, пузыри,
 * поднимающиеся и лопающиеся, тонкие жёлто-зелёные пары, капли, стекающие с
 * разъеденного тела, и шипение там, где они падают. Ярко там, где жидкость
 * толстая, темно у мокрого края (это и есть цвет пола, P3). Ничто не искрит.
 *
 * ПЛЁНКА — СЛЕД, БЛИК — ЧАСТИЦЫ, И НАОБОРОТ БЫЛО НЕЛЬЗЯ. Здесь долго лежал
 * КОВЁР: лужу рисовала россыпь тёмно-зелёных точек поверх бледного следа.
 * Замер 04.09 (зона, t = 1.5 с, глаз `top`, разница с чистой плитой) показал,
 * во что это обходится: 64.5 % пикселей следа бесцветны, средняя
 * насыщенность 0.109 — на белом полу полупрозрачная тёмная точка читается
 * серым крапом, и лужа выглядела лишайником, а не жидкостью. Теперь ролями
 * поменялись: СПЛОШНУЮ ПЛЁНКУ держит след (см. `puddle`), а частицы стали её
 * БЛИКОМ — светлые, короткие, мерцающие третями (см. `sheen`).
 *
 * ЦЕНА В КОЛЬЦЕ СЛЕДОВ. Их 28 на тип на всю арену, и судья первого круга
 * справедливо посчитал это ценой обхода: зона брала ПЯТЬ. После того как
 * ведущий прижал шум формы `acid` к краю (`kit.js`, 04.09), латать середину
 * наложением больше не нужно, и сбор пересобран: зона ТРИ (было пять), навес
 * три, щит три, болт три плюс метка попадания (было один), удар два (был
 * один), конус пять — столько же, сколько было. Считать надо не только
 * слоты, но и время: самая долгоживущая метка кислоты сократилась с 5.5 до
 * 4.3 с, а метка зоны — с 5.5 до 4.0 с (гейт `checkdecay`; кислота ушла из
 * восьмёрки самых длинных хвостов дерева, где стояла первой строкой), и
 * произведение «слоты × жизнь» по всем формам упало с 79 до 60
 * слот-секунд, а по одной зоне — с 27.5 до 12.0. Три
 * одновременные зоны занимают девять слотов из двадцати восьми вместо
 * пятнадцати: выселять старые лужи щелчком стало нечем. Лужа по-прежнему
 * кладётся ПЕРВОЙ — иначе её вытеснит собственный блеск.
 *
 * НАСТРОЙКА. Все размеры, направления и времена идут через `kit.tune(e, {…})`:
 * опись в начале каждой формы — это и есть список того, что можно крутить, а
 * значения по умолчанию равны сегодняшним числам, так что запись без полей
 * даёт прежний кадр. Исключения названы на месте: баллистика капель конуса и
 * болта, дальность и скорость струи и навеса, окно слива и стойкость следа
 * зоны исправлены по замечаниям судей — они и раньше были неверны, просто
 * числом.
 *
 * ПРОЯВЛЕНИЕ ЛУЖИ. `kit.decal` научился фазе входа (`rise`, у типа `acid` —
 * 0.90 с): жалоба основателя была именно на то, что след «появляется почти
 * мгновенно и очень резко». Здесь `rise` идёт от РАЗМЕРА пятна: разлив зоны
 * (3 м) набегает 1.6 с, лужа разбитой колбы — 1.4 с, лужа конуса — 0.9 с,
 * брызги с тела и крылья конуса — полсекунды. Большая лужа растекается,
 * капля шлёпается.
 *
 * СКОЛЬКО ЛУЖА ЛЕЖИТ. Заказ основателя 04.09: «эффект сработал — лужа пусть
 * исчезает сразу после эффекта, не моментально, а постепенно». Прежние 20 с
 * стойкости в четырёх формах нарушали это грубее всех в модуле: болт льётся
 * четверть секунды, а пятно после него лежало восемьдесят его длительностей.
 * Теперь выдержка равна ЖИЗНИ СВОЕЙ ФОРМЫ. У зоны это её `duration` —
 * `decalHold: null`, ровно тот приём, на который время перешло после той же
 * жалобы (см. time.js, шапка перед `zone`: «стойкость каждого теперь равна
 * собственной длительности своей формы»). У мгновенных форм (конус, болт,
 * навес, удар) переживать нечего: там выдержка — короткий ОСТАТОК события,
 * 1.3–2.0 с, ровно столько, сколько летят и садятся последние капли плюс
 * полсекунды блеска.
 *
 * УХОД БЫЛ САМЫМ ДОЛГИМ НА АРЕНЕ (1.8–2.5 с) — И ЭТО БЫЛА ОШИБКА. Довод
 * звучал красиво: ожог гаснет, изморозь тает, а лужа СТЕКАЕТ, значит ей
 * положен долгий хвост. Кадр его опроверг. Судья второго круга по
 * acid-zone-t4_00-top: 10 169 изменённых пикселей, из них 95.5 % с
 * насыщенностью ниже 0.10 — «бледно-серая пятнистая грязь под ногами».
 * Арифметика простая и от неё не уйти: пол арены (224,223,221), и зелень при
 * малой альфе смешивается с ним в СЕРОЕ всегда. Значит долгий уход не может
 * выглядеть «стеканием» — он ровно столько времени выглядит грязью. Уход
 * стал коротким (1.0–1.5 с, вдвое-втрое выше `kit.FADE_MIN` = 0.6 и по
 * полиному 3t²−2t³ с нулевой производной на обоих концах), а ИСЧЕЗАЕТ лужа
 * площадью: слои сохнут по очереди, пятно съёживается к мокрому ядру и
 * пропадает. Обе величины остаются ручками `decalHold` и `decalFade`.
 *
 * БЛЕСК ХОДИТ ЗА СЛЕДОМ. Блестеть дольше, чем лежит лужа, ему нельзя: он и
 * есть блеск лужи, и после ухода следа на полу остались бы зелёные точки —
 * «исчезло» не выполнено. Поэтому `carpetHold` каждой формы опущен до её
 * выдержки (было 4–8 с), а у зоны блеск смолкает ровно с её концом
 * (`carpetAfter` 0).
 *
 * И КРАЙ ЛУЖИ ОТСТУПАЕТ. Замер 04.09: с 1.5 до 4.0 с площадь следа зоны
 * упала всего на 7 % (66 323 → 61 910 пикселей), рамка не сдвинулась вовсе, а
 * разница с полом упала вдвое — лужа не стекала, она РАВНОМЕРНО ВЫЦВЕТАЛА в
 * серое, оставаясь прежнего размера. Теперь внешняя плёнка (самая тонкая)
 * держится долей `edgeHold` от выдержки и уходит первой, средняя — на
 * полпути, ядро — полную: лужа СЪЁЖИВАЕТСЯ к мокрому ядру, как настоящая.
 *
 * ── КРУГ ПРИЁМКИ 04.09 (71 ИЗ 100): ЛУЖУ НЕ НАЗВАЛИ КИСЛОТОЙ ────────────
 *
 * Судья различимости не нашёл на кадре боя ни одной метки, которую можно
 * приписать этой стихии, и был прав дважды. Первое: лужа читалась ЛИШАЙНИКОМ
 * — пятнистая зелень без границы, без блеска, без единого признака мокрого;
 * от выпадения радиации её отделял только тон. Лечение — три приметы
 * жидкости, которых у неё не было: мениск, ползущий блеск и КРУГИ по
 * поверхности (`glossMat`, `ripple`; там же замеры). Второе: единственная
 * зелень в том кадре лежала ЗА КРАЕМ АРЕНЫ — и это была не зона, а лужа
 * болта, которую ставили в 0.86 ПРЕДЕЛЬНОЙ дальности умения вместо
 * расстояния до цели (`aimedRange`, там же разбор кадра по времени).
 * Третье, найденное попутно и не судьями: посадка навеса срабатывала не
 * каждый раз — окно после прилёта было 0.1 с при жизни носителя 0.87 (см.
 * `lob`).
 *
 * Формы: конус (брызги веером), навес (колба), зона (лужа), болт (струя),
 * щит (плёнка на себе) — плюс удар, статус, заряд и стена (§P6). Щита нет в
 * реестре кислоты; почему он всё-таки написан — в шапке перед `self`.
 */

import * as THREE from 'three';
import * as TSL from 'three/tsl';
import { TIME, clamp01, col, markGlow, mulberry, pooled, seedOf, shared, withFade } from './core.js';
import * as kit from './kit.js';
import { EFFECTS } from '../../skills/registry.js';

const {
  float, vec2, vec3, uv, uniform, mix, smoothstep, oneMinus, abs: tabs,
  normalView, positionViewDirection, mx_noise_float, mx_fractal_noise_float, normalLocal,
  sin: tsin,
} = TSL;

const TAU = Math.PI * 2;
const clampN = (v, a, b) => Math.min(b, Math.max(a, v));
const hex = (P) => P.map((c) => c.getHexString()).join();

/* ── стеклянная колба ───────────────────────────────────────────────────── */

/** Копия строения `wellMat` гравитации, но нутро — `P[1]`, а блик белый. */
function flaskMat(P) {
  return pooled(`acid:flask:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.FrontSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    m.userData.u = { fade };
    const fres = oneMinus(tabs(TSL.dot(normalView, positionViewDirection))).clamp(0, 1);
    const rim = fres.pow(2.2);
    /* Зеркальная точка: узкий блик на «верхней» стороне модели. */
    const spec = smoothstep(float(0.55), float(0.9), normalLocal.y.add(normalLocal.x.mul(0.4)));
    m.colorNode = mix(mix(col(P[1]), col(P[2]).mul(0.7), rim), vec3(2.4, 2.6, 2.2), spec.mul(0.8));
    const alpha = mix(float(0.8), float(1.0), rim).mul(fade).clamp(0, 1);
    m.opacityNode = alpha;
    return markGlow(m, spec.mul(0.4).mul(fade).clamp(0, 1));
  }, 4);
}

let FLASK_GEO = null;
function flask(P, r) {
  if (!FLASK_GEO) FLASK_GEO = shared(new THREE.IcosahedronGeometry(1, 3));
  const m = flaskMat(P);
  const mesh = new THREE.Mesh(FLASK_GEO, m);
  mesh.frustumCulled = false;
  mesh.renderOrder = 9;
  mesh.scale.setScalar(r);
  return { mesh, set(fade) { m.userData.fade.value = fade; } };
}

/* ── плёнка на своём теле ───────────────────────────────────────────────── */

/**
 * ПЛЁНКА ЩИТА. Соседка колбы по строению (френель), но противоположная ей по
 * замыслу: колба — предмет, её надо ВИДЕТЬ, а плёнка облегает бойца, и его
 * силуэт обязана оставить читаемым. Отсюда две вещи.
 *
 * ПЕРВАЯ: непрозрачность идёт ТОЛЬКО по касательной. В лоб — 0.10, по
 * кромке — 0.52. Урок здесь чужой и свежий: судья снял гравитации балл за
 * ядро, которое «съедает силуэт жертвы целиком», и был прав — под эффектом
 * должно быть видно, кто под ним стоит, это боевая информация.
 *
 * ВТОРАЯ: белого нет нигде. У колбы в блике стоит `vec3(2.4, 2.6, 2.2)` —
 * HDR-белый, и для стеклянного предмета это верно. Здесь тот же приём дал бы
 * ровно то бело-кремовое зарево, за которое штатный щит и получил замечание.
 * Вся палитра плёнки — между `P[2]` (тёмная зелень в лоб) и `P[1]` (яркая
 * по кромке); ярче `P[1]` не светится ничто.
 *
 * ПОТЁКИ. Кислота на теле СТЕКАЕТ, и это единственное её движение: шум по
 * долготе, ползущий вниз по времени (`TIME·0.5` вычитается из локальной Y).
 * Без него плёнка была бы крашеным пузырём.
 */
function coatMat(P) {
  return pooled(`acid:coat:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    m.userData.u = { fade };
    const fres = oneMinus(tabs(TSL.dot(normalView, positionViewDirection))).clamp(0, 1);
    const rim = fres.pow(2.4);
    const runs = mx_noise_float(vec3(
      normalLocal.x.mul(7.0), normalLocal.y.mul(2.2).sub(TIME.mul(0.5)), normalLocal.z.mul(7.0),
    )).mul(0.5).add(0.5);
    const drip = smoothstep(float(0.55), float(0.86), runs);
    m.colorNode = mix(col(P[2]), col(P[1]), rim.mul(0.75).add(drip.mul(0.25)).clamp(0, 1));
    m.opacityNode = mix(float(0.10), float(0.52), rim).add(drip.mul(0.16)).mul(fade).clamp(0, 1);
    /* Свечение — шёпот по кромке и только зелёное: пол под щитом не имеет
       права стать источником света (§10.1), а тело — тем более. */
    return markGlow(m, rim.mul(0.14).mul(fade).clamp(0, 1));
  }, 4);
}

function coat(P, r) {
  if (!FLASK_GEO) FLASK_GEO = shared(new THREE.IcosahedronGeometry(1, 3));
  const m = coatMat(P);
  const mesh = new THREE.Mesh(FLASK_GEO, m);
  mesh.frustumCulled = false;
  mesh.renderOrder = 8;
  /* Не шар, а НИЗКИЙ купол: боец шире, чем высок, и сфера по его радиусу
     висела бы над головой пузырём. */
  mesh.scale.set(r, r * 0.82, r);
  return { mesh, set(fade) { m.userData.fade.value = fade; } };
}

/* ── капли, блеск, шипение, пары ────────────────────────────────────────── */

/**
 * Одна капля: штрих, вытянутый по скорости, с тяжестью. Возвращает МЕСТО И
 * МОМЕНТ ПАДЕНИЯ — по ним потом блестит и шипит.
 */
function droplet(vfx, P, { x, y, z, vx, vy, vz, rng, at = 0 }) {
  const tLand = (vy + Math.sqrt(vy * vy + 2 * 9 * Math.max(0.02, y))) / 9;
  const emit = (pool, colour, tail, size) => pool.emit(1, (i, s) => {
    s.pos(x, y, z);
    s.vel(vx, vy, vz);
    s.gravity(0, -9, 0);
    s.color(colour, tail);
    s.life(vfx.now + at, tLand, size, kit.SHAPE.streak);
    s.ext(0, 0.9, 1, 0.5);
  });
  emit(vfx.glow, P[1], P[1], 0.1 + rng() * 0.06);
  emit(vfx.body, P[2], P[2], 0.11 + rng() * 0.07);
  return { x: x + vx * tLand, z: z + vz * tLand, t: at + tLand };
}

/**
 * БЛЕСК ЛУЖИ. `landed` — список посадок; на каждой время от времени
 * вспыхивает короткий светлый блик.
 *
 * ПОЧЕМУ ЭТО БОЛЬШЕ НЕ КОВЁР. Раньше здесь лежал ковёр: точка `P[1]` →
 * `P[2]·0.8` (то есть от зелёного к ТЁМНО-зелёному) жила 1.4–1.8 с и
 * переиздавалась каждые 0.7 с — лужа была не плёнкой, а НАРИСОВАНА точками.
 * На белом полу такая точка при своей полупрозрачности даёт серо-зелёный
 * крап, и это померено: зона, t = 1.5 с, глаз `top`, замер по разнице с
 * чистой плитой — с ковром средняя насыщенность следа 0.109 и 64.5 %
 * пикселей бесцветны (насыщенность < 0.10), без ковра 0.132 и 43.3 %.
 * Ковёр не рисовал лужу, он её ОБЕСЦВЕЧИВАЛ — и он же оставался крапом на
 * полу, когда плёнка уже стекла.
 *
 * Теперь точка — БЛИК НА ПОВЕРХНОСТИ: цвет идёт от бледного `P[0]` к
 * зелёному `P[1]` и не имеет тёмного конца вовсе, значит и высохнуть в серое
 * ему нечем. На голом белом полу бледный блик почти не виден — и это
 * правильно: блестеть обязана жидкость, а не пол. Форму лужи держит след
 * `acid` (см. `puddle` ниже), блик только показывает, что она мокрая.
 */
function sheen(vfx, P, landed, hold, rng) {
  if (!landed.length) return;
  const emitDot = (l, k) => vfx.body.emit(1, (i, s) => {
    s.pos(l.x, 0.045, l.z);
    s.vel(0, 0, 0); s.gravity(0, 0, 0);
    /* Бледный → зелёный. Тёмного конца нет: серому взяться неоткуда. */
    s.color(P[0], P[1]);
    /* Блик короткий (0.5–0.8 с) и мелкий: он мерцает, а не лежит. Прежние
       1.4–1.8 с при такте 0.7 с держали на полу постоянный слой точек. */
    s.life(vfx.now, 0.5 + rng() * 0.3, (0.08 + rng() * 0.06) * k, kit.SHAPE.dot);
    /* Конечный размер 0.3: блик СХОДИТ на нет, как высыхающая капля. */
    s.ext(0, 0.3, 0, 0.12);
  });
  const born = new Set();
  let next = 0, tick = 0;
  vfx.spawnMesh(new THREE.Group(), hold, (o, u) => {
    const t = u * hold;
    const left = hold - t;
    /* Блеск сходит РАНЬШЕ плёнки: последнюю секунду лужа уже стекает, и
       мокрого зеркала на ней нет. Множитель идёт в размер, а не в жизнь, —
       блик должен мельчать, а не мигать всё реже. */
    const k = left < 1.0 ? Math.max(0.25, left) : 1;
    /* РАЗЛИВ. Пятно вспыхивает ровно в свой срок `l.t`, и проверка идёт
       каждый кадр, а не по такту: разбег точек по расстоянию (см. `zone`)
       иначе схлопнулся бы в ступени по такту и разлив читался бы рывками. */
    for (let i = 0; i < landed.length; i++) {
      if (!born.has(i) && t >= (landed[i].t || 0)) { born.add(i); emitDot(landed[i], k); }
    }
    /* Последние 0.35 с ничего не зажигаем: иначе блик пережил бы носитель. */
    if (t < next || left < 0.35) return;
    next = t + 0.22;
    /*
     * ТРЕТЯМИ, А НЕ ВСЕ РАЗОМ. Блик живёт 0.5–0.8 с; если переиздавать весь
     * список одним тактом, вся поверхность гаснет и зажигается вместе —
     * лужа ПУЛЬСИРУЕТ. Каждый такт (0.22 с) зажигается своя треть, полный
     * оборот — 0.66 с, чуть дольше жизни блика: горит всегда около двух
     * третей точек, и это каждый раз другие две трети. Мерцание — это то,
     * чем мокрая поверхность отличается от крашеной.
     */
    const ph = (tick++) % 3;
    for (let i = ph; i < landed.length; i += 3) if (born.has(i)) emitDot(landed[i], k);
  });
}

