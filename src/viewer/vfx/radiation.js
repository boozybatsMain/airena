/**
 * `domeMat` — нормально смешанная сфера: рубашка `P[2]·0.8` при 0.8 по краю
 * (она держит форму на белом полу), под ней аддитивный ободок `P[1]` при 0.6
 * с bloom 0.4 ТОЛЬКО по краю, нутро `P[1]` при `0.08 + 0.06·sin(TIME·9.4)` —
 * это и есть пульс около 1.5 Гц; `markDistort` шумом при 0.25 — дрожь.
 * ВАЖНО: пульс живёт в АЛЬФЕ И ЦВЕТЕ, а не в bloom: светящийся пол дал бы
 * вуаль во весь кадр (§10.1).
 *
 * ПЛОТНОСТЬ МАРЕВА — ЖИВАЯ РУЧКА (`veil`), И ВОТ ПОЧЕМУ.
 *
 * Один и тот же купол работает в трёх разных ролях. У замаха (`charge`) это
 * ТЕЛЕГРАФ: шар в руке обязан быть плотным, иначе судья видит «слабый
 * оттенок в тени ноги». А над зоной тот же купол — «дрожь воздуха», и
 * сверху, где смотрят с верхнего глаза, зритель глядит сквозь полюс, где
 * френель мал: наружу выходит РОВНОЕ нутро `0.08–0.14` на весь диск, то есть
 * жёлтая плёнка радиусом 2.7 м. Замер моих кадров «до» (зона, верх, 1.50 с):
 * самая большая связная клякса слабой подкраски — 42 636 пикселей при 46 %
 * заполнения своего круга; на трансляции на 0.40 с чистого пола внутри следа
 * оставалось 12 %. Это и есть «читается лужей».
 *
 * ПЛОТНОСТЬ 0.4 → 0.26 У ЗОНЫ (круг 6). Замер по коробке ног бойца
 * (трансляция, зона 1.50 с, рамка x736..850 y530..590 против чистой плиты):
 * у кадра, который судил судья, 2 353 изменённых пикселя при среднем сдвиге
 * 37.3 уровня — то самое «ноги залиты сплошным болотным тоном». Кромку я
 * прижал (см. `edge`), но плёнку держит и вторая половина формулы, `inner`,
 * а её множит именно `veil`. Дрожь воздуха при этом НЕ страдает:
 * `markDistort` идёт мимо этой ручки — ровно затем она такой и сделана.
 *
 * Одна униформа вместо второго шейдера: материал берётся из пула по ключу,
 * ключ трогать нельзя (иначе на стихию заводится вторая компиляция), а
 * `fade` уже живёт живой униформой ровно так же. `veil` множит альфу и
 * свечение — но НЕ искажение: дрожь воздуха обязана остаться, когда плёнка
 * ушла, она-то и есть то, что не умеет ни кислота, ни лёд.
 */
function domeMat(P) {
  return pooled(`rad:dome:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.FrontSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    const veil = uniform(1);
    /*
     * КРОМКА — ТОЖЕ ЖИВАЯ РУЧКА, И ВОТ ПОЧЕМУ.
     *
     * Судья круга 6 (`radiation-zone-t1_50-broadcast.png`, увеличено в
     * `scratchpad/body-bc.png`): «ноги и низ корпуса залиты сплошным болотным
     * тоном». Я искал эту краску в крупинках и в следе, а нашёл ЗДЕСЬ: купол
     * зоны — сплюснутый эллипсоид (2.7 м поперёк, 1.4 м вверх), и с
     * трансляционной камеры его СИЛУЭТ — то место, где `rim → 1`, — ложится
     * широкой полосой у самого пола, ровно поперёк ног бойца. Цвет там
     * `P[2]·0.8`, то есть болото, а альфа 0.45·veil. Никакого рисунка в этой
     * полосе нет по построению: френель ровен вдоль всего силуэта.
     *
     * Кромка уезжает в униформу, и у зоны с конусом она 0.22–0.26 вместо
     * 0.45: объём остаётся дрожью воздуха, а не покраской бойца. Замах
     * (`charge`) держит свои 0.5 — там купол ТЕЛЕГРАФ, его задача быть
     * плотным шаром в руке, и мерить его надо по кадру замаха, а не по ногам
     * жертвы.
     */
    const edge = uniform(0.45);
    m.userData.u = { fade, veil, edge };
    const fres = oneMinus(tabs(TSL.dot(normalView, positionViewDirection))).clamp(0, 1);
    const rim = smoothstep(float(0.4), float(1.0), fres);
    const pulse = tsin(TIME.mul(9.4)).mul(0.5).add(0.5);
    const inner = float(0.08).add(pulse.mul(0.06));
    m.colorNode = mix(mix(col(P[1]), col(P[2]).mul(0.8), rim.mul(0.7)), col(P[1]).mul(1.6), rim.mul(pulse.mul(0.4).add(0.3)));
    /* Кромка 0.45, не 0.8: над зоной купол читался ЩИТОМ, а не дрожью
       воздуха (замер 03.09 по статусу и зоне). Заражение держит на полу
       сыпь и треск, а купол только подкрашивает объём. */
    const alpha = mix(inner, edge, rim).mul(veil).mul(fade).clamp(0, 1);
    m.opacityNode = alpha;
    /* Дрожь: шумовое смещение, сильное только там, где купол плотный. */
    const n = mx_noise_float(normalLocal.mul(3.0).add(vec3(TIME.mul(1.4), 0, 0)));
    markDistort(m, normalView.xy.mul(n).mul(0.25), rim.mul(0.25).mul(fade));
    /* Свечение купола ПРИВЯЗАНО К КРОМКЕ, а не живёт своей жизнью: на
       верхнем кадре зоны вокруг бойца стоял светлый круг радиусом 2.7 м —
       пол, подсвеченный bloom купола, то есть та же лампа, которую этот файл
       снял с зоны в прошлом круге, только помягче. `edge·2.2` держит замах
       (0.5 → ×1.1) и приглушает зону (0.22 → ×0.48). */
    return markGlow(m, rim.mul(pulse.mul(0.2).add(0.2)).mul(veil).mul(edge.mul(2.2)).mul(fade).clamp(0, 0.4));
  }, 4);
}

let DOME_GEO = null;
function dome(P, r) {
  if (!DOME_GEO) DOME_GEO = shared(new THREE.IcosahedronGeometry(1, 4));
  const m = domeMat(P);
  const mesh = new THREE.Mesh(DOME_GEO, m);
  mesh.frustumCulled = false;
  mesh.renderOrder = 9;
  mesh.scale.setScalar(r);
  /* `veil` ставится каждый кадр вместе с `fade`: материал общий на четыре
     живых купола (кольцо пула), и переживший чужую запись кадр вернул бы
     чужую плотность. */
  return {
    mesh,
    set(fade, v = 1, e = 0.45) {
      m.userData.fade.value = fade;
      m.userData.u.veil.value = v;
      m.userData.u.edge.value = e;
    },
  };
}

/**
 * `puff` — ВЫБРОС ПЫЛИ, И ОН БОЛЬШЕ НЕ ЛАМПА.
 *
 * Здесь стоял `kit.smoke` с `lit: P[1]`: пять клубов формы `SHAPE.smoke` —
 * мягкое гауссово пятно радиусом полметра, СТАРТУЮЩЕЕ жёлтым #ffe14a. Судья
 * круга 6 на `radiation-zone-t0_40-top.png` насчитал «три-четыре насыщенно-
 * жёлтых гауссовых пятна без структуры и краёв: у него нет ни силуэта, ни
 * зерна, ни следа движения, а лежат они в тени и потому светятся» — и это
 * ровно то, что даёт эта запись. Мой собственный замер по тому же кадру:
 * четыре пятна около (950,660), (890,545), (770,590) — три из них ярче
 * чистого пола, то есть выброс РАБОТАЛ ИСТОЧНИКОМ СВЕТА, чего стихии нельзя
 * (§10.1 и первый пункт шапки).
 *
 * Пыль остаётся событием, но говорит она тем же алфавитом, что и всё
 * остальное здесь: три десятка ТЁМНЫХ зёрен (`SHAPE.chip`, резкий край,
 * `P[2]`, доля в свечении ноль), которые всплывают на полметра и оседают.
 * Клуб был один на полметра — теперь на том же месте видно, из чего он
 * состоит, и он ничего не подсвечивает.
 */
function puff(vfx, P, { x, z, r, n, life = 1.1, rng, at = 0 }) {
  const hot = HOT.copy(P[2]).lerp(P[1], 0.3);
  vfx.body.emit(n, (i, s) => {
    const a = rng() * TAU, d = Math.sqrt(rng()) * r;
    s.pos(x + Math.sin(a) * d, 0.10 + rng() * 0.45, z + Math.cos(a) * d);
    s.vel(Math.sin(a) * (0.2 + rng() * 0.5), 0.5 + rng() * 0.9, Math.cos(a) * (0.2 + rng() * 0.5));
    s.gravity(0, -0.9, 0);
    s.color(hot, P[2]);
    s.life(vfx.now + at + rng() * 0.22, life * (0.6 + rng() * 0.7), 0.18 + rng() * 0.18, kit.SHAPE.chip);
    s.ext((rng() * 2 - 1) * 1.2, 0.85, 0, 0);
  });
}

