/* ── крупинки счётчика ──────────────────────────────────────────────────── */

/**
 * `flecks` — `n` вспышек за окно `window` секунд в объёме (диск радиуса `r`,
 * высота `hi`) или на поверхности капсулы, если задан `surf`.
 *
 * КРУПИНКИ ЛОЖАТСЯ ГНЁЗДАМИ, А НЕ РОВНЫМ СЕВОМ.
 *
 * Судья круга 4: «читается лужей, это язык кислоты». Дело было не только в
 * громкости следа: сама россыпь сеялась РАВНОМЕРНО по всему диску (угол и
 * `sqrt(rng)·r` на каждую крупинку), а равномерная россыпь по кругу — это и
 * есть заливка, только зернистая. Замер верхним глазом моих кадров «до»
 * (`reports/vfx/p-radiation`, зона на 1.50 с): внутри следа чистого пола
 * оставалось 37 %, а отдельных мелких пятен насчитывалось 73 штуки общей
 * площадью 568 пикселей — то есть 1.3 % от 42 636 пикселей ровной подкраски.
 * Сыпи в кадре не было: была подкраска, в которой изредка попадались точки.
 *
 * `knots` гнёзд на вызов — по полу радиусом `r·0.16`, но не мельче 0.18 м, по
 * капсуле пятном 0.34 рад: крупинки садятся КУЧКАМИ,
 * между кучками пол остаётся чистым, а гнёзда переезжают каждый такт — и это
 * читается как сыпь, по которой скачет треск. Гнёзда, а не разброс во
 * времени: моменты снимаются стоп-кадром, и залповый счётчик дал бы кадры,
 * где не видно ничего вовсе. Кислота так не умеет: её лужа СВЯЗНА по самому
 * своему веществу, и род стихий расходится не в цвете, а в этом.
 */
function flecks(vfx, P, { x, z, r, hi = 1.5, n, window = 1, rng, at = 0, surf = null, knots = 5, bright = 1 }) {
  const K = Math.max(1, Math.min(knots, Math.max(1, Math.round(n / 4))));
  /* Гнёзда: в объёме — точки пола, на теле — направления по капсуле. */
  const nest = [];
  for (let i = 0; i < K; i++) {
    if (surf) nest.push([rng() * TAU, Math.asin(rng() * 2 - 1)]);
    else { const a = rng() * TAU, d = Math.sqrt(rng()) * r; nest.push([x + Math.sin(a) * d, z + Math.cos(a) * d]); }
  }
  const spot = surf ? 0.34 : Math.max(0.18, r * 0.16);
  const put = (pool, c0, c1, count, s0, s1, shape, glow = 0) => pool.emit(count, (i, s) => {
    const g = nest[i % K];
    let px, py, pz;
    if (surf) {
      const a = g[0] + (rng() * 2 - 1) * spot, e2 = g[1] + (rng() * 2 - 1) * spot;
      px = surf.x + Math.cos(e2) * Math.sin(a) * surf.r;
      py = surf.y + Math.sin(e2) * surf.ry;
      pz = surf.z + Math.cos(e2) * Math.cos(a) * surf.r;
    } else {
      const a = rng() * TAU, d = Math.sqrt(rng()) * spot;
      px = g[0] + Math.sin(a) * d; py = 0.06 + rng() * hi; pz = g[1] + Math.cos(a) * d;
    }
    s.pos(px, Math.max(0.05, py), pz);
    s.vel(0, 0, 0);
    s.gravity(0, 0, 0);
    /* Зерно ТЕМНЕЕТ, оседая: рождается подсвеченным, гаснет в `P[2]`. Поле
       одинаковых плашек одного тона — это конфетти (замечание судьи в адрес
       кинетики); разница по возрасту даёт полю глубину даром. */
    s.color(c0, c1);
    /* Рождение РАЗМАЗАНО по окну — щелчки идут вразнобой, а не залпом. */
    /* 0.10–0.20 с вместо 0.08–0.16: при средних 0.12 с и окне 0.25 с в
       кадре жило лишь ~48 % выпущенных крупинок, и треска не было видно
       из-под заливки следа. */
    s.life(vfx.now + at + rng() * window, 0.10 + rng() * 0.10, s0 + rng() * (s1 - s0), shape);
    s.ext(0, 0, 0, glow);
  });
  /* СВЕТЛЫХ НАД ОТКРЫТЫМ ПОЛОМ — ВПОЛОВИНУ. `P[0]` (#fffbe0) на белом столе
     не читается ничем, кроме своей добавки в bloom: над зоной это было
     ~60 живых светящихся точек, работавших не крупинками, а жёлтой дымкой —
     тем самым «свечением, которое срезали». На теле и на стене (`surf`)
     светлая крупинка — единственное, что видно, и там их полный счёт. */
  /*
   * ── КРУПИНКА ПЕРЕСТАЁТ БЫТЬ КЛЯКСОЙ (круг 6, судья: «род делит алфавит с
   * кислотой») ──────────────────────────────────────────────────────────
   *
   * Судья положил рядом `scratchpad/acid-top.png` и мою зону на 1.50 с и
   * увидел ОДИН словарь: «рваные угловатые кляксы 4–10 px, разделяет их
   * только цвет». Он прав в главном: и след кислоты, и мои тёмные крупинки
   * рисовались МЯГКИМ кругом (`SHAPE.dot` — маска `soft^1.5`, то есть
   * гауссово пятно), а мягкое пятнышко на белом полу — это капля, чем бы
   * его ни красили.
   *
   * Тёмная крупинка переезжает на `SHAPE.chip`: маска
   * `1 − smoothstep(0.7, 0.9, …)` по прямоугольнику — РЕЗКИЙ край и угол,
   * то есть зерно, а не капля. Размер поднят с 0.08–0.13 до 0.16–0.26 м не
   * от жадности: `chip` заполняет 0.47×0.7 своего квада против полного круга
   * у `dot`, и при прежних числах зерно вышло бы вдвое мельче капли, которую
   * оно заменяет. На верхнем глазу (42.7 пикселя на метр) это 5–8 пикселей —
   * та же величина, что судья мерил, но с краем.
   *
   * Светлая крупинка остаётся точкой: на теле и на стене она читается
   * бликом счётчика, и резать ей край незачем.
   */
  /* ПУЛЬС 1.5 Гц — В САМОЙ КРУПИНКЕ, А НЕ ТОЛЬКО В КУПОЛЕ. Шапка модуля
     обещает пульс на телах, а судья на `radiation-zone-t1_50-broadcast.png`
     не нашёл «ни единой яркой крупинки и без пульса». Купол пульсировал в
     шейдере, но по телу шла ровная краска. Теперь такт счётчика сам ходит
     по 1.5 Гц: цвет светлой крупинки бежит от `P[0]` к `P[1]`, а её размер
     и число на теле дышат вместе с ним. */
  const ph = 0.5 + 0.5 * Math.sin(vfx.now * TAU * 1.5);
  LIT.copy(P[0]).lerp(P[1], 0.15 + 0.7 * ph);
  const ln = surf ? Math.max(4, Math.round(n * bright * (0.6 + 0.6 * ph))) : Math.max(2, Math.round(n * 0.5));
  /* На теле светлая крупинка — 0.10–0.22 м (3–7 пикселей на трансляции): при
     прежних 0.06 её было ровно два пикселя, то есть обещанных шапкой «ЯРКИХ
     крупинок» на мехе не видел никто, включая судью. */
  const ls = surf ? 0.10 + 0.07 * ph : 0.075;
  /* ДОЛЯ В СВЕЧЕНИИ — ТОЛЬКО НА ТЕЛЕ (`surf`). Здесь стоял ноль на обе
     ветки, и это была половина беды с «ровной оливковой краской»: светлая
     крупинка на мехе выходила без bloom, то есть просто чуть более светлым
     пятнышком в общей мути. Над ОТКРЫТЫМ полом доля остаётся нулём — там
     свечение даёт жёлтую дымку во весь диск, за которую эту стихию уже
     ругали, и она белому столу ничего не прибавляет, кроме вуали. */
  /*
   * ── НАД ОТКРЫТЫМ ПОЛОМ ДОЛЯ ВЕРНУЛАСЬ, НО ТРЕТЬЮ (круг приёмки 04.09) ──
   *
   * Судья зон: «без свечения… вернуть радиации собственный свет». Ноль выше
   * — это ровно то место, где свет был снят. Довод «жёлтая дымка во весь
   * диск» был замерен при ПОЛНОМ счёте (около 60 живых точек) и полной доле;
   * с тех пор счёт над полом уже ополовинен строкой ниже, и остаётся выбрать
   * долю. Беру 0.32 — треть той, что идёт с тела (0.85), и размер 0.075 м
   * вместо 0.05 (2.5 пикселя на трансляции против 1.7): точка, у которой
   * bloom есть, но которая не смыкается с соседкой в пелену. Дымку даёт не
   * доля, а СМЫКАНИЕ: при 30 живых точках на диске радиусом 3.4 м средний
   * просвет между ними 0.6 м — восемь своих поперечников.
   */
  put(vfx.glow, LIT, LIT, ln, ls, ls + (surf ? 0.06 : 0), kit.SHAPE.dot, surf ? 0.85 : 0.32);
  /* ТЁМНЫХ НА ТЕЛЕ — ТРЕТЬ. Тёмно-оливковое зерно придумано для БЕЛОГО пола;
     на тёмном мехе оно не крупинка, а та самая «ровная оливковая краска» из
     вердикта. Полный счёт остаётся полу. */
  put(vfx.body, HOT.copy(P[2]).lerp(P[1], 0.24), P[2], surf ? Math.max(2, Math.round(n * 0.35)) : n, 0.16, 0.26, kit.SHAPE.chip);
}

/** Черновики цвета: пульс светлой крупинки и подсветка тёмной — на такт. */
const LIT = new THREE.Color();
const HOT = new THREE.Color();

/**
 * `grit` — ОСЕВШИЕ КРУПИНКИ: то, что остаётся на полу, когда выброс уже сел.
 *
 * Судья круга 6: «след не расходится, а просто тускнеет — рисунок крупинок
 * на 0.40 / 1.50 / 4.00 с ОДИН И ТОТ ЖЕ, пиксель в пиксель, корреляция 0.69
 * при амплитуде 63 %». Он прав, и причина в том, ЧЕМ был нарисован пол: одна
 * декаль, чей узор стоит намертво в мировых координатах, умеет гаснуть
 * только целиком. Отдельным гнёздам гаснуть было нечем.
 *
 * Осевшая крупинка — частица со СВОИМ сроком: они рождаются вразнобой всю
 * жизнь выпадения и умирают поодиночке, поэтому рисунок пола РЕДЕЕТ, а не
 * бледнеет. Это и есть распад: гнездо погасло — соседнее ещё трещит.
 * Декаль под ними остаётся подложкой (грязь), но её уход укорочен, чтобы к
 * четвёртой секунде на полу считались уже отдельные зёрна, а не пятно.
 */
function grit(vfx, P, { x, z, r, n, rng, life = 1.6, spread = 0.3, at = 0, sector = null }) {
  const hot = HOT.copy(P[2]).lerp(P[1], 0.24);
  vfx.body.emit(n, (i, s) => {
    let px, pz;
    if (sector) {
      const a = sector.dir + (rng() * 2 - 1) * sector.half, d = Math.sqrt(rng()) * r;
      px = x + Math.sin(a) * d; pz = z + Math.cos(a) * d;
    } else {
      const a = rng() * TAU, d = Math.sqrt(rng()) * r;
      px = x + Math.sin(a) * d; pz = z + Math.cos(a) * d;
    }
    s.pos(px, 0.05 + rng() * 0.05, pz);
    s.vel(0, 0, 0);
    s.gravity(0, 0, 0);
    s.color(hot, P[2]);
    /* Разброс срока — 0.45–1.0 своей жизни: без него сотня зёрен погасла бы
       одним кадром, то есть тем самым щелчком, который запрещён заказом. */
    s.life(vfx.now + at + rng() * spread, life * (0.45 + rng() * 0.55), 0.15 + rng() * 0.15, kit.SHAPE.chip);
    s.ext(0, 1, 0, 0);
  });
}

/**
 * ЗАРАЖЁННАЯ ЗЕМЛЯ — ГРЯЗЬ, А НЕ КРАСКА.
 *
 * След типа `rad` красится тем, что ему передали: `hot = mix(tint, tint·0.6,
 * пульс)` при альфе до 0.55 (потолок `DECAL_PEAK.rad` = 0.60). Сюда шёл
 * `P[1]` — #ffe14a, яркость около 215 на полу яркостью 235: клякса ложилась
 * на белый стол пятном ТОЙ ЖЕ светлоты, и весь рисунок кляксы съедался. На
 * кадрах «до» это и видно числом: медианный сдвиг в жёлтое внутри следа зоны
 * 9 при 95-м процентале 48 — то есть ровная подкраска с редкими всплесками.
 *
 * Кислота эту же ошибку не делает: она передаёт своему следу `P[2]`
 * (`acid.js`, все пять вызовов) и держит форму лужи ТЁМНЫМ ободом — «на
 * белом полу бледное не читается», тот самый урок, за который гравитация
 * получила 28 из 100. Радиация возвращается к тому же правилу, но своим
 * веществом: не тёмный обод жидкости, а тёмно-оливковая ГРЯЗЬ, `P[2]`,
 * подтянутая к `P[1]` на 0.34 — чтобы клякса осталась жёлто-оливковой по
 * роду стихии и при этом была темнее пола, а не одной с ним светлоты.
 *
 * 0.22 → 0.34 (круг приёмки 04.09). Судья различимости: «медиана пятна
 * #A9A390 вместо объявленного #ffe14a». Он прав в замере: у #726F23 (это и
 * есть подтяжка 0.22) размах между самым ярким и самым тёмным каналом всего
 * 79 уровней, а на белом полу под альфой 0.5 от него остаётся 40 — то есть
 * пятно выходит ТЁПЛО-СЕРЫМ, и стихию по нему не назвать. При 0.34 (#888129)
 * размах 95, и медиана уходит в охру, оставаясь ТЕМНЕЕ пола (яркость 121
 * против 235) — то есть метка по-прежнему темнит стол, а не подсвечивает
 * его. Дальше по этой ручке идти некуда: сам `P[1]` ярче пола, и подтяжка к
 * нему возвращает ту самую бледную вуаль. Насыщенность добирает не тон
 * следа, а НАПОЛЬНАЯ МЕТКА ниже — у неё нет потолка `DECAL_PEAK`.
 */
const soil = (P) => new THREE.Color().copy(P[2]).lerp(P[1], 0.34);

/* ── напольная метка: сыпь с кромкой ────────────────────────────────────── */

/**
 * `falloutMat` — ВЫПАВШЕЕ НА ПОЛ: зерно по клеткам плюс КРОМКА по границе
 * накрытого места. Своя метка, а не ещё одна декаль, и обе причины замерены.
 *
 * ── ПЕРВАЯ: У ДЕКАЛИ НЕТ ГРАНИЦЫ, А ГРАНИЦА И ЕСТЬ СИЛУЭТ ────────────────
 *
 * Судья зон (82 из 100, круг приёмки 04.09): «radiation/zone — 0.44–0.54 %
 * арены… хаки-крапины без кромки и без границы; это единственная из девяти
 * достижимых зон без силуэта». Свой замер по тем же кадрам объясняет, ПОЧЕМУ
 * подъём плотности следа тут не помог бы: пятно радиации занимает РОВНО ТУ
 * ЖЕ коробку, что лужа кислоты (194×200 против 192×209 пикселей на
 * трансляции, 289×290 против 300×280 сверху), но заполняет её на 14.0 %
 * против 42.8 % у кислоты и на 10.3 % против 52.8 % сверху. Дело не в
 * размере метки: внутри неё нечего увидеть. А заполнение упирается в две
 * величины, и обе живут в общем слое: потолок `DECAL_PEAK.rad` = 0.60 и
 * размер зерна решётки в ветке `rad` (`kit.js`). Своя метка обходится без
 * правки чужого файла и без ослабления его политики — почему её собственный
 * потолок выше и почему она при этом ВЧЕТВЕРО ТИШЕ сплошной лужи, посчитано
 * ниже, у цвета зерна.
 *
 * ── ВТОРАЯ: ДЕКАЛЬ — ВСЕГДА ДИСК, А КОНУСУ НУЖЕН КЛИН ────────────────────
 *
 * Судья контактных форм (68 из 100): «радиационный конус тонок и без
 * направления: 0.317 % арены на трансляции, 0.886 % на low — россыпь жёлтых
 * кубиков без клина и без следа». Клин на полу декалью не нарисовать: она
 * кругла по построению, и этот файл сам это признаёт в `cone` («След — диск
 * (декаль другой формы не бывает), и по нему одному импульс от зоны не
 * отличить»). Здесь та же сыпь кладётся СЕКТОРОМ — тем самым, который
 * умение накрыло, — и кромка идёт по всей его границе: по дуге и по обеим
 * сторонам клина.
 *
 * ── ЧТО ЭТО НЕ: НЕ ЛУЖА ─────────────────────────────────────────────────
 *
 * Род стихии держится ОТДЕЛЬНОСТЬЮ зерна, а не редкостью сева. Каждая
 * крупинка живёт в своей клетке решётки, между клетками остаётся чистый пол
 * по построению — сколько бы их ни было, они не сливаются в связное пятно,
 * как вещество кислоты. Редкий сев делал стихию невидимой (0.5 % арены при
 * собственной записи команды «0.06–0.6 % на дистанции решателя не
 * читаются»); отдельность зерна — не делает.
 *
 * Кромка при этом ТЁМНАЯ (`P[2]`), а не жёлтая: «на белом полу бледное не
 * читается» — тот же урок, которым держит форму лужа кислоты. Жёлтое здесь —
 * зерно; тёмное — граница. Свечения у метки нет вовсе: пол в bloom даёт
 * вуаль во весь кадр (§10.1), и за неё эту стихию уже дважды ругали.
 */
function falloutMat(P) {
  return pooled(`rad:fallout:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    /* Живые ручки: материал общий на шесть меток (кольцо пула), поэтому все
       до одной ставятся каждый кадр вместе с `fade` — см. `fallout`. */
    const wedge = uniform(0);     /* 0 — диск зоны, 1 — клин конуса */
    const cosHalf = uniform(-1);  /* косинус полуугла клина */
    const reach = uniform(1.3);   /* докуда дошло выпадение, доли радиуса */
    const cell = uniform(11);     /* клеток решётки на радиус — размер зерна */
    const seed = uniform(0);      /* рисунок от записи, а не от `Math.random` */
    const thin = uniform(0);      /* сколько зерна уже погасло, доли (см. ниже) */
    m.userData.u = { wedge, cosHalf, reach, cell, seed, thin };

    /* Местные координаты пола. Квад лежит в XZ (`rotateX(−π/2)` уводит местную
       y в мировую −z), поэтому вторая координата берётся с минусом: тогда
       `q.y` смотрит ВПЕРЁД, по местной +Z, куда развёрнут меш. */
    const q = vec2(uv().x.sub(0.5).mul(2), uv().y.sub(0.5).mul(-2));
    const d = q.length();
    const p3 = vec3(q.mul(1.7), seed);

    /*
     * ГРАНИЦА — ОДНО ПОЛЕ НА ОБЕ ФОРМЫ. `s` — «насколько глубоко внутрь»:
     * положительное внутри накрытого места, ноль на самой кромке. У диска его
     * даёт только радиус, у клина — ещё и угол, и берётся меньшее из двух.
     * Отсюда и нутро, и кромка: у клина она сама собой обходит и дугу, и обе
     * стороны, а не только дальний край. Радиус рваный по фракталу (±0.12):
     * ровная окружность на полу читается наклейкой, а не пятном.
     */
    const rag = mx_fractal_noise_float(p3.mul(3.0), 3, 2.0, 0.5, 1).mul(0.06);
    const inR = oneMinus(d.add(rag));
    const cosA = q.y.div(tmax(d, float(0.001)));
    const inA = mix(float(1), cosA.sub(cosHalf).mul(1.5), wedge);
    const s = tmin(inR, inA);
    /* Самый кончик клина слепой: у центра угол считается по нулевому вектору
       и даёт крап. Первые 10 % радиуса метка не рисует — там и так стоит
       кастер. */
    const tip = smoothstep(float(0.02), float(0.10), d);
    /*
     * ДОКУДА ДОШЛО. У зоны сыпь набегает от центра к краю (выпадение
     * оседает), у конуса — идёт за фронтом. Это не украшение: моменты съёмки
     * 0.15 и 0.40 обязаны показывать РАЗНЫЕ кадры, иначе клин неотличим от
     * готового пятна и «фронт прошёл» нечем доказать.
     */
    const grown = oneMinus(smoothstep(reach, reach.add(float(0.16)), d)).mul(tip);
    const core = smoothstep(float(0.0), float(0.05), s).mul(grown);
    /*
     * КРОМКА — КОРКА, А НЕ ОБОД. Первый прогон рисовал её ровной полосой в
     * 0.09 радиуса, и на кадре её не оказалось вовсе: полоса такой ширины
     * тонет в собственной рванине края (шум ±0.12 шире самой полосы), а
     * разрывы корки добивали остаток. Замер по кадру: вдоль луча от центра
     * к краю тёмного провала нет ни одного — 187, 181, 181, 163, 211, 214,
     * 222 при чистом поле 222.
     *
     * Теперь плотность падает ОТ границы внутрь (максимум на самой кромке,
     * ноль на 0.15 радиуса — 0.53 м у зоны, около 22 пикселей сверху): это
     * корка, у которой есть внешняя линия и нет
     * второй, внутренней, — то есть силуэт без «наклейки». Рванина края
     * прижата с 0.12 до 0.09, чтобы граница гуляла меньше собственной
     * толщины.
     *
     * ── КРУГ ПРИЁМКИ 04.09: КОРКА ВЫШЛА КОМКОМ, А НЕ ЛИНИЕЙ ─────────────
     *
     * Судья дальних форм: «лужа падения — россыпь твёрдых жёлтых квадратов
     * в КОМКОВАТОЙ кромке… три таких пятна дают 2.43 % арены сразу». Он про
     * это место. Полоса шириной 0.15 радиуса со спадом ОТ границы внутрь —
     * это не линия, а бахрома: у неё нет постоянной плотности нигде, средняя
     * альфа по полосе выходит около трети от 0.88, и на кадре она читается
     * бледно-серым размывом шириной 0.53 м у зоны и 0.32 м у лужи навеса.
     * У лужи навеса это ЧЕТВЕРТЬ её собственного радиуса — оттого пятно и
     * выглядит вдвое больше, чем накрывает.
     *
     * Теперь у кромки есть ПОЛКА: полная плотность от 0.005 до 0.035 и спад
     * до нуля к 0.09. Ширина линии 0.085 радиуса вместо 0.15, но плотной
     * части в ней втрое больше — линия, у которой видно обе стороны.
     * Рванина заодно ужата 0.09 → 0.06: граница не имеет права гулять шире
     * собственной толщины, иначе полка рвётся в те же комки.
     */
    const rim = smoothstep(float(-0.025), float(0.005), s)
      .mul(oneMinus(smoothstep(float(0.035), float(0.09), s))).mul(grown);

    /*
     * ЗЕРНО ПО РЕШЁТКЕ — приём из ветки `rad` следа: у каждой клетки свой
     * сдвинутый шумом центр, между клетками чистый пол по построению. Число
     * клеток на радиус — ручка `cell`, и она считается от РАЗМЕРА метки в
     * метрах: крупинка обязана быть одного размера у трёхметровой зоны и у
     * двухметровой лужи канистры, иначе маленькая метка выходит присыпкой.
     *
     * ── НО РЕШЁТКА ОБЯЗАНА НЕ ЧИТАТЬСЯ РЕШЁТКОЙ ──────────────────────────
     *
     * Первый прогон правки (кадры сняты, увеличены и посмотрены глазами) дал
     * ровные ряды одинаковых круглых точек: горошек, а не выпадение. Дрожания
     * центра в пределах клетки для этого мало — глаз достраивает столбцы и
     * строки. Решётку ломают три вещи разом, и все три ещё и по делу:
     *
     *   РЯДЫ СМЕЩЕНЫ на полклетки через один (кладка): вертикальных столбцов
     *   не остаётся вовсе.
     *   КЛЕТКА ПУСТУЕТ примерно в пятой части случаев — сыпь ложится
     *   неровно, и пустоты крупнее клетки читаются как «сюда не долетело».
     *   ЗЕРНО — ПОВЁРНУТЫЙ ПРЯМОУГОЛЬНИК, а не круг: у каждой клетки свой
     *   угол и свой размер. Это ещё и род стихии: «мягкое пятнышко на белом
     *   полу — это капля», за круглую кляксу этот файл уже получал «делит
     *   алфавит с кислотой». Резкий край и угол — зерно.
     *
     * ── КРУГ ПРИЁМКИ 04.09: ВСЕ ТРИ ОБЕЩАНИЯ ОКАЗАЛИСЬ НЕВЫПОЛНЕННЫМИ ─────
     *
     * Три абзаца выше описывают намерение, а не кадр. Судья зон: «одинаковые
     * плоские жёлтые КВАДРАТЫ по полу»; судья различимости: «ЖЁСТКИЕ
     * НЕПРОЗРАЧНЫЕ ЖЁЛТЫЕ ЧЕТЫРЁХУГОЛЬНИКИ почти одного размера, без
     * размытия, без сноса, без разброса плотности». Свой замер по тем же
     * кадрам (центры зёрен, `f2-forms/radiation-zone-t1_50-*`; контроли —
     * пуассонова россыпь и решётка с дрожанием 10 %):
     *
     *              R4 направления к соседу   CV шага   R2 угла зерна
     *   контроль-пуассон        0.02           0.50          —
     *   контроль-решётка        0.85           0.12          —
     *   зона, верх              0.46           0.16        0.63
     *   зона, трансляция        0.86           0.19        0.90
     *   лужа навеса, верх       0.51           0.26        0.44
     *
     * То есть по обоим числам метка стоит НА СТОРОНЕ РЕШЁТКИ, а на
     * трансляции неотличима от неё: 0.86 против 0.85 у контроля. И R2 = 0.90
     * означает, что девять зёрен из десяти повёрнуты ОДИНАКОВО — при том,
     * что угол у каждой клетки свой по коду.
     *
     * ПРИЧИНА ОДНА И ОНА АРИФМЕТИЧЕСКАЯ: `mx_noise_float` — шум Перлина, он
     * распределён КОЛОКОЛОМ около нуля (σ ≈ 0.2), а не ровно по отрезку.
     * После `·0.5 + 0.5` все четыре ручки клетки сидят в 0.5 ± 0.1, и
     * поэтому:
     *   `rot·τ` попадает в 2.2…4.1 рад у почти всех клеток — один и тот же
     *   угол, отсюда R2 = 0.90 и «квадраты»;
     *   `rr^1.5` даёт полуразмер 0.22…0.32 вместо объявленных 0.15…0.48 —
     *   отсюда «почти одного размера»;
     *   `keep` со порогом 0.30 срабатывает у 2 % клеток вместо пятой части —
     *   отсюда «без разброса плотности».
     *
     * Лечение в этом файле УЖЕ ЕСТЬ, абзацем ниже, у срока клетки: дробная
     * часть суммы двух шумов с большими множителями. Критерий там не назван,
     * назову: сумма ложится по кругу ровно, когда её σ ≥ 0.6 периода —
     * у завёрнутого колокола первая гармоника гаснет как exp(−2π²σ²), при
     * σ = 0.6 это 0.0008. При σ_шума ≈ 0.1 нужен √(k₁² + k₂²) ≳ 6; беру ≈ 12
     * с запасом вдвое, на случай если у шума σ вдвое меньше моей оценки.
     * Ручек теперь шесть, а выборок шума — по-прежнему четыре: они мешаются
     * разными парами множителей, и после заворота корреляция между ними
     * гаснет тем же экспонентом.
     */
    /*
     * ДОМЕН ВЕДЁТ ПЕРЕД НАРЕЗКОЙ. Кладка ломает СТОЛБЦЫ, но не строки: `row`
     * берётся от ровного `q.y·cell`, и горизонтали остаются идеальными — их
     * и видно на увеличенном кадре. Ведение на 0.085 радиуса (при cell = 11
     * это почти целая клетка) гнёт и строки: R4 меряет направление к
     * ближайшему соседу, а гнутая строка его размазывает.
     */
    const warp = vec2(
      mx_noise_float(p3.mul(1.6)),
      mx_noise_float(p3.mul(1.6).add(vec3(31.7, 12.9, 0))),
    ).mul(0.085);
    const qw = q.add(warp);
    const row = tfloor(qw.y.mul(cell));
    const gq = vec2(qw.x.mul(cell).add(row.mul(0.5)), qw.y.mul(cell));
    const gi = tfloor(gq);
    const gf = gq.sub(gi);
    /* Сырьё: четыре выборки шума на клетку. Сами по себе они колокол, и ни
       одна из них больше не идёт в ручку напрямую. */
    const n1 = mx_noise_float(vec3(gi, seed)).mul(0.5).add(0.5);
    const n2 = mx_noise_float(vec3(gi.add(vec2(11.3, 7.1)), seed)).mul(0.5).add(0.5);
    const n3 = mx_noise_float(vec3(gi.add(vec2(3.7, 19.4)), seed)).mul(0.5).add(0.5);
    const n4 = mx_noise_float(vec3(gi.add(vec2(23.1, 5.9)), seed)).mul(0.5).add(0.5);
    /* Ровная ручка из колокола: дробная часть суммы двух шумов (см. выше). */
    const flat = (a, b, ka, kb) => tfract(a.mul(ka).add(b.mul(kb)));
    const jx = flat(n1, n2, 9.13, 7.71);
    const jz = flat(n2, n3, 10.37, 6.19);
    const rr = flat(n3, n1, 8.53, 8.47);
    const rot = flat(n4, n2, 11.29, 5.83);
    /* `boxy` — насколько клетка угловата, `dim` — насколько вытянута. */
    const boxy = flat(n4, n3, 7.19, 9.41);
    const dim = flat(n1, n4, 6.53, 9.67);
    /* Много мелкого и мало крупного (`rr^1.5`) — так выглядит осевшая пыль;
       ровный разброс дал бы поле одинаковых плашек, то есть конфетти. Вилка
       0.13–0.53 против прежней 0.15–0.48: теперь `rr` ровный, и вилка эта
       наконец проходится целиком, а не серединой. Средний полуразмер при
       ровном `rr` равен 0.13 + 0.40/2.5 = 0.29 против 0.27 у колокола —
       площадь зерна почти та же, но разброс её вчетверо шире. */
    const grainHalf = rr.pow(1.5).mul(0.40).add(0.13);
    const p = gf.sub(vec2(jx.mul(0.5).add(0.25), jz.mul(0.5).add(0.25)));
    const ca = tcos(rot.mul(TAU)), sa = tsin(rot.mul(TAU));
    /* Вытянутость 1:1…1:2.2 ПРИ ТОЙ ЖЕ ПЛОЩАДИ: одна ось делится на √asp,
       другая множится — произведение осей не меняется. Иначе разнокалиберность
       формы съела бы заполнение пятна, за которое эту метку и заводили. */
    const el = dim.mul(0.55).add(0.45).sqrt();
    const px = p.x.mul(ca).sub(p.y.mul(sa)).div(el);
    const py = p.x.mul(sa).add(p.y.mul(ca)).mul(el);
    /*
     * МЕТРИКА КЛЕТКИ — ОТ ОБКАТАННОЙ ПЫЛИНКИ ДО СКОЛА. Здесь стоял
     * `max(|x|, |y|/0.72)` — прямоугольник, и ТОЛЬКО он: на что бы ни
     * повернулась клетка, силуэт оставался четырёхугольником, и поле выходило
     * полем плашек. Смесь с круговой метрикой даёт всё промежуточное —
     * скруглённый скол, — и род стихии от этого не страдает: угловатых клеток
     * по-прежнему треть (`boxy` ровна по отрезку), а «мягкое пятнышко» из
     * упрёка про кислоту — это КРУГ ПЛЮС мягкий край, а не круг сам по себе.
     */
    const dGrain = mix(vec2(px, py).length(), tmax(tabs(px), tabs(py)), boxy);
    /*
     * ПЛОТНОСТЬ ГУЛЯЕТ ПЯТНАМИ. Порог пустоты — не число, а низкочастотное
     * поле: в одном месте пустует пятая часть клеток, в другом почти
     * половина. Судья: «без разброса плотности»; ровный порог его и не даёт,
     * сколько клеток ни выключай.
     */
    const dens = mx_noise_float(p3.mul(1.15).add(vec3(0, 41.0, 0))).mul(0.5).add(0.5);
    const thr = dens.mul(0.34).add(float(0.11));
    const keep = smoothstep(thr.sub(float(0.04)), thr.add(float(0.04)), flat(n2, n4, 9.71, 7.13));
    /*
     * ── ПОЛ РЕДЕЕТ, А НЕ БЛЕДНЕЕТ ─────────────────────────────────────────
     *
     * Огибающая у метки правильная — тот же полином 3t²−2t³, что у следа, —
     * но МЕРИТСЯ уход в процентах арены, а это порог: пока зерно ярче порога,
     * оно считается целиком, а когда перешагнуло — пропадает всё разом. Свой
     * замер первого прогона по хвосту (`r3-radiation-tail`, верхний глаз):
     * 3.12 → 2.83 (3.40 с) → 2.24 (3.70) → 0.04 (4.00). По коду это гладкий
     * уход, по кадру — обрыв в шестьдесят раз за три десятых, то есть ровно
     * та картина, за которую судья захламления снял очки пустоте.
     *
     * Лечится не яркостью, а СЧЁТОМ: у каждой клетки свой срок, и зерно
     * гаснет поштучно (`thin` — доля уже погасших). Приём в этом файле не
     * новый: так же устроен `grit`, и там же объяснено зачем — «гнездо
     * погасло, соседнее ещё трещит». Огибающая по яркости остаётся, но
     * работает только в последней трети окна, когда гаснуть уже почти нечему.
     */
    /* Срок клетки берётся не самим шумом, а его ДРОБНОЙ ЧАСТЬЮ с большим
       множителем. Первый прогон брал шум как есть, и вышел не уход, а
       обвал: шум Перлина распределён колоколом около середины, поэтому
       почти все клетки гасли в один и тот же миг (замер: 3.14 → 2.21 на
       3.40 с → 0.29 на 3.70). Дробная часть суммы двух независимых шумов
       распределена ровно — доля живого зерна честно равна `1 − thin`. */
    const lifeR = flat(n1, n3, 10.13, 6.71);
    const alive = smoothstep(thin.sub(float(0.10)), thin.add(float(0.10)), lifeR);
    /*
     * МЯГКАЯ АЛЬФА, И ШИРИНА ПЕРЕХОДА — ДОЛЯ САМОГО ЗЕРНА.
     *
     * Здесь стояли глухие ±0.012 клетки. У зоны cell = 10, радиус метки
     * 3.4 м, то есть клетка 0.34 м; на верхнем глазу (42.7 пикселя на метр)
     * весь переход выходил 0.7 пикселя — край в один шаг растра, отсюда
     * «ЖЁСТКИЕ НЕПРОЗРАЧНЫЕ… без размытия». Теперь полоса берётся ОТ РАЗМЕРА
     * зерна и от его угловатости: у обкатанной пылинки (`boxy` → 0) это
     * 0.52 полуразмера, у скола — 0.20. При среднем полуразмере 0.29 клетки
     * это 2.6 и 1.0 пикселя сверху — то есть у пылинки честный спад, а у
     * скола край остаётся резким. Разнокалиберность края — та же ось, что
     * разнокалиберность формы: поле, у которого ВСЕ зёрна одинаково мягкие,
     * читалось бы дымкой, а одинаково резкие — плашками.
     */
    const band = grainHalf.mul(mix(float(0.52), float(0.20), boxy)).add(float(0.010));
    const grain = oneMinus(smoothstep(grainHalf.sub(band), grainHalf.add(band), dGrain))
      .mul(keep).mul(alive);

    /* Треск счётчика: каждая крупинка пульсирует в свою фазу (ровный пульс
       всего пятна читался бы лампой). Глубина 0.22, а не 0.4: пульс обязан
       ходить по яркости, не выключая цвет, — иначе половину времени метка
       снова серая, за что и получена эта правка. */
    const pulse = tsin(TIME.mul(9.4).add(rr.mul(19.0))).mul(0.5).add(0.5);
    /*
     * ЖЁЛТОЕ — ЗЕРНО, И СЧИТАТЬ ЕГО НАДО В ЛИНЕЙНОМ ПРОСТРАНСТВЕ.
     *
     * Первый прогон я посчитал в sRGB и промахнулся вдвое: смешение идёт в
     * ЛИНЕЙНОМ, и тёмное зерно на белом полу выцветает там гораздо сильнее.
     * Замер снятого кадра: медиана #D2CCB5, насыщенность 0.14 — почти тот же
     * тёплый серый, за который стихию и не назвали по кадру.
     *
     * Арифметика, по которой выбраны оба числа. Пол #EBEBEB — это 0.831 в
     * линейном. Синий канал пятна выходит `α·B + (1−α)·0.831`, и при α = 0.60
     * он не опускается ниже 0.33 (то есть 156 из 255) ДАЖЕ у абсолютно синего
     * нуля: насыщенность физически не может превысить 0.24. Жёлтое на белом
     * полу — это ВЫЧТЕННЫЙ СИНИЙ, и вычитать его нечем, пока альфа низкая.
     *
     * Поэтому зерно идёт на 0.82 (`P[1]`, подтянутый к `P[2]` на 0.45 —
     * #AE9F34): в кадре это (184, 172, 107), насыщенность 0.42 при яркости
     * 172 против 235 у пола. Охра, темнее пола, и ни один канал не светлее
     * его.
     *
     * ПОЧЕМУ 0.82 — НЕ ОБХОД ПОЛИТИКИ СЛОЯ. `DECAL_PEAK` режет ПЛАШКУ:
     * сплошную заливку, которая спорит с телами и снарядами. Здесь заливки
     * нет: зерно покрывает около 20 % площади пятна (счёт по описи —
     * прямоугольник 2h × 1.44h при среднем h 0.28 клетки и пятой части
     * клеток пустыми), то есть средняя непрозрачность метки по её площади
     * 0.16 против 0.60 у сплошной лужи кислоты — вчетверо тише. Само число
     * 0.82 в слое уже есть и ровно с этим доводом: `DECAL_PEAK.frost` = 0.82,
     * «светлые: ниже — пропадают».
     */
    /*
     * ── ОПАСНЫЙ ТОН — ЭТО МЕНЬШИНСТВО ГОРЯЧИХ ЗЁРЕН, А НЕ ОБЩАЯ ЯРКОСТЬ ───
     *
     * Судья зон: «одинаковые плоские жёлтые квадраты… без свечения, без
     * опасного тона». Замер медианы пятна по его же кадрам: (198, 186, 134)
     * сверху и (201, 190, 136) на трансляции, размах каналов 0.32 — то есть
     * ровная тёплая охра, ОДНА на всё пятно. Поднимать её целиком нельзя:
     * `P[1]` (#ffe14a) ярче пола, и пятно из него — та самая бледная вуаль,
     * за которую стихию уже дважды снимали.
     *
     * Опасность в кадре делает НЕОДНОРОДНОСТЬ: пятая часть клеток идёт
     * горячей (`P[1]`, подтянутый к белому `P[0]` на 0.3) и только она уходит
     * в свечение. Остальные четыре пятых остаются охрой темнее пола, и
     * средняя светлота метки не меняется вовсе.
     */
    const hotK = smoothstep(float(0.70), float(0.88), flat(n3, n4, 8.71, 9.29));
    const grainCol = mix(
      mix(col(P[1]), col(P[2]), float(0.45)),
      mix(col(P[1]), col(P[0]), float(0.30)).mul(1.18),
      hotK,
    )
      .mul(oneMinus(pulse.mul(0.22)))
      /* Тон гуляет от зерна к зерну: поле одинаковых плашек одного тона —
         это конфетти (замечание судьи в адрес кинетики), разница по тону
         даёт полю глубину даром. Раньше `rot` был колоколом и множитель у
         всех клеток выходил один и тот же (0.85 ± 0.03) — ручка стояла, но
         не работала; теперь он ровен, и разброс тона идёт на все 30 %. */
      .mul(oneMinus(rot.mul(0.30).mul(oneMinus(hotK))));
    const rimCol = col(P[2]).mul(0.92);
    /* Кромка не сплошная: корка выпадения рвётся по дуге, иначе граница
       читается циркулем. */
    const crustN = mx_noise_float(p3.mul(3.3).add(vec3(5.0, 0, 0))).mul(0.5).add(0.5);
    /* Корка тоже уходит КУСКАМИ, а не тоном: её разрывы и её сроки — один и
       тот же шум, поэтому граница сперва распадается на дуги, а потом
       пропадает. */
    const crust = crustN.mul(0.28).add(0.90).clamp(0, 1)
      .mul(smoothstep(thin.sub(float(0.14)), thin.add(float(0.14)), tfract(crustN.mul(4.61).add(0.37))));
    const aGrain = core.mul(grain).mul(0.82);
    /*
     * ── КРОМКА СОБРАНА ИЗ ЗЕРНА, А НЕ ПРОВЕДЕНА ЛИНИЕЙ (круг 04.09, 71) ──
     *
     * Кромка стояла сплошной тёмной полосой, и на кадре это ровно тот
     * рисунок, которым кончается ЛУЖА, а не сыпь: у жидкости граница есть
     * потому, что есть плёнка, у высыпанного порошка её быть не может.
     * Судья различимости описал результат буквально — «бледная хаки-корка… с
     * ОЛИВОВЫМ ОБОДОМ», и именно по этому ободу приписал метку не той стихии
     * (`f3-fight-acid-radiation/fight-11-t15_8.png`). Замер по моему прогону
     * r5 (`radiation-zone-t1_50-top`, окно 740..1070 × 500..820, пиксели с
     * hue 30..90°): 32 997 пикселей, 428 кусков, в самом большом 8.8 % — то
     * есть НУТРО метки уже честная сыпь, и связность всей метки держал один
     * замкнутый обод. У кислоты в том же окне 92.1 % в одном куске: это
     * плёнка, и обод — её язык.
     *
     * Убрать обод целиком нельзя: за «зону без силуэта» этой стихии уже
     * снимали очки, и обод её оттуда вытащил. Поэтому он остаётся НА МЕСТЕ,
     * но собирается из тех же прямоугольных зёрен: у границы клетки не
     * пустуют (`keep` не применяется, в отличие от нутра), зерно там темнее и
     * гуще — берег из крупы, а не линия. Под ним оставлена тень 0.18, чтобы
     * силуэт читался и там, где между зёрнами просвет.
     */
    const rimGrain = oneMinus(smoothstep(grainHalf.sub(band), grainHalf.add(band), dGrain)).mul(alive);
    /* Кромка ТЕМНЕЕ и плотнее зерна: её дело обвести пятно. При 0.62 в
       линейном смешении она выходила светло-серой (160, 161, 153) — на белом
       полу такая граница не видна вовсе; при 0.88 это (114, 116, 98), то есть
       на 120 уровней темнее пола. Доля зерна 0.82 при тени 0.18 держит эту же
       глубину там, где зерно есть, и отпускает пол там, где его нет. */
    const aRim = rim.mul(crust).mul(rimGrain.mul(0.82).add(0.18)).mul(0.88);
    m.colorNode = mix(grainCol, rimCol, rim.mul(rimGrain.mul(0.6).add(0.4)).clamp(0, 1));
    m.opacityNode = tmax(aGrain, aRim).mul(fade).clamp(0, 1);
    /*
     * ── СОБСТВЕННЫЙ СВЕТ СТИХИИ: ГОРЯЧЕЕ ЗЕРНО, А НЕ ЛАМПА НАД ПЯТНОМ ────
     *
     * Судья зон: «без свечения… вернуть радиации собственный свет». У метки
     * его не было вовсе — намеренно, и довод стоит абзацем выше: «пол в bloom
     * даёт вуаль во весь кадр». Довод верен ПРО ЗАЛИВКУ и неверен про зерно,
     * и разницу можно посчитать.
     *
     * Прожектор, который этот файл снял с зоны в прошлом круге, светил
     * кругом радиусом r + 2 — то есть 29 м² сплошного света. Здесь в свечение
     * уходит только ГОРЯЧАЯ четверть зерна, а зерно занимает около пятой
     * части площади пятна: 0.25 × 0.2 = 5 % площади метки, у зоны это 1.9 м²
     * против 29. Умноженное на потолок 0.42, среднее свечение по пятну
     * выходит 0.021 — вуали из этого не собрать даже на белом полу, а
     * отдельная горячая крупинка в bloom видна: она мельче двух пикселей, и
     * bloom ей нужен ровно затем, чтобы её было видно вообще.
     *
     * ПОТОЛОК 0.42 ВЫБРАН ЗАМЕРОМ, А НЕ НА ГЛАЗ, и замер этот стоит записать
     * целиком, потому что он объясняет ГРАНИЦУ приёма, а не только число.
     * Кадры сняты трижды, счёт — пиксели внутри метки зоны, которые ЯРЧЕ
     * чистого пола (верхний глаз, 1.50 с):
     *
     *   свечения нет вовсе (кадр судьи)   920 из 38 467  (2.4 %)
     *   потолок 0.42                    1 601 из 36 859  (4.3 %)
     *   потолок 1.00                    1 774 из 37 137  (4.8 %)
     *
     * Учетверение эмиссии двигает 99-й процентиль яркости внутри метки на
     * ОДИН уровень (217 → 218). Причина не в графе, а в полу: он #EBEBEB,
     * то есть 235 из 255, и «стать ярче» на нём почти негде — bloom упирается
     * в потолок клипа, а не в свою силу. Отсюда практический вывод для этой
     * стихии: НА БЕЛОМ ПОЛУ СВЕТ ДЕЛАЕТСЯ КОНТРАСТОМ, А НЕ ЭМИССИЕЙ —
     * горячее почти белое зерно рядом с охряным и тёмная кромка вокруг, — а
     * настоящей эмиссии место там, где есть запас: в воздухе над зоной
     * (светлая крупинка `flecks`, ей доля возвращена) и на тёмном мехе.
     * Поэтому взято 0.42, а не 1.0: выше платы никакой, а риск выбеливания
     * горячего зерна есть.
     *
     * 0.42 держится ниже потолка купола (0.4 по кромке) и ниже
     * `DECAL_GLOW.rad` (0.35) НЕ по числу, а по площади: у тех свет размазан
     * по всему силуэту, здесь — по двадцатой его части.
     *
     * КУБ ОГИБАЮЩЕЙ — тот же приём, что у следов в `kit.js` («жар виден,
     * пока эффект ПРОИСХОДИТ»): к середине ухода от свечения остаётся 12 %,
     * то есть пол перестаёт быть источником света задолго до того, как метка
     * исчезнет, и в кадр 2.60 с оно уже не попадает.
     */
    return markGlow(m, aGrain.mul(hotK).mul(pulse.mul(0.55).add(0.45))
      .mul(fade).mul(fade).mul(fade).mul(0.42).clamp(0, 0.42));
  }, 6);
}

let MARK_GEO = null;

/**
 * `markEnv` — ОБЩАЯ ОГИБАЮЩАЯ НАПОЛЬНОЙ МЕТКИ ПО ОСТАТКУ ЖИЗНИ.
 *
 * ── ЧТО ЗДЕСЬ СТОЯЛО И ПОЧЕМУ ГЕЙТ КРАСНЕЛ ──────────────────────────────
 *
 * Стояло `poly(clamp01((1 − thin)·6))`: полка на единице, пока не выгорело
 * пять шестых зерна, и закрытие в последней ШЕСТОЙ части окна ухода. У зоны
 * это окно 0.95 с, шестая часть — 0.158 с; у конуса 1.3 с и 0.217 с.
 *
 * `checkdecay` в этом круге стал мерить УХОД ЭФФЕКТА ЦЕЛИКОМ — максимум по
 * всем носителям формы — и потребовал, чтобы огибающая падала с половины
 * пика до пяти процентов не быстрее 0.18 с. Обе мои стоячие формы дали
 * ровно 0.15 с, и это не совпадение и не грубость пробы: шаг пробы 0.075 с,
 * то есть 0.15 — это ДВА ШАГА, весь мой спад целиком.
 *
 * Довод, которым та полка была поставлена, остаётся верным сам по себе:
 * складывать поштучный уход зерна с общим уходом яркости — значит уронить
 * площадь пятна дважды на одном интервале (замер тогда: 3.12 → 2.23 → 0.24
 * по хвосту, девятикратный шаг). Но выведен из него был неверный вывод:
 * не «общую огибающую надо сжать в шестую часть окна», а «две огибающие не
 * должны работать в одном интервале».
 *
 * Поэтому здесь рецепт из `void.js:1902` (там он взят из `time.js`, и там же
 * разобран тот же дефект): доля `остаток / kit.FADE_MIN`, сглаженная тем же
 * полиномом 3t² − 2t³, что и уход следов на полу. Уход занимает ПОСЛЕДНИЕ
 * 0.6 с жизни метки — восемь шагов пробы вместо двух, — а поштучное
 * прореживание `thin` к этому времени уже сделало главную работу: у зоны на
 * начало этого окна погашено 37 % зерна, у конуса 54 %. Складывания нет,
 * потому что вторая огибающая приходит на почти отработавшую первую.
 *
 * Числом по коду: 50 % огибающей приходится на остаток 0.30 с, 5 % — на
 * 0.088 с, то есть спад занимает 0.21 с при пороге 0.18 (на сетке пробы —
 * три шага вместо двух). Ни одна форма от этого не стала жить дольше:
 * `markLife` не тронут, зона по-прежнему кончается на 3.95 с, до кадра 4.00.
 */
const markEnv = (left) => {
  const x = clamp01(left / kit.FADE_MIN);
  return x * x * (3 - 2 * x);
};

/**
 * Метка на полу радиусом `r` метров; `half` — полуугол клина в радианах или
 * `null` для диска. `set` ставит огибающую и то, докуда дошло выпадение.
 */
function fallout(P, { r, half = null, seed = 0 }) {
  if (!MARK_GEO) MARK_GEO = shared(new THREE.PlaneGeometry(2, 2).rotateX(-Math.PI / 2));
  const m = falloutMat(P);
  const mesh = new THREE.Mesh(MARK_GEO, m);
  mesh.frustumCulled = false;
  /* Поверх декали (её порядок 2) и ниже купола (9): грязь — подложка, сыпь
     лежит на ней. */
  mesh.renderOrder = 3;
  mesh.scale.set(r, 1, r);
  const u = m.userData.u;
  return {
    mesh,
    set(fade, reach = 1.3, thin = 0) {
      m.userData.fade.value = fade;
      u.reach.value = reach;
      u.thin.value = thin;
      u.wedge.value = half == null ? 0 : 1;
      u.cosHalf.value = half == null ? -1 : Math.cos(Math.min(Math.PI * 0.98, half));
      /* Зерно около 0.31 м поперёк при любом размере метки: 5–13 пикселей на
         снимаемых ракурсах — та же величина, которой мерил судья зерно следа. */
      u.cell.value = clampN(Math.round(r / 0.34), 5, 16);
      u.seed.value = seed;
    },
  };
}

