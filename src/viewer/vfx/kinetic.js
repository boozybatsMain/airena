/** Плоская пластина на полу; `rz` задаёт вторую полуось (борозда — не круг). */
function slab(P, { x, z, r, rz = null, rot = 0, seed, y = 0.026 }) {
  const m = slabMat(P);
  m.userData.u.seed.value = seed;
  const mesh = new THREE.Mesh(slabGeo(), m);
  mesh.position.set(x, y, z);
  mesh.rotation.y = rot;
  mesh.scale.set(r * 2, 1, (rz ?? r) * 2);
  mesh.renderOrder = 3;
  mesh.frustumCulled = false;
  return { mesh, set(fade, reveal = 1) { m.userData.fade.value = fade; m.userData.u.reveal.value = reveal; } };
}

/** Тёмный брус от `a` к `b` толщиной `w`. */
function rod(P, a, b, w) {
  const m = barMat(P);
  const mesh = new THREE.Mesh(rodGeo(), m);
  const dx = b[0] - a[0], dy = b[1] - a[1], dz = b[2] - a[2];
  const len = Math.hypot(dx, dy, dz) || 0.01;
  mesh.position.set(a[0], a[1], a[2]);
  mesh.rotation.y = yawFor(dx / len, dz / len);
  mesh.rotation.z = Math.asin(clampN(dy / len, -1, 1));
  mesh.scale.set(len, w, w);
  mesh.renderOrder = 9;
  mesh.frustumCulled = false;
  return { mesh, set(fade) { m.userData.fade.value = fade; } };
}

/**
 * Плита: коробка шириной `w` (местная X), высотой `h`, толщиной `d` (местная
 * Z), стоящая основанием на `y`. `yaw` — поворот вокруг Y; при `yaw = a`
 * местная +Z смотрит в `(sin a, cos a)`, то есть наружу от центра кольца.
 */
function plate(P, { x, y = 0, z, w, h, d, yaw = 0, seed = 1, key = 'plate', mat = null }) {
  /*
   * `mat` — ОДИН МАТЕРИАЛ НА ВЕСЬ КАСТ. Это не украшение, это починка
   * замеренного дефекта. Кольцо `pooled` держит шесть материалов на ключ, а
   * стена берёт из него ТРИНАДЦАТЬ плит; две стены подряд (каст идёт раз в
   * 3.9 с, стена живёт 4 с + 0.35 с ухода) делят одни и те же шесть, и
   * гаснущая старая стена переписывает `fade` растущей новой. На кадре
   * круга 3 `kinetic-wall-t0_12-broadcast` это видно прямо: 8850 изменённых
   * пикселей, из них 5089 серых (58 %) со средней (154,161,170) — новая
   * стена стоит СТЕКЛЯННОЙ, потому что ей досталось затухание 0.2 от
   * предыдущей. Один материал на каст: два одновременных каста занимают два
   * места в кольце, а не тринадцать.
   *
   * Зерно и жилы от общего материала не страдают: они считаются по МИРОВЫМ
   * координатам, и у соседних плит рисунок разный сам по себе.
   */
  const m = mat || plateMat(P, key);
  /* Сид пишется ТОЛЬКО своему материалу: общий засеян один раз кастом, и
     затирать его дефолтом на каждой плите значит терять разброс рисунка. */
  if (!mat) m.userData.u.seed.value = seed;
  const mesh = new THREE.Mesh(plateGeo(), m);
  mesh.position.set(x, y, z);
  mesh.rotation.y = yaw;
  mesh.scale.set(w, h, d);
  mesh.renderOrder = 8;
  mesh.frustumCulled = false;
  return { mesh, mat: m, set(fade) { m.userData.fade.value = fade; } };
}

/**
 * Клин упора на полу. Геометрия идёт вдоль местной +X от ОСНОВАНИЯ (x=0) к
 * ОСТРИЮ (x=1), поэтому меш ставится основанием, а местная +X уносится в
 * `dir` — направление, в котором клин смотрит (у замаха это «к телу»).
 */
function wedge(P, { bx, bz, dir, len, w, bias = 1, base = 0.35 }) {
  const m = flatMat(P);
  m.userData.u.bias.value = bias;
  m.userData.u.base.value = base;
  /* `rag` СБРАСЫВАЕТСЯ явно: материал берётся из общего кольца с хомутом
     статуса, а тот ставит `rag = 1`. Униформа кольцевого материала — это
     состояние ПРЕДЫДУЩЕГО владельца, пока её не переписали. */
  m.userData.u.rag.value = 0;
  const mesh = new THREE.Mesh(wedgeGeo(), m);
  mesh.position.set(bx, 0.028, bz);
  mesh.rotation.y = yawFor(Math.sin(dir), Math.cos(dir));
  mesh.scale.set(len, 1, w);
  mesh.renderOrder = 4;
  mesh.frustumCulled = false;
  return { mesh, mat: m, set(fade) { m.userData.fade.value = fade; } };
}

/** Тёмный фронт давления: рваное кольцо (или клин) на полу, без свечения. */
function wave(vfx, P, { x, z, r0 = 0.2, radius = 2, life = 0.4, half = null, seed = 1, dir = 0 }) {
  const m = waveMat(P);
  m.userData.u.seed.value = seed;
  m.userData.u.half.value = half == null ? Math.PI : half;
  const mesh = new THREE.Mesh(ringGeo(), m);
  /* Местная +X кольца должна смотреть в курс: поворот на `dir − π/2`
     (тот же вывод, что у волны набора). */
  mesh.rotation.y = dir - Math.PI / 2;
  mesh.position.set(x, 0.03, z);
  mesh.renderOrder = 5;
  mesh.frustumCulled = false;
  vfx.spawnMesh(mesh, life, (o, u) => {
    const r = r0 + (radius - r0) * (1 - Math.pow(1 - u, 3));
    o.scale.set(r, 1, r);
    /*
     * ПЛОТНОСТЬ ДЕРЖИТСЯ, ПОТОМ ПАДАЕТ. Было `(1−u)^1.3`, то есть уже на
     * трети жизни кольцо шло с альфой 0.64 — и это ровно то, что запрещает
     * шапка файла («ни одной поверхности с альфой ниже ~0.95»). Замер круга
     * 3 поймал волну с поличным: у луча на 0.12 с трансляции из 3680 серых
     * пикселей почти все лежат толстым полумесяцем ровно по кольцу волны
     * (маска изменённых пикселей, разложенная по полосам S/L). Теперь
     * плотность стоит на единице 72 % жизни и падает за оставшиеся 28 %:
     * волна тёмная всё время, пока её видно, и уходит быстро.
     */
    m.userData.fade.value = u < 0.72 ? 1 : Math.max(0, (1 - u) / 0.28);
  });
  return mesh;
}

/**
 * Разлом в полу: одна лента-звезда, прорастающая наружу за `growS` секунд.
 * `len` — размах в метрах, `focus` — сколько очагов (крупный удар колет пол
 * в нескольких местах).
 */
function cracks(vfx, P, { x, z, len, rng, life = 1.6, at = 0, growS = 0.13, focus = 1, hold = 0, rest = 0.95 }) {
  const g = new THREE.Group();
  const mats = [];
  const n = clampN(Math.round(focus), 1, 3);
  for (let i = 0; i < n; i++) {
    const m = crackMat(P);
    m.userData.u.seed.value = (i * 3 + (rng() * 7) | 0) + 1;
    const mesh = new THREE.Mesh(fractureGeo(Math.floor(rng() * 4)), m);
    const a = rng() * TAU, d = i === 0 ? 0 : len * (0.25 + rng() * 0.35);
    mesh.position.set(x + Math.sin(a) * d, 0.032 + i * 0.002, z + Math.cos(a) * d);
    mesh.rotation.y = rng() * TAU;
    mesh.scale.setScalar(len * (i === 0 ? 1 : 0.55 + rng() * 0.25));
    mesh.renderOrder = 4;
    mesh.frustumCulled = false;
    g.add(mesh);
    mats.push(m);
  }
  /*
   * `hold` — сколько секунд разлом ДЕРЖИТСЯ после свежей фазы, на остаточной
   * плотности `rest`. Это ответ на замер судьи «самый долгоживущий след
   * кинетики — бурый гравий, попиксельно как у пустоты»: чаша воронки набора
   * ограничена альфой 0.75 и на белом полу всё равно светлеет до серого, а
   * ТРЕЩИНА держит и цвет, и форму, и она ни на что у пустоты не похожа.
   *
   * `rest` ПО УМОЛЧАНИЮ 0.95, А НЕ 0.55. Круг 2 записал в шапку файла
   * правило «ни одной поверхности с альфой ниже ~0.95» — и тут же нарушил
   * его собственным значением по умолчанию: пять форм из девяти держали
   * остаточный разлом на 0.55. Круг 3 это увидел на кадре: болт на 1.20 с
   * трансляции, 1534 серых пикселя (28 % изменённых) со средней
   * (168,172,177) и насыщенностью ниже 0.15 — это лучи старых разломов, не
   * воронка. Арифметика та же, что у всей остальной кинетики: 0.55 тёмной
   * стали плюс 0.45 белого HDR-пола в ЛИНЕЙНОМ пространстве дают серое.
   * Замах уже стоял на 0.95 по этой же причине; теперь так у всех.
   *
   * ЧТО ЗДЕСЬ ЕЩЁ НЕ ПОЧИНЕНО И ПОЧЕМУ Я ЭТОГО НЕ ТРОГАЛ. Разлом берёт до
   * ТРЁХ материалов на каст из кольца в шесть, а держится 9–12 с при касте
   * раз в 4 с: три живых каста просят девять материалов, и они начинают
   * переписывать друг другу затухание — ровно тот дефект, который я поймал
   * кадром у стены и починил там (`plate({mat})`). У разлома кадра-улики у
   * меня НЕТ, и вред здесь ограничен: с `rest = 0.95` спорящие значения
   * различаются на 0.05, а не на 0.8, как было у стены. Лечится это либо
   * одним материалом на каст (тогда у очагов общий сид), либо кольцом на
   * шестнадцать. Не сделал в этот круг сознательно: правку пришлось бы
   * снимать заново всеми формами, а доказательства вреда у меня нет.
   */
  const total = Math.max(life, hold);
  vfx.spawnMesh(g, total + at, (o, u) => {
    const t = u * (total + at);
    if (t < at) { o.visible = false; return; }
    o.visible = true;
    const k = t - at;
    /* Фронт уходит за единицу, чтобы кончики успели дорасти. */
    const grow = Math.min(1.15, k / Math.max(0.001, growS) * 1.15);
    let fade;
    if (k < life * 0.7) fade = 1;
    else if (k < life) fade = rest + (1 - rest) * (life - k) / (life * 0.3);
    else if (k < total - 1.4) fade = rest;
    else fade = rest * Math.max(0, (total - k) / 1.4);
    for (const m of mats) { m.userData.u.grow.value = grow; m.userData.fade.value = fade; }
  });
  return g;
}

/**
 * ВЫБОИНА НА ПОЛУ: тёмная чаша `pitMat` и `chunks` поднятых кусков породы по
 * её кромке. Это ответ кинетики на «самый долгоживущий след — бурый гравий»:
 * след держит не краска, а ВЕЩЕСТВО — тёмная чаша плюс настоящая геометрия,
 * которая с 26 м читается силуэтом (плиты `plateMat`: тёмная грань, светлее
 * верх, фаска по кромке).
 *
 * `hold` — секунды полной плотности, `fade` — затухание после.
 */
function pit(vfx, P, { x, z, r, rng, hold = 8, fade = 3, chunks = 3, growS = 0.09, seed = 1 }) {
  const g = new THREE.Group();
  const m = pitMat(P);
  m.userData.u.seed.value = seed;
  const bowl = new THREE.Mesh(slabGeo(), m);
  bowl.position.set(x, 0.021, z);
  bowl.rotation.y = rng() * TAU;
  bowl.scale.set(r * 2, 1, r * 2 * (0.82 + rng() * 0.32));
  bowl.renderOrder = 3;
  bowl.frustumCulled = false;
  g.add(bowl);
  /* Куски стоят НА КРОМКЕ и криво: порода выдавлена наружу удара, а не
     расставлена по кругу. Основание утоплено — кусок лежит, а не парит.
     ПЛОСКИЕ И ШИРОКИЕ, а не кубические: на первом кадре круга 3 (болт,
     1.20 с) равносторонние куски читались синими кубиками у ямы. Плита
     вдвое шире своей высоты и завалена до 0.35 рад — это вывернутый кусок
     пола, а не тумбочка. */
  const nk = clampN(Math.round(chunks), 0, 5);
  const plates = [];
  /* Один материал на весь щебень выбоины — см. `plate`. Выбоина лежит
     11–13 с, и без этого она переписывала бы затухание стенам и щитам. */
  const rm = nk ? plateMat(P, 'rubble') : null;
  if (rm) rm.userData.u.seed.value = seed;
  for (let i = 0; i < nk; i++) {
    const a = rng() * TAU, dd = r * (0.7 + rng() * 0.45);
    const hh = r * (0.13 + rng() * 0.19);
    const pl = plate(P, {
      x: x + Math.sin(a) * dd, y: -r * 0.1, z: z + Math.cos(a) * dd,
      w: r * (0.32 + rng() * 0.4), h: hh, d: r * (0.24 + rng() * 0.3),
      yaw: rng() * TAU, mat: rm,
    });
    pl.mesh.rotation.z = (rng() - 0.5) * 0.7;
    g.add(pl.mesh);
    plates.push({ pl, h0: hh });
  }
  const total = hold + fade;
  vfx.spawnMesh(g, total, (o, u) => {
    const t = u * total;
    const k = t < hold ? 1 : Math.max(0, 1 - (t - hold) / Math.max(0.001, fade));
    m.userData.u.grow.value = Math.min(1.1, t / Math.max(0.001, growS) * 1.1);
    m.userData.fade.value = k;
    for (const p of plates) { p.pl.mesh.scale.y = p.h0 * Math.min(1, t / Math.max(0.001, growS)); p.pl.set(k); }
  });
  return g;
}

/* ── частицы: пыль, обломки, осколки ────────────────────────────────────── */

/**
 * КРОШКА, А НЕ ДЫМ. Это самая дорогая правка круга 2, и куплена она замером.
 *
 * Кадры круга 2 (`reports/vfx/r70b/kinetic/r1-before`) я разложил по
 * насыщенности каждого изменённого пикселя. Замах, трансляция, 0.30 с:
 * изменённых 5616, из них 4352 (78 %) имеют насыщенность НИЖЕ 0.15 при
 * средней светлоте 171 — то есть три четверти эффекта это бледно-серое
 * пятно. Тёмных и насыщенных всего 421. Конус на 0.30 с — то же самое:
 * из 11 565 изменённых тёмных 468. Судья назвал это «бледным серым мазком,
 * неотличимым от контактной тени», и он мерил ровно эти пиксели.
 *
 * Причина не в цвете, а в АЛЬФЕ И СМЕШЕНИИ. Маска дыма
 * (`smoothstep(0.12,0.78,…)` в `vfx.js`) по краю спрайта даёт альфу 0.2–0.5,
 * а смешение идёт в ЛИНЕЙНОМ пространстве до тонмаппинга: белый пол
 * (линейно ≈0.73) при альфе 0.3 забирает 70 % пикселя, и тёмная сталь
 * (0.108,0.166,0.234) выходит на экран как (195,198,201). Насыщенность 0.03.
 * Любой полупрозрачный спрайт на этом полу — серый, и это не лечится цветом.
 *
 * Поэтому у кинетики пыли НЕТ. Есть КРОШКА: форма `chip`, у которой маска
 * угловатая и с жёстким краем (`1 − smoothstep(0.7,0.9,…)`).
 *
 * ЧЕГО КРУГ 2 ПРО НЕЁ НЕ ЗНАЛ. Здесь стояло, что у `chip` «внутри спрайта
 * альфа единица и пиксель выходит тем, чем он покрашен». Это НЕВЕРНО, и я
 * проверил это по коду: в `vfx.js` альфа частицы считается как
 * `маска · плавный вход · (1 − возраст)^1.3`, то есть полупрозрачной
 * становится ЛЮБАЯ частица во второй половине жизни, как её ни крась. И
 * второе: крошка размером 0.08–0.3 м с 26 м занимает считанные пиксели (по
 * арифметике кадра — около 4–13, попиксельно я это не мерил), то есть у неё
 * почти нет «внутри» — весь спрайт это кромка.
 *
 * ЧЕГО Я НЕ БУДУ УТВЕРЖДАТЬ. Что серое в кадре — это крошка. Я это ПРОВЕРИЛ
 * и оказалось не так: у луча на 0.12 с трансляции из 3290 серых пикселей
 * 2696 (82 %) лежат в нижней восьмой части рамки изменений, то есть в точке
 * прилёта, — это чаша воронки набора, а не поле крошки вдоль трассы. Крошка
 * даёт серое тоже, но её вклад мельче, и числа под него у меня нет.
 *
 * Отсюда правило: крошка КРУПНЕЕ (размер — единственное, чем на неё можно
 * повлиять здесь: число ей назначает `kit.countFor` от площади следа).
 * Кинетика — вещество, а не дым: из-под удара летит сечка, а не облако.
 */
function dust(vfx, P, { x, y = 0.15, z, n, radius, speed = 2.2, up = 1.4, life = 1.1, size = 0.24, at = null, rng, dir = null, half = null }) {
  const born = at ?? vfx.now;
  const T = tones(P);
  vfx.body.emit(n, (i, s) => {
    const a = dir == null ? rng() * TAU : dir + (rng() * 2 - 1) * (half ?? 0.5);
    const d = Math.sqrt(rng()) * radius;
    s.pos(x + Math.sin(a) * d, y + rng() * 0.3, z + Math.cos(a) * d);
    s.vel(Math.sin(a) * speed * (0.4 + rng() * 0.8), rnd(up * 0.3, up, rng), Math.cos(a) * speed * (0.4 + rng() * 0.8));
    s.gravity(0, -3.4, 0);
    s.color(T.grit, T.deep);
    /* Разброс размера ШИРОКИЙ (0.35…1.6 от базы): ровные по величине чипы
       читаются конфетти, а не породой — видно на кадре конуса круга 2. */
    s.life(born + rng() * 0.08, rnd(life * 0.7, life * 1.3, rng), rnd(size * 0.35, size * 1.6, rng), kit.SHAPE.chip);
    /* Предпоследний аргумент — вытягивание по скорости: летящая крошка идёт
       слайсом, а не квадратом. Последний — доля в свечении, у кинетики НОЛЬ. */
    s.ext(rnd(-4, 4, rng), 0.4, 1, 0);
  });
}

/** Обломки: тяжёлые тёмные чипы, летят и падают. */
function chips(vfx, P, { x, y = 0.3, z, n, radius, speed = 6, up = 6, life = 1.2, size = 0.2, at = null, rng, dir = null, half = null }) {
  const born = at ?? vfx.now;
  const T = tones(P);
  vfx.body.emit(n, (i, s) => {
    const a = dir == null ? rng() * TAU : dir + (rng() * 2 - 1) * (half ?? 0.6);
    s.pos(x + Math.sin(a) * radius * Math.sqrt(rng()), y + rng() * 0.3, z + Math.cos(a) * radius * Math.sqrt(rng()));
    s.vel(Math.sin(a) * rnd(speed * 0.4, speed, rng), rnd(up * 0.3, up, rng), Math.cos(a) * rnd(speed * 0.4, speed, rng));
    s.gravity(0, -14, 0);
    s.color(T.grit, T.deep);
    s.life(born, rnd(life * 0.7, life * 1.3, rng), rnd(size * 0.5, size * 1.6, rng), kit.SHAPE.chip);
    s.ext(rnd(-9, 9, rng), 0.7, 0, 0);
  });
}

/* ── формы ──────────────────────────────────────────────────────────────── */

export function beam(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const T = tones(P);
  const fp = kit.footprint(e, ctx);
  if (!(fp.len > 0.3)) return false;
  const S = kit.tune(e, {
    width: 0.13,        /* толщина ударной линии, м */
    y: 1.15,            /* высота линии, м */
    grow: 0.045,        /* за сколько долетает, с */
    duration: 0.2,      /* держится, с */
    decay: 0.25,        /* гаснет, с */
    /*
     * КОНУСЫ. Судья про круг 0: «серые кости на проволоке». Круг 1 сделал их
     * оболочками, но не тронул РАЗМЕР, и на кадре круга 2
     * (`kinetic-beam-t0_12-side`) они вышли тонкими чёрточками длиной 0.31–
     * 0.62 м и раствором 0.12–0.45 м на трассе в 9.2 м: с 26 м это засечки,
     * а не конусы. Круг 2 дал им размер, но не дал ТЕЛА: замер круга 3 (луч,
     * 0.12 с, трансляция) — 6529 изменённых пикселей при 1074 тёмных и
     * насыщенных (16 %), потому что от оболочки на экране остаётся контур в
     * один-два пикселя, а он весь уходит в сглаживание.
     *
     * Круг 3 добавил две вещи. Первая — ОБОД УСТЬЯ в `coneMat`: плотная
     * тёмная полоса в 12 % длины на широком конце, то есть читаемый эллипс
     * вместо линии. Вторая — конусов СЕМЬ вместо пяти: при `coneLen 11` и
     * `coneFlare 6.5` длина идёт 1.01→1.93 м при шаге 9.19/7 = 1.31 м, то
     * есть конусы перекрываются вдоль ствола и обода идут поездом.
     */
    cones: 7,           /* сколько конусов Маха вдоль ствола (было 5) */
    coneLen: 11,        /* длина конуса, в толщинах ствола */
    coneFlare: 6.5,     /* раствор конуса у хвоста, в толщинах ствола */
    /* Борозда ШИРЕ. Это арифметика, а не замер: при полуширине 0.34 м полоса
       была 0.68 м, а радиальная маска `slabMat` отдавала под спад альфы 0.18
       нормированного радиуса с каждой стороны — почти пятую часть ширины на
       градиент, который на белом полу серый. Полуширина 0.5 м и спад 0.13
       (см. `slabMat`) оставляют плотной заметно большую долю полосы. */
    furrowW: 0.5,       /* полуширина борозды на полу, м (было 0.34) */
    furrowHold: 2.6,    /* сколько борозда держится, с */
    /*
     * КРОШКА КРУПНЕЕ. Замер круга 3: луч на 0.12 с трансляции — 6529
     * изменённых пикселей, серых 3290 (50 %), тёмных и насыщенных 1074
     * (16 %). Серое сидит НЕ вдоль трассы: 2696 серых из 3290 лежат у точки
     * прилёта (гистограмма по строкам кадра) — это чаша воронки набора, и
     * лечится она `markR` и своей выбоиной ниже, а не крошкой.
     *
     * Крошке правится РАЗМЕР: 0.19→0.58 м вместо 0.08–0.3 м, потому что
     * спрайт в 4 экранных пикселя весь состоит из кромки (см. шапку `dust`).
     * Число крошек здесь не ручка, а следствие: `kit.countFor` от площади
     * следа даёт в этой стойке 34 штуки, и нижний зажим не пускает ниже 30.
     */
    dustN: 44,          /* база плотности крошки трассы (в стойке даёт 30) */
    dustSize: 0.34,     /* базовый размер крошки трассы, м (было ~0.19) */
    chipN: 16,          /* обломков в точке прилёта */
    crackLen: 2.0,      /* размах разлома в точке прилёта, м */
    crackN: 3,          /* очагов разлома в точке прилёта */
    /*
     * `markR` — РАДИУС ЧАШИ НАБОРА, в долях радиуса удара. Круг 3 померил её
     * цену: болт на 1.20 с трансляции держал 3473 изменённых пикселя, из них
     * СЕРЫХ (S<0.15) 1746 (50 %), тёмных и насыщенных 1224 (35 %). Полкадра
     * следа — бледная размазня, потому что чаша считается с альфой 0.75 и
     * валом-константой (`kit.js`) и на белом полу светлеет при любом `tint`.
     * Круг 2 ужал её вдвое; круг 3 ужимает ещё и отдаёт место СВОЕЙ выбоине
     * (`pit`, `pitR`): тёмной, почти непрозрачной, с поднятыми кусками
     * породы. Чашу набора я оставляю — по ней стихию видно рядом с воронкой
     * другой стихии (`tint` = `mark`), — но она больше не несёт след одна.
     */
    /* Остаточная плотность разлома. Ниже ~0.9 тёмная сталь на белом полу
       уходит в серое (замер — в шапке `cracks`), поэтому ручка есть, но
       крутить её вниз значит гасить след. */
    crackRest: 0.95,
    markR: 0.3,         /* радиус чаши прилёта, м (круг 2 — 0.7) */
    pitR: 0.85,         /* радиус своей выбоины в точке прилёта, м */
    pitChunks: 3,       /* поднятых кусков породы по кромке выбоины */
    decalHold: 10,      /* стойкость воронки, с */
  });
  const A = [e.x0, S.y, e.z0], B = [e.x1, S.y, e.z1];
  const ux = (B[0] - A[0]) / fp.len, uz = (B[2] - A[2]) / fp.len;
  const LIFE = S.grow + S.duration + S.decay;

  /* РЕЛЬСОТРОН: тёмный стержень и открытые конусы уплотнения вдоль него —
     это не свет, а воздух, который не успел расступиться. Судья про прежние:
     «серые кости на проволоке» — там были БРУСКИ с ровной заливкой; конус
     обязан быть оболочкой, тёмной по силуэту и пустой в середине. */
  const g = new THREE.Group();
  const shaft = rod(P, A, B, S.width);
  g.add(shaft.mesh);
  const n = clampN(Math.round(S.cones), 2, 12);
  const cone = [];
  const cm = coneMat(P);
  for (let i = 0; i < n; i++) {
    const f = (i + 0.5) / n;
    const px = A[0] + ux * fp.len * f, pz = A[2] + uz * fp.len * f;
    /* Конус растёт к хвосту: у головы удара он узкий, позади — раскрыт. */
    const flare = S.width * (0.9 + f * S.coneFlare);
    const len = S.width * S.coneLen * (0.7 + f * 0.7);
    const mesh = new THREE.Mesh(coneGeo(), cm);
    mesh.position.set(px, S.y, pz);
    mesh.rotation.y = yawFor(ux, uz);
    mesh.scale.set(len, flare, flare);
    mesh.renderOrder = 8;
    mesh.frustumCulled = false;
    g.add(mesh);
    cone.push({ mesh, f });
  }
  /*
   * ЧТО У ЛУЧА ОСТАЛОСЬ НЕ ВЫЛЕЧЕНО (замер круга 3, честно). На 0.12 и 1.20 с
   * трансляции луч стал читаемым: 9356 изменённых пикселей при 57 % тёмных и
   * насыщенных и 14 % серых (было 6529 при 16 % и 50 %), 4463 при 40 % и 11 %
   * (было 2326 при 24 % и 18 %). А вот на 0.30 с серых 4766 из 10 996 (43 %),
   * и причин у этого две, обе — ЗАТУХАНИЕ ЧЕРЕЗ СЕРЕДИНУ:
   *   · ствол и конусы гаснут линейно за `decay`, и на 0.30 с их плотность
   *     0.78 — то самое «полупрозрачное», которого у кинетики быть не должно.
   *     Лечится так же, как вылечена волна: держать единицу и падать обрывом.
   *   · крошка на середине жизни: её альфа падает как `(1−возраст)^1.3`
   *     внутри `vfx.js`, и снаружи это не отключается (просьба к набору — в
   *     отчёте раунда).
   * Не тронул в этот круг сознательно: правку ствола пришлось бы снимать
   * заново, а кадры этого круга сняты ровно с тем кодом, который лежит здесь.
   */
  vfx.spawnMesh(g, LIFE, (o, u) => {
    const t = u * LIFE;
    const head = clamp01(t / Math.max(0.001, S.grow));
    const k = t < S.grow + S.duration ? 1 : Math.max(0, 1 - (t - S.grow - S.duration) / Math.max(0.001, S.decay));
    shaft.mesh.scale.set(fp.len * head, S.width, S.width);
    shaft.set(k);
    for (const c of cone) c.mesh.visible = c.f <= head && k > 0.02;
    cm.userData.fade.value = k;
  });

  /* БОРОЗДА: тёмная полоса на полу вдоль всей трассы. Без неё луч кинетики
     оставлял на белом полу только точку прилёта — с 26 м трассы не было
     видно вовсе (замер круга 1: 1798 изменённых пикселей на трансляции,
     из них почти все — воронка). */
  const fw = slab(P, {
    x: (A[0] + B[0]) / 2, z: (A[2] + B[2]) / 2, r: fp.len * 0.5, rz: S.furrowW,
    rot: yawFor(ux, uz), seed: (seed % 5) + 1,
  });
  vfx.spawnMesh(fw.mesh, S.furrowHold, (o, u) => {
    const t = u * S.furrowHold;
    fw.set(t < S.furrowHold * 0.5 ? 1 : Math.max(0, 1 - (t - S.furrowHold * 0.5) / (S.furrowHold * 0.5)),
      clamp01(t / Math.max(0.001, S.grow)));
  });

  /* Пыль, сорванная с пола по всей трассе. */
  /*
   * НИЖНИЙ ЗАЖИМ 12, А НЕ 30. Круг 3 поймал СВОЮ ЖЕ регрессию: крупная
   * крошка (0.19–0.58 м вместо 0.08–0.3) на 0.12 с даёт тёмный плотный
   * выброс, но к 0.30 с её альфа падает как `(1−возраст)^1.3` (`vfx.js`), и
   * тридцать крупных полупрозрачных спрайтов кроют больше площади, чем
   * тридцать мелких: на кадре `beam-t0_30-broadcast` серых стало 5906 из
   * 10 725 против 1012 из 3463 до правки. Размер оставляю (на 0.12 и 1.20 с
   * он выигрывает вчистую), а ЧИСЛО опускаю: прежний зажим в 30 не давал
   * `countFor` (17 в этой стойке) сработать вовсе.
   */
  const nd = clampN(kit.countFor(S.dustN, fp.area, kit.REF_AREA.beam, 220), 12, 220);
  vfx.body.emit(nd, (i, s) => {
    const f = rng();
    const lat = (rng() - 0.5) * 1.1;
    s.pos(A[0] + ux * fp.len * f - uz * lat, 0.1 + rng() * 0.4, A[2] + uz * fp.len * f + ux * lat);
    s.vel(-uz * (rng() - 0.5) * 2.2, rnd(0.6, 2.4, rng), ux * (rng() - 0.5) * 2.2);
    s.gravity(0, -2.4, 0);
    /* Крошка, не дым: полупрозрачный спрайт на белом полу выходит серым при
       любом цвете (замер — в шапке `dust`). */
    s.color(T.grit, T.deep);
    /* Жизнь короче (было 0.8–1.6 с): крошка обязана уйти, пока она плотная,
       а не висеть полупрозрачной. */
    s.life(vfx.now + f * S.grow, rnd(0.5, 1.0, rng), rnd(S.dustSize * 0.55, S.dustSize * 1.7, rng), kit.SHAPE.chip);
    s.ext(rnd(-4, 4, rng), 0.4, 1, 0);
  });
  chips(vfx, P, { x: B[0], y: 0.6, z: B[2], n: clampN(kit.countFor(S.chipN, fp.area, kit.REF_AREA.beam, 40), 8, 40), radius: 0.4, speed: 7, up: 5, rng, dir: Math.atan2(-ux, -uz), half: 1.1 });
  wave(vfx, P, { x: B[0], z: B[2], r0: 0.25, radius: 2.2, life: 0.42, seed: (seed % 5) + 1 });
  kit.decal(vfx, { type: 'crater', x: B[0], z: B[2], radius: S.markR, hold: S.decalHold, fade: 4, rise: 0.06, tint: T.mark, seed: (seed % 9) + 1 });
  cracks(vfx, P, { x: B[0], z: B[2], len: S.crackLen, rng, life: 2.2, focus: S.crackN, hold: S.decalHold, rest: S.crackRest });
  pit(vfx, P, { x: B[0], z: B[2], r: S.pitR, rng, hold: S.decalHold, chunks: S.pitChunks, seed: (seed % 9) + 1 });
  vfx.screen.shake(0.25);
  return true;
}

export function cone(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const T = tones(P);
  const fp = kit.footprint(e, ctx);
  const S = kit.tune(e, {
    sweep: 0.22,        /* за сколько фронт доходит до края, с */
    duration: 0.5,      /* сколько живёт пыль на полу, с */
    /* Крошек вдвое меньше и они крупнее. Замер круга 3 на кадре круга 2
       (`r70b/.../cone-t0_30-broadcast`): 11 565 изменённых пикселей при 178
       тёмных и насыщенных (2 %) и 4815 пастельных (42 %). Чем именно из
       слоёв конуса набраны эти 42 %, я по одному кадру не разделял — но
       двести крошек по 4–13 экранных пикселей в секторе 3.4 м это заведомо
       поле кромок, и сектор от них ничего не выигрывает. */
    dustN: 55,          /* база плотности крошки в секторе (было 200) */
    dustSize: 0.36,     /* базовый размер крошки, м (было ~0.21) */
    chipN: 26,          /* обломков */
    /*
     * СЛЕД КОНУСА — РАЗЛОМ, А НЕ ЧАША. На 1.20 с кадр конуса держали 4115
     * изменённых пикселей, из них читаемых 790 (19 %) при средней светлоте
     * 165: работал один след набора, а его чаша ограничена альфой 0.75 и
     * отсыпанным валом-константой (`kit.js`) и на белом полу всегда светлеет.
     * Поэтому чаша ужата (0.50 → 0.36 дальности), а разлом расширен: тёмное
     * и насыщенное должно занимать в остатке больше места, чем бледное.
     */
    crackLen: 1.7,      /* размах разломов, м */
    crackN: 3,          /* очагов разлома в секторе */
    /* Остаточная плотность разлома. Ниже ~0.9 тёмная сталь на белом полу
       уходит в серое (замер — в шапке `cracks`), поэтому ручка есть, но
       крутить её вниз значит гасить след. */
    crackRest: 0.95,
    markR: 0.16,        /* радиус чаши, в долях дальности (круг 2 — 0.36) */
    pitR: 0.4,          /* радиус своей выбоины, в долях дальности */
    pitChunks: 4,       /* поднятых кусков породы */
    decalHold: 9,       /* стойкость борозд, с */
  });
  /* ВАЛ ДАВЛЕНИЯ, идущий по сектору: своя тёмная волна, не аддитивная
     волна набора (см. шапку — у кинетики нет свечения нигде). */
  wave(vfx, P, {
    x: e.x, z: e.z, r0: 0.4, radius: fp.range, life: S.sweep,
    dir: fp.dir, half: fp.half, seed: (seed % 5) + 1,
  });
  /* Пластина пола под сектором: проявляется вслед за фронтом. */
  const sl = slab(P, { x: e.x + Math.sin(fp.dir) * fp.range * 0.45, z: e.z + Math.cos(fp.dir) * fp.range * 0.45, r: fp.range * 0.6, seed: (seed % 5) + 1 });
  vfx.spawnMesh(sl.mesh, S.duration + 0.6, (o, u) => {
    const t = u * (S.duration + 0.6);
    sl.set(t < S.duration ? 1 : Math.max(0, 1 - (t - S.duration) / 0.6), clamp01(t / S.sweep));
  });
  /* Нижний зажим 20, а не 60: та же арифметика, что у луча (см. там). Замер
     круга 3 на кадре `cone-t0_60-side`: 11 519 изменённых пикселей, из них
     4844 серых (42 %) — это девяносто крупных крошек в середине жизни, когда
     их альфа уже упала. Меньше числом — и полоса серого уходит. */
  const nd = clampN(kit.countFor(S.dustN, fp.area, kit.REF_AREA.cone, 420), 20, 420);
  /* Пыль рождается ВОЛНОЙ: доля пути = доля времени, иначе весь сектор
     вспыхивает разом и фронта не видно. */
  vfx.body.emit(nd, (i, s) => {
    const f = Math.sqrt(rng());
    const a = fp.dir + (rng() * 2 - 1) * fp.half;
    const d = fp.range * f;
    s.pos(e.x + Math.sin(a) * d, 0.1 + rng() * 0.4, e.z + Math.cos(a) * d);
    s.vel(Math.sin(a) * rnd(1.5, 4, rng), rnd(0.8, 2.6, rng), Math.cos(a) * rnd(1.5, 4, rng));
    s.gravity(0, -2.6, 0);
    /* Крошка, не дым: на 0.30 с прежний конус давал 11 565 изменённых
       пикселей, из которых тёмных 468 — «облако», а не фронт. */
    s.color(T.grit, T.deep);
    /* Жизнь короче: крошка обязана уйти, пока она плотная. */
    s.life(vfx.now + f * S.sweep, rnd(0.5, 1.0, rng), rnd(S.dustSize * 0.55, S.dustSize * 1.7, rng), kit.SHAPE.chip);
    s.ext(rnd(-4, 4, rng), 0.4, 1, 0);
  });
  chips(vfx, P, { x: e.x, y: 0.3, z: e.z, n: clampN(kit.countFor(S.chipN, fp.area, kit.REF_AREA.cone, 60), 10, 60), radius: 0.6, speed: 8, up: 5, rng, dir: fp.dir, half: fp.half });
  /* Разлом по сектору: колет пол там, куда дошёл фронт. */
  cracks(vfx, P, {
    x: e.x + Math.sin(fp.dir) * fp.range * 0.55, z: e.z + Math.cos(fp.dir) * fp.range * 0.55,
    len: S.crackLen, rng, life: 2.2, at: S.sweep * 0.6, focus: S.crackN, hold: S.decalHold, rest: S.crackRest,
  });
  kit.decal(vfx, { type: 'crater', x: e.x + Math.sin(fp.dir) * fp.range * 0.55, z: e.z + Math.cos(fp.dir) * fp.range * 0.55, radius: fp.range * S.markR, hold: S.decalHold, fade: 4, rise: 0.1, tint: T.mark, seed: (seed % 9) + 1 });
  pit(vfx, P, {
    x: e.x + Math.sin(fp.dir) * fp.range * 0.55, z: e.z + Math.cos(fp.dir) * fp.range * 0.55,
    r: fp.range * S.pitR, rng, hold: S.decalHold, chunks: S.pitChunks, growS: S.sweep, seed: (seed % 9) + 1,
  });
  vfx.screen.shake(0.2);
  return true;
}

export function zone(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const T = tones(P);
  const fp = kit.footprint(e, ctx);
  const S = kit.tune(e, {
    duration: Math.max(0.8, e.duration || 3),  /* жизнь зоны, с */
    grow: 0.25,          /* проявление плиты, с */
    period: 0.5,         /* как часто бьёт снова, с (тик зоны сима) */
    dustN: 26,           /* крошки на удар */
    dustSize: 0.32,      /* базовый размер крошки, м (было ~0.17) */
    chipN: 8,            /* обломков на удар */
    crackRest: 0.95,     /* остаточная плотность разлома (см. шапку `cracks`) */
    crackLen: 1.0,       /* размах разлома на удар, м */
    waveR: 1.4,          /* радиус волны удара, м */
    tiles: 5,            /* плит, на которые расколот пол зоны */
    chunks: 5,           /* поднятых кусков породы */
    chunkH: 0.28,        /* высота поднятого куска, м */
    markR: 0.3,          /* радиус чаши, в долях радиуса зоны (круг 2 — 0.72) */
    pitR: 0.34,          /* радиус своей выбоины в центре, в долях радиуса */
    pitChunks: 3,        /* поднятых кусков породы по кромке выбоины */
    decalHold: 12,       /* стойкость скола, с */
  });
  const D = S.duration, r = fp.radius;
  /*
   * РАЗБИТАЯ ПЛИТА, А НЕ СИНЯЯ ЛУЖА.
   *
   * Круг 2, `kinetic-zone-t0_60-broadcast`: одна ровная пластина радиусом 3 м
   * давала 19 511 изменённых пикселей — покрытие есть, формы нет. На кадре
   * это плоское синее пятно с ровным краем, ровно та «плоская крашеная
   * плоскость», за которую судья бил кислоту, гравитацию и радиацию. Кинетика
   * не красит пол, она его КОЛЕТ.
   *
   * Поэтому зона собрана из НЕСКОЛЬКИХ рваных плит разного размера и поворота
   * (между ними виден белый пол — шов), а из пола торчат поднятые куски
   * породы (`plateMat`: тёмная грань, светлый верх, фаска). Плиты берутся из
   * кольца `pooled` по шесть на ключ — больше шести брать нечего, седьмая
   * получила бы материал первой.
   */
  const g = new THREE.Group();
  const tiles = [];
  const nt = clampN(Math.round(S.tiles), 2, 6);
  for (let i = 0; i < nt; i++) {
    const a = (i / nt) * TAU + rng() * 0.6;
    /*
     * Плиты НЕ смыкаются: между ними обязан остаться белый пол. Первая проба
     * круга 2 (шесть плит радиусом до 0.44·r на расстоянии до 0.8·r) снова
     * слиплась в сплошное пятно — замер дал 19 147 изменённых пикселей при
     * читаемых 54 %, а на кадре это была лужа с рваным краем. Плиты меньше и
     * разнесены дальше: шов — это белый пол между ними, контраст в сотню
     * уровней, а не градиент альфы.
     */
    const d = i === 0 ? 0 : r * (0.46 + rng() * 0.38);
    const rr = r * (i === 0 ? 0.34 : 0.18 + rng() * 0.16);
    const t = slab(P, {
      x: e.x + Math.sin(a) * d, z: e.z + Math.cos(a) * d,
      r: rr, rz: rr * (0.6 + rng() * 0.7), rot: rng() * TAU,
      seed: (i % 5) + 1, y: 0.024 + i * 0.0012,
    });
    g.add(t.mesh);
    tiles.push(t);
  }
  const chunks = [];
  /* Один материал на все куски каста — см. `plate`. */
  const cm = plateMat(P);
  cm.userData.u.seed.value = (seed % 5) + 1;
  const nk = clampN(Math.round(S.chunks), 0, 6);
  for (let i = 0; i < nk; i++) {
    const a = rng() * TAU, d = Math.sqrt(rng()) * r * 0.78;
    const hh = S.chunkH * (0.6 + rng() * 0.9);
    const pl = plate(P, {
      /* Основание УТОПЛЕНО на 6 см: наклонённая метровая плита поднимает
         дальний угол на 15 см, и без утопления она парит над полом. */
      x: e.x + Math.sin(a) * d, y: -0.06, z: e.z + Math.cos(a) * d,
      w: r * (0.13 + rng() * 0.14), h: hh, d: r * (0.1 + rng() * 0.11),
      yaw: rng() * TAU, mat: cm,
    });
    /* Кусок стоит КРИВО: ровно поставленный он читается тумбой. */
    pl.mesh.rotation.z = (rng() - 0.5) * 0.35;
    g.add(pl.mesh);
    chunks.push({ pl, h0: hh });
  }
  const nd = clampN(kit.countFor(S.dustN, fp.area, kit.REF_AREA.zone, 60), 8, 60);
  const nc = clampN(kit.countFor(S.chipN, fp.area, kit.REF_AREA.zone, 24), 4, 24);
  let next = 0, hit = 0;
  vfx.spawnMesh(g, D + 0.5, (o, u) => {
    const t = u * (D + 0.5);
    const fade = t < D ? 1 : Math.max(0, 1 - (t - D) / 0.5);
    const rev = clamp01(t / S.grow);
    for (const tl of tiles) tl.set(fade, rev);
    for (const ch of chunks) { ch.pl.mesh.scale.y = ch.h0 * rev; ch.pl.set(fade); }
    if (t >= next && t < D) {
      next = t + S.period;
      hit++;
      /* Свой поток на удар — и НЕ `g`: так зовётся группа зоны выше. */
      const hg = mulberry((seed ^ Math.imul(hit, 0x9e3779b1)) >>> 0);
      const a = hg() * TAU, d = Math.sqrt(hg()) * r * 0.85;
      const hx = e.x + Math.sin(a) * d, hz = e.z + Math.cos(a) * d;
      dust(vfx, P, { x: hx, z: hz, n: nd, radius: 0.5, speed: 2.6, up: 1.8, size: S.dustSize, rng: hg });
      chips(vfx, P, { x: hx, z: hz, n: nc, radius: 0.3, speed: 5, up: 5, rng: hg });
      cracks(vfx, P, { x: hx, z: hz, len: S.crackLen, rng: hg, life: Math.min(2.4, D), rest: S.crackRest });
      wave(vfx, P, { x: hx, z: hz, r0: 0.15, radius: S.waveR, life: 0.35, seed: (hit % 5) + 1 });
      vfx.screen.shake(0.12);
    }
  });
  /* След — ОСТАТОК: скол переживает зону, но не на двадцать секунд. */
  kit.decal(vfx, { type: 'crater', x: e.x, z: e.z, radius: r * S.markR, hold: D + S.decalHold, fade: 4, rise: 0.12, tint: T.mark, seed: (seed % 9) + 1 });
  pit(vfx, P, { x: e.x, z: e.z, r: r * S.pitR, rng, hold: D + S.decalHold, chunks: S.pitChunks, growS: S.grow, seed: (seed % 9) + 1 });
  return true;
}

export function self(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const T = tones(P);
  const fp = kit.footprint(e, ctx);
  const S = kit.tune(e, {
    duration: 0.75,     /* беат каста, с */
    plates: 7,          /* сколько пластин брони */
    thick: 0.13,        /* толщина пластины, м */
    plateW: 0.66,       /* ширина щитка, м */
    height: 0.85,       /* высота щитка в долях роста тела */
    dustN: 22,
    crackSpan: 2.4,     /* размах разлома, в радиусах кольца щитков */
    /* Остаточная плотность разлома. Ниже ~0.9 тёмная сталь на белом полу
       уходит в серое (замер — в шапке `cracks`), поэтому ручка есть, но
       крутить её вниз значит гасить след. */
    crackRest: 0.95,
    markR: 0.36,        /* радиус чаши, в радиусах кольца (круг 2 — 0.8) */
    pitR: 0.62,         /* радиус своей выбоины под упором, в радиусах кольца */
    pitChunks: 4,       /* поднятых кусков породы по кромке */
    decalHold: 8,       /* стойкость упора под ногами, с */
  });
  const bs = ctx && ctx.bodyShape ? ctx.bodyShape(e.who) : null;
  const R = (bs ? bs.r : 0.9) * 1.35, H = (bs ? bs.h : 2.0);
  const at = () => (ctx && ctx.bodyPos ? ctx.bodyPos(e.who) : null) || { x: e.x, z: e.z };
  const p0 = at();
  /* УПОР, А НЕ ПУЗЫРЬ: пластины встают вокруг бойца кольцом и упираются в
     пол. Сфера вокруг тела читается энергетическим щитом — а кинетике нужна
     броня, то есть вещество. Плиты — те же, что у стены (`plateMat`): тёмная
     грань, светлая верхняя, резкая фаска по кромке. */
  const g = new THREE.Group();
  const set = [];
  /* Один материал на все щитки каста — см. `plate`. */
  const pm = plateMat(P);
  pm.userData.u.seed.value = (seed % 5) + 1;
  const n = clampN(Math.round(S.plates), 3, 12);
  for (let i = 0; i < n; i++) {
    const a = (i / n) * TAU + rng() * 0.2;
    const px = p0.x + Math.sin(a) * R, pz = p0.z + Math.cos(a) * R;
    /* `yaw = a` уносит местную +Z (толщину) наружу, местную +X (ширину) — по
       касательной: щиток стоит поперёк, а не рёбрами к зрителю. */
    const pl = plate(P, { x: px, z: pz, w: S.plateW, h: H * S.height, d: S.thick, yaw: a, mat: pm });
    g.add(pl.mesh);
    set.push({ pl, a });
  }
  vfx.spawnMesh(g, S.duration, (o, u) => {
    const p = at();
    const k = u < 0.3 ? u / 0.3 : Math.max(0, 1 - (u - 0.3) / 0.7);
    for (let i = 0; i < set.length; i++) {
      const { pl, a } = set[i];
      /* Пластины ВЫЛЕТАЮТ наружу на месте: смещение от тела растёт с рывком. */
      const rr = R * (0.55 + 0.45 * Math.min(1, u / 0.3));
      pl.mesh.position.set(p.x + Math.sin(a) * rr, 0.02, p.z + Math.cos(a) * rr);
      pl.set(k);
    }
  });
  dust(vfx, P, { x: p0.x, z: p0.z, n: clampN(kit.countFor(S.dustN, fp.area, kit.REF_AREA.self, 60), 8, 60), radius: R, speed: 2, up: 1.2, rng });
  /*
   * СЛЕД УПОРА. Щитки живут 0.75 с, и на 1.2 с от щита оставалась только чаша
   * воронки: замер круга 2 — 4425 изменённых пикселей, из них читаемых 745
   * (17 %) при средней (162,170,177). Чаша набора ограничена альфой 0.75 и
   * на белом полу всегда светлеет; разлом — нет. Боец УПЁРСЯ: пол под ним
   * треснул, и это то, что переживает беат.
   *
   * РАЗМАХ — ОТ КОЛЬЦА ЩИТКОВ, А НЕ В МЕТРАХ. Первая проба ставила разлом на
   * 1.15 м, и он дал ровно 147 изменённых пикселей: щупальца осьминога
   * расходятся на два метра и накрыли его целиком. Трещина обязана выходить
   * ЗА силуэт того, кто упёрся, поэтому её размах считается от `R`.
   */
  cracks(vfx, P, { x: p0.x, z: p0.z, len: R * S.crackSpan, rng, life: 2.0, focus: 2, hold: S.decalHold, rest: S.crackRest });
  kit.decal(vfx, { type: 'crater', x: p0.x, z: p0.z, radius: R * S.markR, hold: S.decalHold, fade: 3, rise: 0.1, tint: T.mark, seed: (seed % 9) + 1 });
  pit(vfx, P, { x: p0.x, z: p0.z, r: R * S.pitR, rng, hold: S.decalHold, chunks: S.pitChunks, seed: (seed % 9) + 1 });
  vfx.screen.shake(0.15);
  return true;
}

/** Снаряд: болт — слуг по прямой, навес — та же масса по параболе. */
function slug(vfx, e, P, ctx, arc) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const T = tones(P);
  const fp = kit.footprint(e, ctx);
  const S = kit.tune(e, {
    speed: e.speed || (arc ? 12 : 22),
    size: 0.22,          /* размер слуга, м */
    y: arc ? 1.3 : 1.15, /* высота вылета, м */
    gravity: 18,         /* тяжесть параболы, м/с² */
    trail: 0.07,         /* как часто сыпать след, с (было 0.05) */
    hitRadius: 1.2,
    /* Крошек вдвое меньше и они крупнее: мелкая крошка на белом полу — это
       серый пиксель по площади, а не по цвету (см. шапку `dust`). */
    dustN: 20,           /* крошек в точке прилёта (было 40) */
    dustSize: 0.34,      /* базовый размер крошки, м */
    chipN: 12,           /* обломков в точке прилёта (было 22) */
    crackLen: 2.1,       /* размах разлома, м */
    crackN: 3,           /* очагов разлома */
    /*
     * `markR` — РАДИУС ЧАШИ НАБОРА. Круг 3 перемерил её цену на кадрах круга
     * 2: болт на 1.20 с трансляции — 3473 изменённых пикселя, СЕРЫХ (S<0.15)
     * 1746 (50 %), тёмных и насыщенных 1224 (35 %). Чаша считается с альфой
     * 0.75 и валом-константой (`kit.js`) и на белом полу светлеет при любом
     * `tint`. Поэтому она ужата ещё раз, а след держит СВОЯ выбоина `pit`
     * (`pitR`): тёмная, почти непрозрачная, с поднятыми кусками породы.
     */
    /* Остаточная плотность разлома. Ниже ~0.9 тёмная сталь на белом полу
       уходит в серое (замер — в шапке `cracks`), поэтому ручка есть, но
       крутить её вниз значит гасить след. */
    crackRest: 0.95,
    markR: 0.3,          /* радиус чаши, в долях радиуса удара (круг 2 — 0.7) */
    pitR: 0.62,          /* радиус своей выбоины, в долях радиуса удара */
    pitChunks: 3,        /* поднятых кусков породы по кромке выбоины */
    decalHold: 10,
  });
  const ux = Math.sin(e.h), uz = Math.cos(e.h);
  const len = Math.max(1.2, fp.range);
  const Tt = len / Math.max(4, S.speed);
  const bs = ctx && ctx.bodyShape ? ctx.bodyShape(e.who) : null;
  const off = (bs ? bs.r : 0.7) + 0.1;
  const A = [e.x + ux * off, S.y, e.z + uz * off];
  /* Парабола выводится из дальности и скорости, а не из двух магических
     чисел: у 6-метрового и 22-метрового навеса угол вылета обязан отличаться. */
  const vy = arc ? (S.gravity * Tt) / 2 : 0;

  const state = { hit: null };
  vfx.flight(e.who, e.skill, state);

  const m = barMat(P);
  const mesh = new THREE.Mesh(chipGeo(), m);
  mesh.scale.setScalar(S.size);
  mesh.renderOrder = 9;
  mesh.frustumCulled = false;
  mesh.position.set(A[0], A[1], A[2]);
  const nd = clampN(kit.countFor(S.dustN, fp.area, kit.REF_AREA.impact, 90), 12, 90);
  const nc = clampN(kit.countFor(S.chipN, fp.area, kit.REF_AREA.impact, 50), 8, 50);
  let done = false, trailAt = 0;
  vfx.spawnMesh(mesh, Tt + 0.5, (o, u) => {
    const t = u * (Tt + 0.5);
    if (done) return;
    const land = state.hit ? true : t >= Tt;
    if (!land) {
      const f = t / Tt;
      const x = A[0] + ux * len * f, z = A[2] + uz * len * f;
      const y = Math.max(0.2, A[1] + vy * t - 0.5 * S.gravity * t * t);
      o.position.set(x, y, z);
      o.rotation.set(t * 9, t * 6, t * 3);
      m.userData.fade.value = 1;
      if (t >= trailAt) {
        trailAt = t + S.trail;
        dust(vfx, P, { x, y, z, n: 3, radius: 0.15, speed: 0.4, up: 0.2, life: 0.5, size: 0.28, rng });
      }
      return;
    }
    done = true;
    o.visible = false;
    const X = state.hit ? state.hit.x : A[0] + ux * len;
    const Z = state.hit ? state.hit.z : A[2] + uz * len;
    /* Прилёт массы: волна, пыль, обломки, разлом, скол, отдача камеры. */
    wave(vfx, P, { x: X, z: Z, r0: 0.25, radius: S.hitRadius * 2.2, life: 0.45, seed: (seed % 5) + 1 });
    dust(vfx, P, { x: X, z: Z, n: nd, radius: S.hitRadius, speed: 3.4, up: 2.4, size: S.dustSize, rng });
    chips(vfx, P, { x: X, z: Z, n: nc, radius: 0.4, speed: 8, up: 7, rng });
    cracks(vfx, P, { x: X, z: Z, len: S.crackLen, rng, life: 2.4, focus: S.crackN, hold: S.decalHold, rest: S.crackRest });
    kit.decal(vfx, { type: 'crater', x: X, z: Z, radius: S.hitRadius * S.markR, hold: S.decalHold, fade: 4, rise: 0.06, tint: T.mark, seed: (seed % 9) + 1 });
    pit(vfx, P, { x: X, z: Z, r: S.hitRadius * S.pitR, rng, hold: S.decalHold, chunks: S.pitChunks, seed: (seed % 9) + 1 });
    vfx.screen.shake(arc ? 0.3 : 0.25);
    vfx.flights.delete(`${e.who}:${e.skill}`);
  });
  /* Отдача у ствола: пыль назад и вбок. */
  dust(vfx, P, { x: A[0], y: A[1], z: A[2], n: 14, radius: 0.3, speed: 2.4, up: 0.8, life: 0.7, rng, dir: e.h + Math.PI, half: 0.8 });
  return true;
}

