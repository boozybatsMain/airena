/*
 * ── РАЗЛОМ ────────────────────────────────────────────────────────────────
 *
 * Судья про прежние трещины: «это буквально астериск — семь несужающихся
 * лучей одной длины через ОДИН узел» (кадр `kinetic-bolt-t1_20-broadcast`,
 * коробка 720,590,860,710). Настоящий разлом ветвится, сужается и не расходится
 * ровно из точки.
 *
 * Поэтому здесь строится ЛЕНТА: ломаная с убывающими коленами, шириной,
 * падающей к острию, с развилкой на втором-третьем узле и со стартом,
 * смещённым от центра. Готовых вариантов четыре, они `shared` и строятся один
 * раз от фиксированного сида — «геометрия через `shared()`, ни одной
 * аллокации на каст». Каст выбирает вариант, поворачивает и масштабирует.
 *
 * Атрибут `adist` — доля пути от очага (0…1); по нему материал гонит фронт.
 */
function makeFracture(rng) {
  const pos = [], adist = [];
  let maxD = 0.001;
  const tri = (a, b, c) => {
    pos.push(a[0], 0, a[1], b[0], 0, b[1], c[0], 0, c[1]);
    adist.push(a[2], b[2], c[2]);
  };
  /** Одна ломаная: узлы, сужение, лента. Возвращает узлы для развилки. */
  const line = (x0, z0, ang, len, w0, segs) => {
    const pts = [{ x: x0, z: z0, s: 0 }];
    let px = x0, pz = z0, a = ang, acc = 0;
    /* Колена убывают: у трещины первый шаг длинный, дальше она дробится. */
    const q = 0.72;
    let sum = 0;
    for (let k = 0; k < segs; k++) sum += Math.pow(q, k);
    for (let k = 0; k < segs; k++) {
      const sl = (len / sum) * Math.pow(q, k);
      a += (rng() - 0.5) * 0.85;
      px += Math.sin(a) * sl; pz += Math.cos(a) * sl; acc += sl;
      pts.push({ x: px, z: pz, s: acc });
    }
    /* Нормали в узлах — усреднённые: лента без разрывов на изломах. */
    const nx = [], nz = [];
    for (let k = 0; k < pts.length; k++) {
      const p = pts[Math.max(0, k - 1)], n = pts[Math.min(pts.length - 1, k + 1)];
      const dx = n.x - p.x, dz = n.z - p.z, L = Math.hypot(dx, dz) || 1e-4;
      nx.push(dz / L); nz.push(-dx / L);
    }
    const side = [];
    for (let k = 0; k < pts.length; k++) {
      const t = pts[k].s / len;
      /*
       * Сужение 1.15, а не 1.35. Замер круга 3: замах на 1.20 с трансляции
       * держали 326 изменённых пикселей, из них тёмных и насыщенных 91
       * (28 %) — лента шириной 0.14 м с 26 м это 6 экранных пикселей, у
       * которых почти всё — сглаженная кромка, и резкое сужение убивало
       * вторую половину луча совсем. Ленте нужна не длина, а ТЕЛО.
       */
      const w = w0 * Math.pow(Math.max(0, 1 - t), 1.15);
      const d = pts[k].s;
      if (d > maxD) maxD = d;
      side.push([
        [pts[k].x + nx[k] * w * 0.5, pts[k].z + nz[k] * w * 0.5, d],
        [pts[k].x - nx[k] * w * 0.5, pts[k].z - nz[k] * w * 0.5, d],
      ]);
    }
    for (let k = 0; k < side.length - 1; k++) {
      const [al, ar] = side[k], [bl, br] = side[k + 1];
      tri(al, ar, bl);
      tri(ar, br, bl);
    }
    return pts;
  };

  const n = 5 + Math.floor(rng() * 2);
  let a = rng() * TAU;
  for (let i = 0; i < n; i++) {
    /* Шаг по углу НЕРОВНЫЙ: у астериска он был ровно TAU/n. */
    a += (TAU / n) * (0.45 + rng() * 1.1);
    /* Очаг смещён от центра: лучи не сходятся в одну точку. */
    const off = 0.04 + rng() * 0.13;
    const oa = a + (rng() - 0.5) * 1.4;
    const x0 = Math.sin(oa) * off, z0 = Math.cos(oa) * off;
    const L = 0.46 + rng() * 0.5;
    /* Ширина у очага: 0.085–0.135 доли размаха вместо 0.055–0.09. При
       размахе 2.1 м это 0.18–0.28 м, то есть 8–12 экранных пикселей с 26 м —
       у ленты появляется плотная сердцевина, а не одна кромка. */
    const w0 = 0.085 + rng() * 0.05;
    const pts = line(x0, z0, a, L, w0, 4);
    /* Развилка: ветвь тоньше и короче родителя, отходит под 30–60°. */
    const bi = 1 + Math.floor(rng() * 2);
    const b = pts[bi];
    const t = b.s / L;
    line(b.x, b.z, a + (rng() < 0.5 ? -1 : 1) * (0.5 + rng() * 0.55),
      L * (0.28 + rng() * 0.26), w0 * Math.max(0.25, 1 - t) * 0.7, 3);
  }
  const g = new THREE.BufferGeometry();
  g.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
  g.setAttribute('adist', new THREE.Float32BufferAttribute(adist.map((d) => d / maxD), 1));
  g.computeVertexNormals();
  g.computeBoundingSphere();
  return shared(g);
}
function fractureGeo(i) {
  if (!FRACT.length) for (let v = 0; v < 4; v++) FRACT.push(makeFracture(mulberry(0x1c3a5 + v * 977)));
  return FRACT[((i % FRACT.length) + FRACT.length) % FRACT.length];
}

