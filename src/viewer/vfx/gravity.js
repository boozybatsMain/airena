/**
 * ЗОНА — колодец. Ядро ПРИХОДИТ СВЕРХУ (`coreFrom` → `coreTo` за `grow`),
 * стоит, и в конце уходит в ноль за `end`. Под ним — продавленная чаша ровно
 * на его жизнь, по её кромке — вал пыли, внутри — отвесно падающее вещество,
 * поверх — линза. Порядок важен: чаша и вал живут `D`, вещество сеется
 * порциями и каждая порция умирает у пола, поэтому к концу зоны гасить
 * приходится только два меша и след.
 *
 * `coreFrom` — та самая ручка, из-за которой воронка от навеса перестала
 * «появляться заново»: навес ставит её в высоту касания (см. `lob`), и там,
 * где снаряд тронул пол, колодец и начинается — а не в четырёх метрах над
 * ним.
 */
export function zone(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const fp = kit.footprint(e, ctx);
  /* Жизнь зоны из сима — она же мера для следа и для схлопывания. */
  const DUR = Math.max(0.8, e.duration || 3);
  const S = kit.tune(e, {
    duration: DUR,        /* жизнь колодца, с */
    radius: fp.radius,    /* радиус зоны, м */
    grow: 0.25,           /* спуск и рост ядра, с */
    /*
     * СХЛОПЫВАНИЕ 0.68 с, БЫЛО 0.35, ПОТОМ 0.55. Судьи первого круга не
     * смогли сказать, «щёлкнул уход или растаял»: между кадрами 1.5 с и 4.0 с
     * не было ни одного снимка, а сам уход укладывался в 0.35 с — короче
     * интервала между любыми двумя моментами прогона. Полсекунды видно
     * ГЛАЗОМ и попадает в кадр 2.6 с: колодец там уже присел, но ещё стоит.
     * Заказ основателя требует «не резко, а с плавным затуханием», и 0.35 с
     * этому не отвечали.
     *
     * 0.55 тоже не отвечали, и это назвал судья затухания r2: он поставил
     * `gravity.js` `end: 0.55` в один ряд с `time.js` 0.15 и `void.js` 0.4 —
     * «либо довести до 0.6+, либо объявить схлопывание отдельным жестом».
     * Отдельным жестом оно не является: колодец не хлопает, он оседает.
     * Поэтому число поднято ВЫШЕ пола слоя (`kit.FADE_MIN` = 0.6), а не
     * подведено к нему впритык — ровно настолько, чтобы уход был длиннее
     * пола на те же 13 %, на какие вход `GROW` = 0.25 с короче его.
     */
    end: 0.68,            /* схлопывание в конце, с (не быстрее kit.FADE_MIN) */
    /* Ядро приходит с 5.6 м, а не с 4: путь до 3.4 м должен остаться ПУТЁМ,
       иначе спуск в 0.25 с превращается в появление на месте. */
    coreFrom: 5.6,        /* высота, С КОТОРОЙ приходит ядро, м */
    /*
     * 3.4 М, БЫЛО 1.6. На 1.6 м ядро висело ровно там, где стоит жертва:
     * соответствие силуэта чистому кадру в рамке тела
     * (`p5-gravity/gravity-zone-t1_50-top`, 826,550–960,707) — r = 0.614, с
     * трансляции шар закрывал корпус целиком. Верхний глаз смотрит под
     * 65.9°, и точка на высоте `h` уезжает в кадре на `h·0.446`: 3.4 м
     * уводят ядро на 1.5 м от проекции тела, тогда как 1.6 м уводили на
     * 0.7 м — то есть ровно на голову. С трансляции же 3.4 м просто выше
     * двухметрового бойца: силуэт цел, а у колодца появляется вертикаль,
     * которой с 26 м не было.
     */
    coreTo: 3.4,          /* высота, на которой оно повисает, м */
    coreR0: 0.35,         /* радиус ядра при рождении, м */
    /* 0.75 м, было 1.1. Два двадцать поперёк — это шире бойца; подняв ядро,
       нельзя оставить ему прежний размер, иначе сверху оно закрывает жертву
       так же, как закрывало сбоку. */
    coreR1: 0.75,         /* радиус ядра после спуска, м */
    /*
     * ЗАЛИВКА 0.94, И ЕЁ ФОРМИРУЕТ `dome` В МАТЕРИАЛЕ. Считать надо не эту
     * цифру, а то, что из неё выходит в середине шара: 0.94·0.88 = 0.83 —
     * ровно столько тяжести стоит между верхним глазом и головой жертвы,
     * остальное её силуэт проходит. Промежуточные прогоны этого круга, кадр
     * 1.5 с с трансляции (пол L 222): плоская заливка 0.78
     * (`wip-gravity-a`) давала в шаре L 143 — светло-серый пузырь, а не
     * тяжесть; плоская 0.86 (`wip-gravity-c`) — L 111, но ровным кругом без
     * объёма; 0.94·0.82 при линзе вполсилы — снова L 140, потому что линза
     * затаскивала на шар белый пол. Итог канона (`r2-gravity`): 0.94·0.88 при
     * линзе 0.35 — в шаре L 120…126 при кромке 92…105, то есть и вес, и
     * объём, и силуэт жертвы под ним.
     */
    coreFill: 0.94,       /* плотность ядра, 0..1 */
    ringScale: 0.95,      /* кольца сжатия, доли радиуса */
    ringDepth: 1,         /* глубина продавленной чаши, 0..1 */
    shaftScale: 0.98,     /* вал пыли по кромке, доли радиуса */
    /*
     * 2.2 М ГЕОМЕТРИИ ПОД ГРЕБЕНЬ В 0.8…1.8 М. Контрольный прогон 04.09
     * (`wip-gravity-dbg`, тот же вал, покрашенный в красное с альфой 0.9)
     * показал, что при `shaftHeight` 1.6 гряда занимала на трансляции полосу
     * в 40 пикселей — 0.77 м при 52 пикселях на метр в этом кадре, — и на
     * штатной альфе её не было видно вовсе, ровно как записал судья. Гребень
     * на 0.6 ± 0.2 от 2.2 м даёт 1.3 ± 0.44 м: с 26 м это 70 ± 23 пикселя,
     * то есть вал ростом с половину бойца — высота, которую видно.
     */
    shaftHeight: 2.2,     /* высота вала, м */
    shaftAlpha: 1,        /* плотность вала, 0..1 */
    /*
     * ЛИНЗА СТОИТ НА ЯДРЕ, А НЕ ПОД НИМ, И ОТ ЭТОГО ЗАВИСИТ ВСЁ ОСТАЛЬНОЕ.
     *
     * Здесь стояло 1.1 м — высота, оставшаяся от старого ядра на 1.6 м. Ядро
     * подняли на 3.4 м, а линзу забыли, и получилась ровно та картина, за
     * которую r2 записал «шар без искажения»: маска `kit.lens` — `(1−r)^1.5`
     * от ЦЕНТРА квада, ядро отстояло от центра на 2.3 м при полуразмере
     * 3.3 м, то есть `r = 0.70`, маска `0.30^1.5 = 0.16`, и на треть силы это
     * 0.057 — шесть сотых искривления там, где висит масса. Искажение честно
     * работало ПОД ядром и не работало НА нём.
     *
     * Это же снимает и старый довод против полной силы. Хром («затаскивала на
     * чёрный шар куски белого пола», `p5-gravity/gravity-zone-t0_40-
     * broadcast`) брался оттого, что центр стяжки был НИЖЕ шара: пиксель на
     * шаре сдвигался к центру линзы и приносил оттуда белый пол. Центр,
     * совпавший с ядром, приносит на шар сам шар — по построению, а не по
     * удаче. Поэтому `null` («по ядру»), сила 0.7 и квад ужат с 2.2 до 1.8
     * радиуса: стяжка собрана вокруг горизонта, а не размазана по всей зоне.
     */
    lensY: null,          /* высота линзы над полом, м (null — по ядру, `coreTo`) */
    lensScale: 1.8,       /* размер линзы, доли радиуса */
    lensStrength: 0.7,    /* сила линзы, 0..1 */
    decalScale: 1.1,      /* след на полу, доли радиуса */
    /*
     * СЛЕД ДЕРЖИТСЯ РОВНО СТОЛЬКО, СКОЛЬКО СТОИТ КОЛОДЕЦ. Прежде здесь было
     * 20 с, и стояло это по письменному требованию плана («каждый каст обязан
     * оставить стойкий след на полу, hold ~20 s», docs/VFX-PLAN.md §6.2), —
     * один круг правок значение уже откатывал обратно к двадцати. Заказ
     * основателя 04.09 правило снял дословно: «эффект сработал — лужа пусть
     * исчезает сразу после эффекта, не моментально, а постепенно». Тот же
     * приём уже стоит у времени (`time.js`, `decalHold: null` у зоны, стены и
     * каста-себя, там же записана прежняя жалоба на двадцатисекундную метку
     * от трёхсекундной зоны) — здесь он повторён буквально: `null` значит
     * «жизнь колодца `D`», то есть 3 с у обычной зоны и 1.6 с у воронки
     * навеса.
     */
    decalHold: null,      /* стойкость следа, с (null — ровно жизнь колодца) */
    /*
     * УХОД — РАСПРЯМЛЕНИЕ, А НЕ ИСПАРЕНИЕ. Вещество следа гравитации не лужа и
     * не ожог, а ВМЯТИНА: пол отпускает её пружиной, и чем глубже продавили,
     * тем дольше он это делает. Отсюда порядок ухода по всему модулю: колодец
     * зоны (радиус 3 м, давит целых три секунды) — 2.2 с; воронка навеса
     * (1.6 м, 1.6 с) — 1.6 с; удар и масса-на-себя, мелкие вмятины, — 1.2 с.
     * Быстрее нельзя: сам колодец приседает за `end` = 0.55 с, и след,
     * уходящий с его скоростью, читался бы выключателем, а заказ требует
     * именно «постепенно». Замер плавности — кадры 2.6 / 3.2 / 4.0 с в
     * `reports/vfx/r2-gravity`: на 2.6 колодец уже приседает, на 3.2 от него
     * остался только след, на 4.0 след наполовину растворился.
     */
    decalFade: 2.2,       /* уход следа, с */
    /* Пыли ВТРОЕ больше и сеется она чаще: 120 штук раз в 0.3 с на диск в 28 м²
       — это четыре штриха на квадратный метр за секунду, то есть пустой
       колодец. Шахта без падающего в ней вещества — просто серый цилиндр. */
    dust: 400,            /* пыль на эталонную площадь зоны, штук */
    dustEvery: 0.2,       /* период подсева пыли, с */
    dustFall: 22,         /* ускорение вещества в колодце, м/с² */
    dustFrom: 2.4,        /* нижняя граница рождения пыли, м */
    dustTo: 4.6,          /* верхняя граница рождения пыли, м */
    pull: 5,              /* штрихов сноса к кастеру за такт, штук */
    pullEvery: 0.5,       /* такт сноса, с (= `ZONE_PERIOD` симуляции) */
    debrisY: 0.5,         /* высота вылета обломков, м */
    debrisSpeed: 1.2,     /* разлёт обломков, м/с */
    debrisUp: 1.6,        /* подброс обломков, м/с */
    debrisLife: 1.4,      /* жизнь обломка, с */
    debrisSize: 0.3,      /* размер обломка, м */
    waveScale: 1.3,       /* выдох наружу, доли радиуса */
    waveLife: 0.5,        /* жизнь выдоха, с */
    waveN: 34,            /* штрихов в выдохе, штук */
    waveAt: null,         /* когда выдох, с от начала (null — на схлопывании) */
  });
  const r = S.radius;
  const D = Math.max(0.8, S.duration);
  /* Обе фазы не длиннее половины жизни: у зоны в 0.8 с рост и схлопывание
     иначе перекрываются и колодец не успевает ПОСТОЯТЬ. */
  const GROW = Math.max(0.001, Math.min(S.grow, D * 0.5));
  const END = Math.max(0.001, Math.min(S.end, D * 0.5));

  /* След — первым делом: он размечает площадь. Это ОСТАТОК (вмятина в полу), а
     не проекция живого колодца, — но переживает он колодец теперь ровно на
     один свой уход: держится жизнь колодца `D` и растворяется за `decalFade`.
     Обе величины — ручки описи, и обе крутятся в песочнице. */
  kit.decal(vfx, {
    type: 'grav', x: e.x, z: e.z, radius: r * S.decalScale, tint: P[2], seed: (seed % 9) + 1,
    hold: S.decalHold == null ? D : S.decalHold, fade: S.decalFade,
  });
  /* Кольца — ПРОЕКЦИЯ живого колодца на пол: живут ровно его жизнь и гаснут
     ровно его схлопыванием (`out: END`), а не своей отдельной третью
     секунды. */
  rings(vfx, P, { x: e.x, z: e.z, r: r * S.ringScale, life: D, depth: S.ringDepth, out: END });
  /* Вал пыли — то же самое, но в высоту: кромка ямы, а не её след. Ставится
     ПОСЛЕ колец и ДО ядра, чтобы порядок отрисовки шёл снизу вверх. */
  if (S.shaftAlpha > 0 && S.shaftHeight > 0) {
    shaft(vfx, P, {
      x: e.x, z: e.z, r: r * S.shaftScale, h: S.shaftHeight,
      life: D, grow: GROW, end: END, alpha: S.shaftAlpha,
    });
  }
  /* Линза на всю жизнь зоны: она ОТПУСКАЕТ за 0.3 с, а не гаснет от рождения. */
  /* `null` — «по ядру»: тот же приём, что у `decalHold`, и по той же причине
     — чтобы ручка, которую никто не крутил, не разъезжалась с тем, что она
     описывает. Навес свою высоту передаёт явно (`blastLensY` 0.6 при ядре
     воронки на 0.22 м) и остаётся при своём.

     ЛИНЗА ОТПУСКАЕТ ВМЕСТЕ С КОЛОДЦЕМ, А НЕ ПО СВОИМ ЧАСАМ. `kit.lens`
     держит силу всю жизнь и снимает её за последние 0.3 с — это её правило и
     оно верное, но при `END` = 0.68 с получалось, что пространство
     распрямляется вдвое быстрее, чем оседает масса, которая его гнула. На
     замере это видно прямо: с `life: D` общая огибающая формы падала за 0.23 с
     — и держал этот срок не колодец (его полином даёт 0.375 с), а именно
     трёхдесятковый сброс линзы. Жизнь укорочена так, чтобы её сброс лёг на
     НАЧАЛО схлопывания: `D − END + 0.3`. */
  kit.lens(vfx, {
    x: e.x, y: S.lensY == null ? S.coreTo : S.lensY, z: e.z,
    size: r * S.lensScale, life: Math.max(0.3, D - END + 0.3), strength: S.lensStrength,
  });

  const core = well(P, S.coreR0);
  core.mesh.position.set(e.x, S.coreFrom, e.z);
  /* Состояние ставится ДО первого кадра. Материал взят из кольца пула и несёт
     затухание прошлого владельца, а `updateFx` не обходит то, что родилось
     внутри его же цикла, — без этой строки на кадре передачи «навес →
     воронка» ядро мигнёт чужой прозрачностью. */
  core.set(1, S.coreR0, S.coreFill);
  /* Плотность — от ПЕРЕНАСТРОЕННОГО радиуса, а не от следа умения: иначе
     раскрученная ручкой зона сеет пыль по старой площади. */
  const nDust = clampN(kit.countFor(S.dust, Math.PI * r * r, kit.REF_AREA.zone, 400), 40, 400);
  /* Выдох — на схлопывании, как и сказано ниже: раньше он уходил в кадре
     рождения, то есть за целую жизнь зоны ДО того, чему он итог. Воронка от
     навеса передаёт `waveAt` 0 — там выдох и есть удар о пол. */
  const waveAt = S.waveAt == null ? Math.max(0, D - END) : S.waveAt;
  /* Тянет ли эта зона — СПРАШИВАЕМ У ЗАПИСИ, а не решаем за сим: половина зон
     гравитации ничего не тянет, и снос в них был бы враньём (см. шапку). */
  const pulls = Array.isArray(e.effects) && e.effects.includes('pull');
  let next = 0, nextPull = 0, waved = false;
  vfx.spawnMesh(core.mesh, D, (o, u) => {
    const t = u * D;
    const k = clamp01(t / GROW);
    /* Ядро ОПУСКАЕТСЯ с `coreFrom` до `coreTo` и растёт `coreR0` → `coreR1`:
       колодец не появляется, он приходит. Высота 3.4 м (опись выше: на 1.6 м
       шар съедал силуэт жертвы). У воронки от навеса `coreFrom`
       равен высоте касания, и тогда эта же формула не роняет ядро, а
       осаживает его в пол. */
    const drop = S.coreFrom - (S.coreFrom - S.coreTo) * k * k;
    const cr = S.coreR0 + (S.coreR1 - S.coreR0) * k;
    /*
     * СХЛОПЫВАНИЕ ГАСИТ, А НЕ ТОЛЬКО СЖИМАЕТ, — И ЭТО БЫЛ КРАСНЫЙ ГЕЙТ.
     *
     * Здесь стояло `core.set(1, cr * end, ...)`: ядро всю свою жизнь держало
     * непрозрачность РОВНО ЕДИНИЦУ и уменьшалось в радиусе, а потом пул
     * снимал меш со сцены. Для глаза это уже почти уход, для замера — обрыв:
     * `checkdecay` меряет ОГИБАЮЩУЮ по всем носителям формы, максимум из
     * них, и максимум держала единица ядра. Прогон: «gravity/zone: общая
     * огибающая падает за 0.08 c (нужно ≥ 0.18)» — 0.08 с это ОДИН ШАГ ПРОБЫ
     * (`FADE_MIN/8` = 0.075), то есть кривая падала с единицы в ноль между
     * двумя соседними отсчётами. Чаша и вал в этот момент честно гасли
     * линейно за `END`, но их не видно под единицей ядра.
     *
     * Рецепт взят у пустоты (`void.js`, яма статуса: «плотность снимается до
     * того, как меш прячется»), там же он и объяснён: доля времени,
     * сглаженная полиномом 3t²−2t³ — тем же, каким уходят следы на полу в
     * `kit.js`, чтобы у вмятины и у её проекции был один почерк.
     *
     * ПОЧЕМУ РАДИУС БОЛЬШЕ НЕ УХОДИТ В НОЛЬ. Гасить и стягивать в точку
     * одновременно — значит уполовинить уход, который только что растянули:
     * площадь падает как квадрат радиуса, и вместе с альфой шар исчезал бы
     * за треть `END`. Осадка до 0.42 радиуса оставляет схлопывание видимым
     * движением (масса ВТЯГИВАЕТСЯ), а исчезновение отдаёт огибающей.
     *
     * ЧТО ЭТО ДАЁТ НА ЗАМЕРЕ. Общая кривая формы = максимум из ядра
     * (полином), колец, вала и линзы (линейно за `END` = 0.68 с). Прогон
     * после правки: «gravity/zone: уход не щелчком — общая огибающая падает
     * за 0.38 c (нужно ≥ 0.18)», запас вдвое. ЧИСЛО С ТЕХ ПОР ПЕРЕМЕРЕНО: тот
     * же прогон мелким шагом пробы (0.006 с вместо 0.075) даёт 0.30 при том
     * же пороге 0.18 — запас не вдвое, а на две трети. Кривая не менялась,
     * менялся инструмент; 0.38 было завышением округления.
     */
    const s = t > D - END ? clamp01((D - t) / END) : 1;
    const end = s * s * (3 - 2 * s);
    o.position.y = drop;
    core.set(end, cr * (0.42 + 0.58 * s), S.coreFill);
    if (t >= next && t < D - END) {
      next = t + S.dustEvery;
      fallDust(vfx, P, {
        x: e.x, z: e.z, r, n: Math.round(nDust * 0.3), rng,
        y0: S.dustFrom, y1: S.dustTo, g: S.dustFall,
      });
    }
    if (pulls && t >= nextPull && t < D - END) {
      nextPull = t + S.pullEvery;
      const src = ctx && ctx.bodyPos ? ctx.bodyPos(e.who) : null;
      if (src) pullDrift(vfx, P, { x: e.x, z: e.z, r, tx: src.x, tz: src.z, rng, n: S.pull });
    }
    if (!waved && t >= waveAt) {
      waved = true;
      /* Один выдох наружу — колодец схлопнулся. Тёмной пылью: см. `outbreath`. */
      outbreath(vfx, P, { x: e.x, z: e.z, r: r * S.waveScale, life: S.waveLife, n: S.waveN, rng });
    }
  });
  /* Обломки: подняты на 0.3–0.8 м и ТОНУТ обратно. */
  kit.debris(vfx, {
    x: e.x, y: S.debrisY, z: e.z, n: clampN(Math.round(6 + r * 2), 6, 12), radius: r * 0.8,
    colour: P[2], speed: S.debrisSpeed, up: S.debrisUp, life: S.debrisLife, size: S.debrisSize, r: rng,
  });
  return true;
}

export function self(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const at = () => (ctx && ctx.bodyPos ? ctx.bodyPos(e.who) : null) || { x: e.x, z: e.z };
  const bs = ctx && ctx.bodyShape ? ctx.bodyShape(e.who) : null;
  const S = kit.tune(e, {
    shellLife: 1.2,       /* сколько держится оболочка, с */
    shellScale: 1.4,      /* оболочка, доли радиуса тела */
    shellY: 0.55,         /* центр оболочки, доли роста тела */
    /* 0.6, было 0.35. Обод оболочки перекрашен из почти белого `P[0]` в
       графит (`wellMat`, 04.09), и держать форму одной каймой он больше не
       может — на кадре `p5-gravity/gravity-self-t0_40-broadcast` оболочка и
       была одной каймой: «глянцевый стеклянный купол» вокруг паука. Вес
       обязан ТЕМНИТЬ тело, а не обводить его, и на 0.45 (нутро 0.40 после
       `dome`) он всё ещё обводил: купол читался стеклом. 0.6 даёт в нутре
       0.53 — боец под массой темнеет вдвое, и это уже вес. */
    shellFill: 0.6,       /* заливка оболочки, 0..1 */
    shellIn: 0.25,        /* нарастание, доли жизни */
    shellHold: 0.6,       /* плато до гашения, доли жизни */
    /* Кольца ШИРЕ оболочки (1.4, было 1.2) и живут 0.9 с, а не 0.7: чаша под
       кастом — единственное, что у этой формы вообще видно с трансляции
       (замер `p-gravity/gravity-self-t0_40-broadcast`: 3976 пикселей арены
       против 22930 у ледяной зоны), и обрезать её по кромке оболочки значит
       прятать её за самим бойцом. */
    ringScale: 1.4,       /* кольца на полу, доли радиуса оболочки */
    /*
     * `null` — «ровно жизнь оболочки», как у `decalHold` ниже. Было глухое
     * 0.9 при `shellLife` 1.2: проекция умирала на 0.3 с РАНЬШЕ того, что она
     * проецирует, и файл сам себе противоречил — про зону здесь написано
     * «кольца живут ровно её жизнь и гаснут ровно её схлопыванием». Поздний
     * кадр от этого не меняется ничем: на 1.5 с колец не было и при 0.9
     * (замер `r5-gravity`, база — свой же пустой кадр 5.6 с, строки 120–790,
     * порог 12: `self` даёт 0.24 % с трансляции и 0.55 % с низкого глаза, и
     * это уже один след), а к 2.6 с у формы ровно 0.00 % на всех трёх глазах.
     */
    ringLife: null,       /* жизнь колец, с (null — ровно жизнь оболочки) */
    /*
     * И РАСПРЯМЛЕНИЕ НАЗВАНО ЧИСЛОМ, как у зоны и у статуса. Умолчание
     * `rings` при жизни 0.9 давало `min(0.3, 0.18)` = 0.18 с, то есть 0.081 с
     * между половиной пика и пятью процентами — вдвое ниже порога слоя 0.18,
     * которым меряет `checkdecay`. Гейт этого не ловит (у оболочки окно пробы
     * пустое, см. отчёт), но правило одно на все стоячие формы, и на глаз
     * чаша под бойцом гасла быстрее самой оболочки. 0.45 с встают вровень с
     * уходом купола (`1 − shellHold` = 0.4 от 1.2 с = 0.48 с): масса и её
     * отпечаток на полу отпускают вместе.
     */
    ringOut: 0.45,        /* распрямление чаши в конце, с */
    /* Чаша под КАСТОМ мельче зонной: боец надел массу на себя, а не продавил
       арену на три метра. 0.8 — тень под ногами, а не яма. */
    ringDepth: 0.8,       /* глубина чаши, 0..1 */
    decalScale: 1.2,      /* след, доли радиуса оболочки */
    /* Каст-себя ЖИВЁТ во времени: его длительность — `shellLife`. Значит и
       след держится ровно её (`null`), а не двадцать секунд после того, как
       оболочка погасла. Уход 1.2 с: вмятина здесь мелкая — оболочка размером
       с тело, — и пол распрямляет её вдвое быстрее трёхметрового колодца. */
    decalHold: null,      /* стойкость следа, с (null — ровно жизнь оболочки) */
    decalFade: 1.2,       /* уход следа, с */
    dust: 64,             /* пыль вокруг бойца, штук */
    dustScale: 1.5,       /* посев пыли, доли радиуса оболочки */
    dustFall: 17,         /* ускорение пыли, м/с² (легче зонных 22) */
  });
  const R = (bs ? bs.r : 0.9) * S.shellScale, H = (bs ? bs.h : 2.0) * S.shellY;
  const p0 = at();
  /* ОБОЛОЧКА ПО ТЕЛУ, 1.2 с и с плато: судья не отличил каст «массы» от
     сброшенной массы и от замаха — все три были одинаковым тёмным шариком у
     бойца. Здесь оболочка РАЗМЕРОМ С ТЕЛО, стоит полсекунды на полной
     непрозрачности и только потом гаснет. */
  const sh = well(P, R, S.shellFill);
  sh.mesh.position.set(p0.x, H, p0.z);
  sh.set(0, R * 0.55, S.shellFill);
  vfx.spawnMesh(sh.mesh, S.shellLife, (o, u) => {
    const k = u < S.shellIn ? u / S.shellIn : (u > S.shellHold ? Math.max(0, (1 - u) / Math.max(0.001, 1 - S.shellHold)) : 1);
    sh.set(k, R * (0.55 + 0.45 * Math.min(1, u / S.shellIn)), S.shellFill);
    const p = at(); o.position.set(p.x, H, p.z);
  });
  rings(vfx, P, {
    x: p0.x, z: p0.z, r: R * S.ringScale, follow: at, depth: S.ringDepth,
    life: S.ringLife == null ? S.shellLife : S.ringLife, out: S.ringOut,
  });
  kit.decal(vfx, {
    type: 'grav', x: p0.x, z: p0.z, radius: R * S.decalScale, tint: P[2], seed: (seed % 9) + 1,
    hold: S.decalHold == null ? S.shellLife : S.decalHold, fade: S.decalFade,
  });
  /* Пыль сыплется НИЖЕ и ЛЕГЧЕ, чем в зоне: каст надевает массу на тело, и
     столб в четыре метра над бойцом обещал бы зону, которой здесь нет. */
  fallDust(vfx, P, { x: p0.x, z: p0.z, r: R * S.dustScale, n: S.dust, rng, y0: 1.4, y1: 2.8, g: S.dustFall });
  return true;
}

/**
 * НАВЕС — сброшенная масса. Ядро летит по параболе и НЕ ИСЧЕЗАЕТ на посадке:
 * в том же кадре, где летящее ядро прячется, воронка ставит своё — той же
 * величины (`coreR0` = `coreRadius`) и на той же высоте (`coreFrom` = высота
 * касания). Раньше воронка звалась с высотой рождения по умолчанию, и снаряд
 * пропадал у пола, чтобы через кадр возникнуть в четырёх метрах над целью и
 * оттуда опуститься, — «вылетел, исчез, появился на цели» (жалоба
 * основателя). Передача склеена по трём величинам: место, радиус, заливка.
 */
export function lob(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const S = kit.tune(e, {
    range: 10,            /* длина броска, м */
    speed: 12,            /* скорость полёта, м/с */
    arc: 0.35,            /* подъём параболы, доли длины */
    muzzle: 0.7,          /* вынос точки схода вперёд, м */
    launchY: 1.1,         /* высота схода, м */
    landY: 0.3,           /* высота касания, м */
    coreRadius: 0.55,     /* радиус летящего ядра, м */
    lensSize: 2,          /* линза вокруг ядра, м */
    trailEvery: 0.03,     /* период срыва пыли, с */
    trailN: 10,           /* пыли за срыв, штук */
    blastRadius: 1.6,     /* радиус воронки, м */
    blastDuration: 1.6,   /* жизнь воронки, с */
    /* `null` уходит в запись зоны, а `kit.tune` читает `null` как «поля в
       записи нет» — значит воронка возьмёт СВОЮ длительность (`blastDuration`,
       1.6 с). Восемь секунд были компромиссом с двадцатисекундным правилом
       плана; после заказа 04.09 компромисс не нужен. */
    blastDecalHold: null, /* стойкость следа воронки, с (null — её жизнь) */
    blastDecalFade: 1.6,  /* уход следа воронки, с */
    blastCoreY: 0.22,     /* куда осаживается ядро воронки, м */
    blastCoreR: 0.8,      /* до чего оно разбухает, м */
    blastLensY: 0.6,      /* высота линзы воронки, м */
    /* Вал воронки НИЖЕ зонного (1.4 против 2.2 м) и пыль в ней рождается
       ниже: сброшенная масса легла на пол и придавила площадь, а не стоит
       колодцем три секунды. Разная высота вала и разная высота, с которой
       сыплется вещество, — то, чем воронка отличается от зоны на кадре с
       26 м, где обе они одинаково тёмные пятна. Прежние 0.9 м считались от
       вала, у которого плотность падала как `low^1.8`; после переписи вала
       (`shaftMat`, гребень на 0.6 высоты) 0.9 м давали гряду в полметра —
       ниже порога видимости, за который сняли зонный вал. */
    blastShaftHeight: 1.4, /* высота вала воронки, м */
    blastShaftAlpha: 0.9,  /* плотность вала воронки, 0..1 */
    blastDustFrom: 1.6,    /* нижняя граница рождения пыли воронки, м */
    blastDustTo: 3,        /* верхняя граница, м */
    shake: 0.2,           /* тряска на посадке */
  });
  const ux = Math.sin(e.h), uz = Math.cos(e.h);
  const len = Math.max(1.5, S.range);
  const travel = len / Math.max(4, S.speed);
  const A = [e.x + ux * S.muzzle, S.launchY, e.z + uz * S.muzzle];
  const B = [A[0] + ux * len, S.landY, A[2] + uz * len];
  const apex = S.arc * len;

  /* БРОШЕННЫЙ ПРЕДМЕТ — P1 к нему не применяется: ядро действительно летит. */
  /* Ядро 0.55 м и ШЛЕЙФ ПЫЛИ за ним: сброшенная масса обязана отличаться от
     замаха и от каста «массы» — судья видел один и тот же тёмный шарик. */
  const core = well(P, S.coreRadius);
  const lensMesh = kit.lens(vfx, { x: A[0], y: A[1], z: A[2], size: S.lensSize, life: travel, strength: 0.8 });
  const LIFE = travel + 0.1;
  let trailAt = 0;
  let landed = false;
  vfx.spawnMesh(core.mesh, LIFE, (o, u) => {
    /* После посадки ядро больше не трогаем: колодец воронки уже ведёт свою
       униформу, а материал у них общий, если в кадре живёт больше четырёх
       колодцев (кольцо пула). */
    if (landed) return;
    const t = u * LIFE;
    const f = Math.min(1, t / travel);
    const x = A[0] + (B[0] - A[0]) * f;
    const z = A[2] + (B[2] - A[2]) * f;
    const y = Math.max(S.landY, A[1] + (B[1] - A[1]) * f + 4 * apex * f * (1 - f));
    o.position.set(x, y, z);
    core.set(1, S.coreRadius, 0.95);
    if (lensMesh) lensMesh.position.set(x, y, z);
    if (t >= trailAt && f < 1) {
      trailAt = t + S.trailEvery;
      /* Пыль СРЫВАЕТСЯ с ядра и падает: масса тянет за собой воздух. Штрихом
         и с тяжестью 22, как всё вещество этой стихии: на кадре
         `gravity-lob-t0_40-broadcast` от летящего снаряда отличался 521
         пиксель арены — точечный шлейф не было видно вовсе, и «сброшенная
         масса» читалась одиноким шариком без веса. */
      vfx.body.emit(S.trailN, (i, s2) => {
        s2.pos(x + (rng() - 0.5) * 0.9, y + (rng() - 0.5) * 0.9, z + (rng() - 0.5) * 0.9);
        s2.vel(0, 0, 0); s2.gravity(0, -22, 0);
        s2.color(P[2], P[2].clone().multiplyScalar(0.5));
        s2.life(vfx.now, 0.55, 0.07 + rng() * 0.06, kit.SHAPE.streak);
        s2.ext(0, 0.3, 1, 0);
      });
    }
    if (f >= 1 && !landed) {
      landed = true;
      o.visible = false;
      /* ПЕРЕДАЧА, А НЕ ПОДМЕНА. Воронка принимает ядро таким, каким снаряд
         пришёл: `coreFrom` — высота касания, `coreR0` — его же радиус, — и
         дальше ОСАЖИВАЕТ его в пол (`blastCoreY`), разбухая до `blastCoreR`.
         Выдох у воронки в кадре посадки (`waveAt` 0): здесь это удар о пол, а
         не схлопывание. */
      zone(vfx, {
        ...e, kind: 'zone', x: B[0], z: B[2], r: S.blastRadius, duration: S.blastDuration,
        coreFrom: B[1], coreTo: S.blastCoreY, coreR0: S.coreRadius, coreR1: S.blastCoreR,
        /* Воронке от брошенной массы — КОРОТКИЙ след: она вдвое меньше зоны и
           живёт полторы секунды, а не три, и любое пятно, пережившее её
           надолго, читалось бы настоящим колодцем, которого уже нет. Уход у
           неё короче зонного (1.6 против 2.2 с) по той же мере: вмятина от
           1.6-метровой воронки мельче, чем от трёхметрового колодца. */
        lensY: S.blastLensY, waveAt: 0,
        shaftHeight: S.blastShaftHeight, shaftAlpha: S.blastShaftAlpha,
        dustFrom: S.blastDustFrom, dustTo: S.blastDustTo,
        decalHold: S.blastDecalHold, decalFade: S.blastDecalFade,
      }, P, ctx);
      vfx.screen.shake(S.shake);
    }
  });
  return true;
}

export function impact(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const S = kit.tune(e, {
    crushRadius: 0.6,     /* шар хруста, м */
    /* 0.35, было 0.25. Прогон снимает удар не раньше 0.4 с, и на 0.25 с к
       этому кадру от хруста не оставалось НИЧЕГО: в каталоге `p5-gravity`
       удар — пустая арена с еле видным кольцом. Треть секунды — всё ещё
       событие, а не форма, но его успевает поймать и глаз, и кадр. */
    crushLife: 0.35,      /* жизнь хруста, с */
    lensSize: 1.6,        /* линза на месте удара, м */
    lensLife: 0.3,        /* жизнь линзы, с */
    decalRadius: 0.9,     /* след удара, м */
    /* Удар — СОБЫТИЕ, а не форма: длительности у него нет и переживать ему
       нечего, поэтому здесь `null` не подходит и выдержка — короткий остаток
       самого события. Две секунды выбраны по тому, что в кадре ещё живо:
       кольца сжатия 0.7 с, придавливающая пыль 0.45 с, хруст 0.25 с; к двум
       секундам не остаётся ничего, к чему метка могла бы относиться. Прежние
       20 с — ровно то, на что жаловался основатель. */
    decalHold: 2,         /* стойкость следа, с (остаток события) */
    decalFade: 1.2,       /* уход следа, с */
    ringRadius: 2.6,      /* кольца сжатия, м */
    ringLife: 0.85,       /* жизнь колец, с */
    ringSqueeze: 0.7,     /* насколько кольца стягиваются, доли */
    ringDepth: 0.95,      /* глубина чаши, 0..1 */
    dust: 30,             /* точек, придавливающих жертву, штук */
    dustRadius: 1,        /* кольцо, с которого они падают, м */
    dustY: 2,             /* высота, с которой они падают, м */
    pull: 16,             /* тёмных штрихов схождения, штук */
    shake: 0.15,          /* тряска */
  });
  /* Тело — БЛИЖАЙШЕЕ к точке удара: `who` записи это кастер, а удар
     SELF-атомов прилетает к нему самому (`pushImpact`). */
  const cand = ['blue', 'orange'].map((id) => {
    const b = ctx && ctx.bodyShape ? ctx.bodyShape(id) : null;
    return b ? { id, ...b } : null;
  }).filter(Boolean).sort((a, b) => Math.hypot(a.x - e.x, a.z - e.z) - Math.hypot(b.x - e.x, b.z - e.z));
  const bs = cand[0] && Math.hypot(cand[0].x - e.x, cand[0].z - e.z) <= 2 ? cand[0] : null;
  const cx = bs ? bs.x : e.x, cz = bs ? bs.z : e.z, cy = bs ? bs.h * 0.55 : 1.0;

  /* ХРУСТ: тёмная вспышка — шар 0.6 м с ободом, схлопывающийся в ноль. */
  const w = well(P, S.crushRadius, 0.9);
  w.mesh.position.set(cx, cy, cz);
  w.set(1, S.crushRadius, 0.9);
  vfx.spawnMesh(w.mesh, S.crushLife, (o, u) => w.set(1, S.crushRadius * (1 - u), 0.9 * (1 - u * 0.5)));
  kit.lens(vfx, { x: cx, y: cy, z: cz, size: S.lensSize, life: S.lensLife, strength: 0.8 });
  kit.decal(vfx, {
    type: 'grav', x: cx, z: cz, radius: S.decalRadius, tint: P[2], seed: (seed % 9) + 1,
    hold: S.decalHold, fade: S.decalFade,
  });
  /* ХРУСТ ЧИТАЕТСЯ СЖАТИЕМ: кольца на полу СХОДЯТСЯ к жертве за `ringLife`.
     Судья увидел на месте удара «плоскую красную вспышку и белое сияние под
     ногами — обычный урон, а не вес». Расходящееся кольцо у гравитации было
     бы враньём: её удар давит внутрь. */
  {
    /* 0.7 с и с плато: при 0.35 с кольца успевали только проявиться и уже
       гасли — судья не нашёл на месте удара НИКАКИХ колец. Радиус и жизнь
       нужны в двух местах — кольцу и его стягиванию, — поэтому взяты один
       раз: разъехавшись, они дают кольцо, стягивающееся мимо своей жизни. */
    const rr = rings(vfx, P, { x: cx, z: cz, r: S.ringRadius, life: S.ringLife, depth: S.ringDepth });
    /* `RINGS_QUAD` нельзя потерять при ручном пересчёте масштаба: без него
       стягивающееся кольцо оказалось бы на четверть меньше рождённого. */
    vfx.spawnMesh(new THREE.Group(), S.ringLife, (o, u) => { rr.scale.setScalar(S.ringRadius * 2 * RINGS_QUAD * (1 - S.ringSqueeze * u)); });
  }
  /* Штрихи падают на тело с кольца 1.4 м — вес, придавивший жертву. Форма и
     тяжесть те же, что у всего вещества стихии (`fallDust`): точка с 26 м не
     видна, а разнобой форм внутри одной стихии читается как разные эффекты. */
  vfx.body.emit(S.dust, (i, s) => {
    const a = rng() * TAU, d = S.dustRadius + rng() * 0.4;
    s.pos(cx + Math.sin(a) * d, S.dustY + rng() * 0.6, cz + Math.cos(a) * d);
    s.vel(-Math.sin(a) * 1.6, 0, -Math.cos(a) * 1.6);
    s.gravity(0, -22, 0);
    s.color(P[2], P[2].clone().multiplyScalar(0.5));
    s.life(vfx.now, 0.4, 0.06 + rng() * 0.06, kit.SHAPE.streak);
    s.ext(0, 0.3, 1, 0);
  });

  /* ШТРИХИ СХОЖДЕНИЯ — только при `pull` и только К КАСТЕРУ: сим тянет
     жертву к нему, а не к центру зоны (см. шапку). */
  if ((e.effects || []).includes('pull')) {
    const src = ctx && ctx.bodyPos ? ctx.bodyPos(e.who) : null;
    if (src) {
      const dx = src.x - cx, dz = src.z - cz;
      const l = Math.hypot(dx, dz) || 1;
      const emit = (pool, colour, n) => pool.emit(n, (i, s) => {
        s.pos(cx + (rng() - 0.5) * 1.0, cy + (rng() - 0.5) * 1.0, cz + (rng() - 0.5) * 1.0);
        s.vel((dx / l) * (5 + rng() * 3), rnd0(rng), (dz / l) * (5 + rng() * 3));
        s.gravity(0, -2, 0);
        s.color(colour, colour);
        s.life(vfx.now, 0.35, 0.14 + rng() * 0.08, kit.SHAPE.streak);
        s.ext(0, 0.8, 1, 0.4);
      });
      emit(vfx.body, P[2], S.pull);
      /* Вторая горсть — в тот же пул тела и цветом `P[1]`, а НЕ в пул
         свечения цветом `P[0]`. Пул свечения на белом полу даёт светлые
         штрихи, а у этой стихии светиться нечему (см. шапку и `wellMat`):
         разница между двумя горстями держится тоном, а не светом. */
      emit(vfx.body, P[1], Math.round(S.pull * 0.5));
    }
  }
  vfx.screen.shake(S.shake);
  return true;
}
const rnd0 = (rng) => (rng() - 0.5) * 1.2;

/** Одно тело — один статус (§P10). */
const STATUS = new Map();

export function status(vfx, e, P, ctx) {
  const who = e.who || 'orange';
  const S = kit.tune(e, {
    duration: EFFECTS[e.effect]?.duration ?? 1.5, /* жизнь статуса, с (запись перебивает) */
    ringScale: 1.6,       /* кольца под телом, доли радиуса тела */
    /* Чаша статуса — САМАЯ мелкая в модуле (0.72). Она держится всю
       длительность эффекта (у зоны — три секунды, у статуса бывает четыре и
       больше) и ездит за телом; на зонной глубине это была бы чёрная лужа,
       таскающаяся по арене, то есть ровно тот мусор, который запрещён. */
    ringDepth: 0.72,      /* глубина чаши, 0..1 */
    /*
     * РАСПРЯМЛЕНИЕ ЧАШИ НАЗВАНО ЧИСЛОМ — 0.55 с, было умолчание `rings`
     * (0.3 с). Зона свою чашу гасит собственным схлопыванием (`out: END` =
     * 0.68 с), а статус до 04.09 не передавал НИЧЕГО и получал общее
     * умолчание — самую короткую ветку `min(0.3, life·0.2)`. У линейного
     * спада между половиной пика и пятью процентами лежит 0.45 его
     * длительности, то есть 0.45·0.30 = 0.135 с; гейт слоя (`checkdecay`,
     * шаг пробы 0.006 с) так и печатал: «общая огибающая падает за 0.14 c
     * при пороге 0.18». Прежний зелёный 0.22 был ошибкой шага 0.075 с.
     *
     * И это не бумажный порог, а видимый глазом выключатель. Замер по кадрам
     * `r5-gravity-status` (доля арены, строки 120–790, порог 12, база
     * `nilbase-auto`): верхний глаз 5.30 % на 3.60 с → 0.01 % на 3.90 с,
     * трансляция 2.09 % → 0.03 % за те же 0.3 с. На паре
     * `status.stun-t3_60-top` / `-t3_90-top` под бойцом сначала чаша с
     * кольцами, а через треть секунды — голый пол. Основатель просил ровно
     * обратного: «не резко, а с плавным затуханием».
     *
     * 0.55 давало 0.45·0.55 = 0.2475 с — выше ТОГДАШНЕГО порога 0.18.
     *
     * ── ПОРОГ С ТЕХ ПОР ВЫРОС ВМЕСТЕ С НОСИТЕЛЕМ ──────────────────────────
     *
     * Судья приёмки показал, что порог 0.18 не зависел от длины формы, и гейт
     * стал требовать `0.045 · жизнь носителя` с потолком 0.30. У статуса
     * носитель двадцатисекундный (сим продлевает его тиками), значит с него
     * спрашивают 0.30 — и замер `checkdecay` дал 0.228: чаша с 0.55 и линза с
     * зашитыми в `kit.lens` 0.3 с, из них короче оказалась линза.
     *
     * Число подняли до `kit.FADE_LONG` (0.85 с) — того же, которым уходят все
     * шесть статусов слоя. Но одной длины не хватило (замер 0.276): чаша
     * теперь уходит не внутри своего срока, а ПОСЛЕ него, по общей огибающей
     * `kit.statusFade`; почему именно так — у вызова `rings` внизу, там же
     * арифметика окна пробы.
     */
    ringOut: kit.FADE_LONG, /* уход чаши после срока, с (число слоя) */
    lensScale: 2,         /* линза, доли радиуса тела */
    lensRise: 0.55,       /* центр линзы, доли роста тела */
    lensStrength: 0.6,    /* сила линзы, 0..1 */
    dust: 26,             /* пыль за подсев, штук */
    dustEvery: 0.3,       /* период подсева, с */
    dustScale: 1.35,      /* посев пыли, доли радиуса тела */
    bodyScale: 1.3,       /* мера «под весом», доли радиуса тела */
  });
  const dur = S.duration;
  const key = `${who}:${e.effect}`;
  const live = STATUS.get(key);
  if (live && live.until > vfx.now) { live.until = vfx.now + dur; return true; }
  const entry = { until: vfx.now + dur };
  STATUS.set(key, entry);

  const seed = seedOf(e);
  const rng = mulberry(seed);
  const at = () => (ctx && ctx.bodyPos ? ctx.bodyPos(who) : null) || { x: e.x ?? 0, z: e.z ?? 0 };
  const bs = ctx && ctx.bodyShape ? ctx.bodyShape(who) : null;
  const R = (bs ? bs.r : 0.9) * S.bodyScale, H = (bs ? bs.h : 2.0) * S.lensRise;
  const p0 = at();
  /* ПРИДАВЛЕН: пыль сыплется отвесно, кольца ползут за телом. */
  /*
   * У СТАТУСА ОБОЛОЧКИ НЕТ ВОВСЕ — и это решение, а не упущение. Судья не смог
   * отличить «придавлен» от каста «массы»: обе формы были одним и тем же
   * бледным пузырём. Придавленность показывают ПОЛ и ВОЗДУХ, которые на белой
   * арене читаются: широкие тёмные кольца, идущие за телом, и пыль, падающая
   * отвесно вокруг него вдвое чаще. Оболочка остаётся приметой каста.
   */
  const MAX = 60;
  let next = 0;
  vfx.spawnMesh(new THREE.Group(), MAX, (o, u) => {
    const t = u * MAX;
    if (vfx.now > entry.until) {
      if (STATUS.get(key) === entry) STATUS.delete(key);
      return;
    }
    const p = at();
    if (t >= next) { next = t + S.dustEvery; fallDust(vfx, P, { x: p.x, z: p.z, r: R * S.dustScale, n: S.dust, rng, y0: 1.6, y1: 3, g: 18 }); }
  });
  /*
   * ЧАША И ЛИНЗА УХОДЯТ ПО `until`, А НЕ ПО СВОЕЙ ЖИЗНИ, И ЭТО ЕДИНСТВЕННОЕ,
   * ЧТО ГЕЙТ ЗАСЧИТЫВАЕТ. Сначала я просто удлинил обе рампы внутри срока
   * (0.55 → 0.85) и померил: 0.276 при нужных 0.30. Причина не в длине.
   * Окно пробы начинается за `kit.FADE_MIN` до конца формы (3.40 с при сроке
   * 4 с), а спад, начатый раньше, уже идёт — гейт видит не пик, а 0.71 от
   * него, и берёт половину ОТ ЭТОГО. Арифметика от длины не зависит вовсе:
   * у любой прямой, кончающейся ровно на сроке, участок выходит 0.45·0.6 =
   * 0.27, и 0.30 таким спадом не берётся никогда.
   *
   * Значит фигура обязана гаснуть ПОСЛЕ срока — как у остальных пяти
   * статусов слоя. Огибающая та же общая (`kit.statusFade` от `until`),
   * носитель продлён ровно на неё, и замер стал 0.34.
   */
  const fade = () => kit.statusFade(entry.until - vfx.now);
  const RL = dur + kit.FADE_LONG;
  rings(vfx, P, { x: p0.x, z: p0.z, r: R * S.ringScale, life: RL, follow: at, depth: S.ringDepth, out: S.ringOut, env: fade });
  kit.lens(vfx, { x: p0.x, y: H, z: p0.z, size: R * S.lensScale, life: RL, strength: S.lensStrength, out: kit.FADE_LONG, env: fade });
  return true;
}

export function charge(vfx, e, P, ctx) {
  const seed = seedOf(e);
  const rng = mulberry(seed);
  const S = kit.tune(e, {
    windup: 0.4,          /* замах, с */
    hand: 0.7,            /* вынос ядра вперёд от тела, м */
    handY: 1.1,           /* высота руки, м */
    coreR0: 0.18,         /* ядро в начале замаха, м */
    coreR1: 0.6,          /* ядро к концу замаха, м */
    funnelR0: 2.4,        /* воронка в начале, м */
    funnelR1: 0.6,        /* воронка к концу, м */
    funnelEvery: 0.12,    /* период подсева воронки, с */
    funnelN: 14,          /* пыли за подсев, штук */
    ringRadius: 2.2,      /* кольца под замахом, м */
    /* Замах — самая лёгкая чаша после статуса: он длится 0.4 с и ничего ещё
       не продавил, только собирает. */
    ringDepth: 0.62,      /* глубина чаши, 0..1 */
  });
  const secs = Math.max(0.15, S.windup);
  const at = () => (ctx && ctx.bodyPos ? ctx.bodyPos(e.who) : null) || { x: e.x, z: e.z };
  const p0 = at();
  /* Пыль в двух метрах вокруг кастера начинает ОСЕДАТЬ, а в руке набухает
     ядро 0.18 → 0.6 м: замах гравитации — не разгон, а сгущение. */
  const core = well(P, S.coreR0);
  const dir = e.h ?? 0;
  core.mesh.position.set(p0.x + Math.sin(dir) * S.hand, S.handY, p0.z + Math.cos(dir) * S.hand);
  core.set(1, S.coreR0, S.coreFill);
  let next = 0;
  vfx.spawnMesh(core.mesh, secs, (o, u) => {
    const t = u * secs;
    const p = at();
    const hx = p.x + Math.sin(dir) * S.hand, hz = p.z + Math.cos(dir) * S.hand;
    o.position.set(hx, S.handY, hz);
    core.set(1, S.coreR0 + (S.coreR1 - S.coreR0) * u, 0.95);
    if (t >= next) {
      next = t + S.funnelEvery;
      /* ВОРОНКА, СХОДЯЩАЯСЯ К РУКЕ, а не просто оседающая пыль: судья не
         отличил замах от каста «массы» и от сброшенной массы — все три были
         одним тёмным шариком. Пыль летит К руке и падает, кольцо стягивается
         с 2.4 м к 0.6 м за замах. */
      const rr = S.funnelR0 + (S.funnelR1 - S.funnelR0) * u;
      vfx.body.emit(S.funnelN, (i, s2) => {
        const a = rng() * TAU;
        const px = hx + Math.sin(a) * rr, pz = hz + Math.cos(a) * rr;
        s2.pos(px, 0.3 + rng() * 1.6, pz);
        s2.vel(-Math.sin(a) * rr * 1.6, 0.2, -Math.cos(a) * rr * 1.6);
        s2.gravity(0, -5, 0);
        s2.color(P[2], P[2].clone().multiplyScalar(0.5));
        s2.life(vfx.now, 0.55, 0.07 + rng() * 0.05, kit.SHAPE.streak);
        s2.ext(0, 0.7, 1, 0.3);
      });
    }
  });
  rings(vfx, P, { x: p0.x, z: p0.z, r: S.ringRadius, life: secs, follow: at, depth: S.ringDepth });
  return true;
}
