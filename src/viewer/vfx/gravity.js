/**
 * ГРАВИТАЦИЯ (`gravity`) — ВЕС (план §6.2).
 *
 * Что это такое. Что-то тяжёлое и тёмное, гнущее пространство вокруг себя:
 * почти чёрное ядро с тонкой ГРАФИТОВОЙ линией горизонта, линза, поджимающая
 * картинку за ним, пыль, падающая ОТВЕСНО и оседающая, обломки, тонущие в
 * пол, продавленная чаша на полу, — ВЕС. Это тихо, медленно и неотвратимо;
 * здесь ничто не искрит и НИЧТО НЕ СВЕТИТ. Ни одного пикселя ярче арены:
 * замер 04.09 по кадру `p5-gravity/gravity-zone-t0_40-broadcast` поймал у
 * ядра L 239 при полу L 222 — это была белая кайма обода плюс bloom, и её
 * больше нет (см. `wellMat`).
 *
 * ТЁМНОЕ ПОВЕРХ ТЁМНОГО НЕВИДИМО — И ПОЭТОМУ ВЕС НЕСЁТ БЕЛЫЙ ПОЛ. За это
 * гравитация получила 28 из 100: всё, что она умела, было тёмным и лежало
 * либо на теле, либо в воздухе. Замер 04.09 (кадр `gravity-zone-t1_50-
 * broadcast` против того же каста на 4.0 с): с трансляционных 26 м от
 * трёхметрового колодца отличались 4694 пикселя арены — 1.8% кадра, при 22930
 * у ледяной зоны и 49529 у огненной. Отсюда порядок сил в этом файле:
 *
 *   1. ЧАША на полу (`ringsMat`) — главное. Тёмная яма на белом столе видна
 *      с любой дистанции и с любого ракурса.
 *   2. ВАЛ ПЫЛИ по кромке (`shaftMat`) — гряда с РВАНЫМ гребнем в метр с
 *      небольшим, край воронки. Без него у колодца не было НИКАКОЙ высоты, и
 *      с почти горизонтальной трансляционной камеры от него оставались одни
 *      кольца.
 *   3. ВЕЩЕСТВО, падающее отвесно ШТРИХАМИ и с тяжестью 22 м/с² вместо
 *      мировых 9 (`fallDust`) — единственное, что в колодце движется.
 *   4. ЯДРО — тяжесть, ВИСЯЩАЯ НАД ЯМОЙ. Оно поднято на 3.4 м и сжато до
 *      0.75 м радиуса именно потому, что до 04.09 висело на 1.6 м при 1.1 м
 *      и ПРОГЛАТЫВАЛО бойца: соответствие силуэта жертвы чистому кадру в
 *      рамке тела (`p5-gravity/gravity-zone-t1_50-top`, 826,550–960,707,
 *      против того же каста на 4.0 с) было r = 0.614 — из-под шара торчали
 *      лапа и наплечник; в каноне `r2-gravity` там же r = 0.757, а с
 *      трансляции 0.844 против 0.764. Силуэт бойца — боевая информация, а не
 *      фон, и стихия не вправе его закрывать; поднятое ядро вдобавок даёт
 *      колодцу ВЕРТИКАЛЬ, которой у него с трансляции не было.
 *
 *      ЯДРО ПЕРЕСТАЛО БЫТЬ ОТЛАДОЧНЫМ ШАРОМ (r2 → r4). Приёмка r2 записала
 *      про него ровно три слова — «без обода, без шейдинга и без искажения»,
 *      — и все три оказались буквальны: обод `fres^9` жил во внешних 0.27 %
 *      радиуса (на `f2-forms/gravity-zone-t0_15-low` это ОДИН пиксель L 41.8
 *      при шаре радиусом 57 px), рампа плотности `fres^2.2` брала половину
 *      хода при `u = 0.963`, отчего 85 % диска стояли на ΔL 14 при поле
 *      L 222, а линза висела на 1.1 м — под ядром, поднятым на 3.4 м, — и
 *      давала на нём 0.057 силы вместо заявленной трети. Вылечено на месте:
 *      полоса обода названа числом (внешние 12.3 % радиуса), плотность
 *      растянута на две трети диска, венец даёт шару верх и низ, линза встала
 *      НА ядро. Замер по канону `r4-gravity`, тот же луч из центра шара,
 *      `gravity-zone-t1_50-broadcast`: ΔL по внутренним 85 % радиуса 14 → 54,
 *      обод на низком глазу 26 → 104 при небе L 3. Проверено и то, что этим
 *      не сломано: силуэт бойца под ядром сверху r 0.724 → 0.738, с
 *      трансляции 0.910 → 0.896, а самый яркий пиксель в рамке ядра как был,
 *      так и остался 224 при чистом кадре 225 — стихия по-прежнему не даёт
 *      НИ ОДНОГО пикселя ярче арены.
 *
 * ПРАВДА СИМА, ПРОТИВ КОТОРОЙ НЕЛЬЗЯ РИСОВАТЬ. Атом `pull` тянет жертву к
 * ПОЗИЦИИ КАСТЕРА (`effects.js`: `dx = src.x − to.x`), а не к центру зоны, и
 * зона применяет его заново каждые 0.5 с. Поэтому всё, что показывает СИЛУ —
 * штрихи схождения, — направлено на тело кастера и живёт ровно тем же тактом
 * 0.5 с: на беате удара (`impact`) и, когда запись зоны несёт атом,
 * `pullDrift` внутри самого колодца. Всё остальное в колодце — ядро, обод,
 * кольца, чаша, вал, след, линза — размечает ПЛОЩАДЬ зоны и стоит
 * симметрично; это форма ямы, а не обещание того, куда полетит жертва.
 *
 * ОТСЮДА ПРАВИЛО ДВИЖЕНИЯ, И У НЕГО ДВА РАЗРЕШЁННЫХ НАПРАВЛЕНИЯ.
 *
 * ВНИЗ честно всегда: тяжесть — это и есть «вниз», и никакого положения
 * кастера это не касается. Поэтому вещество падает отвесно, рисунок на валу
 * ползёт вниз, чаша проседает на месте.
 *
 * К ЦЕНТРУ КОЛОДЦА — тоже честно, но это ФОРМА, а не сила: концентрические
 * кольца ползут внутрь ровно так же, как ползёт след `grav` в общем слое
 * (`kit.js`, `TIME·0.6`), потому что проекция и вмятина обязаны быть одним
 * почерком — иначе на полу видно, где кончилась одна и началась другая. До
 * 04.09 здесь кольца СТОЯЛИ (а ещё раньше ползли наружу), и колодец с 26 м
 * не двигался вовсе.
 *
 * К КАСТЕРУ — только когда сим действительно тянет. Атом `pull` тянет жертву
 * к ПОЗИЦИИ КАСТЕРА, и с 04.09 запись зоны наконец несёт список своих атомов
 * (`src/core/deliver.js`), так что зона может СПРОСИТЬ, тянет ли она. Тянет —
 * идёт снос вещества к телу кастера (`pullDrift` в `zone`); не тянет — не
 * идёт ничего, потому что половина зон гравитации ничего не тянет, и рисовать
 * схождение во всех значило бы врать в половине случаев.
 *
 * Формы: зона (колодец), себя (масса), навес (сброшенная масса) — плюс удар,
 * статус, заряд и стена, которые доходят до всякой стихии (§P6).
 *
 * ГДЕ УЛИКИ. Каталог `reports/vfx/r5-gravity` — КАНОНИЧЕСКИЙ: зона, оболочка
 * и навес × три глаза (низкий 15 м, верхний 22 м, трансляция 26 м) × шесть
 * моментов (0.15 / 0.4 / 1.5 / 2.6 / 4.0 / 5.6 с), 54 кадра, ошибок консоли
 * ноль. Рядом `r5-gravity-status` и `r5-gravity-status2` — статус до и после
 * правки распрямления чаши, и `r5-gravity-self2` — оболочка после правки
 * колец. Прогон r5 снят потому, что волна приёмки 04.09 сняла ПЯТЬ стихий из
 * десяти, и гравитации в галерее круга не было вовсе, хотя файл правился
 * после своей последней съёмки: «доведено» без кадра — это слово, а не факт.
 * Прежние каноны `reports/vfx/r4-gravity` (зона и оболочка × три глаза × пять
 * моментов) и `reports/vfx/r2-gravity` держатся как «до».
 * Рядом `reports/vfx/r2-gravity-pull` — добор с записью зоны, несущей атом
 * `pull` (штатная стойка `vfxfixture.fxFor` его не кладёт, и без добора снос к
 * кастеру нельзя увидеть ни в одном кадре прогона). Всё, что называется
 * `p2-` / `p3-` / `p4-` / `p5-` / `wip-`, — ПРОМЕЖУТОЧНОЕ: первый круг судей
 * послали в `p2-gravity`, то есть в выброшенный прогон с конусом-прожектором,
 * и это была главная беда прошлого отчёта. Один каталог из `wip-` держится
 * нарочно: `wip-gravity-dbg2` — контрольный кадр, где вал покрашен в красное,
 * по нему вырезана маска для замеров `shaftMat`.
 *
 * Свет НЕ ЗОВЁТСЯ вовсе: у гравитации нечему светить. Четыре источника пула
 * достаются тем, кому они нужны.
 *
 * НАСТРОЙКА. Все размеры, высоты и времена идут через `kit.tune(e, {...})`:
 * опись в начале каждой формы — это и есть список того, что можно крутить, а
 * значения по умолчанию равны сегодняшним числам, так что запись без полей
 * даёт прежний кадр. Отсюда же лечится и главная жалоба на навес: воронка
 * принимает ядро на высоте касания (`coreFrom`), а не рождает своё в четырёх
 * метрах над целью.
 */

