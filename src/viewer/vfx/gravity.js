const TAU = Math.PI * 2;
const clampN = (v, a, b) => Math.min(b, Math.max(a, v));
const hex = (P) => P.map((c) => c.getHexString()).join();

/* ── колодец: почти чёрный шар с ободком горизонта ──────────────────────── */

/**
 * `wellMat` — нормально смешанный шар: середина `(0.015,0.015,0.022)` при
 * альфе `fill` и френелевый ободок по силуэту. В bloom НЕ УХОДИТ НИЧЕГО.
 *
 * ЗДЕСЬ БЫЛ ЕДИНСТВЕННЫЙ СВЕТ СТИХИИ, И ЕГО ПРИШЛОСЬ УБРАТЬ. До 04.09 обод
 * красился в `P[0]` (`#eef0f4` — почти белый) и поверх него шёл ВОЛОСОК
 * HDR-белого `(2.2,2.2,2.4)`, помеченный в bloom. Замер по кадру
 * `p5-gravity/gravity-zone-t0_40-broadcast` (рамка ядра 730,470–850,590):
 * самый яркий пиксель ядра L 239 при белом полу арены L 222 — ядро выходило
 * СВЕТЛЕЕ пола, и судья прочёл это как зеркальный блик на глянцевом шаре.
 * Тот же замер сверху (`gravity-zone-t1_50-top`, рамка 800,540–990,730):
 * L max 237 против 222 на чистом кадре. Шапка файла запрещает стихии светить
 * дословно — «всё похожее на свет у неё враньё», — и белая кайма была ровно
 * этим. Теперь обод графитовый (`P[1]·0.7` ≈ 0.12,0.15,0.20 в линейном, то
 * есть вчетверо ТЕМНЕЕ пола), а `markGlow` отдаёт ноль: в кадре не остаётся
 * ни одного пикселя гравитации ярче арены.
 *
 * Обод при этом НУЖЕН: без него шар — плоская дыра, а дыра уже занята
 * пустотой (`void.js`, «снаряд стал дырой»). Графитовая линия по силуэту
 * говорит «шар», не говоря «свет».
 */
function wellMat(P) {
  return pooled(`grav:well:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.FrontSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    const fill = uniform(0.95);
    m.userData.u = { fade, fill };
    const fres = oneMinus(tabs(TSL.dot(normalView, positionViewDirection))).clamp(0, 1);
    /*
     * ОБОД — ПОЛОСА, ШИРИНА КОТОРОЙ НАЗВАНА ЧИСЛОМ (было `fres^9`).
     *
     * Судья приёмки r2 сказал про ядро три слова: «без обода, без шейдинга и
     * без искажения» — и все три оказались буквально верны, а не на глаз.
     * Обод: `fres = 1 − |N·V|`, у шара это `1 − sqrt(1 − u²)` по экранному
     * радиусу `u`, значит `fres^9 ≥ 0.5` живёт при `u ≥ 0.9973` — ВНЕШНИЕ
     * 0.27 % РАДИУСА. Замер по кадру `f2-forms/gravity-zone-t0_15-low`
     * (строка 240, хорда шара 114 px, нутро L 13.5…14.5, небо L 2.1): от
     * кромки внутрь идёт 52, 38, 26, 19, 17, 16 — то есть выше L 25 держатся
     * ТРИ пикселя из 57, и пик всего 61. Обод не «узкий»: на экране от него
     * остаётся волосок толщиной с антиалиасинг.
     *
     * Полоса `smoothstep(0.52, 0.95, fres)` начинается при `u = 0.877` и
     * доходит до силуэта: внешние 12.3 % радиуса, то есть 7 px из тех же 57.
     * Половина силы — при `u = 0.964`. Это по-прежнему ЛИНИЯ ГОРИЗОНТА, а не
     * половина шара: `^2.6`, за который стихию били 03.09, набирал десятую
     * долю уже при `u = 0.81` — полоса в 19 % радиуса — И красился почти
     * белым `P[0]`. Здесь полоса на треть уже (12.3 %), а краска графитовая
     * (`P[1]·0.7`, sRGB ≈ 96,105,120) — светлее пола она стать не может по
     * построению. На кадре: `r4-gravity/gravity-zone-t0_15-low`, та же строка
     * 240 — от кромки внутрь 40, 96, 72, 56, 42, 28, 19: шесть пикселей выше
     * L 25 вместо трёх, пик 104 вместо 61, нутро прежнее (13.5…15.8).
     *
     * ВЕНЕЦ (`crown`) — вторая половина слова «шейдинг», и он не свет. Шар
     * без единого источника читается наклейкой с любой стороны; здесь к
     * графиту добавлена доля, растущая к ВЕРХУ шара в экранных осях
     * (`normalView.y`, то есть независимо от камеры), с квадратом — чтобы она
     * жила у самой макушки, а не разливалась по половине. Доля 0.30 — это
     * треть графита поверх почти чёрного нутра: на `r4-gravity/gravity-zone-
     * t1_50-broadcast` верх шара L 75 против низа L 32 при поле L 222, то
     * есть у массы появились верх и низ, а подсветкой это стать не может —
     * самый яркий пиксель в рамке ядра как был 224, так и остался (чистый
     * кадр той же рамки 225).
     */
    const rim = smoothstep(float(0.52), float(0.95), fres);
    const crown = normalView.y.clamp(0, 1).pow(2.0).mul(0.30);
    m.colorNode = mix(vec3(0.015, 0.015, 0.022), col(P[1]).mul(0.7), rim.add(crown).clamp(0, 1));
    /*
     * ПЛОТНОСТЬ РАСТЁТ К СИЛУЭТУ (`dome`), а не стоит ровной заливкой. Ровная
     * давала плоский серый круг — «шарик», а не массу; вдобавок самой плотной
     * оказывалась именно середина, то есть то место, где под шаром стоит
     * жертва. Здесь наоборот: середина 0.88 от `fill` (сквозь неё читается
     * силуэт), край — единица (силуэт самого шара остаётся резким). Толща по
     * лучу зрения у шара и правда растёт к краю — это не приём, а его форма.
     *
     * НО РАМПА БЫЛА В ПОСЛЕДНИХ ДВУХ ПРОЦЕНТАХ РАДИУСА, И ОТТОГО ЕЁ НЕ БЫЛО.
     * `fres^2.2` берёт половину хода при `u = 0.963`, а десятую долю — при
     * `u = 0.807`: 96 % диска стояли на одной и той же заливке 0.83. Это и
     * померено на кадрах: `f2-forms/gravity-zone-t1_50-broadcast`, луч из
     * центра шара (786,454) наружу — L 126.8 / 120.5 / 124.8 / 123.5 / 118.8 /
     * 114.6 при `u` 0 … 0.85, то есть ΔL 12 на 85 % радиуса, и только в
     * последних четырёх процентах падение до L 91.6 и 85.6. С низкого глаза
     * (тот же кадр `t0_15-low`, хорда 113 px) ΔL 2.0 — РОВНАЯ заливка.
     * Концы рампы (0.88 в середине, единица на кромке) сохранены дословно —
     * спорить с их обоснованием выше нечем, — а ход растянут на диск:
     * `smoothstep(0.07, 0.66, fres)` идёт от `u = 0.37` до `u = 0.94`, две
     * трети радиуса, и весь перепад 0.83 → 1.0 достаётся глазу, а не кромке
     * в четыре процента.
     */
    const dome = smoothstep(float(0.07), float(0.66), fres).clamp(0, 1);
    /* Нутро при `fill` = 0 не исчезает совсем: 0.10 тёмного даёт линзу, за
       которой тело чуть темнеет, — вес виден и без заливки. */
    const alpha = mix(fill.max(0.1).mul(0.88), float(1.0), dome).mul(fade).clamp(0, 1);
    m.opacityNode = alpha;
    /* Ноль, а не маска: см. шапку материала. Гравитация не отдаёт в bloom
       НИЧЕГО — это единственный способ гарантировать, что тонмаппинг не
       вытащит ядро светлее пола. */
    return markGlow(m, float(0));
  }, 4);
}

let WELL_GEO = null;
function well(P, radius, fill = 0.95) {
  if (!WELL_GEO) WELL_GEO = shared(new THREE.IcosahedronGeometry(1, 4));
  const m = wellMat(P);
  const mesh = new THREE.Mesh(WELL_GEO, m);
  mesh.frustumCulled = false;
  mesh.renderOrder = 9;
  mesh.scale.setScalar(radius);
  return {
    mesh,
    set(fade, r = radius, f = fill) {
      m.userData.fade.value = fade;
      m.userData.u.fill.value = f;
      mesh.scale.setScalar(Math.max(0.001, r));
    },
  };
}

/* ── продавленный пол: чаша, кольца, кромка ─────────────────────────────── */

/*
 * КВАД ШИРЕ ФОРМЫ. Тень чаши не кончается ровно на кромке зоны — она сходит
 * на нет ЗА ней, и если квад равен диску, край тени срезается прямой линией
 * (та же жалоба, из-за которой 04.09 расширили квад луж). Поэтому меш строится
 * в `RINGS_QUAD` раз шире радиуса, а шейдер делит расстояние обратно: `dz` = 1
 * ровно на кромке зоны, и дальше до 1.2 живёт вылет тени.
 */
const RINGS_QUAD = 1.28;

/**
 * `ringsMat` — ПРОДАВЛЕННЫЙ ПОЛ. Обычный блендинг тёмного `P[2]`: на этой
 * арене тёмную стихию несёт БЕЛЫЙ ПОЛ, и всё, что гравитация умеет показать
 * издалека, она показывает им.
 *
 * ЗАМЕР, ИЗ-ЗА КОТОРОГО ЭТО ПЕРЕПИСАНО. Кадр `gravity-zone-t1_50-broadcast`
 * против того же каста на 4.0 с (эффекта уже нет): с трансляционных 26 м от
 * трёхметрового колодца отличались 4694 пикселя арены — 1.8% кадра, при 22930
 * у ледяной зоны и 49529 у огненной. Прежний диск давал в центре альфу
 * `line·0.6 + 0.18` — светло-серую вуаль, из которой на дистанции выживали
 * два тонких кольца. Поэтому вес теперь несёт ЧАША: тёмное пятно, глубокое в
 * середине и сходящее на нет к кромке, а кольца и кромка — рисунок ПОВЕРХ
 * него, а не вместо.
 *
 * КОЛЬЦА ПОЛЗУТ К ЦЕНТРУ. Прежде они ПОЛЗЛИ НАРУЖУ (в фазе `26·d^0.55 − 0.6·t`
 * точка постоянной фазы уходит к краю) — проекция колодца показывала волны,
 * убегающие ОТ центра, ровно наоборот к строке палитры «тяжесть и
 * притяжение»; потом их остановили совсем, и с 26 м колодец перестал
 * двигаться. Теперь знак ТОТ ЖЕ, что у следа `grav` в общем слое (`kit.js`:
 * `d^0.55·26 + TIME·0.6`), потому что проекция и вмятина обязаны быть одним
 * почерком. Это не обещание силы, а форма ямы: стенки сходятся к дну, и
 * рисунок на них идёт туда же. Настоящую силу — снос к кастеру — рисует
 * `pullDrift`, и только когда запись зоны несёт атом `pull`.
 *
 * Чаша при этом дышит на месте (`breath`): пол проседает и отпускает, никуда
 * не двигаясь.
 *
 * Не путать со следом `grav` (`kit.decal`): тот ОСТАТОК — вмятина, которая
 * распрямляется ПОСЛЕ эффекта, — а этот ПРОЕКЦИЯ, живущая ровно пока стоит
 * колодец. Кольца гасит `out` (у зоны — её же схлопывание), след — `decalFade`.
 *
 * `depth` — сколько этой чаши берёт форма: зона давит на всю (1.0), статус
 * «придавлен» держит под телом тень вдвое легче (0.72). Одна ручка вместо
 * пяти материалов.
 */
function ringsMat(P) {
  return pooled(`grav:rings:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    const depth = uniform(1);
    m.userData.u = { depth };
    const q = uv().sub(vec2(0.5, 0.5)).mul(2);
    const dz = q.length().mul(RINGS_QUAD);
    /* ЧАША. Показатель 1.15, а не 1.7: на кадре `p3` при 1.7 темнота сидела в
       середине — ровно там, где её закрывает тело жертвы, стоящей в зоне, — а
       на видимом кольце оставалось 0.15 альфы, и умение читалось «кругами на
       воде». Показатель чуть выше единицы растягивает яму почти во весь диск,
       но всё же оставляет уклон: ровная заливка была бы наклейкой, а вес —
       это ЯМА, у неё есть дно. */
    const bowl = oneMinus(dz.div(1.2)).clamp(0, 1).pow(1.15);
    const breath = tsin(TIME.mul(2.0)).mul(0.5).add(0.5);
    const sink = bowl.mul(mix(float(0.84), float(1.0), breath));
    /* Шаг сжимается к центру (`dz^0.55`), множитель 26 и снос `+TIME·0.6` — всё
       три взяты из следа `grav` в `kit.js` буквально: проекция и вмятина
       обязаны быть одним почерком, иначе на полу видно, где кончилась одна и
       началась другая. Знак `+` гонит точку постоянной фазы К ЦЕНТРУ.
       Линии УЗКИЕ (окно 0.52…0.95, было 0.30…0.88): широкие светлые полосы на
       кадре `p3` читались кругами на воде, а узкие и чёрные — насечкой,
       выдавленной в полу, то есть горизонталями на карте ямы. */
    const wave = tsin(dz.pow(0.55).mul(26.0).add(TIME.mul(0.6))).mul(0.5).add(0.5);
    const inside = oneMinus(smoothstep(float(0.9), float(1.06), dz));
    const line = smoothstep(float(0.52), float(0.95), wave).mul(inside);
    /* КРОМКА — граница площади умения. Зона поражает диск, и зритель обязан
       видеть, где этот диск кончается: без кромки чаша расплывается и по ней
       нельзя сказать, откуда шагнуть. Край РВАНЫЙ на ±0.045: идеальная
       окружность на полу читается наклейкой, а не продавленным грунтом (тот
       же приём, что у края лужи и ожога в `kit.js`). */
    const rough = mx_noise_float(vec3(q.mul(2.2), 3.1)).mul(0.045);
    const rim = oneMinus(dz.add(rough).sub(1.0).abs().mul(11.0)).clamp(0, 1).pow(1.4);
    /*
     * ВЕСА СТОЛЬКО ЖЕ, СКОЛЬКО БЫЛО У КОЛЕЦ. Первая попытка чаши раздала
     * плотность поровну (0.52/0.30/0.34) и на кадре `p2` дала на белом полу
     * (L 217) провал только до L 167 — альфа 0.25 вместо прежних 0.63 у
     * тонкого кольца (L 87 на том же профиле). Широкая светлая рябь ЗАМЕНИЛА
     * тёмное кольцо вместо того, чтобы его окружить: с 26 м это читалось
     * кругами на воде. Поэтому линии вернули прежнюю черноту (0.58 сверх
     * чаши), а чаша (0.78) добавляется к ним, а не вместо них.
     */
    const ink = sink.mul(0.78).add(line.mul(0.58)).add(rim.mul(0.5));
    m.colorNode = mix(col(P[2]).mul(0.5), vec3(0.015, 0.015, 0.022), sink.add(line.mul(0.5)).clamp(0, 1));
    m.opacityNode = ink.mul(depth).mul(fade).clamp(0, 0.92);
    return markGlow(m, float(0));
  }, 6);
}

let RINGS_GEO = null;
function rings(vfx, P, { x, z, r, life, at = 0, follow = null, depth = 1, out = null, env = null }) {
  if (!RINGS_GEO) RINGS_GEO = shared(new THREE.PlaneGeometry(1, 1).rotateX(-Math.PI / 2));
  const m = ringsMat(P);
  const mesh = new THREE.Mesh(RINGS_GEO, m);
  mesh.position.set(x, 0.028, z);
  mesh.scale.setScalar(r * 2 * RINGS_QUAD);
  mesh.renderOrder = 3;
  mesh.frustumCulled = false;
  vfx.spawnMesh(mesh, life + at, (o, u) => {
    const t = u * (life + at);
    /* Вход 0.08 с, выход — последняя пятая часть жизни (не длиннее 0.3 с):
       прежний вход 0.25 с и выход 0.35 с съедали короткое кольцо удара
       целиком. `out` перебивает эту меру там, где кольца обязаны гаснуть
       ВМЕСТЕ с формой: у зоны это её схлопывание (`END`), и без совпадения
       колодец приседал полсекунды, а пол под ним щёлкал за 0.3 с. */
    const outT = out == null ? Math.min(0.3, life * 0.2) : Math.min(out, life * 0.5);
    /* `env` — ВНЕШНЯЯ огибающая (уход статуса по `until`): чаша статуса ездит
       за телом, а срок ей держит сим, а не собственная жизнь. Своя рампа при
       этом не заменяется, а УМНОЖАЕТСЯ — иначе продлённый статус кончился бы
       обрывом в тот миг, когда пул снимает носитель. */
    m.userData.fade.value = t < at ? 0
      : Math.min(1, (t - at) / 0.08) * (t > life + at - outT ? Math.max(0, (life + at - t) / outT) : 1)
        * (env ? env() : 1);
    /* Глубина ставится КАЖДЫЙ кадр, а не при рождении: материал взят из
       кольца пула и мог достаться другой форме с другой чашей. */
    m.userData.u.depth.value = depth;
    if (follow) { const p = follow(); if (p) { o.position.x = p.x; o.position.z = p.z; } }
  });
  return mesh;
}

/* ── вал тяжёлой пыли по кромке ─────────────────────────────────────────── */

/**
 * `shaftMat` — ВАЛ ТЯЖЁЛОЙ ПЫЛИ, стоящий по кромке продавленной чаши.
 *
 * Зачем он вообще. У колодца не было ВЫСОТЫ: ядро на 1.6 м сливалось с телом
 * жертвы, стоящей в зоне, а всё остальное лежало на полу, — и с почти
 * горизонтальной трансляционной камеры (наклон 0.46 рад) умение на три метра
 * радиуса не читалось ничем, кроме колец (замер в шапке, 4694 пикселя).
 *
 * ПОЧЕМУ ЭТО ВАЛ, А НЕ КОЛОННА. Первая версия ставила конус в 2.8 м высотой
 * на всю площадь зоны. На кадре `p2/gravity-zone-t1_50-broadcast` он дал ровно
 * то, чего гравитации нельзя: бледный трапецеидальный клин с ПРЯМЫМИ рёбрами,
 * расходящийся кверху, — конус ПРОЖЕКТОРА. Гравитация не светит; всё, что
 * похоже на свет, у неё враньё.
 *
 * ВТОРАЯ ВЕРСИЯ СПАСАЛАСЬ ОТ КЛИНА ТЕМ, ЧТО ПРОПАДАЛА. Плотность там падала
 * как `low^1.8`: к метру над полом от неё оставалась пятая часть, к 1.6 м —
 * ничего. Судья 04.09 записал результат дословно: «на
 * `p5-gravity/gravity-zone-t0_40-broadcast` у кромки высоты нет — только чуть
 * более мутный пол», и вал в отчёте нельзя было считать сделанным.
 *
 * ЗАМЕР, ПО КОТОРОМУ ЭТО ЧИНИЛОСЬ. Экранную площадь вала снял контрольный
 * прогон `wip-gravity-dbg2` — тот же вал, покрашенный в красное с альфой
 * 0.95; по нему вырезана маска «левая дуга вала НАД полом» (1875 пикселей,
 * x 660…745, y 505…625 на трансляции). Средняя яркость в маске на 1.5 с:
 * чистая арена 218.7, отправленное состояние `p5-gravity` 181.4 (Δ 37),
 * канон `r2-gravity` — 161.1 (Δ 57.6). Вал стал темнить кромку в полтора раза
 * сильнее, и это уже не «чуть более мутный пол», а гряда.
 *
 * ТРЕТЬЯ ВЕРСИЯ БЕРЁТ ВЫСОТУ, НО НЕ ЛОМАЕТ СИЛУЭТ. Клин читался прожектором
 * не из-за высоты, а из-за ПРЯМОЙ верхней кромки: ровная линия поперёк кадра
 * — это край луча, ничем другим она быть не может. Поэтому здесь верх РВАНЫЙ:
 * гребень гуляет по кругу шумом (`crest`, 0.40…0.80 высоты вала = 0.9…1.8 м
 * при `shaftHeight` 2.2), и вал читается грядой пыли, у которой нет ни одной
 * прямой. Плотность при этом держится до самого гребня (`low^0.7` вместо
 * `^1.8`) и только там срезается за 0.26 высоты, а под срезом идёт полоса
 * погуще (`edge`) — тёмная кромка НА БЕЛОМ, по которой и читается высота.
 *
 * И ВАЛ ОБЯЗАН БЫТЬ ПРОЗРАЧНЫМ. Трансляционная камера смотрит под 0.46 рад:
 * непрозрачная гряда в 1.3 м на ближней кромке закрыла бы за собой всё до
 * 1.3 + 3·tg(26°) ≈ 2.8 м, то есть бойца целиком — ту же ошибку, за которую
 * сняли ядро. Поэтому потолок альфы 0.55: тёмная гряда, СКВОЗЬ которую видно
 * жертву (соответствие силуэта чистому кадру в рамке тела на трансляции
 * r = 0.844 в каноне против 0.764 у отправленного состояния — вал ставился
 * ВМЕСТЕ с поднятым ядром, и вместе они не убавили читаемости, а прибавили).
 *
 * Почему это честно. Вал СТОИТ и повторяет площадь зоны — это её объём, а не
 * движение вещества: он ничего не обещает про то, куда полетит жертва (см.
 * правду сима в шапке). Единственное, что в нём движется, — рисунок `rain`,
 * ползущий ВНИЗ: вниз честно всегда.
 */
function shaftMat(P) {
  return pooled(`grav:shaft:${hex(P)}`, () => {
    const m = new THREE.MeshBasicNodeMaterial({
      transparent: true, depthWrite: false, side: THREE.DoubleSide, blending: THREE.NormalBlending,
    });
    const fade = withFade(m);
    /* uv цилиндра: y = 1 наверху, 0 у пола (`CylinderGeometry` пишет 1−v). */
    const up = uv().y.clamp(0, 1);
    const low = oneMinus(up).pow(0.7);
    /* ГРЕБЕНЬ РВАНЫЙ. Шум берётся не от `uv.x` напрямую, а от точки НА
       ОКРУЖНОСТИ (`cos/sin` того же угла): у цилиндра `uv.x` рвётся с 1 на 0
       на шве, и шум по нему дал бы ровно в этом месте вертикальный обрыв —
       единственную прямую линию во всём вале. */
    const ang = uv().x.mul(TAU);
    const crest = mx_noise_float(vec3(tcos(ang).mul(2.3), tsin(ang).mul(2.3), 1.7)).mul(0.20).add(0.60);
    /* Срез за 0.26 высоты до гребня: не ступенька и не дымка на весь рост. */
    const body = oneMinus(smoothstep(crest.sub(0.26), crest, up)).clamp(0, 1);
    /* ГРЕБЕНЬ ПЛОТНЕЕ ТЕЛА. Без этой полосы вал был телом без края: тёмная
       муть у пола ложилась на такие же тёмные кольца проекции и не давала
       глазу ЛИНИИ, по которой читается высота. Контрольный прогон
       (`wip-gravity-dbg2`, вал в красном с альфой 0.95) показал гряду в 237
       пикселей по вертикали — она была на месте и в тёмном виде, но верх
       растворялся в белом полу за ней. Полоса под срезом даёт рваную тёмную
       кромку НА БЕЛОМ, и это единственное место вала, которое обязано быть
       заметным. */
    const edge = smoothstep(crest.sub(0.26), crest.sub(0.06), up).mul(body);
    const fres = oneMinus(tabs(TSL.dot(normalView, positionViewDirection))).clamp(0, 1);
    /* Дождь тяжести: рисунок ползёт ВНИЗ. Знак `+TIME` именно поэтому — при
       `−TIME` точка постоянной фазы уходит вверх, и вал начинает всплывать. */
    const rain = mx_noise_float(vec3(uv().x.mul(9.0), uv().y.mul(2.6).add(TIME.mul(0.55)), 0.0)).mul(0.5).add(0.5);
    /* Френель ВЗВЕШЕН телом гряды, а не высотой: он сгущает ближние и дальние
       стенки (там, где взгляд идёт вдоль поверхности) и молчит там, где вала
       уже нет, — иначе рисовал бы рёбра выше гребня, то есть возвращал бы
       прожекторный клин. */
    const veil = body.mul(mix(float(0.30), float(0.50), low)).add(edge.mul(0.42)).add(fres.pow(2.0).mul(body).mul(0.22));
    m.colorNode = mix(col(P[2]).mul(0.6), vec3(0.02, 0.02, 0.03), low.clamp(0, 1));
    m.opacityNode = veil.mul(mix(float(0.68), float(1.2), rain)).mul(fade).clamp(0, 0.55);
    return markGlow(m, float(0));
  }, 3);
}

let SHAFT_GEO = null;
/**
 * Вал: открытая труба от пола вверх, почти без поджатия (0.86). `grow`/`end`
 * — те же фазы, что у ядра: вал ВСТАЁТ вместе с колодцем и ПРИСЕДАЕТ на
 * схлопывании, а не гаснет прозрачностью на месте (гаснущий на месте читался
 * бы выключателем).
 */
function shaft(vfx, P, { x, z, r, h, life, grow, end, alpha = 1 }) {
  if (!SHAFT_GEO) SHAFT_GEO = shared(new THREE.CylinderGeometry(0.86, 1, 1, 56, 1, true));
  const m = shaftMat(P);
  const mesh = new THREE.Mesh(SHAFT_GEO, m);
  mesh.position.set(x, h * 0.5, z);
  mesh.scale.set(r, h, r);
  mesh.renderOrder = 5;
  mesh.frustumCulled = false;
  m.userData.fade.value = 0;
  vfx.spawnMesh(mesh, life, (o, u) => {
    const t = u * life;
    const inK = Math.min(1, t / Math.max(0.001, grow));
    const outK = t > life - end ? Math.max(0, (life - t) / Math.max(0.001, end)) : 1;
    m.userData.fade.value = alpha * inK * outK;
    const hh = h * (0.55 + 0.45 * inK) * (0.45 + 0.55 * outK);
    o.scale.set(r, hh, r);
    o.position.y = hh * 0.5;
  });
  return mesh;
}

/* ── падающая пыль и тонущие обломки ────────────────────────────────────── */

/**
 * ВЕЩЕСТВО, ПАДАЮЩЕЕ ОТВЕСНО: начальная скорость нулевая, жизнь — ровно до
 * пола, `sqrt(2y/g)`.
 *
 * ДВЕ ПРАВКИ ПОСЛЕ ЗАМЕРА 04.09, и обе про «этого не видно с трансляции».
 *
 * 1. ФОРМА — ШТРИХ, А НЕ ТОЧКА. Точка 0.05–0.10 м с 26 м занимает меньше
 *    пикселя: единственное, что в колодце двигалось, не было видно вовсе.
 *    Штрих (`SHAPE.streak`) вытягивается по скорости (`ext.z` = 1, множитель
 *    `1 + |v|·0.18`), и на 11 м/с у пола он даёт тёмную вертикаль около метра
 *    — на белом полу это читается и с дистанции решателя.
 *
 * 2. ТЯЖЕСТЬ 22, А НЕ 9. Девять — это ускорение, с которым на арене падает
 *    ВСЁ; им нельзя сказать «здесь тяжелее». Двадцать два — вдвое с лишним
 *    против мира: вещество в колодце заметно обгоняет обычное падение, и это
 *    и есть вся заявка гравитации, сделанная движением. Побочно это ещё и
 *    ЧИСТИТ кадр: с 4 м частица долетает до пола за 0.6 с вместо 0.94 с.
 *
 * `glow` = 0: тёмное вещество не имеет права попасть в bloom — у этой стихии
 * не светится НИЧТО, включая обод (см. `wellMat`).
 */
function fallDust(vfx, P, { x, z, r, n, rng, y0 = 2.2, y1 = 4.2, at = 0, g = 22, size = 0.06, size2 = 0.11 }) {
  vfx.body.emit(n, (i, s) => {
    const a = rng() * TAU, d = Math.sqrt(rng()) * r;
    const y = y0 + rng() * (y1 - y0);
    const life = Math.sqrt((2 * y) / g);
    s.pos(x + Math.sin(a) * d, y, z + Math.cos(a) * d);
    s.vel(0, 0, 0);
    s.gravity(0, -g, 0);
    s.color(P[2], P[2].clone().multiplyScalar(0.5));
    s.life(vfx.now + at, life, size + rng() * (size2 - size), kit.SHAPE.streak);
    /* `endSize` 0.3 — штрих СЪЁЖИВАЕТСЯ у пола, а не пропадает во весь рост:
       пыль оседает, а не выключается. */
    s.ext(0, 0.3, 1, 0);
  });
}

/**
 * ВЫДОХ — ТЁМНАЯ ПЫЛЬ, А НЕ УДАРНАЯ ВОЛНА.
 *
 * Здесь стоял `kit.shockwave`, и это была последняя дыра в правиле «у
 * гравитации ничто не светит». Общее кольцо всегда рисует ДВА слоя, и второй
 * (`hot`) — аддитивный, помеченный в bloom, с цветом `mix(colour, белый, 0.5)`
 * в кадре рождения: каким бы тёмным ни был `colour`, на выходе получается
 * серо-белая вспышка. Первый круг судей её не поймал только потому, что между
 * 1.5 с и 4.0 с не было ни одного кадра, а выдох живёт 0.5 с и целиком
 * укладывался в этот провал. Теперь момент 2.6 с снимается обязательно, и
 * оставлять там аддитивное кольцо нельзя.
 *
 * Взамен — то же движение частицами: низкое кольцо тяжёлых штрихов, идущее
 * наружу и оседающее (`gravity` −6). Это ВЫДОХ: колодец схлопнулся и выдавил
 * из-под себя воздух. Скорость подобрана так, чтобы штрих дошёл до заявленной
 * кромки ровно за свою жизнь, — кольцо расширяется, а не рассыпается.
 */
function outbreath(vfx, P, { x, z, r, life, n, rng }) {
  const v = r / Math.max(0.1, life);
  vfx.body.emit(n, (i, s) => {
    const a = (i / n) * TAU + rng() * 0.35;
    s.pos(x + Math.sin(a) * 0.35, 0.10 + rng() * 0.30, z + Math.cos(a) * 0.35);
    s.vel(Math.sin(a) * v, 0.5 + rng() * 0.6, Math.cos(a) * v);
    s.gravity(0, -6, 0);
    s.color(P[2], P[2].clone().multiplyScalar(0.5));
    s.life(vfx.now, life, 0.13 + rng() * 0.08, kit.SHAPE.streak);
    s.ext(0, 0.4, 1, 0.3);
  });
}

/**
 * СНОС К КАСТЕРУ — единственное в колодце, что показывает СИЛУ, а не форму.
 *
 * Судья первого круга: «нет ни одного элемента, указывающего НА КАСТЕРА
 * (`p5-gravity/gravity-zone-t1_50-broadcast`, паук стоит слева вверху) —
 * визуал говорит „придавило на месте“, а сим тащит жертву к кастеру». Он был
 * прав, и прав был первый круг, что чинится это не здесь: запись `zone` не
 * несла списка своих атомов, и зона не могла ОТЛИЧИТЬ себя тянущую от себя
 * жгущей. С 04.09 несёт (`src/core/deliver.js`), и запрет снят.
 *
 * Что рисуем. Низкий (0.2…0.9 м) снос тяжёлого вещества ОТ ямы К ТЕЛУ
 * КАСТЕРА, тем же тактом 0.5 с, которым сим применяет атомы зоны
 * (`ZONE_PERIOD`): не «эффект поверх эффекта», а видимая механика. Направление
 * взято из `effects.js` буквально (`dx = src.x − to.x`) — к позиции кастера, а
 * не к центру зоны; штрих живёт 0.42 с и пролетает 3.4–4.6 м, то есть не
 * выходит за площадь и ничего не копит на полу.
 *
 * Пять штрихов на такт, а не двадцать: общий слой на том же такте уже сыплет
 * восемь штрихов, сходящихся к центру (`vfx.zonePull`), и вместе это должно
 * читаться одной механикой — «яму затягивает внутрь, а яму тянет на кастера»,
 * — а не двумя эффектами на одном месте. Захламление у стихии 88 из 100, и
 * терять его на подпись атома нельзя.
 */
function pullDrift(vfx, P, { x, z, r, tx, tz, rng, n = 5 }) {
  const dx = tx - x, dz = tz - z;
  const l = Math.hypot(dx, dz);
  /* Кастер В САМОЙ яме тянуть некуда: направление не определено, и штрихи
     разлетелись бы веером. */
  if (l < 0.8) return;
  const ux = dx / l, uz = dz / l;
  vfx.body.emit(n, (i, s) => {
    const a = rng() * TAU, d = Math.sqrt(rng()) * r * 0.8;
    s.pos(x + Math.sin(a) * d, 0.2 + rng() * 0.7, z + Math.cos(a) * d);
    /* 8…11 м/с: при `ext.z` = 1 штрих вытягивается на `1 + |v|·0.18`, то есть
       вдвое с лишним, и 0.175 м зерна дают на кадре тёмную черту около
       полуметра — вровень с падающим веществом у пола. Медленнее — точка. */
    const v = 8 + rng() * 3;
    s.vel(ux * v, 0.15, uz * v);
    s.gravity(0, -3, 0);
    s.color(P[2], P[2].clone().multiplyScalar(0.5));
    s.life(vfx.now, 0.42, 0.15 + rng() * 0.05, kit.SHAPE.streak);
    s.ext(0, 0.35, 1, 0.3);
  });
}

