/**
 * Рукописный эталон для грамматики §8 — сторона гориллы.
 *
 * У него две работы, и вторая важнее первой.
 *
 * ПЕРВАЯ: быть настоящим слабым спарринг-партнёром (§7.3) — тем, на ком
 * новичок выигрывает и понимает почему. N4 запрещает постановку, а не
 * слабость: он играет в полную силу своей несложной головы, его винрейт
 * замерен и напечатан, и на экране он назван тренировочным.
 *
 * ВТОРАЯ: быть ИЗМЕРИТЕЛЬНЫМ ПРИБОРОМ для баланса. `tools/kitbalance.mjs`
 * ставит его по обе стороны, и тогда единственное, чем различаются бойцы, —
 * набор умений. Из этого следует требование, которого у обычного мозга нет:
 * он обязан пользоваться КАЖДЫМ видом умения хотя бы разумно. Прибор,
 * который умеет только бить, покажет, что все четырнадцать атомов, кроме
 * урона, ничего не стоят, — и это будет измерение прибора, а не грамматики.
 * Ровно это и вышло на первом прогоне: двенадцать атомов из четырнадцати
 * получили ровно 50%, потому что мозг их не применял ни разу.
 *
 * Чего он НЕ делает и делать не должен: не строит планов, не считает
 * размены, не запоминает противника. Он ровный исполнитель, и цифры,
 * снятые на нём, — нижняя граница силы набора, а не её оценка.
 *
 * Он читает свой набор из перцепции (F10) и не знает ни одного имени умения
 * заранее: смена набора его не ломает и не требует перегенерации.
 */

let lastSay = -99;

function think(p, api) {
  const me = p.self;
  const en = p.enemy;
  if (!me || !me.alive || !en) return;

  const say = function (text, gap) {
    if (p.t - lastSay > gap) { api.say(text); lastSay = p.t; }
  };

  /* Заткнули — двигаемся, а не стоим. Молча стоящее существо читается
     сломанным, а сломало его умение противника, и это надо показать. */
  if (me.silenced) {
    const away = V.away({ x: me.x, z: me.z }, { x: en.x, z: en.z });
    api.moveTo(me.x + away.x * 5, me.z + away.z * 5);
    say('нечем ответить', 6);
    return;
  }

  /*
   * КУДА идти и ЧЕМ бить — два независимых решения, и их нельзя объединять.
   *
   * Первая версия выходила из чужой зоны через `return`: ушёл — и на этом
   * ход закончен. Выглядит разумно и разрушает замер. Против набора с зоной
   * противник всю драку только убегает и не стреляет ни разу, и зона в лиге
   * доставок берёт 100.0% — цифра не про зону, а про то, что соперник
   * добровольно перестал драться.
   *
   * Живой человек в горящем круге делает две вещи сразу: выходит и стреляет.
   * Поэтому здесь считается ЦЕЛЬ движения, а выбор умения идёт своим
   * чередом ниже и на движение не смотрит.
   */
  let goal = null;

  const zones = (p.arena && p.arena.zones) || [];
  for (let zi = 0; zi < zones.length; zi++) {
    const z = zones[zi];
    if (z.mine) continue;
    if (V.dist({ x: me.x, z: me.z }, { x: z.x, z: z.z }) > z.r + me.radius) continue;
    const out = V.away({ x: me.x, z: me.z }, { x: z.x, z: z.z });
    goal = { x: z.x + out.x * (z.r + 3.5), z: z.z + out.z * (z.r + 3.5) };
    say('горячо', 9);
    break;
  }

  /* Ослеплённый знает, что видит прошлое, и не лезет в упор по памяти. */
  if (!goal && me.blinded) {
    const away = V.away({ x: me.x, z: me.z }, { x: en.x, z: en.z });
    goal = { x: me.x + away.x * 6, z: me.z + away.z * 6 };
    say('вижу вчерашний день', 8);
  }

  api.faceAt(en.x, en.z);

  const kit = me.kit || {};
  const names = [];
  for (let i = 0; i < me.skills.length; i++) {
    const n = me.skills[i];
    /* Оси «триггер» больше нет: КАЖДОЕ умение вызывается мозгом. Фильтр
       `trigger === 'active'` после её снятия отбрасывал весь набор — поле
       стало undefined, и эталонный мозг перестал применять что-либо вообще.
       Отсев по имени 'jump' тоже снят: после D160 `namesOf` отдаёт существу
       с набором ровно ключи набора, имени 'jump' там быть не может, а сам
       прыжок приезжает доставкой под именем k1..k3 и обязан рассматриваться
       наравне с остальными. */
    if (kit[n]) names.push(n);
  }

  const hpFrac = me.hp / me.maxHp;
  const enemyCasting = !!(en.casting && en.casting.telegraph);
  const has = function (k, id) {
    for (let i = 0; i < k.effects.length; i++) if (k.effects[i] === id) return true;
    return false;
  };
  const reachOf = function (k) {
    if (k.range !== undefined) return k.range;
    if (k.distance !== undefined) return k.distance;
    /*
     * Доставки, которые применяются К КАСТЕРУ, достают до себя — расстояние
     * до врага им безразлично. Их ТРИ: `self`, `blink` и прыжок (D160).
     *
     * Здесь проверялся только `self`, и это делало прибор слепым к двум
     * формам из девяти: и мигание, и прыжок получали дальность 3 м, то есть
     * применялись, только когда враг стоял вплотную. В лиге доставок обе
     * читались как «почти ничего не даёт» — а измерялось при этом не умение,
     * а собственный фильтр. Ровно та ошибка, против которой написан весь
     * комментарий в шапке файла.
     */
    return (k.kind === 'self' || k.kind === 'blink' || k.kind === 'jump') ? 1e9 : 3;
  };

  /**
   * Стоит ли применять умение ПРЯМО СЕЙЧАС.
   *
   * Оценка, а не список: у каждого умения свой момент, и «первое, что
   * готово» — это политика, при которой лечение уходит на полном здоровье,
   * а немота на пустой каст. Ноль означает «не сейчас».
   */
  const worth = function (k) {
    let v = 0;
    if (has(k, 'damage')) v += 10 + (k.damage || 0) * 0.25;
    if (has(k, 'burn')) v += 8;
    /* Лечение и щит — по нужде, а не по готовности. */
    if (has(k, 'heal')) v += hpFrac < 0.65 ? 14 * (1 - hpFrac) : 0;
    if (has(k, 'shield')) v += hpFrac < 0.8 || en.dist < 6 ? 9 : 0;
    if (has(k, 'cleanse')) v += (me.rooted || me.burning || me.blinded || me.silenced) ? 16 : 0;
    /* Контроль — когда он что-то отменяет или что-то держит. */
    if (has(k, 'stun') || has(k, 'silence')) v += enemyCasting ? 15 : 5;
    if (has(k, 'root')) v += en.dist < 9 ? 9 : 3;
    if (has(k, 'blind')) v += en.dist < 12 ? 9 : 4;
    if (has(k, 'knock')) v += en.dist < 4 ? 9 : 2;
    if (has(k, 'pull')) v += en.dist > 8 ? 8 : 2;
    if (has(k, 'weaken')) v += en.dist < 10 ? 7 : 2;
    if (has(k, 'boost')) v += en.dist < 12 ? 7 : 3;
    /* Стена — между собой и тем, кто идёт в упор. */
    if (has(k, 'wall')) v += en.dist < 8 ? 8 : 1;
    /* Мигание без эффекта — это разрыв дистанции, и он нужен под каст. */
    if (k.kind === 'blink') v += enemyCasting ? 12 : (en.dist < 5 ? 7 : 1);
    /*
     * Прыжок стоит ровно столько, сколько стоит то, ОТ ЧЕГО он уклоняет.
     *
     * Три доставки идут по земле и проходят под тем, кто в воздухе: конус,
     * зона и рывок. Против остальных ШЕСТИ (луч, снаряд, навес, мигание,
     * «на себя» и сам прыжок) он — чистая потеря 0.77 с, потому что в воздухе
     * нельзя приказать ничего. Значит применять его «когда готов» нельзя:
     * это не умение готовности, а умение момента.
     *
     * Что за умение летит, видно из перцепции: `en.casting.skill` называет
     * имя, `en.kit` отдаёт его живые параметры (F10). Замах конуса 0.28 с,
     * зоны — 0.45, рывка — 0.18; замах прыжка 0.06, и он поднимается выше
     * порога за ещё 0.033. То есть окно есть у всех трёх, и у рывка оно
     * ровно нулевое по запасу: 0.067 + 0.06 + 0.033 = 0.16 против 0.18.
     */
    if (k.kind === 'jump') {
      let inc = null;
      if (enemyCasting && en.kit && en.casting) inc = en.kit[en.casting.skill];
      const ground = !!inc && (inc.kind === 'cone' || inc.kind === 'zone' || inc.kind === 'dash');
      v += ground ? 18 : 0;
    }
    return v;
  };

  let best = null;
  for (let i = 0; i < names.length; i++) {
    const n = names[i];
    const k = kit[n];
    if (!api.ready(n)) continue;
    /* Дальность считается так же, как в симуляции: плюс радиус цели. */
    if (en.dist > reachOf(k) + (en.radius || 0)) continue;
    /* Луч и конус упираются в укрытие; снаряд и навес — нет. */
    if ((k.kind === 'beam' || k.kind === 'cone') && !en.visible) continue;
    const v = worth(k);
    if (v <= 0) continue;
    if (!best || v > best.v) best = { name: n, v: v, k: k };
  }

  if (best) {
    say('держи', 7);
    api.use(best.name, en.x - me.x, en.z - me.z);
  }

  /* Движение. Если есть срочная цель — уйти из огня, отойти вслепую — идём
     туда; иначе держим дистанцию, с которой достаёт самое дальнобойное из
     того, что есть. Каст и шаг в одном ходу не мешают друг другу: сим сам
     решит, что каст стопорит движение, и это его дело, а не мозга. */
  if (goal) { api.moveTo(goal.x, goal.z); return; }

  /* Дистанции — в СВОИХ радиусах, а не в метрах: см. тот же блок в
     octopus.js. Мозг-прибор, работающий по-разному на разных размерах,
     меряет себя, а не размер. */
  const R = me.radius || 1;
  /*
   * Зазор — радиус ЦЕЛИ, а не сумма радиусов.
   *
   * Симуляция считает попадание как `dist <= range + radius цели`
   * (`deliver.js`), то есть свой радиус в дальность не входит. Прибавляя оба,
   * мозг вставал ДАЛЬШЕ собственной дальности: крупное существо с конусом на
   * 3.4 м желало дистанцию 5.4 и не доставало вовсе. На лиге размеров это
   * читалось как «0.90 выигрывает 100%», то есть как свойство размера.
   */
  const gap = en.radius || 0;
  /*
   * СТОЙКА ВЫБИРАЕТСЯ ПО ТОМУ УМЕНИЮ, КОТОРЫМ СОБИРАЕШЬСЯ БИТЬ.
   *
   * Здесь бралась САМАЯ ДАЛЬНАЯ доставка в наборе, и это делало всё короткое
   * мёртвым: с лучом на 24 метра стойка вставала на 16.8, а конус достаёт на
   * 3.4 — то есть конус не применялся НИ РАЗУ за бой.
   *
   * Замерено: на сорока тысячах случайных законных наборов у 80.2% есть
   * умение, которое этот мозг не может применить, и мертвы 37.4% всех
   * умений. Хуже того: в основе лиги атомов (навес+конус) мёртв был конус —
   * значит вся таблица цен снята ОДНИМ умением вместо двух.
   *
   * Теперь дистанция берётся у того умения, которое СЕЙЧАС стоит применить —
   * по той же оценке `worth`, что и выбор удара. Хочешь ударить конусом —
   * подойди на конус.
   */
  let far = 4 * R;
  let bestWorth = -1;
  for (let i = 0; i < names.length; i++) {
    const k = kit[names[i]];
    if (!api.ready(names[i])) continue;
    const v = worth(k);
    if (v <= 0) continue;
    const r = reachOf(k);
    if (v > bestWorth) { bestWorth = v; far = r < 1e8 ? Math.max(r, 4 * R) : 4 * R; }
  }
  if (bestWorth < 0) {
    /* Ничего не готово — держимся на самой дальней, чтобы не лезть зря. */
    for (let i = 0; i < names.length; i++) {
      const r = reachOf(kit[names[i]]);
      if (r < 1e8 && r > far) far = r;
    }
  }
  const want = far * 0.45 + gap;
  const band = 1.5 * R;
  const step = 4 * R;
  const to = V.toward({ x: me.x, z: me.z }, { x: en.x, z: en.z });
  if (en.dist > want + band) api.moveTo(en.x - to.x * want, en.z - to.z * want);
  else if (en.dist < want - band) api.moveTo(me.x - to.x * step, me.z - to.z * step);
  else {
    const side = V.perp(to);
    api.moveTo(me.x + side.x * step, me.z + side.z * step);
  }
}
